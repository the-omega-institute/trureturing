from math import comb, gcd, isqrt, lcm


@lru_cache(None)
def factors(n: int) -> tuple[tuple[int, int], ...]:
    if n < 1:
        raise ValueError('positive integer required')
    out = []
    p = 2
    while p*p <= n:
        e = 0
        while n % p == 0:
            n //= p
            e += 1
        if e:
            out.append((p, e))
        p = 3 if p == 2 else p+2
    if n > 1:
        out.append((n, 1))
    return tuple(out)


def prime(p: int) -> bool:
    return p >= 2 and factors(p) == ((p, 1),)


def v2(n: int) -> int:
    if n <= 0:
        raise ValueError('positive integer required')
    return (n & -n).bit_length()-1


@lru_cache(None)
def order2(p: int) -> int:
    if p <= 2 or not prime(p):
        raise ValueError('an odd prime is required')
    r = 1
    for o in range(1, p):
        r = 2*r % p
        if r == 1:
            return o
    raise AssertionError('order not found')


def reduced_order2(p: int) -> int:
    # Independent computation by removing divisors from p-1.
    o = p-1
    for r, _ in factors(p-1):
        while o % r == 0 and pow(2, o//r, p) == 1:
            o //= r
    return o


@lru_cache(None)
def layer(p: int) -> int:
    return v2(order2(p))


@lru_cache(None)
def chi(p: int) -> int:
    o = order2(p)
    if p == 3 or o % 2:
        raise ValueError('requires p>=5 with even order')
    value = pow(3, o//2, p)
    return 1 if value == 1 else -1 if value == p-1 else 0


def same_positive_layer(ps: tuple[int, ...]) -> bool:
    return bool(ps) and layer(ps[0]) > 0 and all(layer(p) == layer(ps[0]) for p in ps)


def no_opposite_chi(ps: tuple[int, ...]) -> bool:
    if any(p == 3 or layer(p) == 0 for p in ps):
        return False
    signs = {chi(p) for p in ps} - {0}
    return len(signs) <= 1


def odd_primes(n: int) -> tuple[int, ...]:
    return tuple(p for p, _ in factors(n) if p > 2)


def column_predicate(j: int) -> bool:
    ps = odd_primes(j)
    return len(ps) == 2 and 3 not in ps and same_positive_layer(ps) and no_opposite_chi(ps)


def residue_column(j: int) -> bool:
    ps = odd_primes(j)
    return len(ps) == 2 and ps[0] % 24 in (5, 11, 13, 19) and ps[1] % 24 == ps[0] % 24


def residue_gcd_pair(n: int, j: int) -> bool:
    d = gcd(n, j)
    ps = odd_primes(j)
    return (d & (d-1) == 0 and bool(ps) and ps[0] % 24 in (5, 11, 13, 19)
            and all(p % 24 == ps[0] % 24 for p in ps))


def vpbinom(n: int, j: int, p: int) -> int:
    ans, power = 0, p
    while power <= n:
        ans += n//power-j//power-(n-j)//power
        power *= p
    return ans


def carries(n: int, j: int, p: int) -> int:
    x, y, carry, ans = j, n-j, 0, 0
    while x or y or carry:
        carry = (x % p+y % p+carry)//p
        ans += carry
        x //= p
        y //= p
    return ans


def witness(n: int, j: int) -> int:
    # Factor three small integers, not the potentially large binomial.
    candidates = sorted(set(p for z in (n, n-1, n-2) for p, _ in factors(z) if p >= 3))
    for p in candidates:
        if vpbinom(n, 3, p) and vpbinom(n, j, p):
            assert carries(n, j, p) == vpbinom(n, j, p)
            return p
    raise AssertionError(('no shared prime', n, j))


def local_audit(pmax: int) -> dict:
    ps = [p for p in range(5, pmax+1) if prime(p)]
    gauss = minus = zero_chi = periodic_pairs = 0
    class_counts = Counter()
    for p in ps:
        o = order2(p)
        assert o == reduced_order2(p)
        for a, count in ((2, (p-1)//2-p//4), (3, p//3-p//6)):
            direct = sum((a*k) % p > p//2 for k in range(1, (p-1)//2+1))
            assert direct == count
            assert pow(a, (p-1)//2, p) == (1 if count % 2 == 0 else p-1)
            gauss += 1
        if layer(p):
            h = layer(p)
            for k in range(1, 2*o+1):
                value = pow(2, k, p)
                if value == 1:
                    assert k % (1 << h) == 0
                if value == p-1:
                    assert v2(k) == h-1
                    minus += 1
            ch = chi(p)
            if ch == 0:
                assert all((3*pow(2, N, p)) % p not in (1, 2) for N in range(o))
                zero_chi += 1
        residue = p % 24
        if residue in (5, 11, 13, 19):
            assert layer(p) == (1 if residue in (11, 19) else 2)
            expected = -1 if residue in (5, 19) else 1
            assert chi(p) in (0, expected)
            class_counts[residue] += 1
    # Fully inspect small prime pairs over their complete common exponent period.
    small = [p for p in ps if p <= 127]
    for a, p in enumerate(small):
        for q in small[a+1:]:
            if same_positive_layer((p, q)) and no_opposite_chi((p, q)):
                period = lcm(order2(p), order2(q))
                for N in range(period):
                    x, y = 3*pow(2, N, p) % p, 3*pow(2, N, q) % q
                    assert (x, y) not in ((1, 2), (2, 1))
                periodic_pairs += 1
    order_exception = []
    for N in range(5, 257):
        for h in range(1, 10):
            if N % (1 << h) == 0:
                assert h != 1+v2(N)
                if h == 1+v2(N-2):
                    assert h == 2
                    order_exception.append(N)
    # h=2 is genuinely possible in the order equations but fails the j-congruence.
    assert 8 in order_exception and pow(2, 8, 5) == 1 and pow(2, 6, 5) == 4
    assert all(3*j*(j+1) % 4 != 0 for j in range(1, 16, 4))
    assert 3*4*5 % 16 == 12 != 4
    # Hypotheses not interchangeable: opposite chi admits the local assignment.
    assert layer(11) == layer(19) == 1 and (chi(11), chi(19)) == (1, -1)
    assert 3*pow(2, 42, 11) % 11 == 1 and 3*pow(2, 42, 19) % 19 == 2
    assert not column_predicate(11*19)
    assert not same_positive_layer((11, 13)) and not column_predicate(11*13)
    assert layer(23) == 0 and not column_predicate(23*31)
    return {'primes': len(ps), 'gauss_counts': gauss, 'minus_one_order_controls': minus,
            'zero_chi_full_cycle_checks': zero_chi, 'complete_small_pair_periods': periodic_pairs,
            'four_class_prime_counts': dict(sorted(class_counts.items())),
            'h2_exception_retained_and_closed': True, 'opposite_sign_control_not_a_counterexample': True}


def ratio_audit(nmax: int) -> dict:
    identities = 0
    for n in range(8, nmax+1):
        for R in range(1, n):
            if (n-1) % R:
                continue
            L = (n-1)//R
            for m in range(1, (L-1)//2+1):
                j = 1+m*R
                theta = F((n-j)*(n-j-1), (n-1)*(n-2))
                k, D = theta.numerator, theta.denominator
                residual = D*(L-m)**2-k*L*L
                assert residual*(n-2) == D*(L-m)*m > 0
                assert residual >= 1 and 4*(n-2) < D*L*L
                identities += 1
    return {'exact_merged_denominator_gap_interfaces': identities,
            'premise_j_is_one_plus_mR': True, 'new_lean_certification_claimed': False}


def original_audit(nmax: int) -> dict:
    columns = [j for j in range(4, nmax//2+1) if column_predicate(j)]
    counts = Counter()
    new_vs_thin = []
    witnesses = Counter()
    for j in columns:
        if residue_column(j):
            counts['residue_class_columns'] += 1
        if len(odd_primes(j-1)) >= 2:
            new_vs_thin.append(j)
        for n in range(2*j, nmax+1):
            p = witness(n, j)
            witnesses[p] += 1
            counts['column_pairs'] += 1
            if n <= 500:
                assert gcd(comb(n, 3), comb(n, j)) % p == 0
                counts['direct_binomial_column_checks'] += 1
    row_counts = Counter()
    for multiplier in (1, 3):
        N = 3
        while (n := multiplier*(1 << N)) <= nmax:
            for j in range(4, n//2+1):
                ps = odd_primes(j)
                applies = same_positive_layer(ps)
                if multiplier == 3:
                    applies = applies and no_opposite_chi(ps)
                if applies:
                    witness(n, j)
                    row_counts[f'{multiplier}_times_power2_pairs'] += 1
                    if len(ps) >= 3:
                        row_counts['at_least_three_odd_prime_pairs'] += 1
            N += 1
    # Test the natural arbitrary-n, power-of-two-gcd corollary on a full small box.
    gcd_pairs = 0
    for n in range(8, min(nmax, 500)+1):
        for j in range(4, n//2+1):
            if residue_gcd_pair(n, j):
                witness(n, j)
                gcd_pairs += 1
    examples = []
    for j in (481, 817, 913, 1177, 145, 205):
        assert column_predicate(j)
        n = 2*j+13
        p = witness(n, j)
        examples.append({'j': j, 'factors': factors(j), 'example_n': n, 'shared_prime': p})
    if nmax >= 1826:
        assert 817 in new_vs_thin and 913 in new_vs_thin and 481 in new_vs_thin
    return {'nmax': nmax, 'general_order_columns': len(columns), **dict(counts),
            'columns_also_outside_old_j_minus_one_thin_test': new_vs_thin,
            'row_theorems': dict(row_counts), 'small_box_gcd_corollary_pairs': gcd_pairs,
            'named_columns_with_sample_witnesses': examples,
            'regression_is_not_the_unbounded_proof': True}


def symbolic_audit() -> dict:
    try:
        import sympy as S
    except ImportError as exc:
        raise SystemExit('--symbolic requires SymPy') from exc
    n, j, x = S.symbols('n j x')
    one = 3*(n-j)*(n-j-1)-(n-1)*(n-2)
    two = 3*(n-j)*(n-j-1)-2*(n-1)*(n-2)
    assert S.expand(one-(2*(n-1)*(n+1)-3*j*(2*n-1-j))) == 0
    assert S.expand(two-((n-1)*(n+4)-3*j*(2*n-1-j))) == 0
    assert S.expand(S.Rational(4, 27)-x*x*(1-x)-(x-S.Rational(2, 3))**2*(x+S.Rational(1, 3))) == 0
    L, R, m, D, k = S.symbols('L R m D k')
    ratio = D*(n-j)*(n-j-1)-k*(n-1)*(n-2)
    factor = R*((D*(L-m)**2-k*L*L)*(n-2)-D*(L-m)*m)
    substitutions = {n: L*R+1, j: 1+m*R}
    assert S.expand((factor-L*ratio).subs(substitutions)) == 0
    return {'two_theta_equations': True, 'inherited_integer_extremum': True,
            'exact_formal_gap_identity': True}


