def certificate()->dict:
    rows=[];group_elements=0;hom_checks=0;power_checks=0
    for S,roots,tables in EXAMPLES:
        assert all(prime(p) and p%4==1 for p in S)
        assert len({p%24 for p in S})>1
        assert {(p,q) for p,q,*_ in tables}==set(combinations(S,2))
        for p,q,m,a,b,expected in tables:
            gp,gq=roots[p],roots[q]
            assert a*(p-1)%m==0 and b*(q-1)%m==0
            lp,lq=log_table(p,gp),log_table(q,gq)
            gens=((2,2),)+tuple((r%p,r%q) for r in S if r not in (p,q))
            chi=lambda z:eval_character(z,p,q,gp,gq,m,a,b)
            assert all(chi(z)==0 for z in gens)
            vals=tuple(chi(z) for z in targets(p,q))
            assert vals==expected and all(vals)
            H=subgroup(p,q,gens)
            assert not (H&set(targets(p,q)))
            assert all(chi(z)==0 for z in H)
            assert len(H)*m==(p-1)*(q-1)
            group_elements+=len(H)
            # Homomorphism check on all generator edges of the whole product.
            for u in range(1,p):
                for v in range(1,q):
                    z=(u,v)
                    for h in gens:
                        assert chi((u*h[0]%p,v*h[1]%q))==(chi(z)+chi(h))%m
                        hom_checks+=1
            # Independent field-power realization of EACH character coordinate.
            for P,g,A in ((p,gp,a),(q,gq,b)):
                tab=log_table(P,g);d0=gcd(abs(A),m);order=m//d0
                assert (P-1)%order==0
                root=pow(g,(P-1)//order,P)
                images={pow(root,r,P):r for r in range(order)}
                assert len(images)==order
                for u in range(1,P):
                    exponent=images[pow(u,(P-1)//order,P)]
                    assert (A*tab[u])%m==(A*exponent)%m
                    power_checks+=1
            rows.append({'support':S,'pair':(p,q),'primitive_roots':(gp,gq),
                         'modulus':m,'weights':(a,b),'generator_images':[chi(z) for z in gens],
                         'target_images':vals,'subgroup_size':len(H),
                         'ambient_size':(p-1)*(q-1),'index':m})
    assert eval_character((1,568),5,569,2,3,8,2,1)==4
    z=targets(61,701)[5]
    assert eval_character(z,61,701,2,2,20,1,-1)==4
    return {'certificates':rows,'separated_targets':6*len(rows),
            'independently_enumerated_subgroup_elements':group_elements,
            'full_product_generator_homomorphism_checks':hom_checks,
            'independent_modular_power_coordinate_checks':power_checks,
            'C8_and_C20_refinement_controls':True}


def abstract_audit()->dict:
    vectors=0; shifts=0; dual_checks=0
    for size in range(1,6):
        for x in product(range(4),repeat=size):
            D=tuple((t-x[0])%4 for t in x[1:])
            assert (not any(D))==(len(set(x))==1)
            vectors+=1
            for shift in range(4):
                y=tuple((t+shift)%4 for t in x)
                assert tuple((t-y[0])%4 for t in y[1:])==D
                shifts+=1
    # Exhaust complete small cyclic products, including full and proper subgroups.
    for m in range(2,9):
        for n in range(2,9):
            ell=m*n//gcd(m,n)
            for a,b in product(range(m),range(n)):
                H={(k*a%m,k*b%n) for k in range(ell)}
                chars=[(u,v) for u in range(m) for v in range(n)
                       if (u*a*(ell//m)+v*b*(ell//n))%ell==0]
                for x,y in product(range(m),range(n)):
                    seen=any((u*x*(ell//m)+v*y*(ell//n))%ell for u,v in chars)
                    assert seen==((x,y) not in H)
                    dual_checks+=1
    return {'diagonal_vectors':vectors,'common_shifts':shifts,
            'finite_abelian_separation_controls':dual_checks}


def residual_audit(limit:int)->dict:
    count=twothirds=0
    for n in range(8,limit+1):
        for j in range(4,n//2+1):
            m=n-j
            assert 3*m*(m-1)-(n-1)*(n-2)==2*(n-1)*(n+1)-3*j*(2*n-1-j)
            assert 3*m*(m-1)-2*(n-1)*(n-2)==(n-1)*(n+4)-3*j*(2*n-1-j)
            if v2(n)>=v2(j)+2 and (j>>v2(j))%4==1:
                assert 3*m*(m-1)!=2*(n-1)*(n-2)
                twothirds+=1
            count+=1
    assert Q((56-11)*(56-12),55*54)==Q(2,3)
    return {'original_residual_pairs':count,'two_thirds_exclusions':twothirds,
            'negative_control_56_11':True}


def valuation_binom(n:int,j:int,p:int)->int:
    ans=0;power=p
    while power<=n:
        ans+=n//power-j//power-(n-j)//power;power*=p
    return ans


def carries(n:int,j:int,p:int)->int:
    a,b,c,total=j,n-j,0,0
    while a or b or c:
        c=(a%p+b%p+c)//p;total+=c;a//=p;b//=p
    return total


SMALL_PRIMES=tuple(p for p in range(3,2000) if prime(p))

def witness(n:int,j:int)->int:
    p=next((p for p in SMALL_PRIMES if valuation_binom(n,3,p)>0 and
            valuation_binom(n,j,p)>0),None)
    if p is None:raise AssertionError(('no small witness in this regression',n,j))
    assert carries(n,j,p)==valuation_binom(n,j,p)>0
    assert carries(n,3,p)==valuation_binom(n,3,p)>0
    return p


def original_audit(nmax:int)->dict:
    count=direct=0;cols=set();targeted=[]
    for S,_,_ in EXAMPLES:
        for j in range(4,nmax//2+1):
            rem=j
            for p in (2,)+S:
                while rem%p==0:rem//=p
            if rem!=1:continue
            cols.add((S,j))
            for n in range(2*j,nmax+1):
                p=witness(n,j)
                if n<=200:
                    assert gcd(comb(n,3),comb(n,j))%p==0;direct+=1
                count+=1
        for shared in S:
            for f in range(1,4):
                e=shared**f
                for b in range(3):
                    j=(1<<b)*e*prod(p for p in S if p!=shared)
                    N=max(b+2,((2*j-1)//e).bit_length())
                    for shift in (0,1,3):
                        n=e*(1<<(N+shift))
                        assert n>=2*j and gcd(n,j)==e*(1<<b)
                        p=witness(n,j)
                        targeted.append({'support':S,'shared_prime':shared,'shared_exponent':f,
                                         'n':n,'j':j,'odd_gcd':e,'common_prime':p})
    return {'small_box_nmax':nmax,'support_columns':len(cols),'small_box_pairs':count,
            'direct_binomial_checks':direct,'true_three_prime_odd_gcd_pairs':len(targeted),
            'targeted_examples':targeted,'finite_regression_is_not_unbounded_proof':True}


