def factor(n: int) -> tuple[tuple[int,int], ...]:
    if n<1: raise ValueError('positive integer required')
    out=[]; p=2
    while p*p<=n:
        e=0
        while n%p==0:n//=p;e+=1
        if e:out.append((p,e))
        p=3 if p==2 else p+2
    if n>1:out.append((n,1))
    return tuple(out)


def prime(p:int)->bool:
    return p>=2 and all(p%d for d in range(2,isqrt(p)+1))


def v2(n:int)->int:
    if n<=0:raise ValueError('positive integer required')
    return (n&-n).bit_length()-1


@lru_cache(None)
def log_table(p:int,root:int)->dict[int,int]:
    assert prime(p) and pow(root,p-1,p)==1
    assert all(pow(root,(p-1)//q,p)!=1 for q,_ in factor(p-1))
    out={};z=1
    for k in range(p-1):
        assert z not in out
        out[z]=k;z=z*root%p
    assert z==1 and len(out)==p-1
    return out


def subgroup(p:int,q:int,generators:tuple[tuple[int,int],...])->set[tuple[int,int]]:
    seen={(1,1)};stack=[(1,1)]
    while stack:
        u,v=stack.pop()
        for a,b in generators:
            assert a%p and b%q
            w=(u*a%p,v*b%q)
            if w not in seen:seen.add(w);stack.append(w)
    return seen


def targets(p:int,q:int)->tuple[tuple[int,int],...]:
    a,b=pow(3,-1,p),pow(3,-1,q)
    return ((1,2),(2,1),(1,q-1),(p-1,1),(a,2*b%q),(2*a%p,b))


def eval_character(z:tuple[int,int],p:int,q:int,gp:int,gq:int,m:int,a:int,b:int)->int:
    return (a*log_table(p,gp)[z[0]%p]+b*log_table(q,gq)[z[1]%q])%m


