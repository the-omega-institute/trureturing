using System.Collections.Immutable;
using System.Globalization;
using System.Text;
using StrataLint.Engine;

namespace StrataLint.Scribe;

/// Renders the repository truth DAG as a canonical Markdown projection.
///
/// The DAG itself is owned by StrataLint.Engine (AcyclicTruthDag); this writer only projects it,
/// exactly as CanonicalMarkdownWriter projects Scribe documents and FileMapProjectionWriter
/// projects Meta/FILEMAP.toml. It derives nothing: node state, graph depth, edge direction and the
/// content address all come from the capability, so the picture cannot disagree with the harness.
///
/// Mermaid vertex identifiers are positional (n0, n1, ...) over the DAG's ordinal node order rather
/// than escaped repository paths: escaping is not injective (A/B.lean and A_B.lean collapse under
/// separator replacement) and a collision would silently merge two truth nodes into one vertex.
public static class CanonicalDagWriter
{
    private static readonly UTF8Encoding StrictUtf8 = new(false, true);

    public static ImmutableArray<byte> Write(AcyclicTruthDag dag)
    {
        ArgumentNullException.ThrowIfNull(dag);

        var nodes = dag.Nodes
            .OrderBy(static node => node.RepoPath.Value, StringComparer.Ordinal)
            .ToImmutableArray();

        // The DAG spans every repository file, but only managed Lean modules carry imports and so
        // only they carry edges; everything else is an isolated vertex. Drawing those would bury
        // the proof topology (and overrun mermaid) without adding a single relationship, so the
        // flowchart and the depth listing take the formal nodes and the census states the rest.
        var formal = nodes
            .Where(static node => node.ModuleName is not null)
            .ToImmutableArray();
        var identifiers = formal
            .Select(static (node, index) => (node.RepoPath, Id: "n" + index.ToString(CultureInfo.InvariantCulture)))
            .ToImmutableDictionary(static item => item.RepoPath, static item => item.Id);

        var builder = new StringBuilder();
        AppendPreamble(builder, dag, nodes, formal);
        AppendGraph(builder, dag, formal, identifiers);
        AppendBlockers(builder, dag);
        AppendNodesByDepth(builder, dag, formal);
        return ImmutableArray.CreateRange(StrictUtf8.GetBytes(builder.ToString()));
    }

    private static void AppendPreamble(
        StringBuilder builder,
        AcyclicTruthDag dag,
        ImmutableArray<TruthNode> nodes,
        ImmutableArray<TruthNode> formal)
    {
        builder.Append("# Truth DAG\n\n")
            .Append("<!-- Generated by DagEmitter from the repository truth DAG. Do not edit. -->\n\n")
            .Append("- root: `")
            .Append(dag.RootSha256)
            .Append("`\n- nodes: ")
            .Append(Count(nodes.Length))
            .Append(" total, ")
            .Append(Count(formal.Length))
            .Append(" formal (")
            .Append(Count(nodes.Length - formal.Length))
            .Append(" carry no module and are not drawn)")
            .Append("\n- edges: ")
            .Append(Count(dag.Edges.Length))
            .Append("\n- open blockers: ")
            .Append(Count(dag.OpenBlockers.Length))
            .Append("\n- max depth: ")
            .Append(Count(MaxDepth(dag, formal)))
            .Append("\n- states: ");
        var census = Enum.GetValues<TruthState>()
            .Select(state => Name(state)
                + " "
                + Count(nodes.Count(node => node.State == state)));
        builder.AppendJoin(" | ", census).Append("\n\n");
    }

    private static void AppendGraph(
        StringBuilder builder,
        AcyclicTruthDag dag,
        ImmutableArray<TruthNode> formal,
        ImmutableDictionary<RepoPath, string> identifiers)
    {
        builder.Append("## Graph\n\n```mermaid\nflowchart TD\n");

        // Every class is declared unconditionally: a reader comparing two revisions should see the
        // legend stay put rather than appear and vanish with the census.
        foreach (var state in Enum.GetValues<TruthState>())
        {
            builder.Append("  classDef ")
                .Append(Name(state))
                .Append(' ')
                .Append(Style(state))
                .Append('\n');
        }

        foreach (var node in formal)
        {
            builder.Append("  ")
                .Append(identifiers[node.RepoPath])
                .Append("[\"")
                .Append(Label(node.RepoPath.Value))
                .Append("\"]:::")
                .Append(Name(node.State))
                .Append('\n');
        }

        foreach (var edge in dag.Edges
            .OrderBy(static edge => edge.Dependency.Value, StringComparer.Ordinal)
            .ThenBy(static edge => edge.Dependent.Value, StringComparer.Ordinal))
        {
            builder.Append("  ")
                .Append(identifiers[edge.Dependency])
                .Append(" --> ")
                .Append(identifiers[edge.Dependent])
                .Append('\n');
        }

        builder.Append("```\n\n");
    }

    private static void AppendBlockers(StringBuilder builder, AcyclicTruthDag dag)
    {
        builder.Append("## Open dependency blockers\n\n");
        if (dag.OpenBlockers.IsEmpty)
        {
            builder.Append("None.\n\n");
            return;
        }

        // A managed import with no node behind it is a hole in the graph. Listing it keeps the
        // picture honest: the flowchart above shows no edge there, and this says why.
        foreach (var blocker in dag.OpenBlockers
            .OrderBy(static blocker => blocker.Dependent.Value, StringComparer.Ordinal)
            .ThenBy(static blocker => blocker.DependencyModule, StringComparer.Ordinal))
        {
            builder.Append("- `")
                .Append(blocker.Dependent.Value)
                .Append("` imports `")
                .Append(blocker.DependencyModule)
                .Append("`, which this snapshot does not carry\n");
        }

        builder.Append('\n');
    }

    private static void AppendNodesByDepth(
        StringBuilder builder,
        AcyclicTruthDag dag,
        ImmutableArray<TruthNode> formal)
    {
        builder.Append("## Nodes by depth\n\n");
        if (formal.IsEmpty)
        {
            builder.Append("None.\n");
            return;
        }

        var groups = formal
            .GroupBy(node => dag.Depth(node.RepoPath))
            .OrderBy(static group => group.Key);
        foreach (var group in groups)
        {
            builder.Append("### depth ")
                .Append(Count(group.Key))
                .Append("\n\n");
            foreach (var node in group.OrderBy(static node => node.RepoPath.Value, StringComparer.Ordinal))
            {
                builder.Append("- `")
                    .Append(node.RepoPath.Value)
                    .Append("` — ")
                    .Append(Name(node.State))
                    .Append(" — ")
                    .Append(node.Gid is null ? "no GID" : "`" + node.Gid.Value + "`")
                    .Append('\n');
            }

            builder.Append('\n');
        }

        builder.Length -= 1;
    }

    private static int MaxDepth(AcyclicTruthDag dag, ImmutableArray<TruthNode> formal) =>
        formal.IsEmpty ? 0 : formal.Max(node => dag.Depth(node.RepoPath));

    private static string Count(int value) => value.ToString(CultureInfo.InvariantCulture);

    private static string Name(TruthState state) => state switch
    {
        TruthState.Closed => "closed",
        TruthState.Open => "open",
        TruthState.Tail => "tail",
        TruthState.Semantic => "semantic",
        _ => throw new ArgumentOutOfRangeException(nameof(state), state, "unknown truth state"),
    };

    private static string Style(TruthState state) => state switch
    {
        TruthState.Closed => "fill:#dcfce7,stroke:#166534,color:#052e16",
        TruthState.Open => "fill:#fef9c3,stroke:#854d0e,color:#1c1917",
        TruthState.Tail => "fill:#fee2e2,stroke:#991b1b,color:#450a0a",
        TruthState.Semantic => "fill:#e5e7eb,stroke:#374151,color:#111827",
        _ => throw new ArgumentOutOfRangeException(nameof(state), state, "unknown truth state"),
    };

    /// Mermaid ends a quoted label at the first unescaped quote. Repository paths cannot contain
    /// one today, so this is a guard against a future path shape silently truncating the graph.
    private static string Label(string value) => value.Replace("\"", "#quot;", StringComparison.Ordinal);
}
