#!/usr/bin/env python3
"""Exact finite diagnostics for the Fibonacci/Monster character-carry bridge.

No VOA, intertwining operator, Monster, or categorical realization is built.
All integers encode explicitly defined F_2 vectors or exact series coefficients.
"""
from collections import Counter
from fractions import Fraction
from itertools import combinations, permutations, product
from math import comb
from functools import reduce
from operator import xor
import json

COUNTS = Counter()
def check(name, condition):
    if not condition:
        raise AssertionError(name)
    COUNTS[name] += 1

def bit(x, i): return (x >> i) & 1
def dot(x, y): return (x & y).bit_count() & 1
def det(x, y, z):
    return sum(bit(x,i)*bit(y,j)*bit(z,k)
               for i,j,k in permutations(range(3))) & 1

def f0(x, y):
    return (sum(bit(x,i)*bit(y,i) for i in range(3))
        + sum(bit(x,i)*bit(y,j) for i,j in combinations(range(3),2))
        + bit(x,0)*bit(x,1)*bit(y,2)
        + bit(x,0)*bit(x,2)*bit(y,1)
        + bit(x,1)*bit(x,2)*bit(y,0)) & 1

PAIRS = tuple(combinations(range(3),2))
def quadratic(mask, x):
    return sum(bit(mask,k)*bit(x,i)*bit(x,j)
               for k,(i,j) in enumerate(PAIRS)) & 1

def f(mask, x, y):
    return f0(x,y)^quadratic(mask,x)^quadratic(mask,y)^quadratic(mask,x^y)
def ell(mask,x): return sum(f(mask,x,1<<i)<<i for i in range(3))
def carry(mask,x,y): return ell(mask,x)^ell(mask,y)^ell(mask,x^y)
def charge(mask,x): return x | (ell(mask,x)<<3)
def rank(rows):
    pivots={}
    for v in rows:
        while v:
            p=v.bit_length()-1
            if p in pivots: v ^= pivots[p]
            else: pivots[p]=v; break
    return len(pivots)
def spanned(rows):
    out={0}
    for v in rows: out |= {a^v for a in tuple(out)}
    return out

def mul_basis(mask,a,b):
    s,x=a; t,y=b
    return s^t^f(mask,x,y), x^y

def ordinary_charge(g,c): return g | (c<<3)
def qcharge(v): return dot(v&7,v>>3)
def paircharge(v,w):
    return qcharge(v^w)^qcharge(v)^qcharge(w)

def pmul(a,b,N):
    r=[0]*(N+1)
    for i,x in enumerate(a):
        for j,y in enumerate(b[:N+1-i]): r[i+j]+=x*y
    return r

def euler_plus(power,N):
    a=[1]+[0]*N
    for n in range(1,N+1):
        factor=[0]*(N+1)
        for k in range(N//n+1):
            if power>=0: v=comb(power,k) if k<=power else 0
            else: v=(-1)**k*comb(-power+k-1,k)
            factor[n*k]=v
        a=pmul(a,factor,N)
    return a

def series(N=30):
    minus=euler_plus(-24,N+2); plus=euler_plus(24,N+2)
    t={k-1:v for k,v in enumerate(minus)}
    p={k+1:v for k,v in enumerate(plus)}
    p2=Counter()
    for i,a in p.items():
        for j,b in p.items():
            if i+j<=N: p2[i+j]+=a*b
    F={k:t.get(k,0)+(24 if k==0 else 0)+4096*p.get(k,0)
       for k in range(-1,N+1)}
    J={k:t.get(k,0)+(24 if k==0 else 0)+196608*p.get(k,0)+16777216*p2[k]
       for k in range(-1,N+1)}
    # G=x^-1 E_6(x^2) prod_n (1-x^(2n))^-12.
    inv=[1]+[0]*N
    for n in range(1,N+1):
        factor=[0]*(N+1)
        for k in range(N//n+1): factor[n*k]=comb(11+k,k)
        inv=pmul(inv,factor,N)
    e6=[1]+[-504*sum(d**5 for d in range(1,n+1) if n%d==0) for n in range(1,N+1)]
    gg=pmul(e6,inv,N)
    G={2*k-1:v for k,v in enumerate(gg)}
    chars=[{}, {}, {}, {}]
    for k in range(-2,N+1):
        fx=F.get(k//2,0) if k%2==0 else 0
        jx=J.get(k//2,0) if k%2==0 else 0
        A=F.get(k,0); B=A*(-1 if k%2 else 1)
        check('integer_channel_character_identity', A+B==jx-fx)
        numerators=[jx+7*fx,A-B+6*G.get(k,0),A-B-2*G.get(k,0),jx-fx]
        for c,v in enumerate(numerators):
            check('character_coefficient_integrality_positivity',v%8==0 and v>=0)
            chars[c][k]=v//8
    return chars

def run():
    # Exhaust the eight forms generated by alternating changes, not 2^21 arbitrary tables.
    forms=[]
    for mask in range(8):
        ls=[ell(mask,x) for x in range(8)];forms.append(ls)
        for x,y in product(range(8),repeat=2):
            check('diagonal_and_reciprocal', f(mask,x,x)==int(x!=0)
                  and f(mask,x,y)^f(mask,y,x)==int(x!=0 and y!=0 and x!=y))
            for z in range(8):
                check('row_character',f(mask,x,y^z)==f(mask,x,y)^f(mask,x,z))
                df=f(mask,x,y)^f(mask,x^y,z)^f(mask,y,z)^f(mask,x,y^z)
                check('associator_and_carry',df==det(x,y,z)==dot(carry(mask,x,y),z))
                check('carry_cocycle',carry(mask,x,y)^carry(mask,x^y,z)
                    ==carry(mask,y,z)^carry(mask,x,y^z))
                check('basis_gauge_isomorphism',
                    f(mask,x,y)^quadratic(mask,x^y)==f0(x,y)^quadratic(mask,x)^quadratic(mask,y))
        ss=[charge(mask,x) for x in range(1,8)]
        check('full_fusion_closure',len(spanned(ss))==64 and rank(ss)==6 and reduce(xor,ss)==0)
        labels={}
        for size in range(4):
            for sub in combinations(range(7),size):
                v=reduce(xor,(ss[i] for i in sub),0)
                check('subset_classification',v not in labels and qcharge(v)==(size*(size+1)//2)%2)
                labels[v]=size
        check('all_64_labels',Counter(labels.values())==Counter({0:1,1:7,2:21,3:35}))
        for g,h in combinations(range(1,8),2):
            k=g^h; target=ls[g]^ls[h]
            check('no_ground_channel',target!=ls[k] and dot(target,k)==1)
            # Exact Fourier multiplicities on V(k)_{3/2}.
            traces=[4372 if a==0 else -4372 if a==k else -492*((-1)**dot(ls[k],a)) for a in range(8)]
            mult=Fraction(sum((-1)**dot(target,a)*traces[a] for a in range(8)),8)
            check('forced_1216_channel',mult==1216)
            for c in range(8):
                actual=Fraction(sum((-1)**dot(c,a)*traces[a] for a in range(8)),8)
                expected=0 if dot(c,k)==0 else 724 if c==ls[k] else 1216
                check('excited_full_fourier',actual==expected)
            a=(0,g);b=(0,h);seq=[a,b]
            for j in range(2,18):seq.append(mul_basis(mask,seq[-1],seq[-2]))
            check('two_atom_fibonacci_period',all(seq[j]==seq[j%3] for j in range(18)))
        for v,w in product(range(64),repeat=2):
            g=v&7; c=v>>3;h=w&7;d=w>>3
            expanded=ordinary_charge(g,c^ls[g])^ordinary_charge(h,d^ls[h])
            result=ordinary_charge(g^h,c^d^carry(mask,g,h)^ls[g^h])
            check('recorded_carry_composition',expanded==result)
    check('eight_distinct_forms',len({tuple(x) for x in forms})==8)
    old=[0,1,3,6,7,4,5,2]
    check('existing_rank_three_table',old in forms)
    # All 5040 permutations preserve the quadratic form and subset classes.
    ss=[charge(0,x) for x in range(1,8)]
    coeffs={reduce(xor,(ss[i] for i in range(6) if m>>i&1),0):m for m in range(64)}
    ancestral=0
    for perm in permutations(range(7)):
        image=[ss[i] for i in perm]
        check('heptad_permutation_extends',rank(image[:6])==6 and reduce(xor,image)==0)
        for v,m in coeffs.items():
            w=reduce(xor,(image[i] for i in range(6) if m>>i&1),0)
            check('heptad_quadratic_isometry',qcharge(v)==qcharge(w))
        pi=[0]+[i+1 for i in perm]
        if all(pi[x^y]==pi[x]^pi[y] for x,y in product(range(8),repeat=2)):ancestral+=1
    check('ancestral_GL3_count',ancestral==168)
    # Matrix identities use literal 2x2 integer tuples.
    def mm(A,B):return tuple(tuple(sum(A[i][k]*B[k][j] for k in range(2))for j in range(2))for i in range(2))
    M=((0,1),(1,1)); C=mm(M,M);H=mm(C,C);Ui=((1,-1),(0,1));L=mm(C,Ui)
    check('modular_word_identities',H==((2,3),(3,5)) and L==((1,0),(1,1)) and mm(mm(Ui,L),Ui)==((0,-1),(1,0)))
    for g,h in product(range(8),repeat=2):
        image=tuple(reduce(xor,(v for a,v in zip(row,(g,h)) if a%2),0) for row in H)
        check('H_defect_cycle',image==(h,g^h))
        orbit=[(g,h),(h,g^h),(g^h,g)]
        check('mod_two_three_cycle',all(orbit[(i+1)%3]==(orbit[i][1],orbit[i][0]^orbit[i][1])for i in range(3)))
    # Deliberate failures: collapsed ground labels and a third independent input.
    check('negative_ground_closure',charge(0,1)^charge(0,2)!=charge(0,3))
    left=mul_basis(0,mul_basis(0,(0,1),(0,2)),(0,4))
    right=mul_basis(0,(0,1),mul_basis(0,(0,2),(0,4)))
    check('negative_two_atom_extrapolation',left[1]==right[1] and left[0]!=right[0])
    chars=series()
    leading=[]
    for ch in chars:
        leading.append([[k,v] for k,v in ch.items() if v][:4])
    expected=[[(-2,1),(2,28436)],[(-1,1),(1,724)],[(1,1216)],[(2,24064)]]
    for ch,ls in zip(chars,expected):
        for k,v in ls:check('leading_multiplicities',ch[k]==v)
    return {'status':'passed','arithmetic':'exact integers and Fraction',
        'scope':'Finite diagnostics only; no actual VOA, fusion-category realization, intertwining nonzero coefficient, Monster or Lean proof.',
        'counts':dict(sorted(COUNTS.items())), 'canonical_dual_labels':forms[0],
        'type_counts':{'vacuum':1,'ground_half_weight':7,'other_half_integer':21,'nonzero_integer':35},
        'character_leading_terms_x_q_half':leading,
        'spectral_fusion_stabilizer_order':5040,'ancestry_preserving_order':ancestral,
        'generic_independent_pair_first_allowed_weight':'3/2','first_channel_multiplicity':1216,
        'ordinary_type_record_bits':3,
        'auxiliary_associator_cohomology_class':'zero: explicitly a coboundary'}

