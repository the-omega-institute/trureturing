using System.Collections.Immutable;
using System.Text;

namespace StrataLint.Scribe;

internal static class FileMapProjectionWriter
{
    private static readonly UTF8Encoding StrictUtf8 = new(false, true);

    internal static ImmutableArray<byte> Write(FileMapManifest manifest)
    {
        ArgumentNullException.ThrowIfNull(manifest);
        var builder = new StringBuilder();
        builder.Append("# Repository File Dependency Flow\n\n")
            .Append("<!-- Generated by FileMapEmitter from Meta/FILEMAP.toml. Do not edit. -->\n\n")
            .Append("```text\n")
            .Append("FILEMAP: Meta/FILEMAP.toml\n\n");
        foreach (var entry in manifest.Entries)
        {
            var node = $"[{entry.Pattern} | {KindName(entry.Kind)}]";
            builder.Append(entry.ProducedBy)
                .Append(entry.ProducedBy == "none" ? " --declares--> " : " --produces--> ")
                .Append(node)
                .Append('\n')
                .Append(node)
                .Append(" --consumed-by--> ")
                .AppendJoin(", ", entry.ConsumedBy)
                .Append('\n')
                .Append(node)
                .Append(" --verified-by--> ")
                .AppendJoin(", ", entry.VerifiedBy)
                .Append("\n\n");
        }

        builder.Append("```\n");
        return ImmutableArray.CreateRange(StrictUtf8.GetBytes(builder.ToString()));
    }

    private static string KindName(FileMapKind kind) => kind.ToString().ToLowerInvariant();
}
