    /// Flips one hex digit of the first event hash, preserving length, JSON shape and canonical
    /// form so only the chain breaks.
    private static string TamperOneHashDigit(string ledger)
    {
        const string marker = "\"event_hash\": \"sha256:";
        var index = ledger.IndexOf(marker, StringComparison.Ordinal);
        Assert.True(index >= 0, "ledger must carry an event_hash to tamper");
        var digit = index + marker.Length;
        var replacement = ledger[digit] == '0' ? '1' : '0';
        return ledger[..digit] + replacement + ledger[(digit + 1)..];
    }

    private static FrozenLedgerTestData.ModuleSpec FrozenCarrierA =>
        FrozenLedgerTestData.Module(
            "A",
            opaqueNameKeys: true,
            source: "namespace D5.S0.Carrier.A\n\ntheorem a : True := by trivial\n\nend D5.S0.Carrier.A\n");

    /// One carrier module is frozen through the production genesis writer, and the fixture proves
    /// its own premise: the generated bytes are loaded and validated into the authoritative
    /// FrozenLedgerConsistent capability, whose single active node is asserted to carry exactly
    /// one declaration statement id. Every predicate the current validator checks — canonical
    /// recipe bytes, target files on disk, the Lean declaration present in its namespace — stays
    /// satisfied, so frozen-ledger membership is the only predicate left to decide the outcome.
    private static CarrierFixture CarrierLedgerRepository(
        FrozenLedgerTestData.ModuleSpec frozenModule,
        IReadOnlyList<string> declarationGids,
        string blueprintGid,
        (string Name, string Source)? unfrozen = null,
        bool revokeFrozenNode = false,
        string? currentSource = null,
        FrozenLedgerTestData.ModuleSpec? alsoFrozen = null,
        IReadOnlyList<string>? evidenceGids = null,
        bool tamperLedgerChain = false,
        bool reattestFrozenNode = false,
        IReadOnlyList<string>? excludedDeclarations = null)
    {
        var repository = new TemporaryDirectory();
        var files = new Dictionary<string, string>(StringComparer.Ordinal);
        void Record(string relativePath, string content)
        {
            files[relativePath] = content;
            Write(repository.Path, relativePath, content);
        }

        var frozenModules = alsoFrozen is null ? [frozenModule] : new[] { frozenModule, alsoFrozen };
        var catalog = FrozenLedgerTestData.BuildCatalog(frozenModules);
        var ledgerBytes = FrozenLedgerGenerator.GenerateGenesis(
            catalog,
            new FrozenGenesisDescriptor(
                FrozenLedgerTestData.GitOid('e'),
                RuleCatalog.Default.RootSha256));

        var syntax = Assert.IsType<DagLedgerLoadOutcome.Loaded>(
            DagLedgerLoader.Load(ledgerBytes.AsSpan().ToArray())).Syntax;
        var active = Assert.IsType<FrozenLedgerValidationOutcome.Accepted>(
            FrozenLedgerTestData.ValidateGenesis(syntax, catalog)).Capability;
        // Indexed by path rather than Assert.Single: with a second frozen module the premise is
        // that each module has its own active node, which is what lets a recipe naming the
        // second one distinguish a real lookup from one that only reads ActiveFrozenNodes[0].
        Assert.Equal(frozenModules.Length, active.ActiveFrozenNodes.Length);
        foreach (var spec in frozenModules)
        {
            var each = Assert.Single(
                active.ActiveFrozenNodes,
                candidate => candidate.RepoPath == FrozenLedgerTestData.RepoPathFor(spec.Name));
            Assert.NotEmpty(each.DeclarationStatementIds);
        }

        var node = active.ActiveFrozenNodes.Single(
            candidate => candidate.RepoPath == FrozenLedgerTestData.RepoPathFor(frozenModule.Name));

        if (reattestFrozenNode)
        {
            // The three-argument overload reuses entry.Payload.SemanticReceipt, so it is a plain
            // reattestation and preserves the node id by construction. The extended form takes a
            // candidate catalog; re-freezing the same declarations from a differently-spelled
            // source is what mints a new node id while admission holds the declaration set equal.
            // `with` rather than a fresh Module: every flag the frozen spec carries -- declaration
            // set, exclusions, opaque name keys -- has to survive into the reattested catalog, or
            // the two halves of the ledger stop describing the same declarations.
            var reattestCatalog = FrozenLedgerTestData.BuildCatalog(
                frozenModule with { Source = "-- reattested\n" + frozenModule.Source });
            ledgerBytes = FrozenLedgerGenerator.AppendReattestation(active, reattestCatalog);
            var reattestedSyntax = Assert.IsType<DagLedgerLoadOutcome.Loaded>(
                DagLedgerLoader.Load(ledgerBytes.AsSpan().ToArray())).Syntax;
            active = Assert.IsType<FrozenLedgerValidationOutcome.Accepted>(
                FrozenLedger.ValidateHistoryPrefix(
                    reattestedSyntax,
                    reattestCatalog,
                    FrozenLedgerTestData.Trust(reattestedSyntax))).Capability;
            catalog = reattestCatalog;
            var reattested = Assert.Single(active.ActiveFrozenNodes);
            // The premise of this whole family: reattestation replaces the node id while the
            // declaration set is held constant by admission (FrozenLedgerCandidateValidation).
            Assert.NotEqual(node.FrozenNodeId, reattested.FrozenNodeId);
            Assert.Equal(
                node.DeclarationStatementIds.Select(static entry => entry.DeclarationNameKey),
                reattested.DeclarationStatementIds.Select(static entry => entry.DeclarationNameKey));
            node = reattested;
        }

        string? receiptPath = null;
        string? receiptText = null;
        if (revokeFrozenNode)
        {
            (ledgerBytes, receiptPath, receiptText) = RevokeSingleNode(active, node);
            var revokedSyntax = Assert.IsType<DagLedgerLoadOutcome.Loaded>(
                DagLedgerLoader.Load(ledgerBytes.AsSpan().ToArray())).Syntax;
            // ValidateHistory is the wrong entry point here: it also demands completeness and
            // rejects with "Closed modules are missing Freeze events", because a module whose
            // only Freeze has been revoked may no longer be Closed. Production reads a ledger
            // through ValidateHistoryPrefix (DagLedgerCommandPreparation), which drops that
            // completeness demand while still validating hash, canonical form and event
            // semantics -- so the premise is checkable after all.
            var revoked = Assert.IsType<FrozenLedgerValidationOutcome.Accepted>(
                FrozenLedger.ValidateHistoryPrefix(
                    revokedSyntax,
                    catalog,
                    FrozenLedgerTestData.Trust(revokedSyntax))).Capability;
            Assert.DoesNotContain(node.FrozenNodeId, revoked.ActiveFrozenNodes.Select(static n => n.FrozenNodeId));
            Assert.Contains(node.FrozenNodeId, revoked.RevokedFrozenNodeIds);
            Assert.Equal(active.ActiveFrozenNodes.Length - 1, revoked.ActiveFrozenNodes.Length);
        }

        Record("lean-toolchain", "leanprover/lean4:v4.24.0\n");
        Record("lake-manifest.json", "{}\n");
        var ledgerText = Encoding.UTF8.GetString(ledgerBytes.AsSpan());
        if (tamperLedgerChain)
        {
            ledgerText = TamperOneHashDigit(ledgerText);
            // The premise is that this stays a well-formed, canonical ledger and fails only on
            // its hash chain: a loader-level rejection would test JSON shape, not authority.
            var tamperedSyntax = Assert.IsType<DagLedgerLoadOutcome.Loaded>(
                DagLedgerLoader.Load(Encoding.UTF8.GetBytes(ledgerText))).Syntax;
            Assert.IsType<FrozenLedgerValidationOutcome.Rejected>(
                FrozenLedger.ValidateHistoryPrefix(
                    tamperedSyntax,
                    catalog,
                    FrozenLedgerTestData.Trust(tamperedSyntax)));
        }

        var ledgerFiles = new Dictionary<string, string>(StringComparer.Ordinal);
        FrozenLedgerTestData.AddLedgerFiles(
            ledgerFiles,
            ImmutableArray.CreateRange(Encoding.UTF8.GetBytes(ledgerText)));
        foreach (var (path, content) in ledgerFiles)
        {
            Record(path, content);
        }
        // currentSource models a working tree that moved on after the freeze: the ledger node
        // still records the declarations of the attested source, not of what is on disk now.
        Record(
            FrozenLedgerTestData.PathFor(frozenModule.Name),
            currentSource ?? (reattestFrozenNode ? "-- reattested\n" + frozenModule.Source : frozenModule.Source));
        if (alsoFrozen is { } second)
        {
            Record(FrozenLedgerTestData.PathFor(second.Name), second.Source);
        }

        if (unfrozen is { } module)
        {
            Record(FrozenLedgerTestData.PathFor(module.Name), module.Source);
        }

        if (receiptPath is not null && receiptText is not null)
        {
            Record(receiptPath, receiptText);
        }

        Record(PathFor(blueprintGid), "# Carrier\n");
        foreach (var evidenceGid in evidenceGids ?? [])
        {
            Record(PathFor(evidenceGid), "{}\n");
        }

        Record(
            PathFor("D5/P/D5-P001"),
            $"""
            blueprint:
              - {blueprintGid}
            decls:
            {string.Join("\n", declarationGids.Select(static gid => "  - " + gid))}
            evidence:{EvidenceBlock(evidenceGids)}
            id: D5-P001
            narrative_order:
              - carrier claim
            venue: arXiv-math.NT
            """ + "\n");

        // The doubles carry the fixture's own bytes. A hollow gateway (null snapshots) and an
        // empty report would let an implementation that skips the trust chain go green while a
        // faithful one broke every floor -- the reward pointing the wrong way.
        //
        // The report must describe *every* managed Lean file in the snapshot, not just the frozen
        // modules: LeanClosureValidator rejects a managed file with no report, so an unfrozen
        // carrier or a declaration added after the freeze would fail there instead of on
        // membership -- red for the wrong reason. Declarations are read from the source that is
        // actually on disk, so the current report describes the current tree while the ledger
        // keeps describing what was attested.
        var snapshot = RawRepositorySnapshot.Create(
            files.Select(static pair => RawRepositoryEntry.FromText(pair.Key, pair.Value)));
        var reports = files
            .Where(static pair => pair.Key.EndsWith(".lean", StringComparison.Ordinal))
            .ToDictionary(
                pair => pair.Key,
                pair => new LeanFileReport(
                    ImmutableArray<string>.Empty,
                    DeclarationsIn(pair.Value)
                        .Select(name => new LeanDeclaration(
                            name,
                            "theorem",
                            "True",
                            ImmutableArray<string>.Empty)
                        {
                            NameKey = FrozenLedgerTestData.NameKeyFor(name),
                            IncludeInStatement = excludedDeclarations is null
                                || !excludedDeclarations.Contains(name),
                        })
                        .ToImmutableArray()),
                StringComparer.Ordinal);
        Assert.NotEmpty(reports);
        return new CarrierFixture(repository, snapshot, LeanAxiomReport.Create(reports));
    }

    /// Carries the fixture's own snapshot and Lean report so the injected capabilities are the
    /// ones a faithful implementation would actually consume.
    private sealed class CarrierFixture(
        TemporaryDirectory directory,
        RawRepositorySnapshot snapshot,
        LeanAxiomReport report) : IDisposable
    {
        internal string Path => directory.Path;

        /// FakeRepositoryGateway already counts ValidateFrozenReferences calls, so an
        /// implementation that manufactures TrustedFrozenGitReferences itself instead of asking
        /// the gateway is observable through FrozenReferenceValidationCount -- no second double.
        internal FakeRepositoryGateway Gateway { get; } = new(
            RawChangeSet.Create([]),
            snapshot,
            snapshot,
            static references => TrustedFrozenGitReferences.CreateForTrustedAdapter(references.Inputs));

        internal FixedLeanReportSource Reports { get; } = new(report);

        /// Stands in for a report that is absent or unreadable on disk. Infrastructure, not a
        /// verdict about the recipe -- so it must not be folded into the same exit code as a
        /// recipe that genuinely fails validation.
        internal ILeanReportSource UnavailableReports { get; } = new ThrowingLeanReportSource();

        /// A report that is present but does not parse. RawLeanReportArtifact raises
        /// FormatException for malformed, non-canonical, schema-mismatched and stale reports --
        /// the same type the ledger path raises, which is exactly why the two must be told apart.
        internal ILeanReportSource MalformedReports { get; } =
            new FormatFailingLeanReportSource();

        /// Strict UTF-8 decoding fails before the JSON layer, so this one never becomes a
        /// FormatException. Covering only FormatException let it slip past papergen's own
        /// diagnostic into the CLI's generic handler.
        internal ILeanReportSource UndecodableReports { get; } = new UndecodableLeanReportSource();

        /// A report that parses but does not describe this tree: closure validation rejects it
        /// inside preparation, which is a second way a report fault can surface. Covering only the
        /// load call let this one be reported as a ledger verdict.
        internal ILeanReportSource IncoherentReports { get; } =
            new FixedLeanReportSource(LeanAxiomReport.Create(
                new Dictionary<string, LeanFileReport>(StringComparer.Ordinal)));

        /// A gateway that refuses to validate frozen references. An implementation that ignores
        /// the refusal and manufactures trust itself, or that silently falls back, stays green
        /// without this.
        /// Returns a capability that does not cover the ledger's inputs -- without throwing. A
        /// gateway that is called, whose refusal propagates, still cannot tell an implementation
        /// that *uses* the returned capability from one that calls ceremonially and then
        /// manufactures its own trust: on the ordinary fake those two values are identical.
        internal FakeRepositoryGateway NonCoveringGateway { get; } = new(
            RawChangeSet.Create([]),
            snapshot,
            snapshot,
            static _ => TrustedFrozenGitReferences.CreateForTrustedAdapter(ImmutableArray<FrozenLedgerInput>.Empty));

        /// A gateway whose repository read fails outright -- the environment, not the ledger.
        internal FakeRepositoryGateway UnreadableGateway { get; } = new(
            RawChangeSet.Create([]),
            null,
            null,
            static references => TrustedFrozenGitReferences.CreateForTrustedAdapter(references.Inputs));

        /// A gateway that reads successfully but hands back bytes no snapshot can be decoded from.
        /// Distinct from UnreadableGateway: the read itself works, so a marker placed only around
        /// the gateway call misses this, and spec A16 still classifies snapshot rejection as
        /// infrastructure rather than as a verdict about the ledger.
        internal FakeRepositoryGateway UndecodableGateway { get; } = new(
            RawChangeSet.Create([]),
            RawRepositorySnapshot.Create(
                [new RawRepositoryEntry("D5/S0/Carrier/A.lean", ImmutableArray.Create<byte>(0xFF, 0xFE))]),
            null,
            static references => TrustedFrozenGitReferences.CreateForTrustedAdapter(references.Inputs));

        internal FakeRepositoryGateway DenyingGateway { get; } = new(
            RawChangeSet.Create([]),
            snapshot,
            snapshot,
            static _ => throw new InvalidOperationException("frozen Git object is not a reachable commit"));

        public void Dispose() => directory.Dispose();
    }

    private sealed class UndecodableLeanReportSource : ILeanReportSource
    {
        public LeanAxiomReport Load(RepositorySnapshot snapshot) =>
            throw new DecoderFallbackException("raw Lean report is not valid UTF-8");
    }

    private sealed class FormatFailingLeanReportSource : ILeanReportSource
    {
        public LeanAxiomReport Load(RepositorySnapshot snapshot) =>
            throw new FormatException("Raw Lean report bytes are not canonical JSON at byte 0.");
    }

    private sealed class ThrowingLeanReportSource : ILeanReportSource
    {
        public LeanAxiomReport Load(RepositorySnapshot snapshot) =>
            throw new FileNotFoundException("raw Lean report is absent");
    }

    private sealed class FixedLeanReportSource(LeanAxiomReport report) : ILeanReportSource
    {
        internal int LoadCount { get; private set; }

        public LeanAxiomReport Load(RepositorySnapshot snapshot)
        {
            LoadCount++;
            return report;
        }
    }

    /// Appends a revocation for the single active node through the production revocation path
    /// (receipt writer, trusted receipt store, evidence validator, planner, ledger generator), so
    /// the resulting ledger is one the engine itself accepts rather than hand-written bytes.
    private static (ImmutableArray<byte> Ledger, string ReceiptPath, string ReceiptText) RevokeSingleNode(
        FrozenLedgerConsistent active,
        FrozenNodeMaterial node)
    {
        const string receiptPath = "Evidence/D5/revocation-receipt.json";
        var provisional = new RevocationEvidence.KernelWitnessFailure(
            node.FrozenNodeId,
            node.WitnessId,
            string.Empty,
            string.Empty);
        var receiptText = Encoding.UTF8.GetString(RevocationReceiptWriter.Write(active, provisional).AsSpan());
        var receiptOid = FrozenLedgerTestData.GitBlobOid(receiptText);
        var evidence = provisional with
        {
            ReceiptBlobOid = receiptOid,
            ReceiptSha256 = FrozenLedgerTestData.Sha256(receiptText),
        };
        var files = new Dictionary<string, string>(StringComparer.Ordinal)
        {
            [receiptPath] = receiptText,
            ["lean-toolchain"] = "leanprover/lean4:v4.24.0\n",
            ["lake-manifest.json"] = "{}\n",
        };
        var snapshot = Assert.IsType<SnapshotDecodeOutcome.Decoded>(SnapshotDecoder.Decode(
            RawRepositorySnapshot.Create(
                files.Select(static pair => RawRepositoryEntry.FromText(pair.Key, pair.Value))))).Snapshot;
        var receipts = Assert.IsType<RevocationReceiptStoreOutcome.Accepted>(
            TrustedRevocationReceiptStore.Materialize(active, snapshot, [receiptOid])).Capability;
        var validated = Assert.IsType<RevocationEvidenceValidationOutcome.Accepted>(
            RevocationEvidenceValidator.Validate(evidence, active, receipts)).Capability;
        var plan = Assert.IsType<RevocationPlanOutcome.Accepted>(
            RevocationPlanner.Plan(active, [validated])).Capability;
        return (FrozenLedgerGenerator.AppendRevocation(active, plan), receiptPath, receiptText);
    }

    /// Trust cannot come from a TemporaryDirectory: GitRepositoryGateway.ValidateFrozenReferences
    /// resolves every recorded object with `git cat-file -t`, and these fixtures use synthetic
    /// OIDs in a directory that is not a repository. Tests therefore inject the adapter-trusted
    /// path that FrozenLedgerTestData already uses.
    private static IRepositoryGateway TestGateway() =>
        new FakeRepositoryGateway(
            RawChangeSet.Create([]),
            null,
            null,
            static references => TrustedFrozenGitReferences.CreateForTrustedAdapter(references.Inputs));

    private static ILeanReportSource TestReportSource() => new EmptyLeanReportSource();

    private sealed class EmptyLeanReportSource : ILeanReportSource
    {
        public LeanAxiomReport Load(RepositorySnapshot snapshot) =>
            LeanAxiomReport.Create(new Dictionary<string, LeanFileReport>(StringComparer.Ordinal));
    }

    private static TemporaryDirectory RecipeRepository(bool includeTargets = false)
    {
        var repository = new TemporaryDirectory();
        Write(repository.Path, RecipePath, CanonicalRecipe);
        Directory.CreateDirectory(Path.GetDirectoryName(Path.Combine(repository.Path, FormalPath))!);
        Directory.CreateDirectory(Path.GetDirectoryName(Path.Combine(repository.Path, BlueprintPath))!);
        if (includeTargets)
        {
            Write(
                repository.Path,
                FormalPath,
                "namespace D5.S3.Zeros.CompletedZeta\n\ntheorem xi_reading_reflection : True := by trivial\n\nend D5.S3.Zeros.CompletedZeta\n");
            Write(
                repository.Path,
                BlueprintPath,
                "# Completed Zeta\n");
        }

        return repository;
    }

    private static void Write(string root, string relativePath, string content)
    {
        var path = Path.Combine(root, relativePath);
        Directory.CreateDirectory(Path.GetDirectoryName(path)!);
        File.WriteAllText(path, content, new UTF8Encoding(false, true));
    }

    private static ImmutableArray<byte> CanonicalBytes(string value) =>
        ImmutableArray.CreateRange(new UTF8Encoding(false, true).GetBytes(value));

    private static string PathFor(string gidText)
    {
        Assert.True(Gid.TryParse(gidText, out var gid));
        return gid.Path.Value;
    }


