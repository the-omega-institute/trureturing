using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S1.Digit.Carry;

internal sealed class SuccessorDocument : IScribeDocumentDefinition
{
    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeDocument.Create(
        Header(
            "D5/S1/Digit/Carry/Successor",
            "Zeckendorf successor carry chains terminate within the highest occupied index."),
        H("Termination of Zeckendorf Successor Carries"),
        Blocks(
            DocumentBlock.Describe.Definition(
                DescribeId.Create("exact-carry-chain"),
                H("CarrySteps records the exact number of local rewrites"),
                LeanInductive("D5/S1/Digit/Carry/Successor.CarrySteps"),
                DescribeProvenance.RepoDerived(),
                Blocks(Paragraph(Text(
                    "CarrySteps k before after is generated by a zero-step identity and "
                    + "a constructor that appends one existing CarryStep. The natural "
                    + "parameter therefore measures the chain length rather than merely "
                    + "asserting reflexive-transitive reachability.")))
            ),
            DocumentBlock.Describe.Theorem(
                DescribeId.Create("zeckendorf-successor-carry-terminates"),
                H("Successor carries terminate before passing the highest index"),
                LeanTheorem(
                    "D5/S1/Digit/Carry/Successor.zeckendorf_successor_carry_terminates"),
                Disp(Seq(
                    Forall, Sp, F.Id("n"), Comma, Esc,
                    Exists, Sp, F.Id("k"), Comma, Esc,
                    F.Id("k"), Le, Operatorname, Grp(F.Id("highestIndex")),
                    Open, F.Id("z"), Underscore, F.Id("n"), Close,
                    Sp, Land, Sp,
                    Operatorname, Grp(F.Id("CarrySteps")),
                    Open, F.Id("k"), Comma,
                    F.Id("z"), Underscore, F.Id("n"), Plus, F.Id("e"), Underscore, D(0),
                    Comma, F.Id("z"), Underscore, Grp(F.Id("n"), Plus, D(1)), Close)),
                DescribeProvenance.RepoDerived(),
                Blocks(
                    Paragraph(Text(
                        "Adding the least Fibonacci digit has two possible cascades. If "
                        + "the least digit is occupied, the first rewrite is the special "
                        + "double-zero carry and subsequent carries consume occupied even "
                        + "indices. Otherwise, adjacent carries consume occupied odd "
                        + "indices. In either case the first missing digit of that parity "
                        + "gives the exact number of rewrites.")),
                    Paragraph(Text(
                        "Finite support places that first missing digit no later than one "
                        + "plus the largest occupied raw index. The endpoint is canonical, "
                        + "every local rewrite preserves raw value, and Zeckendorf "
                        + "uniqueness identifies the endpoint with the representation of "
                        + "n+1.")),
                    Paragraph(Text(
                        "Pinned Mathlib and the repository were searched before proving. "
                        + "Mathlib provides Zeckendorf existence and uniqueness, while the "
                        + "repository already provides the four local carry rules and a "
                        + "general well-founded normalizer. No existing theorem exposed "
                        + "the exact successor carry chain together with this highest-index "
                        + "bound, so the result is derived here from those checked parts.")))
            )),
        [
            DocumentEdge.Dependency.Create(
                GidRef.Create("D5/S1/Digit/Carry")),
        ]));

    private static LeanDeclarationRef LeanInductive(string value) =>
        LeanDeclarationRef.Create(
            value,
            expectedKind: LeanDeclarationKind.Inductive,
            requireNoSorry: true);
}
