using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S1.Ledger;

internal sealed class DyadicRelationKernelDocument : IScribeDocumentDefinition
{
    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "The adjacent dyadic relations generate exactly the vectors with zero dyadic evaluation.",
        H("Dyadic Relation Kernel"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("telescoping-membership"),
                DeclarationHandle.Create("D5/S1/Ledger/DyadicRelationKernel.telescoping_mem"),
                H("Telescoping rows lie in the adjacent-row span"),
                StatementSource.WithoutFormula(),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "For every starting index j and distance d, the endpoint difference "
                    + "eps j minus 2^d times eps (j+d) is generated by the adjacent rows "
                    + "eps n minus 2 times eps (n+1). The proof inducts on d and adds the "
                    + "next adjacent generator at each step."))),
                DescribeRole.Theorem),
            Describe.Lean(
                DescribeId.Create("support-bounded-decomposition"),
                DeclarationHandle.Create("D5/S1/Ledger/DyadicRelationKernel.support_bounded_decomposition"),
                H("Support-bounded dyadic decomposition"),
                StatementSource.WithoutFormula(),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "A finitely supported vector whose support lies at or below m is the sum of "
                    + "its lower coordinate coefficients times the telescoping rows to m, "
                    + "together with z times eps m, where z is an integer and equals 2^m times "
                    + "the dyadic evaluation of the vector. This equality also proves the "
                    + "endpoint coefficient is integral under the support bound, including m = 0."))),
                DescribeRole.Theorem),
            Describe.Lean(
                DescribeId.Create("dyadic-evaluation-kernel"),
                DeclarationHandle.Create("D5/S1/Ledger/DyadicRelationKernel.mem_H_iff_ellDy_eq_zero"),
                H("The adjacent-row span is the evaluation kernel"),
                StatementSource.WithoutFormula(),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "An integer vector with finite support belongs to the adjacent-row span "
                    + "if and only if its image under the additive homomorphism ellDy to the "
                    + "dyadic rational subgroup is zero. The subgroup consists exactly of "
                    + "the fractions z/2^k with integer z and natural k. Evaluation sums "
                    + "the coordinates divided by the corresponding "
                    + "powers of two, and finite sums remain in that subgroup. Each adjacent relation has zero evaluation. "
                    + "Conversely, the finite decomposition reduces a vector to its endpoint "
                    + "coefficient, and zero evaluation forces that coefficient to vanish."))),
                DescribeRole.Theorem),
            Describe.Lean(
                DescribeId.Create("finite-coordinate-surjectivity"),
                DeclarationHandle.Create("D5/S1/Ledger/DyadicRelationKernel.finite_projection_surjective"),
                H("Every finite coordinate assignment is realized"),
                StatementSource.WithoutFormula(),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "For any finite set of indices, restriction from the adjacent-row span "
                    + "onto the integer assignments on that set is surjective. Choose an "
                    + "endpoint beyond every specified index and sum the corresponding "
                    + "telescoping rows with the desired coefficients. All endpoint corrections "
                    + "lie outside the specified set. The empty set is included."))),
                DescribeRole.Theorem))));
}
