    private const string QuestionQuote =
        "Page 16, Question 7.5: “Let u_i = (u_i(n)) for i = 0, 1 be the increasing sequence "
        + "of nonnegative integers such that r(u_i(n)) = i. Is the sequence u_i is k-regular for some k?”";

    private static DocumentBlock Node(string name, string title, Formula formula,
        string prose, DescribeRole role, AssessedProvenance provenance) => Describe.Lean(
        DescribeId.Create("su-parity-" + name.ToLowerInvariant()),
        DeclarationHandle.Create(Prefix + name), H(title), StatementSource.FromAuthor(formula),
        provenance, Blocks(Paragraph(Text(prose))), role);

    private static Formula SequenceFormula()
    {
        var n = F.Id("n");
        var successor = Add(n, D(1));
        var current = Add(n, D(2));
        var index = Call("min", Subtract(current, Call("h", successor)), successor);
        return Disp(new Formula.Aligned([
            Equal(Call("h", D(0)), D(1)),
            Equal(Call("h", D(1)), D(1)),
            All("n", Naturals(), Equal(Call("h", current), Add(Call("h", index), Call("h", n)))),
        ]));
    }

    private static Formula ParityFormula() => Disp(All("n", Naturals(),
        Equal(Call("r", F.Id("n")), App(Qualified("Nat", "mod"), Call("h", F.Id("n")), D(2)))));

    private static Formula PositionsFormula()
    {
        var i = F.Id("i");
        var n = F.Id("n");
        var predicate = LambdaIn("m", Naturals(), Equal(Call("r", F.Id("m")), i));
        return Disp(All("i", Naturals(), All("n", Naturals(),
            Equal(Call("u", i, n), App(Qualified("Nat", "nth"), predicate, n)))));
    }

    private static Formula KernelFormula()
    {
        var k = F.Id("k");
        var a = F.Id("a");
        var j = F.Id("j");
        var i = F.Id("i");
        var step = new Formula.Power(k, j);
        var subsequence = LambdaIn("n", Naturals(),
            App(a, Add(Multiply(step, F.Id("n")), i)));
        var membership = Some("j", Naturals(), Some("i", Naturals(),
            And(Less(i, step), Equal(F.Id("f"), subsequence))));
        return Disp(All("k", Naturals(), All("a", SequenceType(), Equal(Call("kKernel", k, a),
            Seq(OpenBrace, Sp, F.Id("f"), Colon, Sp, SequenceType(), Sp, Mid, Sp,
                membership, Sp, CloseBrace)))));
    }

    private static Formula RegularityFormula()
    {
        var k = F.Id("k");
        var a = F.Id("a");
        var span = App(Qualified("Submodule", "span"), Integers(), Call("kKernel", k, a));
        return Disp(All("k", Naturals(), All("a", SequenceType(),
            Iff(Call("IsKRegular", k, a), Seq(Parenthesized(span), Dot, F.Id("FG"))))));
    }

    private static Formula ClaimBody()
    {
        var i = F.Id("i");
        var k = F.Id("k");
        var sequence = LambdaIn("n", Naturals(),
            Parenthesized(Seq(Call("u", i, F.Id("n")), Colon, Sp, Integers())));
        return All("i", Naturals(), Implies(Less(i, D(2)), Some("k", Naturals(),
            And(LessOrEqual(D(2), k), Call("IsKRegular", k, sequence)))));
    }

    private static Formula Naturals() => new Formula.NamedConstant(FormulaIdentifier.Create("Nat"));
    private static Formula Integers() => new Formula.Integers();
    private static Formula SequenceType() => Seq(Naturals(), Sp, To, Sp, Integers());
    private static Formula Qualified(string owner, string name) => Seq(F.Id(owner), Dot, F.Id(name));
    private static Formula App(Formula function, params Formula[] arguments) => new Formula.Apply(function, [.. arguments]);
    private static Formula Call(string name, params Formula[] arguments) => new Formula.FunctionCall(FormulaIdentifier.Create(name), [.. arguments]);
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula Subtract(Formula left, Formula right) => new Formula.Binary(left, FormulaBinaryOperator.Subtract, right);
    private static Formula And(Formula left, Formula right) => new Formula.Logic(left, FormulaLogicOperator.And, right);
    private static Formula Iff(Formula left, Formula right) => new Formula.Logic(left, FormulaLogicOperator.Iff, right);
    private static Formula Implies(Formula left, Formula right) => new Formula.Logic(left, FormulaLogicOperator.Implies, right);
    private static Formula Less(Formula left, Formula right) => new Formula.Relation(left, FormulaRelationOperator.LessThan, right);
    private static Formula LessOrEqual(Formula left, Formula right) => new Formula.Relation(left, FormulaRelationOperator.LessThanOrEqual, right);
    private static Formula All(string variable, Formula domain, Formula body) => new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(variable), domain, body);
    private static Formula Some(string variable, Formula domain, Formula body) => new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create(variable), domain, body);
    private static Formula LambdaIn(string variable, Formula domain, Formula body) => Seq(
        Operatorname, Grp(F.Id("fun")), Sp, F.Id(variable), Colon, Sp, domain, Sp, Mapsto, Sp, Parenthesized(body));
}
