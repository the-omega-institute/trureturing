    private static readonly LibraryNoteRef Source =
        LibraryNoteRef.Create("D5/L/RecurrenceComposition/sobolewskiulas2022metafibonacci");

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Both parity-position sequences of h(1,1) have finitely generated binary-kernel spans.",
        H("Parity positions in the Sobolewski–Ulas meta-Fibonacci sequence"),
        Blocks(
            Node("h", "The nested recurrence", SequenceFormula(),
                "Page 4: “We write h(n) = h_{1,1}(n) and in the sequel, we consider the sequence "
                    + "h = (h(n))_{n∈ℕ}.” Page 3 defines h_{a,b}; taking a=b=1 gives "
                    + "h(n)=1 for n≤1 and h(n)=h(n−h(n−1))+h(n−2) for n>1. Natural subtraction sends a negative "
                    + "argument to zero, where h is one. Positivity makes the minimum in "
                    + "the recursive definition select its first argument.",
                DescribeRole.Definition, AssessedProvenance.FromLiterature(Source)),
            Node("r", "Parity", ParityFormula(),
                "Page 8: “Let us write r(n) = h(n) (mod 2).” Values are natural numbers zero and one.",
                DescribeRole.Definition, AssessedProvenance.FromLiterature(Source)),
            Node("u", "Increasing occurrence enumerations", PositionsFormula(),
                QuestionQuote + " Nat.nth lists the nonnegative positions in increasing order, "
                    + "starting with index zero. Each aligned block of sixteen positions "
                    + "contains eight positions of each parity, so both enumerations are infinite.",
                DescribeRole.Definition, AssessedProvenance.FromLiterature(Source)),
            Node("kKernel", "The k-kernel", KernelFormula(),
                "Section 2, page 4: “Let k ≥ 2 be a fixed integer.” The k-kernel is "
                    + "“K_k(a) = {(a_{k^j n+i})_{n∈ℕ} : j ∈ ℕ, 0 ≤ i < k^j}”. "
                    + "The carrier here is the space of integer-valued sequences.",
                DescribeRole.Definition, AssessedProvenance.FromLiterature(Source)),
            Node("IsKRegular", "Finite generation of the kernel span", RegularityFormula(),
                "Section 2, page 4: “In other words, the ℤ-submodule generated by K_k(a) "
                    + "is finitely generated.” Submodule.FG expresses finite generation over ℤ.",
                DescribeRole.Definition, AssessedProvenance.FromLiterature(Source)),
            Node("claim", "Question 7.5", Disp(Iff(F.Id("claim"), ClaimBody())),
                QuestionQuote + " The variable i ranges over zero and one; the base k is "
                    + "at least two, as required in Section 2. Natural positions are cast to ℤ.",
                DescribeRole.Definition, AssessedProvenance.FromLiterature(Source)),
            Node("result", "Both occurrence enumerations are regular", Disp(ClaimBody()),
                "The proof chooses k=2 for both parities. Odd-index and even-index identities "
                    + "for h yield an exact parity table for each block of length sixteen. "
                    + "Every block contains eight zeros and eight ones. Thus the nth position "
                    + "is twice n plus an integer correction obtained by selecting within a block. "
                    + "The correction is the output of a finite state space stable under n↦2n "
                    + "and n↦2n+1, so its binary kernel is finite. Every binary-kernel sequence "
