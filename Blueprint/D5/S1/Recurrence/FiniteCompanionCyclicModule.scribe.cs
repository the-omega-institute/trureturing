using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S1.Recurrence;

internal sealed class FiniteCompanionCyclicModuleDocument : IScribeDocumentDefinition
{
    private static Formula I(string name) => F.Id(name);
    private static Formula.BoundVariable B(string name, Formula type) =>
        new(FormulaIdentifier.Create(name), type);
    private static Formula All(Formula body, params Formula.BoundVariable[] variables) =>
        new Formula.BindMany(FormulaQuantifier.ForAll, [.. variables], body);
    private static Formula And(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.And, right);
    private static Formula Parameters(Formula body) => All(body,
        B("A", I("CommRingType")), B("u", I("A")), B("q", I("Nat")),
        B("hq", Call("Positive", I("q"))));
    private static Formula Beta(Formula x) => Call("cyclicEquiv", I("u"), I("q"), I("hq"), x);
    private static Formula Of(Formula x) => Call("of", Call("time", I("u"), I("q"), I("hq")), x);
    private static Formula Projection(Formula x) => Call("projection", I("u"), I("q"), x);

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Forward companion time is cyclic at the first vertex over every commutative ring.",
        H("First-vertex cyclic companion module"),
        Blocks(
            Paragraph(Text("A is any commutative ring, u is any element, and q is positive. "
                + "CommRingType includes the ring instance; Positive(q) is the premise 0<q. "
                + "The zero ring and q=1 are included. No involution, unit, nontriviality, domain "
                + "or field assumption occurs. Row(A,q) means Fin q -> A. Forward time is exactly "
                + "(Tv)(0)=(sum over j in Fin q of v(j))*u and (Tv)(j+1)=v(j). "
                + "The linear map extends FiniteCompanionSquareDefect.time with J(a)=a*u. "
                + "The vector e0 has 1 at vertex zero and 0 elsewhere and serves as the cyclic "
                + "generator.")),
            Paragraph(Text("Set H(u,j)=X^j-C(u)*sum over k<j of X^k, and P(u,q)=H(u,q). "
                + "CyclicQ is the canonical ring quotient A[X]/(P), with its polynomial-module action. "
                + "projection sends a polynomial to its class. coordinatePolynomial(u,q,v) "
                + "is sum over j in Fin q of C(v(j))*H(u,j). Module.AEval' time is the row module "
                + "where X acts by forward time; of is its underlying A-linear identification. "
                + "evaluate(f)=f(T)e0 is polynomial-linear.")),
            Describe.Lean(DescribeId.Create("companion-exact-principal-kernel"),
                DeclarationHandle.Create("D5/S1/Recurrence/FiniteCompanionCyclicModule.evaluate_ker"),
                H("Exact polynomial kernel"),
                StatementSource.FromAuthor(Disp(Parameters(Equal(
                    Call("ker", Call("evaluate", I("u"), I("q"), I("hq"))),
                    Call("principalIdeal", Call("P", I("u"), I("q"))))))),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text("The kernel is exactly the principal ideal generated by P. "
                    + "The quotient coordinate map sends f(T)e0 back to projection(f), so no additional "
                    + "polynomial relation is lost. Conversely P(T)e0=0 annihilates every multiple of P. "
                    + "This exact equality is used by the quotient equivalence constructor."))),
                DescribeRole.Theorem),
            Describe.Lean(DescribeId.Create("companion-normalized-cyclic-presentation"),
                DeclarationHandle.Create("D5/S1/Recurrence/FiniteCompanionCyclicModule.cyclic_presentation"),
                H("Normalized equivalence and explicit inverse"),
                StatementSource.FromAuthor(Disp(Parameters(And(
                    All(Equal(Beta(Projection(I("f"))),
                        Of(Call("apply", Call("aeval", Call("time", I("u"), I("q"), I("hq")),
                            I("f")), Call("ezero", I("q"), I("hq"))))),
                        B("f", Call("Polynomial", I("A")))),
                    And(All(Equal(Call("inverse", Call("cyclicEquiv", I("u"), I("q"), I("hq")),
                            Of(I("v"))), Projection(Call("coordinatePolynomial", I("u"), I("q"), I("v")))),
                            B("v", Call("Row", I("A"), I("q")))),
                        Equal(Beta(Num(1)), Of(Call("ezero", I("q"), I("hq"))))))))),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text("cyclicEquiv is an A[X]-linear equivalence. The displayed "
                    + "forward formula, coordinate inverse and normalization are all conjuncts "
                    + "of the Lean theorem. H(u,0)=1 and H(u,j+1)=X*H(u,j)-C(u). The original "
                    + "time equations give H(u,j)(T)e0=e(j) for j<q, and H(u,q)(T)e0=0. "
                    + "The coordinate map intertwines T with X and reconstructs every row. "
                    + "Polynomial linearity and its value 1 at e0 give the other inverse identity. "
                    + "This proof uses no degree reindexing, so it works uniformly over the zero ring. "
                    + "At q=1, P=X-C(u), time is multiplication by u, and the inverse is projection(C(v(0)))."))),
                DescribeRole.Theorem),
            Paragraph(Text("The intended next consumer specializes A to the literal integer sign group ring "
                + "and u to its reset label. The normalization sends e0 to the polynomial class 1, "
                + "while forward time is X. This supplies the module presentation needed to relate "
                + "the original square quotient by range(id+Theta^2) to the additional polynomial "
                + "relation 1+X^2. That image correspondence, native bridge, oriented branch "
                + "classifications, five-clock equality and full-action character remain separate "
                + "proof obligations. This module establishes no global Sign-equivariance, history "
                + "lift, later classification or literature novelty.")))));
}
