using static StrataLint.Scribe.DefinitionDsl;

namespace StrataLint.Scribe.Blueprint.D5.S1.Dynamics.PeriodicOrbits;

internal sealed class SkewGroupHolonomyDocument : IScribeDocumentDefinition
{
    private const string Prefix =
        "D5/S1/Dynamics/PeriodicOrbits/SkewGroupHolonomy.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Ordered noncommutative holonomy controls periods and orbit families of a finite-group skew product.",
        H("Noncommutative Holonomy in Finite-Group Skew Products"),
        Blocks(
            Paragraph(Text(
                "Let f be a self-map of X, let c assign a group element to each base state, "
                    + "and update the fibre by right multiplication. The ordered product of "
                    + "charges along the actual base orbit is the holonomy; its order matters "
                    + "when the fibre group is noncommutative.")),
            Paragraph(Text(
                "A returning base cycle therefore acts on the fibre by one right translation. "
                    + "For a finite fibre group, the lifted period is the base period times the "
                    + "order of that translation. Two lifts lie on the same periodic orbit exactly "
                    + "when their displacement belongs to the subgroup generated by holonomy, "
                    + "and the resulting orbit-family cardinality is the corresponding subgroup index.")),
            Node("group-holonomy", "groupHolonomy", "Ordered holonomy", "The recursive ordered product of fibre charges along a base orbit.", DescribeRole.Definition),
            Node("group-holonomy-zero", "groupHolonomy_zero", "Empty holonomy", "The length-zero holonomy is the group identity."),
            Node("group-holonomy-add", "groupHolonomy_add", "Concatenation of holonomy", "Holonomy over a concatenated time interval factors into the first ordered product followed by the product along the shifted orbit."),
            Node("group-skew-step", "groupSkewStepRight", "Right skew step", "The base advances by f and the fibre is multiplied on the right by the current charge.", DescribeRole.Definition),
            Node("group-skew-iterate", "groupSkew_iterate", "Iterated skew transport", "Every natural iterate is the base iterate paired with right multiplication by the ordered holonomy."),
            Node("group-skew-block", "groupSkew_iterate_block", "Repeated returning blocks", "When the base returns after p steps, k repeated blocks multiply the fibre by the kth power of the p-step holonomy."),
            Node("group-skew-return", "groupSkew_return_iff", "Exact lifted return criterion", "A lifted state returns at time n exactly when the base minimal period times the order of its holonomy divides n."),
            Node("group-skew-minimum", "groupSkew_minimalPeriod", "Lifted minimal period", "For a finite fibre group, the lifted minimal period is the base minimal period multiplied by the holonomy order."),
            Node("group-skew-orbit", "groupSkew_periodicOrbit_eq_iff", "Equality of lifted periodic orbits", "Two lifts over one periodic base point have the same periodic orbit exactly when the fibre displacement lies in the subgroup of holonomy powers."),
            Node("group-skew-family", "groupSkewOrbitFamily", "Orbit family over a base point", "The family collects the periodic orbits obtained by varying the initial fibre coordinate.", DescribeRole.Definition),
            Node("group-skew-quotient", "groupSkewOrbitQuotientEquivFamily", "Coset quotient parametrization", "The left-coset quotient by the holonomy subgroup is equivalent to the lifted orbit family over a periodic base point.", DescribeRole.Definition),
            Node("group-skew-card", "groupSkewOrbitFamily_card", "Orbit-family cardinality", "The number of lifted orbit classes is the index of the subgroup generated by the ordered holonomy.")
        )));

    private static DocumentBlock.Describe Node(
        string id, string declaration, string title, string text,
        DescribeRole role = DescribeRole.Theorem) =>
        Describe.Lean(
            DescribeId.Create(id),
            DeclarationHandle.Create(Prefix + declaration),
            H(title),
            StatementSource.WithoutFormula(),
            AssessedProvenance.FromRepo(),
            Blocks(Paragraph(Text(text))),
            role);
}
