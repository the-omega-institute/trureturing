using static StrataLint.Scribe.DefinitionDsl;

namespace StrataLint.Scribe.Blueprint.D5.S1.Dynamics.PeriodicOrbits;

internal sealed class SkewOrbitCoordinatesDocument : IScribeDocumentDefinition
{
    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "A periodic skew orbit splits into base positions and a holonomy phase subgroup.",
        H("Coordinates on a lifted periodic orbit"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("skew-orbit-coordinates"),
                DeclarationHandle.Create("D5/S1/Dynamics/PeriodicOrbits/SkewOrbitCoordinates.skew_orbit_coordinates"),
                H("Base position and holonomy phase"),
                StatementSource.WithoutFormula(),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "Let x be a periodic base point with minimal period p, and let h be "
                        + "the Birkhoff sum of the charge over one turn. Suppose h has finite "
                        + "additive order. The map sending (i,s) to "
                        + "(f^i(x), a+s+BirkhoffSum(i,x)) is a bijection from "
                        + "Fin p times the subgroup generated by h onto the lifted periodic "
                        + "orbit through (x,a). The fiber group may be infinite.")),
                    Paragraph(Text(
                        "Divide an orbit time n into its remainder i modulo p and its number "
                        + "of complete base turns. Complete turns contribute multiples of h; "
                        + "finite order ensures that every integer multiple is also a "
                        + "nonnegative multiple. Distinct remainders give distinct base points, "
                        + "and additive cancellation then identifies the phase uniquely.")),
                    Paragraph(Text(
                        "Consequently, each fiber of the orbit projection is a translate of "
                        + "the same holonomy subgroup. For a nonzero cyclic modulus q, the "
                        + "subgroup has q/gcd(q,h.val) elements by Mathlib's cyclic order "
                        + "formula. These coordinates describe the individual phase fibers, "
                        + "beyond the total minimal-period formula."))),
                DescribeRole.Theorem)
        )));
}
