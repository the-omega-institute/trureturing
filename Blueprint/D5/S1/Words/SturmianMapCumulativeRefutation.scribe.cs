    private static Formula MapLengthFormula()
    {
        var d = F.Id("d"); var i = F.Id("i"); var a = F.Id("a"); var k = F.Id("k");
        var samples = All(k, Naturals, Imply(Less(k, Ell), Equal(
            Call("lowerMechanicalWord", Alpha, Alpha,
                new Formula.Binary(i, FormulaBinaryOperator.Add,
                    new Formula.Binary(k, FormulaBinaryOperator.Multiply, d))), a)));
        var condition = new Formula.Logic(Less(D(0), Ell), FormulaLogicOperator.And,
            Parenthesized(samples));
        var body = Sup(Seq(i, Colon, Naturals), Sup(Seq(a, Colon, F.Id("Bool")),
            Sup(Seq(Ell, Colon, Naturals), Sup(Parenthesized(condition),
                Parenthesized(Seq(Ell, Colon, new Formula.Power(Naturals, Infty)))))));
        return Disp(All(Alpha, Reals, All(d, Naturals,
            Equal(Call("mapLength", Alpha, d), Parenthesized(body)))));
    }

    private static Formula ClaimBody()
    {
        var n = F.Id("n"); var q = F.Id("q"); var d = F.Id("d");
        var denominator = new Formula.Apply(Seq(
            Parenthesized(new Formula.Apply(Qualified("GenContFract", "of"), [Alpha])),
            Dot, Seq(Operatorname, Grp(F.Id("dens")))), [n]);
        var comparison = AtMost(Call("mapLength", Alpha, d), Call("mapLength", Alpha, q));
        var differences = All(d, Naturals, Imply(AtMost(D(1), d), Imply(AtMost(d, q), comparison)));
        var denominatorCase = All(q, Naturals,
            Imply(Equal(Parenthesized(Seq(q, Colon, Reals)), denominator), differences));
        var levels = All(n, Naturals, Imply(AtMost(D(1), n), denominatorCase));
        return All(Alpha, Reals, Imply(Call("Irrational", Alpha),
            Imply(Less(D(0), Alpha), Imply(Less(Alpha, new Formula.Fraction(D(1), D(2))), levels))));
    }

    private static Formula Naturals => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula Reals => Seq(Mathbb, Grp(F.Id("R")));
    private static Formula Parenthesized(Formula body) => Seq(Open, body, Close);
    private static Formula Call(string name, params Formula[] args) => new Formula.Apply(F.Id(name), [.. args]);
    private static Formula Qualified(string owner, string name) =>
        Seq(Operatorname, Grp(F.Id(owner)), Dot, Operatorname, Grp(F.Id(name)));
    private static Formula Sup(Formula index, Formula body) =>
        Seq(new Formula.Subscript(Seq(Operatorname, Grp(F.Id("iSup"))), index), Sp, body);
    private static Formula All(Formula name, Formula type, Formula body) =>
        Seq(Forall, Sp, Parenthesized(Seq(name, Colon, Sp, type)), Comma, Sp, body);
    private static Formula Imply(Formula premise, Formula conclusion) =>
        new Formula.Logic(Parenthesized(premise), FormulaLogicOperator.Implies, Parenthesized(conclusion));
    private static Formula Equal(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.Equal, b);
    private static Formula Less(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThan, b);
    private static Formula AtMost(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThanOrEqual, b);
}
