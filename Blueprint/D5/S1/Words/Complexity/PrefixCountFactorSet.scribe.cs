using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S1.Words.Complexity;

internal sealed class PrefixCountFactorSetDocument : IScribeDocumentDefinition
{
    private const string Owner = "D5/S1/Words/Complexity/PrefixCountFactorSet.";
    private static Formula Id(string s) => F.Id(s);
    private static Formula Call(string s, params Formula[] args)
    {
        var name = new List<Formula>();
        foreach (var part in s.Split('.'))
        {
            if (name.Count > 0) name.Add(Dot);
            name.Add(Id(part));
        }
        var items = new List<Formula> { Seq(Operatorname, Grp(Seq([.. name]))), Open };
        for (var i = 0; i < args.Length; i++)
        {
            if (i > 0) items.AddRange([Comma, Sp]);
            items.Add(args[i]);
        }
        items.Add(Close);
        return Seq([.. items]);
    }

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Prefix growth on the subshift generated by a word equals the cardinality of its factor set.",
        H("Prefix Count and Factor Sets"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("prefix-count-word-subshift-factor-set"),
                DeclarationHandle.Create(Owner + "prefixCount_wordSubshift_eq_factorSet_card"),
                H("Word-subshift prefixes are exactly word factors"),
                StatementSource.FromAuthor(Disp(Seq(
                    Forall, Sp, Id("x"), Colon, Sp, Seq(Mathbb, Grp(Id("N"))), Caret, Id("N"), Comma, Sp,
                    Forall, Sp, Id("n"), Colon, Sp, Seq(Mathbb, Grp(Id("N"))), Comma, Sp,
                    Call("prefixCount", Call("wordSubshift", Id("x")), Id("n")),
                    Sp, Eq, Sp,
                    Call("Finset.card", Call("wordFactorSet", Id("x"), Id("n")))))),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "Every prefix realized in the word subshift is a factor of the base word, "
                    + "and every base factor is realized by the corresponding shifted point. "
                    + "The equality therefore identifies symbolic prefix growth with the "
                    + "classical factor-complexity cardinality."))),
                DescribeRole.Theorem))));
}
