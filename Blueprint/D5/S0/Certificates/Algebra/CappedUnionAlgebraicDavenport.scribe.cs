using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S0.Certificates.Algebra;

internal sealed class CappedUnionAlgebraicDavenportDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S0/Certificates/Algebra/CappedUnionAlgebraicDavenport.";
    private static readonly LibraryNoteRef Source = LibraryNoteRef.Create("D5/L/Semigroups/mazhang2026wangcounterexamples");

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "In the ordinary semigroup algebra of the capped union monoid the level-one differences multiply to zero, and the algebraic Davenport constant is one over every nonzero commutative ring.",
        H("The algebraic Davenport constant of the capped union monoid"),
        Blocks(
            Node("capped-alg-idem", "The cyclic idempotent", "cyclicIdempotent_eq",
                Disp(All("x", Call("Capped", F.Id("U")), Equal(Call("cyclicIdempotent", F.Id("x")), Add(F.Id("x"), F.Id("x"))))),
                "For every x=(A,i) in S_U the positive cyclic subsemigroup generated by x is {x, x+x}, because x+(x+x)=(x+x)+(x+x)=x+x with level min(2,3i)=min(2,2i). Its only idempotent is x+x=(A,min(2,2i)), so the cyclic idempotent chosen by the existing WangConjecture326Refutation.cyclicIdempotent is x+x.",
                DescribeRole.Theorem, AssessedProvenance.FromLiterature(Source)),
            Node("capped-alg-result", "Lemma 2", "result", ResultFormula(),
                "For every commutative ring R, (X^(A,1)-X^(A,2))(X^(B,1)-X^(B,2))=0 in R[S_U], since all four monomials carry the label (A union B, 2) with coefficients summing to 1-1-1+1. If R is nonzero, the algebraic Davenport constant algebraicD(S_U,R) of WangConjecture326Refutation equals 1. A one-term sequence (empty,1) is good, since its factor X^(empty,1)-c X^(empty,2) has coefficient 1 at (empty,1). In any sequence of length at least two, choosing every coefficient equal to 1 kills the product: an idempotent label x+x=x gives a zero factor, and otherwise the first two labels have level one and their factors multiply to zero as above. This is Lemma 2 of Ma and Zhang, Zenodo 10.5281/zenodo.23884901, for every set U, including the empty one, and every nonzero commutative ring.",
                DescribeRole.Theorem, AssessedProvenance.FromLiterature(Source)))));

    private static Formula ResultFormula()
    {
        Formula X(Formula a, Formula k) => Call("X", Call("pair", a, k));
        var prod = Multiply(Par(Subtract(X(F.Id("A"), D(1)), X(F.Id("A"), D(2)))),
            Par(Subtract(X(F.Id("B"), D(1)), X(F.Id("B"), D(2)))));
        return Disp(And(All("A", Call("Finset", F.Id("U")), All("B", Call("Finset", F.Id("U")), Equal(prod, D(0)))),
            Imp(Call("Nontrivial", F.Id("R")), Equal(Call("algebraicD", Call("Capped", F.Id("U")), F.Id("R")), D(1)))));
    }

    private static DocumentBlock Node(string id, string title, string declaration, Formula formula,
        string prose, DescribeRole role, AssessedProvenance provenance) =>
        Describe.Lean(DescribeId.Create(id), DeclarationHandle.Create(Prefix + declaration), H(title),
            StatementSource.FromAuthor(formula), provenance, Blocks(Paragraph(Text(prose))), role);
    private static Formula Par(Formula x) => Seq(Open, x, Close);
    private static Formula And(Formula a, Formula b) => new Formula.Logic(Par(a), FormulaLogicOperator.And, Par(b));
    private static Formula Imp(Formula a, Formula b) => new Formula.Logic(Par(a), FormulaLogicOperator.Implies, Par(b));
    private static Formula All(string n, Formula type, Formula body) => new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(n), type, body);
}
