using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S0.Certificates.Algebra;

internal sealed class BergmanCyclicSemigroupDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S0/Certificates/Algebra/BergmanCyclicSemigroup.";
    private static readonly LibraryNoteRef Source =
        LibraryNoteRef.Create("D5/L/Certificates/bergman2014eggert");

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Cyclic terminal relations give commutative semigroups with a literal xyz-zero quotient.",
        H("Cyclic terminal monomial semigroups"),
        Blocks(
            Node("carrier", "The normal forms", "Model",
                "For a positive integer n, the carrier has an absorbing zero, the distinct "
                + "monomials of degrees one through n-1, and three distinct terminal elements. "
                + "The Boolean q specifies whether lower monomials divisible by xyz are also "
                + "removed. Monomials use the existing bounded multiset representation; no "
                + "constant monomial or multiplicative identity is added.", DescribeRole.Definition),
            Node("cyclic-lists", "The terminal lists", "terminalLabel",
                "The first terminal class consists of degree-n monomials in x,y with a "
                + "positive x exponent; the second consists of those in y,z with a positive "
                + "y exponent; the third consists of those in z,x with a positive z exponent. "
                + "Degree-n monomials involving all three generators are zero. These are "
                + "the cyclic lists, rather than the earlier Question-15 partition.",
                DescribeRole.Definition),
            Node("multiplication", "Reduction and multiplication", "normal_mul",
                "For every natural n, either Boolean q, and any two positive-degree monomials "
                + "a,b, the product of their reductions is the reduction of a+b. If a factor "
                + "has already reached degree n, every further positive-degree multiple is "
                + "zero. Divisibility by xyz is preserved under multiplication. These facts "
                + "ensure that reduction is compatible with the full multiplication.", DescribeRole.Theorem),
            Node("associativity", "A commutative semigroup with zero", "modelSemigroup",
                "Both bracketings of a triple product reduce the same sum of monomials. "
                + "The resulting multiplication is associative, and zero absorbs on both "
                + "sides. Commutativity follows from addition of monomial multisets.", DescribeRole.Definition),
            Node("powers", "Actual generator powers", "generator_power",
                "The positivePower index k denotes k+1 factors, with no zeroth power. "
                + "For every generator i, its positivePower at index k is precisely the "
                + "reduction of k+1 copies of i.", DescribeRole.Theorem),
            Node("terminal-powers", "Distinct nonzero nth powers", "terminal_powers",
                "For every positive n and either presentation, generator i raised to the "
                + "nth power is the terminal constructor with label i. In particular all "
                + "three terminal powers are nonzero and pairwise distinct. This applies "
                + "to every positive multiple of six, without a field hypothesis.", DescribeRole.Theorem),
            Node("generation", "The generators generate the entire semigroup", "generated",
                "For every positive n, the subsemigroup generated by the three degree-one "
                + "elements is the whole carrier. Every normal form has a positive monomial "
                + "representative, including zero, represented by n+1 copies of x.", DescribeRole.Theorem),
            Node("representatives", "Every normal form is attained", "normal_surjective",
                "For every positive n and either value of q, every carrier element is "
                + "the reduction of a positive monomial. This connects the literal carrier "
                + "to the generators and the presentation, including its absorbing zero.", DescribeRole.Theorem),
            Node("quotient", "The quotient homomorphism", "quotient_mul",
                "The map from q=false to q=true preserves zero and multiplication. It "
                + "fixes the three terminals and each lower monomial not divisible by xyz, "
                + "and sends every lower multiple of xyz to zero. The map is surjective.", DescribeRole.Theorem),
            Node("surjection", "Every quotient element is attained", "quotient_surjective",
                "Each surviving lower monomial and each terminal has the identical "
                + "normal form as a preimage in the cyclic carrier; zero has zero as a "
                + "preimage. This is surjectivity of the actual map on the full carriers.", DescribeRole.Theorem),
            Node("fibers", "The exact fibers", "quotient_fibers",
                "Two cyclic normal forms have the same quotient image exactly when they "
                + "are equal, or both belong to the ideal consisting of zero and the lower "
                + "monomials divisible by xyz. Every nonzero quotient fiber is a singleton; "
                + "no terminal powers are identified.", DescribeRole.Theorem),
            Paragraph(Text("Over any field, applying BergmanContractedAlgebra.mapHom "
                + "to quotient, its zero-preservation equation and quotient_mul "
                + "gives a homomorphism between "
                + "the original contracted nonunital algebras. It sends each basis image "
                + "to the basis image of its quotient, and sends a collapsed monomial to "
                + "the zero vector. No characteristic or root-of-unity premise is needed "
                + "for this structural map. Cancellation and the field criterion require "
                + "their separate coefficient arguments.")),
            Describe.Lean(DescribeId.Create("presentation"),
                DeclarationHandle.Create("D5/S0/Certificates/Algebra/BergmanCyclicSemigroup.normal_form_complete"),
                H("Completeness of the written presentation"), StatementSource.WithoutFormula(),
                AssessedProvenance.FromRepo(Source), Blocks(Paragraph(Text(
                    "Start with the free commutative semigroup on x,y,z and an absorbing zero. "
                    + "Take the congruence generated by the cyclic degree-n lists, the "
                    + "degree-n all-three-variable zero relations, the degree-(n+1) zero "
                    + "relations, and optionally the single relation xyz=0. Two words are "
                    + "equivalent under this generated congruence if and only if their "
                    + "normal forms agree. Thus the normal forms impose exactly the stated "
                    + "relations, with neither missing identifications nor additional ones."))),
                DescribeRole.Theorem),
            Paragraph(Text("The original Question-15 refutation retains its separate "
                + "59-element partition. The cyclic presentation and its xyz-zero quotient "
                + "are the presentations used in the revised examples. At n=6 the "
                + "positive monomials of degrees at most five number 55, by the existing "
                + "bounded-multiset cardinality result. Subtraction of one copy of each "
                + "generator identifies the 10 lower multiples of xyz with the monomials "
                + "of degree at most two. Thus the cyclic carrier has 55+3+1=59 elements "
                + "and its quotient has 45+3+1=49 elements. These count the actual "
                + "normal-form carriers. General cardinalities, coefficient cancellations, "
                + "field criterion, product-set counts and exact "
                + "nilpotency indices are separate assertions. No universal conclusion for "
                + "Question 11, Questions 16-18, or the characteristic-p Eggert conjecture "
                + "follows from the structural statements here.")))));

    private static DocumentBlock Node(string id, string title, string declaration, string prose,
        DescribeRole role) => Describe.Lean(DescribeId.Create(id),
            DeclarationHandle.Create(Prefix + declaration), H(title),
            StatementSource.WithoutFormula(), AssessedProvenance.FromRepo(Source),
            Blocks(Paragraph(Text(prose))), role);
}
