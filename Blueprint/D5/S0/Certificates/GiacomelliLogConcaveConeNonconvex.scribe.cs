using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S0.Certificates;

internal sealed class GiacomelliLogConcaveConeNonconvexDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S0/Certificates/GiacomelliLogConcaveConeNonconvex.";
    private static readonly LibraryNoteRef Source =
        LibraryNoteRef.Create("D5/L/Certificates/giacomelli2026logconcavity");

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Two positive geometric solutions have infinitely log-concave initial data, "
            + "but their midpoint has a negative first log-concavity determinant.",
        H("Giacomelli's cone of infinitely log-concave initial data"),
        Blocks(
            Node("recurrence", "seq", "The recurrent sequence", SequenceFormula(),
                AssessedProvenance.FromLiterature(Source),
                "Equation (3), printed page 2: a_{n+1} = Σ_{k=0}^{d−1} (p_k n + q_k) a_{n−k}, "
                    + "n ≥ d − 1, with p_k, q_k ∈ ℝ and initial data (a_0, …, a_{d−1}) ∈ ℝ^d. "
                    + "The argument m is n + 1, and the entries of v0 are in increasing index order. "
                    + "Subtraction in natural indices is truncated. The cast to Real follows subtraction.",
                DescribeRole.Definition),
            Node("operator", "logConcaveOp", "The log-concave operator", OperatorFormula(),
                AssessedProvenance.FromLiterature(Source),
                "Definition 2.1, printed page 3: “Let (aₖ)ₖ∈ℕ be a sequence of real numbers. "
                    + "The log-concave operator L is defined by L(aₖ) = (bₖ), bₖ = aₖ² − aₖ₊₁aₖ₋₁. "
                    + "The sequence (aₖ) is log-concave if bₖ ≥ 0 for all k. For i ≥ 1, (aₖ) is "
                    + "i-fold log-concave if Lⁱ(aₖ) ≥ 0, and ∞-log-concave if Lⁱ(aₖ) ≥ 0 for all i ∈ ℕ.” "
                    + "The function argument a has domain Nat; k − 1 uses natural subtraction.",
                DescribeRole.Definition),
            Node("cone", "coneInf", "Infinitely log-concave initial data", ConeFormula(),
                AssessedProvenance.FromLiterature(Source),
                "Section 7 (1), printed page 13, defines “C∞ = {v₀ : Lⁱ(aₙ) ≥ 0 ∀ n, i}”. "
                    + "The function seq is the sequence generated by v0. Iteration is function "
                    + "iteration on Nat → Real, and i ≤ n restricts evaluation to interior indices. "
                    + "Iteration zero includes nonnegativity of the original sequence.",
                DescribeRole.Definition),
            Node("convexity-question", "claim", "The affirmative convexity assertion",
                Disp(Iff(F.Id("claim"), ClaimBody())), AssessedProvenance.FromLiterature(Source),
                "Section 7 (1), printed page 13: “(Cone of initial data for variable coefficients.) "
                    + "Proposition 3.4 gives a matrix condition on v₀ for log-concavity of a general "
                    + "P-recursive sequence. Characterize the geometry of the cone C∞ = "
                    + "{v₀ : Lⁱ(aₙ) ≥ 0 ∀ n, i} for d ≥ 3. Is it convex? Simply connected?” "
                    + "The affirmative convexity assertion ranges over every natural d ≥ 3 and "
                    + "every pair p, q of real coefficient vectors. Convex is Mathlib's real convexity predicate.",
                DescribeRole.Definition),
            Node("convexity-refuted", "result", "The cone need not be convex",
                Disp(new Formula.Not(Parenthesized(ClaimBody()))), AssessedProvenance.FromRepo(Source),
                "Take d = 3, p = (1, −3, 2), q = (3, −2, 0). Strong induction shows that "
                    + "U = (1, 1, 1) and V = (1, 2, 4) generate 1 and 2ⁿ. Induction on the "
                    + "iterate shows that each positive iterate is zero whenever 1 ≤ i ≤ n. "
                    + "Both sequences are nonnegative, so U and V belong to coneInf p q. "
                    + "Their midpoint is (1, 3/2, 5/2). At index 1 its first determinant is "
                    + "(3/2)² − (5/2)·1 = −1/4. This contradicts convexity. "
                    + "Characterization and simple connectedness are separate questions.", DescribeRole.Theorem))));

    private static DocumentBlock.Describe Node(string id, string name, string title, Formula formula,
        AssessedProvenance provenance, string prose, DescribeRole role) => Describe.Lean(
            DescribeId.Create("giacomelli-" + id), DeclarationHandle.Create(Prefix + name),
            H(title), StatementSource.FromAuthor(formula), provenance,
            Blocks(Paragraph(Text(prose))), role);

    private static Formula Nat() => new Formula.NamedConstant(FormulaIdentifier.Create("Nat"));
    private static Formula Real() => new Formula.NamedConstant(FormulaIdentifier.Create("Real"));
    private static Formula Vector(Formula d) => Seq(Call("Fin", d), Sp, To, Sp, Real());
    private static Formula SequenceFormula()
    {
        var d = F.Id("d");
        var m = F.Id("m");
        var k = F.Id("k");
        var p = F.Id("p");
        var q = F.Id("q");
        var v = F.Id("v0");
        var h = F.Id("h");
        var cast = Parenthesized(Seq(Parenthesized(Seq(Sub(m, D(1)), Sp, Colon, Sp, Nat())), Sp, Colon, Sp, Real()));
        var summand = Mul(Parenthesized(Add(Mul(Call("p", k), cast), Call("q", k))),
            Call("seq", p, q, v, Sub(Sub(m, D(1)), Call("val", k))));
        var sum = Seq(new Formula.Subscript(Sum, Seq(k, Sp, Colon, Sp, Call("Fin", d))), Sp, summand);
        var branch = Parenthesized(Seq(Seq(Operatorname, Grp(F.Id("if"))), Sp, h, Sp, Colon, Sp,
            Less(m, d), Sp, Seq(Operatorname, Grp(F.Id("then"))), Sp,
            Call("v0", Seq(Langle, Sp, m, Comma, Sp, h, Rangle)), Sp, Seq(Operatorname, Grp(F.Id("else"))), Sp, sum));
        return Disp(All("d", Nat(), All("p", Vector(d), All("q", Vector(d),
            All("v0", Vector(d), All("m", Nat(), Equal(Call("seq", p, q, v, m), branch)))))));
    }

    private static Formula OperatorFormula()
    {
        var a = F.Id("a");
        var k = F.Id("k");
        return Disp(All("a", Seq(Nat(), Sp, To, Sp, Real()), All("k", Nat(),
            Equal(Call("logConcaveOp", a, k), Sub(new Formula.Power(Call("a", k), D(2)),
                Mul(Call("a", Add(k, D(1))), Call("a", Sub(k, D(1)))))))));
    }

    private static Formula ConeFormula()
    {
        var d = F.Id("d");
        var p = F.Id("p");
        var q = F.Id("q");
        var v = F.Id("v0");
        var i = F.Id("i");
        var n = F.Id("n");
        var iterate = Seq(new Formula.Power(F.Id("logConcaveOp"), Seq(OpenBracket, i, CloseBracket)),
            Parenthesized(Call("seq", p, q, v)), Parenthesized(n));
        var body = All("i", Nat(), All("n", Nat(), Implies(Le(i, n), Le(D(0), iterate))));
        var set = Seq(OpenBrace, v, Sp, Colon, Sp, Parenthesized(Vector(d)), Sp, Mid, Sp,
            Parenthesized(body), CloseBrace);
        return Disp(All("d", Nat(), All("p", Vector(d), All("q", Vector(d),
            Equal(Call("coneInf", p, q), set)))));
    }

    private static Formula ClaimBody()
    {
        var d = F.Id("d");
        return All("d", Nat(), Implies(Le(D(3), d), All("p", Vector(d), All("q", Vector(d),
            Call("Convex", Real(), Call("coneInf", F.Id("p"), F.Id("q")))))));
    }

    private static Formula All(string name, Formula type, Formula body) => new Formula.Bind(
        FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), type, Parenthesized(body));
    private static Formula Call(string name, params Formula[] args) =>
        new Formula.FunctionCall(FormulaIdentifier.Create(name), [.. args]);
    private static Formula Equal(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.Equal, b);
    private static Formula Less(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThan, b);
    private static Formula Le(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThanOrEqual, b);
    private static Formula Add(Formula a, Formula b) => new Formula.Binary(a, FormulaBinaryOperator.Add, b);
    private static Formula Sub(Formula a, Formula b) => new Formula.Binary(a, FormulaBinaryOperator.Subtract, b);
    private static Formula Mul(Formula a, Formula b) => new Formula.Binary(a, FormulaBinaryOperator.Multiply, b);
    private static Formula Implies(Formula a, Formula b) =>
        new Formula.Logic(Parenthesized(a), FormulaLogicOperator.Implies, Parenthesized(b));
    private static Formula Iff(Formula a, Formula b) =>
        new Formula.Logic(Parenthesized(a), FormulaLogicOperator.Iff, Parenthesized(b));
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
}
