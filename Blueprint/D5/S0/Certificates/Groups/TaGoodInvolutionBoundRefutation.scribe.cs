    private static Formula Named(string name) => Seq(Operatorname, Grp(F.Id(name)));
    private static Formula Call(string name, params Formula[] args) => new Formula.Apply(Named(name), [.. args]);
    private static Formula App(Formula function, params Formula[] args) => new Formula.Apply(function, [.. args]);
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula GroupContext(Formula body)
    {
        Formula g = F.Id("G");
        return Seq(Forall, Sp, Parenthesized(Seq(g, Sp, Colon, Sp, Named("Type"))), Sp,
            OpenBracket, Call("Group", g), CloseBracket, Sp,
            OpenBracket, Call("DecidableEq", g), CloseBracket, Comma, Sp,
            Parenthesized(body));
    }
    private static Formula Equal(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.Equal, right);
    private static Formula InSet(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.MemberOf, right);
    private static Formula And(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.And, Parenthesized(right));
    private static Formula Implies(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Implies, Parenthesized(right));
    private static Formula Iff(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.Iff, Parenthesized(right));
    private static Formula All(Formula variable, Formula domain, Formula body) =>
        Seq(Forall, Sp, variable, Sp, Colon, Sp, domain, Comma, Sp, Parenthesized(body));
    private static Formula Some(Formula variable, Formula domain, Formula body) =>
        Seq(Exists, Sp, variable, Sp, Colon, Sp, domain, Comma, Sp, Parenthesized(body));
    private static Formula LambdaOf(Formula variable, Formula body) =>
        Parenthesized(Seq(variable, Sp, Mapsto, Sp, body));
    private static Formula Arrow(Formula left, Formula right) => Seq(left, Sp, To, Sp, right);
    private static Formula Inverse(Formula value) => new Formula.Power(value, new Formula.Negate(D(1)));
    private static Formula Mul(Formula left, Formula right) => new Formula.Binary(left, FormulaBinaryOperator.Multiply, right);
    private static Formula Conjugate(Formula x, Formula y) => Mul(Mul(x, y), Inverse(x));
    private static Formula Subtype(Formula variable, Formula type, Formula predicate) =>
        Seq(OpenBrace, variable, Sp, Colon, Sp, type, Sp, Mid, Sp, Parenthesized(predicate), CloseBrace);
    private static Formula Operation(Formula h, Formula x, Formula y) => Call("s", h, x, y);
    private static Formula Closure(Formula x) => Call("closure", Parenthesized(Seq(x, Sp, Colon, Sp, Call("Set", F.Id("G")))));
    private static Formula CenterSize(Formula x) => Call("NatCard", Call("center", Closure(x)));
    private static Formula Count(Formula type) => Call("FintypeCard", type);

    private static Formula ClosedFormula()
    {
        Formula x = F.Id("x"), y = F.Id("y"), set = F.Id("X"), g = F.Id("G");
        Formula e = Iff(Call("ConjClosed", set), All(x, g, Implies(InSet(x, set),
            All(y, g, Implies(InSet(y, set), InSet(Conjugate(x, y), set))))));
        return Disp(GroupContext(All(set, Call("Finset", g), e)));
    }

    private static Formula OperationFormula()
    {
        Formula set = F.Id("X"), h = F.Id("h"), x = F.Id("x"), y = F.Id("y");
        Formula value = Conjugate(Call("val", x), Call("val", y));
        Formula proof = App(h, Call("val", x), Call("property", x), Call("val", y), Call("property", y));
        Formula e = Equal(Operation(h, x, y), Seq(Langle, value, Comma, Sp, proof, Rangle));
        return Disp(GroupContext(All(set, Call("Finset", F.Id("G")),
            All(h, Call("ConjClosed", set), All(x, set, All(y, set, e))))));
    }

    private static Formula GoodFormula()
    {
        Formula set = F.Id("X"), h = F.Id("h"), x = F.Id("x"), y = F.Id("y"), rho = Rho;
        Formula involutive = All(y, set, Equal(App(rho, App(rho, y)), y));
        Formula sx = Call("s", h, x), sr = Call("s", h, App(rho, x));
        Formula commute = Equal(Seq(rho, Sp, Circ, Sp, sx), Seq(sx, Sp, Circ, Sp, rho));
        Formula left = All(y, set, Equal(App(sr, App(sx, y)), y));
        Formula right = All(y, set, Equal(App(sx, App(sr, y)), y));
        Formula predicate = And(involutive, All(x, set, And(commute, And(left, right))));
        Formula e = Equal(Call("Good", set, h), Subtype(rho, Arrow(set, set), predicate));
        return Disp(GroupContext(All(set, Call("Finset", F.Id("G")),
            All(h, Call("ConjClosed", set), e))));
    }

    private static Formula AutFormula()
    {
        Formula set = F.Id("X"), h = F.Id("h"), x = F.Id("x"), y = F.Id("y"), phi = Phi;
        Formula preserves = All(x, set, All(y, set,
            Equal(App(phi, Operation(h, x, y)), Operation(h, App(phi, x), App(phi, y)))));
        Formula e = Equal(Call("Aut", set, h),
            Subtype(phi, Arrow(set, set), And(Call("Bijective", phi), preserves)));
        return Disp(GroupContext(All(set, Call("Finset", F.Id("G")),
            All(h, Call("ConjClosed", set), e))));
    }

    private static Formula OrbitFormula()
    {
        Formula set = F.Id("X"), x = F.Id("x"), y = F.Id("y"), g = F.Id("g");
        Formula orbit = Call("filter", LambdaOf(y,
            Some(g, F.Id("G"), And(InSet(g, Closure(set)), Equal(Conjugate(g, x), y)))), set);
        Formula e = Equal(Call("orbitCount", set),
            Call("FinsetCard", Call("image", LambdaOf(x, orbit), set)));
        return Disp(GroupContext(All(set, Call("Finset", F.Id("G")), e)));
    }

    private static Formula ClaimFormula()
    {
        Formula g = F.Id("G"), set = F.Id("X"), h = F.Id("h");
        Formula z = CenterSize(set), k = Call("orbitCount", set);
        Formula bound = new Formula.Relation(Count(Call("Good", set, h)),
            FormulaRelationOperator.LessThan,
            Call("min", Count(Call("Aut", set, h)), new Formula.Power(z, k)));
        Formula largeCenter = new Formula.Relation(D(2), FormulaRelationOperator.LessThanOrEqual, z);
        Formula manyOrbits = new Formula.Relation(D(2), FormulaRelationOperator.LessThanOrEqual, k);
        Formula body = Seq(Forall, Sp, Parenthesized(Seq(g, Sp, Colon, Sp, Named("Type"))), Sp,
            OpenBracket, Call("Group", g), CloseBracket, Sp,
            OpenBracket, Call("Fintype", g), CloseBracket, Sp,
            OpenBracket, Call("DecidableEq", g), CloseBracket, Comma, Sp,
            Parenthesized(All(set, Call("Finset", g), All(h, Call("ConjClosed", set),
                Implies(largeCenter, Implies(manyOrbits, bound))))));
        return Disp(Iff(F.Id("claim"), body));
    }
