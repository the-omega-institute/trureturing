using static StrataLint.Scribe.DefinitionDsl;

namespace StrataLint.Scribe.Blueprint.D5.S0.Tower.Tribonacci;

internal sealed class TribonacciNamesDocument : IScribeDocumentDefinition
{
    public DocumentDefinition Create()
    {
        var n = Id("n");
        var q = Id("Q");
        var naturals = Id("N");

        return DocumentDefinition.Create(ScribeNode.Create(
            "Binary words avoiding 111 form Tribonacci-sized name layers.",
            H("Tribonacci Names"),
            Blocks(
                Paragraph(Text(
                    "A length-Q Tribonacci name is a binary word with no three consecutive true "
                    + "digits. The empty, one-digit, and two-digit layers contain 1, 2, and 4 "
                    + "names, fixing the sequence offset rather than copying the golden offset.")),
                Describe.Lean(
                    DescribeId.Create("tribonacci-sequence"),
                    DeclarationHandle.Create("D5/S0/Tower/Tribonacci/Names.tribonacci"),
                    H("Tribonacci sequence"),
                    StatementSource.WithoutFormula(),
                    AssessedProvenance.FromRepo(),
                    Blocks(Paragraph(Text(
                        "The sequence starts with T(0)=0, T(1)=1, and T(2)=1, then each term is "
                        + "the sum of the preceding three terms."))),
                    DescribeRole.Definition
                ),
                Describe.Lean(
                    DescribeId.Create("tribonacci-three-term-recurrence"),
                    DeclarationHandle.Create("D5/S0/Tower/Tribonacci/Names.tribonacci_add_three"),
                    H("Tribonacci three-term recurrence"),
                    StatementSource.FromAuthor(new Formula.Bind(
                        FormulaQuantifier.ForAll,
                        FormulaIdentifier.Create("n"),
                        naturals,
                        Equal(
                            Call("T", Add(n, Num(3))),
                            Add(
                                Add(Call("T", Add(n, Num(2))), Call("T", Add(n, Num(1)))),
                                Call("T", n))))),
                    AssessedProvenance.FromRepo(),
                    Blocks(Paragraph(Text(
                        "This is the public recurrence equation generated by the recursive "
                        + "definition and used by the cardinality induction."))),
                    DescribeRole.Theorem
                ),
                Describe.Lean(
                    DescribeId.Create("no-three-consecutive-true-name"),
                    DeclarationHandle.Create("D5/S0/Tower/Tribonacci/Names.TribonacciName"),
                    H("No-three-consecutive-true name"),
                    StatementSource.WithoutFormula(),
                    AssessedProvenance.FromRepo(),
                    Blocks(Paragraph(Text(
                        "The recursive predicate checks the first three positions and then the "
                        + "tail, so every length-three window is covered."))),
                    DescribeRole.Definition
                ),
                Describe.Lean(
                    DescribeId.Create("tribonacci-name-initial-interval-equivalence"),
                    DeclarationHandle.Create("D5/S0/Tower/Tribonacci/Names.tribonacciNameEquiv"),
                    H("Tribonacci-name initial-interval equivalence"),
                    StatementSource.WithoutFormula(),
                    AssessedProvenance.FromRepo(),
                    Blocks(Paragraph(Text(
                        "Each admissible name layer is equivalent to the finite initial interval "
                        + "with endpoint T(Q+2)."))),
                    DescribeRole.Definition
                ),
                Describe.Lean(
                    DescribeId.Create("tribonacci-name-layers-have-tribonacci-cardinality"),
                    DeclarationHandle.Create("D5/S0/Tower/Tribonacci/Names.tribonacci_name_card"),
                    H("Tribonacci-name layers have Tribonacci cardinality"),
                    StatementSource.FromAuthor(new Formula.Bind(
                        FormulaQuantifier.ForAll,
                        FormulaIdentifier.Create("Q"),
                        naturals,
                        Equal(
                            Call("card", Call("TribonacciName", q)),
                            Call("T", Add(q, Num(2)))))),
                    AssessedProvenance.FromRepo(),
                    Blocks(Paragraph(Text(
                        "Every admissible nonempty word begins uniquely with 0, 10, or 110. "
                        + "Removing that prefix yields the preceding three admissible layers, "
                        + "which gives the three-term count recurrence."))),
                    DescribeRole.Theorem
                )),
            []));
    }
}
