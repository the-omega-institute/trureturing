using static StrataLint.Scribe.DefinitionDsl;

namespace StrataLint.Scribe.Blueprint.D5.S0.Tower.NonPisotFrontier;

internal sealed class ConjugateValuationDocument : IScribeDocumentDefinition
{
    public DocumentDefinition Create()
    {
        var n = Id("n");
        var naturals = Id("N");
        var conj = Id("betaThirteenConjugate");

        var recurrence = new Formula.BindMany(
            FormulaQuantifier.ForAll,
            [new Formula.BoundVariable(FormulaIdentifier.Create("n"), naturals)],
            Equal(
                Call("conjugateRemainder", Add(n, Num(1))),
                Subtract(
                    Multiply(conj, Call("conjugateRemainder", n)),
                    Call("beta13GreedyDigit", n))));

        const string declarationPrefix =
            "D5/S0/Tower/NonPisotFrontier/ConjugateValuation.";

        return DocumentDefinition.Create(ScribeNode.Create(
            "An exact code read at the conjugate is driven by the same digits, so repeating "
                + "digits leave the conjugate orbit only finitely many values.",
            H("Conjugate Valuation"),
            Blocks(
                Paragraph(Text(
                    "The greedy expansion of one is already carried exactly, as integer pairs "
                        + "standing for a value in the ring generated by the base, together with "
                        + "the multiplication that the base's own quadratic relation reduces. "
                        + "Nothing of that is rebuilt here.")),
                Paragraph(Text(
                    "What is added is a second reading of the same pairs, at the conjugate root "
                        + "rather than at the base. The reduction inside the multiplication is "
                        + "the base's relation, and the conjugate satisfies the same relation, "
                        + "so the reading intertwines with it. That is the whole content: the "
                        + "conjugate orbit is not a separate object to be tracked, it is the "
                        + "same integer stream read elsewhere, and it obeys the same digits.")),
                Paragraph(Text(
                    "Two consequences follow without further work. Once the codes repeat, so "
                        + "does the conjugate reading; and then every value the conjugate orbit "
                        + "ever takes is one it already took before the period closed. That is "
                        + "boundedness in the form the escape estimate can be set against, and "
                        + "it needs no measure of how large those values are.")),
                Describe.Lean(
                    DescribeId.Create("the-conjugate-reading-of-the-expansion"),
                    DeclarationHandle.Create(
                        declarationPrefix + "conjugate_reading_of_the_expansion"),
                    H("The conjugate reading of the expansion"),
                    StatementSource.FromAuthor(FormulaDsl.Disp(recurrence)),
                    AssessedProvenance.FromRepo(),
                    Blocks(Paragraph(Text(
                        "The displayed half is the recurrence; the second half of the statement "
                            + "is the collapse to finitely many values under repeating codes. "
                            + "Neither says the digits do repeat, and neither supplies the "
                            + "contradiction; they supply the side of it that periodicity would "
                            + "force."))),
                    DescribeRole.Theorem)),
            [
                DocumentEdge.Dependency.Create(GidRef.Create(
                    "D5/S0/Tower/NonPisotFrontier/BaseIdentification")),
            ]));
    }
}
