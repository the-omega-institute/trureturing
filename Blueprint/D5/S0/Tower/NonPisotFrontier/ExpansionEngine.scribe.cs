using static StrataLint.Scribe.DefinitionDsl;

namespace StrataLint.Scribe.Blueprint.D5.S0.Tower.NonPisotFrontier;

internal sealed class ExpansionEngineDocument : IScribeDocumentDefinition
{
    public DocumentDefinition Create()
    {
        var beta = Id("betaThirteen");
        var p = Id("p");
        var q = Id("q");
        var reals = Id("R");

        var mulRule = new Formula.BindMany(
            FormulaQuantifier.ForAll,
            [
                new Formula.BoundVariable(FormulaIdentifier.Create("p"), reals),
                new Formula.BoundVariable(FormulaIdentifier.Create("q"), reals),
            ],
            Equal(
                Multiply(beta, Add(p, Multiply(q, beta))),
                Add(Multiply(Num(3), q), Multiply(Add(p, q), beta))));

        Formula Window(Formula x) => new Formula.Logic(
            new Formula.Relation(Num(0), FormulaRelationOperator.LessThan, x),
            FormulaLogicOperator.And,
            new Formula.Relation(x, FormulaRelationOperator.LessThan, Num(1)));

        var statement = new Formula.Logic(
            new Formula.Logic(
                mulRule,
                FormulaLogicOperator.And,
                new Formula.Logic(
                    new Formula.Relation(Num(2), FormulaRelationOperator.LessThan, beta),
                    FormulaLogicOperator.And,
                    new Formula.Relation(beta, FormulaRelationOperator.LessThan, Num(3)))),
            FormulaLogicOperator.And,
            new Formula.Logic(
                Window(Subtract(beta, Num(2))),
                FormulaLogicOperator.And,
                Window(Subtract(Num(3), beta))));

        const string declarationPrefix =
            "D5/S0/Tower/NonPisotFrontier/ExpansionEngine.";

        return DocumentDefinition.Create(ScribeNode.Create(
            "Multiplying by the frontier base is an integer map on coordinate pairs, which "
                + "is the algebraic engine of any expansion argument at that base.",
            H("Expansion Engine"),
            Blocks(
                Paragraph(Text(
                    "Every element of the ring generated by the base is a coordinate pair "
                        + "against one and the base. Because the base squares to itself plus "
                        + "three, multiplying by it sends the pair to three times the second "
                        + "coordinate, paired with the sum of the two. Subtracting a digit "
                        + "changes only the first coordinate, so a greedy step stays integral.")),
                Describe.Lean(
                    DescribeId.Create("the-frontier-expansion-engine"),
                    DeclarationHandle.Create(declarationPrefix + "frontier_expansion_engine"),
                    H("The frontier expansion engine"),
                    StatementSource.FromAuthor(FormulaDsl.Disp(statement)),
                    AssessedProvenance.FromRepo(),
                    Blocks(Paragraph(Text(
                        "The two window facts pin the first two greedy digits of one at two "
                            + "and zero. The expansion itself, and the growth of the gap "
                            + "alphabet that the source reports, are not proved here."))),
                    DescribeRole.Theorem)),
            [
                DocumentEdge.Dependency.Create(GidRef.Create(
                    "D5/S0/Tower/NonPisotFrontier/BetaThirteen")),
            ]));
    }
}
