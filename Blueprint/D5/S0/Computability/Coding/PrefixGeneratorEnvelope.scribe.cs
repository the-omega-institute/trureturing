using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S0.Computability.Coding;

internal sealed class PrefixGeneratorEnvelopeDocument : IScribeDocumentDefinition
{
    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Every finite labelled word family has exact factorizations through at most as many nonempty prefix-separated generators.",
        H("Prefix-generator envelopes for finite labelled word families"),
        Blocks(
            Paragraph(Text(
                "Fix an arbitrary universe u, a type alpha in that universe, a natural number n, "
                    + "and a family f assigning a finite word over alpha to each label in Fin n. "
                    + "Labels retain multiplicity: different labels may carry the same word. "
                    + "A prefix-generator envelope consists of a natural number m at most n, "
                    + "a family g indexed by Fin m, and a coefficient word c(i) over Fin m for "
                    + "each original label i. Every g(i) is nonempty, and a prefix relation "
                    + "from g(i) to g(j) forces the labels i and j to agree.")),
            Paragraph(Text(
                "IsPrefix(x,y) means that there is a finite residual word r with x ++ r = y, "
                    + "including the reflexive case r = []. The expression flatMap(g,s) "
                    + "concatenates the words g(j) in the order of the labels in s; the empty "
                    + "coefficient word concatenates to the empty word.")),
            Describe.Lean(
                DescribeId.Create("prefix-generator-envelope"),
                DeclarationHandle.Create(
                    "D5/S0/Computability/Coding/PrefixGeneratorEnvelope.prefix_generator_envelope"),
                H("Exact prefix-generator envelope"),
                StatementSource.FromAuthor(EnvelopeFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "Induct first on the number of labels and then strongly on the sum "
                            + "of all word lengths at that label count. With no labels, use "
                            + "m = 0 and the empty functions. If a labelled word is empty, "
                            + "delete that label using succAbove, apply the induction on the "
                            + "number of labels, and reinsert an empty coefficient word. All "
                            + "other coefficients are transported along succAbove.")),
                    Paragraph(Text(
                        "If all words are nonempty and the labelled family is already "
                            + "prefix-separated, take g = f, m = n, and c(i) = [i]. Otherwise "
                            + "choose distinct labels i and j and a residual r with "
                            + "f(j) = f(i) ++ r. Replace only the word at j by r to obtain q. "
                            + "The total length strictly decreases by the positive length of "
                            + "f(i), so the inner induction supplies a prefix-generator "
                            + "envelope and exact coefficients d for q.")),
                    Paragraph(Text(
                        "Define the substitution sigma by sigma(j) = [i,j] and "
                            + "sigma(k) = [k] for k different from j. Then "
                            + "f(k) = flatMap(q,sigma(k)) for every original label k. "
                            + "Set c(k) = flatMap(d,sigma(k)). Associativity of flatMap "
                            + "gives the required exact factorization through the generators "
                            + "returned by the induction, together with all their nonemptiness "
                            + "and prefix-separation properties. Equal words at distinct labels "
                            + "give an empty residual, which the deletion branch accommodates.")),
                    Paragraph(Text(
                        "The alphabet may be empty or infinite, n may be zero, and the input "
                            + "may consist entirely of empty words or include duplicate nonempty "
                            + "words. No decidable equality or injectivity premise is imposed. "
                            + "The conclusion allows m = 0. The generators need not belong to "
                            + "the monoid generated by the input words. The bound m at most n "
                            + "does not assert a strict decrease, a minimum rank, or a least "
                            + "envelope."))),
                DescribeRole.Theorem)),
        []));

    private static Formula EnvelopeFormula()
    {
        Formula alpha = F.Id("alpha");
        Formula n = F.Id("n");
        Formula m = F.Id("m");
        Formula i = F.Id("i");
        Formula j = F.Id("j");
        Formula word = Call("List", alpha);
        Formula generators = Arrow(Call("Fin", m), word);
        Formula coefficients = Arrow(Call("Fin", n), Call("List", Call("Fin", m)));
        Formula nonempty = All("i", Call("Fin", m),
            Seq(Call("g", i), Sp, Neq, Sp, OpenBracket, CloseBracket));
        Formula separated = All("i", Call("Fin", m), All("j", Call("Fin", m),
            Imp(Call("IsPrefix", Call("g", i), Call("g", j)), Equal(i, j))));
        Formula exact = All("i", Call("Fin", n),
            Equal(Call("f", i), Call("flatMap", F.Id("g"), Call("c", i))));
        Formula conclusion = Some("m", NatType(), And(Le(m, n),
            Some("g", generators, Some("c", coefficients,
                And(nonempty, And(separated, exact))))));
        return Disp(All("alpha", Seq(Type(), Caret, Grp(Star)),
            All("n", NatType(), All("f", Arrow(Call("Fin", n), word), conclusion))));
    }

    private static Formula NatType() =>
        new Formula.NamedConstant(FormulaIdentifier.Create("Nat"));
    private static Formula Type() =>
        new Formula.NamedConstant(FormulaIdentifier.Create("Type"));
    private static Formula Call(string name, params Formula[] arguments) =>
        new Formula.FunctionCall(FormulaIdentifier.Create(name), [.. arguments]);
    private static Formula Arrow(Formula a, Formula b) => Seq(Open, a, Sp, To, Sp, b, Close);
    private static Formula All(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), type, body);
    private static Formula Some(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create(name), type, body);
    private static Formula Equal(Formula a, Formula b) =>
        new Formula.Relation(a, FormulaRelationOperator.Equal, b);
    private static Formula Le(Formula a, Formula b) =>
        new Formula.Relation(a, FormulaRelationOperator.LessThanOrEqual, b);
    private static Formula And(Formula a, Formula b) =>
        new Formula.Logic(a, FormulaLogicOperator.And, b);
    private static Formula Imp(Formula a, Formula b) =>
        new Formula.Logic(a, FormulaLogicOperator.Implies, b);
}
