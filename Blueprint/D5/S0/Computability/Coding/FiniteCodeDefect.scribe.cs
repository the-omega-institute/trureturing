using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S0.Computability.Coding;

internal sealed class FiniteCodeDefectDocument : IScribeDocumentDefinition
{
    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "An ambiguous finite labelled family of words factors through strictly fewer generators.",
        H("Finite Labelled Word Defect"),
        Blocks(
            Paragraph(Text(
                "For a natural number n, Fin(n) is the set of n labels. List(A) is the free "
                + "monoid of finite words on A, including the empty word. The operation "
                + "flatMap(s,f) replaces each label in s by its word f(i) and concatenates "
                + "the results. Injective refers to equality of the complete labelled lists. "
                + "The alphabet is an arbitrary type in any universe; it has no finiteness, "
                + "inhabitation or decidable equality assumption.")),
            Describe.Lean(
                DescribeId.Create("finite-labelled-code-defect"),
                DeclarationHandle.Create(
                    "D5/S0/Computability/Coding/FiniteCodeDefect.finite_code_defect"),
                H("Ambiguity forces a smaller generating family"),
                StatementSource.FromAuthor(DefectFormula()),
                AssessedProvenance.FromLiterature(LibraryNoteRef.Create(
                    "D5/L/Computability/neraudselmi2020invariantcodes")),
                Blocks(
                    Paragraph(Text(
                        "The construction descends on the sum of the lengths of the n words, "
                        + "keeping n fixed. If a label carries the empty word, erase that label "
                        + "using succAbove and insertNth. Its coefficient is empty and every "
                        + "other coefficient is a singleton, giving n-1 generators directly.")),
                    Paragraph(Text(
                        "Otherwise, absence of a directed prefix pair at distinct labels would "
                        + "make the family injective and its range prefix-free. Existing "
                        + "prefix-free unique decoding from pinned Mathlib's "
                        + "IsPrefixFree.isUniquelyDecodable would then contradict the ambiguity. "
                        + "Choose distinct labels i and j with f(j)=f(i)r and replace f(j) by r. "
                        + "The substitution j maps to [i,j] and every other label k maps to [k]. "
                        + "Each substitution word ends in its original label, so reversing each "
                        + "substitution word gives an injective prefix-free family of nonempty words. "
                        + "The same pinned prefix-free decoding theorem applies to that reversed "
                        + "family. Reversing an encoded equality reverses both the order of labels "
                        + "and each substitution word; decoding and injectivity of reversal then "
                        + "give injectivity of the original substitution on whole lists.")),
                    Paragraph(Text(
                        "Factoring the old evaluation through this injective substitution "
                        + "transports ambiguity to the shorter family. The total length strictly "
                        + "decreases because f(i) is nonempty. Strong induction gives fewer "
                        + "generators for the shorter family, and flatMap associativity composes "
                        + "its coefficients with the substitution to reconstruct every original word.")),
                    Paragraph(Text(
                        "The statement includes distinct labels with equal codewords, empty words and n=0. For n=0 "
                        + "the ambiguity premise is impossible. The new generators may lie "
                        + "outside the monoid generated by the original words. No converse, "
                        + "minimality, free-basis property or algorithmic complexity is asserted. "
                        + "The cited primary source supplies the classical finite-set defect "
                        + "theorem; the labelled formulation explicitly handles duplicates and emptiness."))),
                DescribeRole.Theorem)),
        []));

    private static Formula DefectFormula()
    {
        Formula u = F.Id("u"), a = F.Id("A"), n = F.Id("n"), f = F.Id("f");
        Formula m = F.Id("m"), g = F.Id("g"), c = F.Id("c"), i = F.Id("i"), s = F.Id("s");
        Formula alphabet = Call("Type", u);
        Formula finN = Call("Fin", n), finM = Call("Fin", m);
        Formula words = Call("List", a);
        Formula evaluation = Par(Seq(Lambda, Sp, s, Colon, Call("List", finN), Comma, Sp,
            Call("flatMap", s, f)));
        return Disp(Seq(
            Forall, Sp, u, Colon, F.Id("Level"), Comma, Sp,
            Forall, Sp, a, Colon, alphabet, Comma, Sp,
            Forall, Sp, n, Colon, F.Id("Nat"), Comma, Sp,
            Forall, Sp, f, Colon, finN, Sp, To, Sp, words, Comma, Sp,
            Neg, Sp, Call("Injective", evaluation), Sp, Rightarrow, Sp,
            Exists, Sp, m, Colon, F.Id("Nat"), Comma, Sp,
            m, Sp, Lt, Sp, n, Sp, Land, Sp,
            Exists, Sp, g, Colon, finM, Sp, To, Sp, words, Comma, Sp,
            Exists, Sp, c, Colon, finN, Sp, To, Sp, Call("List", finM), Comma, Sp,
            Forall, Sp, i, Colon, finN, Comma, Sp,
            Call("f", i), Sp, Eq, Sp, Call("flatMap", Call("c", i), g), Dot));
    }

    private static Formula Par(Formula body) => Seq(Open, body, Close);
    private static Formula Call(string name, params Formula[] arguments) =>
        new Formula.FunctionCall(FormulaIdentifier.Create(name), [.. arguments]);
}
