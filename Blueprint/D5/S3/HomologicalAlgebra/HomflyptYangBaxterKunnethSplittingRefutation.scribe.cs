    private static Formula C(Formula m, Formula n) => Parenthesized(Seq(Parenthesized(Words(m,n)), Sp,
        new Formula.Subscript(Rightarrow, D(0)), Sp, Ring()));
    private static Formula Dsub(Formula m, Formula a, Formula b, Formula n)
    {
        Formula w = F.Id("w");
        Formula set = Seq(OpenBrace, w, Colon, Sp, Words(m,n), Sp, Mid, Sp,
            Call("blockWord",m,a,b,n,w), CloseBrace);
        return Call("Finsupp.supported",Ring(),Ring(),set);
    }
    private static Formula Linear(Formula x, Formula y) => Seq(x, Sp, new Formula.Subscript(Rightarrow, Ring()), Sp, y);
    private static Formula Iota(Formula m, Formula a, Formula b, Formula n, Formula x) =>
        new Formula.Apply(Call("Submodule.subtype",Dsub(m,a,b,n)),[x]);
    private static Formula Boundary(Formula m, Formula n, Formula x) => Call("differential", m, n, x);
    private static Formula Let(Formula x, Formula type, Formula value, Formula body) =>
