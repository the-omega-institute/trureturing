    private static Formula MoveFormula(bool right)
    {
        Formula m = F.Id("m"), n = F.Id("n"), w = F.Id("w"), k = F.Id("k"), h = F.Id("h"),
            hz = F.Id("z"), j = F.Id("j"), jp = F.Id("jp"), jq = F.Id("jq"),
            next = F.Id("next"), ab = F.Id("ab");
        Formula nn = Plus(n,D(1));
        string move = right ? "rightMove" : "leftMove";
        Formula basis = Equal(Call(move,m,n,w,Call("Fin.mk",D(0),hz)),
            Call("Finsupp.single",Call(right ? "Fin.init" : "Matrix.vecTail",w),D(1)));
        Formula index = Parenthesized(Seq(Call("Fin.mk",k,Call("Nat.lt_of_succ_lt_succ",h)),Colon,Sp,Fin(n)));
        Formula updated = Call("Function.update",
            Call("Function.update",w,Call("Fin.castSucc",j),Seq(ab,Dot,D(1))),
            Call("Fin.succ",j),Seq(ab,Dot,D(2)));
        Formula lambda = Parenthesized(Seq(LambdaLower,Sp,
            Parenthesized(Seq(ab,Colon,Sp,Seq(Fin(m),Sp,F.Times,Sp,Fin(m)))),Comma,Sp,
            Call(move,m,n,updated,right ? next : Call("Fin.castSucc",j))));
        Formula body = Call("Finsupp.linearCombination",Ring(),lambda,
            Call("normalizedR",m,new Formula.Apply(w,[jp]),new Formula.Apply(w,[jq])));
        if (right)
            body = Let(next,Fin(nn),Call("Fin.mk",k,Seq(Named("by"),Sp,Named("omega"))),body);
        body = Let(j,Fin(n),right ? Call("Fin.rev",index) : index,
            Let(jp,Fin(nn),Call("Fin.castSucc",j),Let(jq,Fin(nn),Call("Fin.succ",j),body)));
        Formula successor = All(k,Nat(),All(h,Lt(Plus(k,D(1)),nn),
            Equal(Call(move,m,n,w,Call("Fin.mk",Plus(k,D(1)),h)),body)));
        return Disp(All(m,Nat(),All(n,Nat(),All(w,Words(m,nn),
            And(All(hz,Lt(D(0),nn),basis),successor)))));
    }

    private static Formula RFormula()
    {
        Formula m = F.Id("m"), a = F.Id("a"), b = F.Id("b"), t = F.Id("t");
        Formula rhs = Call("ite", Le(b,a), Call("Finsupp.single",Pair(b,a),D(1)),
            Plus(Call("Finsupp.single",Pair(a,b),Minus(D(1),t)),Call("Finsupp.single",Pair(b,a),t)));
        return Disp(All(m,Nat(),All(a,Fin(m),All(b,Fin(m),Equal(Call("normalizedR",m,a,b),rhs)))));
    }
    private static Formula FaceFormula(bool right)
    {
        Formula m = F.Id("m"), n = F.Id("n"), i = F.Id("i"), w = F.Id("w");
        Formula lambda = Parenthesized(Seq(LambdaLower, Sp, Parenthesized(Seq(w,Colon,Sp,Words(m,Plus(n,D(1))))), Comma, Sp,
            Call(right ? "rightMove" : "leftMove",m,n,w,right ? Call("Fin.rev",i) : i)));
        return Disp(All(m,Nat(),All(n,Nat(),All(i,Fin(Plus(n,D(1))),Equal(
            Call(right ? "rightFace" : "leftFace",m,n,i), Call("Finsupp.linearCombination",Ring(),lambda))))));
    }
    private static Formula DifferentialFormula()
    {
        Formula m = F.Id("m"), n = F.Id("n"), i = F.Id("i");
        Formula term = Times(Pow(Parenthesized(Seq(F.Minus,D(1))),Plus(Call("Fin.val",i),D(1))),
            Parenthesized(Minus(Call("leftFace",m,n,i),Call("rightFace",m,n,i))));
        Formula sum = Seq(F.Sum,Underscore,Grp(Seq(i,Colon,Sp,Fin(Plus(n,D(1))))),Sp,term);
        return Disp(All(m,Nat(),And(Equal(Call("differential",m,D(0)),D(0)),
            All(n,Nat(),Equal(Call("differential",m,Plus(n,D(1))),sum)))));
    }
    private static Formula BlockWordFormula()
    {
        Formula m = F.Id("m"), a = F.Id("A"), b = F.Id("B"), n = F.Id("n"), w = F.Id("w"), i = F.Id("i"), j = F.Id("j");
        Formula left = All(j,Fin(n),Implies(Lt(Call("Fin.val",j),Call("Fin.val",i)),Member(new Formula.Apply(w,[j]),a)));
        Formula right = All(j,Fin(n),Implies(Le(Call("Fin.val",i),Call("Fin.val",j)),Member(new Formula.Apply(w,[j]),b)));
        return Disp(All(m,Nat(),All(a,Finset(m),All(b,Finset(m),All(n,Nat(),All(w,Words(m,n),
            Iff(Call("blockWord",m,a,b,n,w),Some(i,Fin(Plus(n,D(1))),And(left,right)))))))));
    }
    private static Formula SplitsFormula()
    {
        Formula m = F.Id("m"), a = F.Id("A"), b = F.Id("B"), n = F.Id("n"), p = F.Id("p"), c = F.Id("c");
        Formula pn = new Formula.Apply(p,[n]);
        Formula pt = Seq(Forall,Sp,n,Colon,Sp,Nat(),Comma,Sp,Linear(C(m,n),Dsub(m,a,b,n)));
        Formula retraction = All(n,Nat(),Equal(Seq(pn,Sp,Circ,Sp,Call("Submodule.subtype",Dsub(m,a,b,n))),Named("LinearMap.id")));
        Formula commutes = All(n,Nat(),All(c,C(m,Plus(n,D(1))),Equal(
            Iota(m,a,b,n,new Formula.Apply(pn,[Boundary(m,Plus(n,D(1)),c)])),
            Boundary(m,Plus(n,D(1)),Iota(m,a,b,Plus(n,D(1)),new Formula.Apply(new Formula.Apply(p,[Plus(n,D(1))]),[c]))))));
        return Disp(All(m,Nat(),All(a,Finset(m),All(b,Finset(m),Iff(Call("splits",m,a,b),Some(p,Parenthesized(pt),And(retraction,commutes)))))));
    }
    private static Formula ClaimFormula()
    {
        Formula m = F.Id("m"), a = F.Id("A"), b = F.Id("B"), x = F.Id("a"), y = F.Id("b");
        Formula ordered = All(x,Fin(m),Implies(Member(x,a),All(y,Fin(m),Implies(Member(y,b),Le(y,x)))));
        Formula union = Equal(Seq(a,Sp,Cup,Sp,b),Call("univ",Fin(m)));
        return Disp(Iff(F.Id("claim"),All(m,Nat(),All(a,Finset(m),All(b,Finset(m),
            Implies(union,Implies(ordered,Call("splits",m,a,b))))))));
    }
