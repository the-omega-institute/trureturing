    private static Formula Nat() => new Formula.NamedConstant(FormulaIdentifier.Create("Nat"));
    private static Formula Real() => new Formula.NamedConstant(FormulaIdentifier.Create("Real"));
    private static Formula Call(string name, params Formula[] args) =>
        new Formula.FunctionCall(FormulaIdentifier.Create(name), [.. args]);
    private static Formula All(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), type, body);
    private static Formula ExistsF(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create(name), type, body);
    private static Formula Negative(Formula f) => Seq(Minus, Open, f, Close);
    private static Formula Not(Formula f) => Seq(Neg, Sp, Open, f, Close);
    private static Formula EqF(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.Equal, b);
    private static Formula NeF(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.NotEqual, b);
    private static Formula ImpliesF(Formula a, Formula b) => new Formula.Logic(a, FormulaLogicOperator.Implies, b);
    private static Formula Add(Formula a, Formula b) => new Formula.Binary(a, FormulaBinaryOperator.Add, b);
    private static Formula Sub(Formula a, Formula b) => new Formula.Binary(a, FormulaBinaryOperator.Subtract, b);
    private static Formula Mul(Formula a, Formula b) => new Formula.Binary(a, FormulaBinaryOperator.Multiply, b);
    private static Formula Pow(Formula a, Formula b) => new Formula.Power(a, b);
    private static Formula Paper() => Call("Paper", F.Id("n"), F.Id("m"));
    private static Formula Ham(Formula s, Formula f, Formula g) => Call("ham",
        Call("bracket", Call("paperPoisson", F.Id("n"), F.Id("m"), F.Id("omega"), s)), f, g);
    private static Formula GeneratorValue(string f, string g, Formula value) =>
        EqF(Ham(F.Id("s"), F.Id(f), F.Id(g)), value);
    private static Formula Mixed() =>
        Mul(Negative(new Formula.Fraction(F.Id("omega"), D(2))),
            Mul(Mul(Pow(F.Id("u"), Sub(F.Id("n"), D(1))), Pow(F.Id("v"), Sub(F.Id("m"), D(1)))),
                Seq(Open, Add(Mul(F.Id("n"), F.Id("v")),
                    Mul(F.Id("s"), Mul(F.Id("m"), F.Id("u")))), Close)));
    private static Formula Presentation() => EqF(Paper(),
        Seq(Real(), OpenBracket, F.Id("u"), Comma, F.Id("v"), Comma, F.Id("x"), Comma, F.Id("y"),
            CloseBracket, Slash, Langle, Sp,
            Sub(Add(Pow(F.Id("x"), D(2)), Pow(F.Id("y"), D(2))),
                Mul(Pow(F.Id("u"), F.Id("n")), Pow(F.Id("v"), F.Id("m")))),
            Sp, Rangle));
    private static Formula Image(Formula f) => new Formula.Apply(F.Id("e"), [f]);
    private static Formula Statement()
    {
        var f = F.Id("f");
        var g = F.Id("g");
        var preserve = All("f", Paper(), All("g", Paper(),
            EqF(Image(Ham(Negative(D(1)), f, g)), Ham(D(1), Image(f), Image(g)))));
        var noEquiv = Not(ExistsF("e", Call("AlgEquiv", Real(), Paper(), Paper()), preserve));
        var frequency = All("omega", Real(), ImpliesF(NeF(F.Id("omega"), D(0)), noEquiv));
        return All("n", Nat(), All("m", Nat(),
            ImpliesF(Call("Odd", F.Id("n")), ImpliesF(Call("Odd", F.Id("m")), frequency))));
    }
