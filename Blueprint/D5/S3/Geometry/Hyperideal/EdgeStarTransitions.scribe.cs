using System;
using System.Linq;
using static StrataLint.Scribe.DefinitionDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Geometry.Hyperideal;

internal sealed class EdgeStarTransitionsDocument : IScribeDocumentDefinition
{
    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Each actual occurrence contributes one transition; path ends are signature changes.", H("Balanced transitions on actual face-paired edge stars"),
        Blocks(Paragraph(Text("RawFacePairing on an arbitrary finite type T retains every actual face slot, the involutive face pairing and its inverse slot maps. GlobalEdge is the equivalence class generated by paired slots. A Boolean color is shared on that class. ValidColoring requires every local face to have one or two low edges. No manifold or geometric realization is a hypothesis of these combinatorial statements. Prefix notation denotes the named definitions; snd is the second projection of an occurrence.")),
            Describe.Lean(
                DescribeId.Create("edge-star-path-signature"),
                DeclarationHandle.Create("D5/S3/Geometry/Hyperideal/EdgeStarTransitions.path_end_signature_and_next"),
                H("Path ends and successor signature"), StatementSource.FromAuthor(F.Disp(PathSignature())),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text("An occurrence is a path end exactly when its incoming and successor signatures differ. Face-slot transport identifies the successor signature with the outgoing face low-count-two indicator. The local six-bit incidence classification relates these signatures to the color counts on the adjacent faces."))), DescribeRole.Theorem),
            Describe.Lean(
                DescribeId.Create("actual-edge-transition-balance"),
                DeclarationHandle.Create("D5/S3/Geometry/Hyperideal/EdgeStarTransitions.global_edge_balance"),
                H("Rise equals fall and path-end count is even"), StatementSource.FromAuthor(F.Disp(Balance())),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text("Paired flags admit a reversed orientation because partner flags cannot lie in one successor cycle. The resulting successor preserves the global edge. Reindexing the finite fiber balances false-to-true and true-to-false transitions; each path end is one of these two transitions."))), DescribeRole.Theorem))));

    private static Formula Balance()
    {
        var T = F.Id("T"); var p = F.Id("p"); var color = F.Id("color");
        var valid = F.Id("valid"); var e = F.Id("e");
        return All(Telescope(T, p, color), Imp(Call("Fintype", T),
            And(Eq(Call("rise", p, color, valid, e), Call("fall", p, color, valid, e)),
                Call("Even", Call("pathEndCount", p, color, valid, e)))));
    }
    private static Formula PathSignature()
    {
        var T = F.Id("T"); var E = F.Id("Edge"); var s = F.Id("s"); var i = F.Id("i");
        var next = Call("next", s, i);
        return All([("T", F.Id("Type")), ("Edge", F.Id("Type")),
            ("s", Call("EdgeStars", T, E)), ("i", Call("Occurrence", T))],
            Imp(Call("Fintype", T), And(
                Iff(Call("isPathEnd", Call("localColor", s, i), Call("snd", i)),
                    Ne(Call("signature", s, i), Call("signature", s, next))),
                Eq(Call("signature", s, next),
                    Call("decide", Eq(Call("faceLowCount", Call("localColor", s, i),
                        Call("outgoing", s, i)), F.D(2)))))));
    }

    private static Formula All((string Name, Formula Type)[] vs, Formula body) =>
        new Formula.BindMany(FormulaQuantifier.ForAll,
            [..vs.Select(v => new Formula.BoundVariable(FormulaIdentifier.Create(v.Name), v.Type))], body);
    private static Formula And(params Formula[] ps)
    {
        var r = ps[^1];
        for (var j = ps.Length - 2; j >= 0; j--) r = new Formula.Logic(ps[j], FormulaLogicOperator.And, r);
        return r;
    }
    private static Formula Or(Formula a, Formula b) => new Formula.Logic(a, FormulaLogicOperator.Or, b);
    private static Formula Imp(Formula a, Formula b) => new Formula.Logic(a, FormulaLogicOperator.Implies, b);
    private static Formula Iff(Formula a, Formula b) => new Formula.Logic(a, FormulaLogicOperator.Iff, b);
    private static Formula Eq(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.Equal, b);
    private static Formula Ne(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.NotEqual, b);
    private static Formula Le(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThanOrEqual, b);
    private static Formula Gt(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.GreaterThan, b);
    private static Formula Call(string name, params Formula[] args) => new Formula.Apply(F.Id(name), [..args]);
    private static Formula Star(Formula p, Formula color, Formula valid) =>
        Call("edgeStars", Call("toFacePairedTriangulation", p, color, valid));
    private static (string Name, Formula Type)[] Telescope(Formula T, Formula p, Formula color) =>
        [("T", F.Id("Type")), ("p", Call("RawFacePairing", T)),
         ("color", new Formula.TypeArrow(Call("GlobalEdge", p), F.Id("Bool"))),
         ("valid", Call("ValidColoring", p, color)), ("e", Call("GlobalEdge", p))];
}
