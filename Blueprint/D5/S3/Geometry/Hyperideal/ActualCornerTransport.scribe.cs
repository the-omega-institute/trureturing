    private static Formula Statement()
    {
        var q=F.Id("q"); var u=F.Id("u"); var v=F.Id("v");
        var w=F.Id("w"); var b=F.Id("B"); var s=F.Id("s"); var z=F.Id("z");
        var T=F.Id("T"); var S=F.Id("S"); var K=F.Id("K");
        var corner=Call("Corner",T);
        var same=All([("s",S)],Eq(Call("label",q,Apply(u,s)),Call("label",q,Apply(v,s))));
        var nonnegative=All([("s",S)],Le(F.D(0),Apply(w,s)));
        var bounded=All([("z",Call("Vertex",q))],Le(Call("mass",q,u,w,z),b));
        var premises=And(Call("Fintype",T),Call("Fintype",S),Call("Field",K),
            Call("LinearOrder",K),Call("IsStrictOrderedRing",K),same,nonnegative,bounded);
        return All([("T",F.Id("Type")),("S",F.Id("Type")),("K",F.Id("Type")),
            ("q",Call("Pairing",T)),("u",new Formula.TypeArrow(S,corner)),
            ("v",new Formula.TypeArrow(S,corner)),("w",new Formula.TypeArrow(S,K)),("B",K)],
            new Formula.Logic(premises,FormulaLogicOperator.Implies,Call("Transport",q,u,v,w,b)));
    }

    private static Formula All((string Name,Formula Type)[] vs,Formula body)=>
        new Formula.BindMany(FormulaQuantifier.ForAll,
            [..vs.Select(v=>new Formula.BoundVariable(FormulaIdentifier.Create(v.Name),v.Type))],body);
    private static Formula And(params Formula[] ps)
    {
        var result=ps[^1];
        for(var j=ps.Length-2;j>=0;j--) result=new Formula.Logic(ps[j],FormulaLogicOperator.And,result);
        return result;
    }
    private static Formula Eq(Formula a,Formula b)=>new Formula.Relation(a,FormulaRelationOperator.Equal,b);
    private static Formula Le(Formula a,Formula b)=>
        new Formula.Relation(a,FormulaRelationOperator.LessThanOrEqual,b);
    private static Formula Apply(Formula f,params Formula[] args)=>new Formula.Apply(f,[..args]);
    private static Formula Call(string name,params Formula[] args)=>Apply(F.Id(name),args);
