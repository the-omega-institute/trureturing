    private static Formula Statement()
    {
        var t = F.Id("T");
        var p = F.Id("p");
        var color = F.Id("c");
        var valid = F.Id("v");
        var edge = Call("GlobalEdge", p);
        var s = Call("edgeStars", Call("toFacePairedTriangulation", p, color, valid));
        var e = F.Id("e");
        var i = F.Id("i");
        var j = F.Id("j");
        var turn = F.Seq(F.D(2), F.Cdot, F.Sp, F.Pi);
        var cycleExact = All([("i", Call("Occurrence", t)),
            ("j", Call("Occurrence", t))],
            Iff(Call("SameCycle", Call("next", s), i, j),
                Equal(Call("globalEdge", s, i), Call("globalEdge", s, j))));
        var preserved = All([("i", Call("Occurrence", t))],
            Equal(Call("globalEdge", s, Call("next", s, i)),
                Call("globalEdge", s, i)));
        var low = Imp(Equal(Call("color", s, e), F.Id("true")),
            And(Equal(Call("lowBudget", s, e), Call("lowMatrixTotal", s, e)),
                Iff(Gt(Call("lowBudget", s, e), turn),
                    Gt(Call("lowMatrixTotal", s, e), turn))));
        var high = Imp(Equal(Call("color", s, e), F.Id("false")),
            And(Equal(Call("highBudget", s, e), Call("highMatrixTotal", s, e)),
                Iff(Gt(Call("highBudget", s, e), turn),
                    Gt(Call("highMatrixTotal", s, e), turn))));
        return All([("T", F.Id("Type")), ("finite", Call("Fintype", t)),
            ("p", Call("RawFacePairing", t)),
            ("c", new Formula.TypeArrow(edge, F.Id("Bool"))),
            ("v", Call("ValidColoring", p, color)), ("e", edge)],
            And(cycleExact, preserved, low, high));
    }

    private static Formula All((string Name, Formula Type)[] variables, Formula body) =>
        new Formula.BindMany(FormulaQuantifier.ForAll,
            [.. variables.Select(v => new Formula.BoundVariable(
                FormulaIdentifier.Create(v.Name), v.Type))], body);
    private static Formula Call(string name, params Formula[] arguments) =>
        new Formula.Apply(F.Id(name), [.. arguments]);
    private static Formula Equal(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.Equal, right);
    private static Formula Gt(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.GreaterThan, right);
    private static Formula Imp(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.Implies, right);
    private static Formula Iff(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.Iff, right);
    private static Formula And(params Formula[] parts)
    {
        if (parts.Length == 0) throw new ArgumentException("Empty conjunction");
        var result = parts[^1];
        for (var j = parts.Length - 2; j >= 0; j--)
            result = new Formula.Logic(parts[j], FormulaLogicOperator.And, result);
        return result;
    }
}
