    private static Formula Transport()
    {
        var K = F.Id("K"); var T = F.Id("T"); var S = F.Id("S"); var p = F.Id("p");
        var source = F.Id("source"); var target = F.Id("target"); var weight = F.Id("weight");
        var bound = F.Id("bound"); var a = F.Id("a"); var s = F.Id("s");
        var b = F.Id("b"); var c = F.Id("c"); var o = F.Id("o");
        var corners = Call("Corner", T);
        var occurrences = Call("Occurrence", T);
        var sourceLabel = Call("vertexLabel", p, Call("source", s));
        var targetLabel = Call("vertexLabel", p, Call("target", s));
        var hypotheses = And(
            Call("Field", K), Call("LinearOrder", K), Call("IsStrictOrderedRing", K),
            Call("Fintype", T), Call("DecidableEq", T), Call("Fintype", S),
            All([("s", S)], Eq(sourceLabel, targetLabel)),
            All([("s", S)], Le(F.D(0), Call("weight", s))),
            All([("b", Call("GlobalVertex", p))],
                Le(Sum(s, S, Mul(Indicator(Eq(sourceLabel, b)), Call("weight", s))), bound)));
        var conclusion = And(
            Eq(Call("edgeTotalMap", p, a), F.D(0)),
            All([("c", corners)], Eq(new Formula.Negate(Call("cornerTotalMap", a, c)),
                Sum(s, S, Mul(Call("weight", s), Sub(
                    Indicator(Eq(Call("source", s), c)),
                    Indicator(Eq(Call("target", s), c))))))),
            All([("o", occurrences)], Le(new Formula.Absolute(Call("a", o)), Mul(F.D(3), bound))));
        return All([
            ("K", F.Id("Type")), ("T", F.Id("Type")), ("S", F.Id("Type")),
            ("p", Call("RawFacePairing", T)),
            ("source", new Formula.TypeArrow(S, corners)),
            ("target", new Formula.TypeArrow(S, corners)),
            ("weight", new Formula.TypeArrow(S, K)), ("bound", K)],
            Imp(hypotheses, new Formula.Bind(FormulaQuantifier.Exists,
                FormulaIdentifier.Create("a"), new Formula.TypeArrow(occurrences, K), conclusion)));
    }

    private static Formula All((string Name, Formula Type)[] vs, Formula body) =>
        new Formula.BindMany(FormulaQuantifier.ForAll,
            [..vs.Select(v => new Formula.BoundVariable(FormulaIdentifier.Create(v.Name), v.Type))], body);
    private static Formula And(params Formula[] ps)
    {
        var r = ps[^1];
        for (var j = ps.Length - 2; j >= 0; j--) r = new Formula.Logic(ps[j], FormulaLogicOperator.And, r);
        return r;
    }
    private static Formula Imp(Formula a, Formula b) => new Formula.Logic(a, FormulaLogicOperator.Implies, b);
    private static Formula Eq(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.Equal, b);
    private static Formula Le(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThanOrEqual, b);
    private static Formula Mul(Formula a, Formula b) => new Formula.Binary(a, FormulaBinaryOperator.Multiply, b);
    private static Formula Sub(Formula a, Formula b) => new Formula.Binary(a, FormulaBinaryOperator.Subtract, b);
    private static Formula Call(string name, params Formula[] args) => new Formula.Apply(F.Id(name), [..args]);
    private static Formula Indicator(Formula p) => Call("indicator", p);
    private static Formula Sum(Formula variable, Formula domain, Formula body) =>
        F.Seq(new Formula.Subscript(F.Sum,
            new Formula.Relation(variable, FormulaRelationOperator.MemberOf, domain)), F.Grp(body));
}
