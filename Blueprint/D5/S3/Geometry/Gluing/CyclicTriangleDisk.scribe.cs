    private static DocumentBlock Definition(string name, string title, Formula formula, string body) =>
        Node(name, title, formula, body, DescribeRole.Definition);
    private static DocumentBlock Theorem(string name, string title, Formula formula, string body) =>
        Node(name, title, formula, body, DescribeRole.Theorem);
    private static DocumentBlock Node(string name, string title, Formula formula, string body, DescribeRole role) =>
        Describe.Lean(DescribeId.Create("cyclic-triangle-" + name.Replace('_', '-').ToLowerInvariant()),
            DeclarationHandle.Create(Prefix + name), H(title), StatementSource.FromAuthor(F.Disp(formula)),
            AssessedProvenance.FromRepo(), Blocks(Paragraph(Text(body))), role);
    private static Formula TriangleFormula() => All("p", Product(F.Id("R"), F.Id("R")),
        Iff(In(F.Id("p"), F.Id("Triangle")), And(Le(F.D(0), Call("first", F.Id("p"))),
            Le(F.D(0), Call("second", F.Id("p"))),
            Le(Add(Call("first", F.Id("p")), Call("second", F.Id("p"))), F.D(1)))));
    private static Formula NormalFormula() => Positive(X(And(
        Implies(Eq(Radius(), F.D(0)), Eq(Call("normal", F.Id("x")), F.Id("None"))),
        Implies(And(Ne(Radius(), F.D(0)), Eq(B(), F.D(0))),
            Eq(Call("normal", F.Id("x")), Call("Some", NextPoint()))),
        Implies(And(Ne(Radius(), F.D(0)), Ne(B(), F.D(0))),
            Eq(Call("normal", F.Id("x")), Call("Some", F.Id("x")))))));
    private static Formula RadialFormula() => Positive(X(And(
        Implies(Eq(Radius(), F.D(0)), Eq(Call("radial", F.Id("x")), F.D(0))),
        Implies(Ne(Radius(), F.D(0)), Eq(Call("radial", F.Id("x")),
            Multiply(Radius(), Call("exp", Multiply(Call("angle", F.Id("x")), F.Id("imaginary")))))))));
    private static Formula Positive(Formula body) => All("n", F.Id("N"), Implies(Lt(F.D(0), F.Id("n")), body));
    private static Formula X(Formula body) => All("x", Points(), body);
    private static Formula XY(Formula body) => X(All("y", Points(), body));
    private static Formula Points() => Call("Point", F.Id("n"));
    private static Formula A() => Call("first", Call("carrier", F.Id("x")));
    private static Formula B() => Call("second", Call("carrier", F.Id("x")));
    private static Formula Radius() => Call("radius", F.Id("x"));
    private static Formula NextPoint() => Pair(Call("next", Call("sector", F.Id("x"))),
        Call("swap", Call("carrier", F.Id("x"))));
    private static Formula All(string name, Formula domain, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), domain, body);
    private static Formula Call(string name, params Formula[] args) => new Formula.Apply(F.Id(name), [.. args]);
    private static Formula Pair(Formula left, Formula right) => F.Seq(F.Open, left, F.Comma, F.Sp, right, F.Close);
    private static Formula Product(Formula left, Formula right) => F.Seq(left, F.Sp, F.Times, F.Sp, right);
    private static Formula And(params Formula[] clauses)
    {
        var result = clauses[^1];
        for (var i = clauses.Length - 2; i >= 0; i--)
            result = new Formula.Logic(clauses[i], FormulaLogicOperator.And, result);
        return result;
    }
    private static Formula Eq(Formula left, Formula right) => new Formula.Relation(left, FormulaRelationOperator.Equal, right);
    private static Formula Ne(Formula left, Formula right) => F.Seq(left, F.Sp, F.Neq, F.Sp, right);
    private static Formula In(Formula left, Formula right) => new Formula.Relation(left, FormulaRelationOperator.MemberOf, right);
    private static Formula Lt(Formula left, Formula right) => new Formula.Relation(left, FormulaRelationOperator.LessThan, right);
    private static Formula Le(Formula left, Formula right) => new Formula.Relation(left, FormulaRelationOperator.LessThanOrEqual, right);
    private static Formula Iff(Formula left, Formula right) => new Formula.Logic(left, FormulaLogicOperator.Iff, right);
    private static Formula Implies(Formula left, Formula right) => new Formula.Logic(left, FormulaLogicOperator.Implies, right);
    private static Formula Add(Formula left, Formula right) => new Formula.Binary(left, FormulaBinaryOperator.Add, right);
    private static Formula Multiply(Formula left, Formula right) => new Formula.Binary(left, FormulaBinaryOperator.Multiply, right);
    private static Formula Divide(Formula left, Formula right) => new Formula.Fraction(left, right);
}
