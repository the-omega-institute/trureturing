    private static Formula Reals() => Seq(Mathbb, Grp(F.Id("R")));

    private static Formula Typed(Formula value) =>
        Seq(value, Colon, Sp, Reals());

    private static Formula PowerTwo(Formula value) =>
        Seq(value, Caret, Grp(D(2)));

    private static Formula Call(string name, params Formula[] arguments)
    {
        var items = new List<Formula> { Operatorname, Grp(F.Id(name)), Open };
        for (var index = 0; index < arguments.Length; index++)
        {
            if (index > 0) items.AddRange([Comma, Sp]);
            items.Add(arguments[index]);
        }
        items.Add(Close);
        return Seq([.. items]);
    }

    private static Formula SecondOrderSpectrumFormula()
    {
        Formula delta = F.Id("delta");
        Formula time = F.Id("t");
        Formula positiveFunction = Call("positiveRateBranch", delta);
        Formula negativeFunction = Call("negativeRateBranch", delta);
        Formula symmetricFunction = Call("reflectedGrowthSum", delta);
        Formula signedDeterminant = Call("reflectionPairSignedDeterminant", delta);
        Formula positiveValue = Call("positiveRateBranch", delta, time);
        Formula negativeValue = Call("negativeRateBranch", delta, time);
        Formula symmetricValue = Call("reflectedGrowthSum", delta, time);
        return Disp(Seq(
            Forall, Sp, Typed(delta), Comma, Sp, Typed(time), Comma, Sp,
            Call("negativeSecondDerivative", positiveFunction, time), Sp, Eq, Sp,
            signedDeterminant, Sp, Cdot, Sp, positiveValue, Sp, Land, Sp,
            Call("negativeSecondDerivative", negativeFunction, time), Sp, Eq, Sp,
            signedDeterminant, Sp, Cdot, Sp, negativeValue, Sp, Land, Sp,
            Call("negativeSecondDerivative", symmetricFunction, time), Sp, Eq, Sp,
            signedDeterminant, Sp, Cdot, Sp, symmetricValue, Dot));
    }

    private static Formula FirstDerivativeFormula()
    {
        Formula delta = F.Id("delta");
        return Disp(Seq(
            Forall, Sp, Typed(delta), Comma, Sp,
            Call("iteratedDeriv", D(1), Call("reflectedGrowthSum", delta), D(0)),
            Sp, Eq, Sp, D(0), Dot));
    }

    private static Formula SecondDerivativeFormula()
    {
        Formula delta = F.Id("delta");
        return Disp(Seq(
            Forall, Sp, Typed(delta), Comma, Sp,
            Call("iteratedDeriv", D(2), Call("reflectedGrowthSum", delta), D(0)),
            Sp, Eq, Sp, D(2), Sp, Cdot, Sp, PowerTwo(delta), Dot));
    }

    private static Formula VisibilityFormula()
    {
        Formula delta = F.Id("delta");
        return Disp(Seq(
            Forall, Sp, Typed(delta), Comma, Sp,
            delta, Sp, Neq, Sp, D(0), Sp, Rightarrow, Sp,
            D(0), Sp, Lt, Sp,
            Call("iteratedDeriv", D(2), Call("reflectedGrowthSum", delta), D(0)),
            Dot));
    }
}
