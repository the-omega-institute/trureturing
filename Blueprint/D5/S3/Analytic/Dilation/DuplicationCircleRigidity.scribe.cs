using static StrataLint.Scribe.DefinitionDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Analytic.Dilation;

internal sealed class DuplicationCircleRigidityDocument : IScribeDocumentDefinition
{
    private const string Module = "D5/S3/Analytic/Dilation/DuplicationCircleRigidity";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "The unit fibre of a continuous duplication solution can determine its frequency.",
        H("Rigidity for the Cosine Duplication Law"),
        Blocks(
            Describe.Lean(DescribeId.Create("duplication-on-the-line"),
                DeclarationHandle.Create(Module + ".no_faithful_duplication_on_line"),
                H("Return to one on the line"),
                StatementSource.FromAuthor(LineFormula()), AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "If the solution never returns to one on the positive ray, duplication excludes "
                    + "both minus one and zero there. Continuity then forces positivity. Every "
                    + "doubling increases the positive defect from one by a factor of at least two, "
                    + "which contradicts the range bound."))),
                DescribeRole.Theorem),
            Describe.Lean(DescribeId.Create("duplication-on-the-circle"),
                DeclarationHandle.Create(Module + ".eq_cos_of_circle_duplication"),
                H("The faithful solution on the circle"),
                StatementSource.FromAuthor(CircleFormula()), AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "The prescribed fibre at one determines the fibres at minus one and zero by "
                    + "duplication. On the half-circle these fibres and continuity determine which "
                    + "half of the arccosine range the angle occupies. Doubling followed by "
                    + "reflection into the half-circle doubles the absolute difference between the "
                    + "angle read from the solution and the original angle. This bounded difference "
                    + "therefore vanishes."))),
                DescribeRole.Theorem),
            Describe.Lean(DescribeId.Create("duplication-with-a-discrete-fibre"),
                DeclarationHandle.Create(Module + ".eq_scaled_cos_of_discrete_fibre"),
                H("The period lattice determines the frequency"),
                StatementSource.FromAuthor(DiscreteFormula()), AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "If each point of the unit fibre is a period, the fibre is an additive subgroup. "
                    + "Isolation at zero rules out density. The return to one gives a nonzero group "
                    + "element, so the subgroup is generated by a positive period T. Rescaling this "
                    + "period to two pi gives the faithful solution on the circle."))),
                DescribeRole.Theorem))));

    private static Formula Reals => F.Seq(F.Mathbb, F.Grp(F.Id("R")));
    private static Formula Ints => F.Seq(F.Mathbb, F.Grp(F.Id("Z")));
    private static Formula FunctionType => F.Seq(Reals, F.Sp, F.To, F.Sp, Reals);
    private static Formula P => F.Id("p");
    private static Formula X => F.Id("t");
    private static Formula T => F.Id("T");
    private static Formula TwoPi => Mul(F.D(2), F.Pi);
    private static Formula Bind(FormulaQuantifier quantifier, string name, Formula type, Formula body) =>
        new Formula.BindMany(quantifier, [new Formula.BoundVariable(FormulaIdentifier.Create(name), type)], body);
    private static Formula All(string name, Formula type, Formula body) =>
        Bind(FormulaQuantifier.ForAll, name, type, body);
    private static Formula Exists(string name, Formula type, Formula body) =>
        Bind(FormulaQuantifier.Exists, name, type, body);
    private static Formula At(Formula argument) => new Formula.Apply(P, [argument]);
    private static Formula Call(string name, params Formula[] arguments) =>
        new Formula.FunctionCall(FormulaIdentifier.Create(name), [.. arguments]);
    private static Formula Eq(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.Equal, right);
    private static Formula Lt(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.LessThan, right);
    private static Formula Le(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.LessThanOrEqual, right);
    private static Formula And(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.And, right);
    private static Formula If(Formula assumption, Formula body) =>
        new Formula.Logic(assumption, FormulaLogicOperator.Implies, body);
    private static Formula Iff(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.Iff, right);
    private static Formula Mul(Formula left, Formula right) => F.Seq(left, F.Sp, F.Cdot, F.Sp, right);
    private static Formula Neg(Formula arg) => F.Seq(F.Minus, arg);
    private static Formula OneAt(Formula arg) => Eq(At(arg), F.D(1));
    private static Formula Continuous => Call("Continuous", P);
    private static Formula Bound => All("t", Reals, Le(new Formula.Absolute(At(X)), F.D(1)));
    private static Formula Even => All("t", Reals, Eq(At(Neg(X)), At(X)));
    private static Formula Duplication => All("t", Reals,
        Eq(At(Mul(F.D(2), X)), F.Seq(Mul(F.D(2), new Formula.Power(At(X), F.D(2))), F.Minus, F.D(1))));
    private static Formula Fibre(Formula period) => All("t", Reals,
        Iff(OneAt(X), Exists("k", Ints, Eq(X, Mul(period, F.Id("k"))))));

    private static Formula LineFormula()
    {
        Formula strict = All("t", Reals, If(Lt(F.D(0), X), Lt(At(X), F.D(1))));
        Formula conditions = And(Continuous, And(OneAt(F.D(0)), And(Bound, And(Duplication, strict))));
        return F.Disp(new Formula.Not(Exists("p", FunctionType, conditions)));
    }

    private static Formula CircleFormula() => F.Disp(All("p", FunctionType,
        If(Continuous, If(Call("Periodic", P, TwoPi), If(Even, If(Bound,
            If(Duplication, If(Fibre(TwoPi), Eq(P, F.Id("cos"))))))))));

    private static Formula DiscreteFormula()
    {
        Formula e = F.Id("e"), s = F.Id("s");
        Formula isolated = Exists("e", Reals, And(Lt(F.D(0), e), All("t", Reals,
            If(And(Lt(Neg(e), X), Lt(X, e)), If(OneAt(X), Eq(X, F.D(0)))))));
        Formula periods = All("s", Reals, If(OneAt(s), Call("Periodic", P, s)));
        Formula value = Eq(At(X), Call("cos", new Formula.Fraction(Mul(TwoPi, X), T)));
        Formula result = Exists("T", Reals, And(Lt(F.D(0), T), And(Fibre(T), All("t", Reals, value))));
        return F.Disp(All("p", FunctionType, If(Continuous, If(Bound, If(OneAt(F.D(0)),
            If(Even, If(Duplication, If(isolated, If(periods, result)))))))));
    }
}
