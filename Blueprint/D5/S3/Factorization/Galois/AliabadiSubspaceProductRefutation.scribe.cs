    private static Formula Call(string name, params Formula[] args) =>
        new Formula.Apply(Seq(Operatorname, Grp(F.Id(name))), [.. args]);
    private static Formula Eq(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.Equal, b);
    private static Formula Le(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThanOrEqual, b);
    private static Formula Lt(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThan, b);
    private static Formula And(Formula a, Formula b) => new Formula.Logic(a, FormulaLogicOperator.And, b);
    private static Formula Imp(Formula a, Formula b) => new Formula.Logic(a, FormulaLogicOperator.Implies, b);
    private static Formula All(string name, Formula type, Formula body) =>
        Seq(Forall, Sp, Open, F.Id(name), Colon, type, Close, Comma, Sp, body);
    private static Formula Inst(Formula type, Formula body) => Seq(OpenBracket, type, CloseBracket, Comma, Sp, body);
    private static Formula Dim(Formula k, Formula s) => Call("finrank", k, s);
    private static Formula SpanProd(Formula k, Formula s, Formula t) => Call("span", k, Seq(s, Sp, t));
    private static Formula Subspace(Formula k, Formula l) => Call("Submodule", k, l);
    private static Formula Finite(Formula k, Formula s) => Call("FiniteDimensional", k, s);
    private static Formula Q() => Seq(Mathbb, Grp(F.Id("Q")));
    private static Formula PS(byte n) => Call("powerSpan", D(n));
    private static Formula Lower(Formula k, Formula s, Formula t) =>
        Le(Seq(Dim(k, s), Plus, Dim(k, t), Minus, D(1)), SpanDim(k, s, t));
    private static Formula SpanDim(Formula k, Formula s, Formula t) => Dim(k, SpanProd(k, s, t));
    private static Formula FieldBinders(Formula body) =>
        All("K", F.Id("Type"), All("L", F.Id("Type"),
            Inst(Call("Field", F.Id("K")), Inst(Call("Field", F.Id("L")),
                Inst(Call("Algebra", F.Id("K"), F.Id("L")), body)))));

    private static Formula TranslateFormula() => Disp(FieldBinders(
        All("a", F.Id("L"), All("M", Call("IntermediateField", F.Id("K"), F.Id("L")),
            Eq(Call("translate", F.Id("a"), F.Id("M")),
                Call("map", Call("mulLeft", F.Id("K"), F.Id("a")), F.Id("M")))))));

    private static Formula PremiseFormula()
    {
        Formula k = F.Id("K"), l = F.Id("L"), a = F.Id("a"), b = F.Id("b"), m = F.Id("M");
        Formula x = F.Id("A"), y = F.Id("B");
        Formula lhs = Seq(Dim(k, Call("inf", Call("translate", a, m), x)), Plus,
            Dim(k, Call("inf", Call("translate", b, m), y)));
        Formula quantified = All("a", l, All("b", l, All("M", Call("IntermediateField", k, l),
            Imp(And(Lt(Call("bot"), m), And(Lt(m, Call("top")), Finite(k, m))),
                Le(lhs, Seq(Dim(k, m), Plus, D(1)))))));
        return Disp(FieldBinders(All("A", Subspace(k, l), All("B", Subspace(k, l),
            new Formula.Logic(Call("intersectionPremise", x, y), FormulaLogicOperator.Iff, quantified)))));
    }

    private static Formula ClaimFormula()
    {
        Formula k = F.Id("K"), l = F.Id("L"), a = F.Id("A"), b = F.Id("B"), s = F.Id("S"), t = F.Id("T");
        Formula hypotheses = And(Finite(k, a), And(Finite(k, b),
            And(Lt(D(0), Dim(k, a)), And(Lt(D(0), Dim(k, b)), Call("intersectionPremise", a, b)))));
        Formula conclusion = All("S", Subspace(k, l), All("T", Subspace(k, l),
            Imp(And(Le(s, a), Le(t, b)), Lower(k, s, t))));
        return Disp(new Formula.Logic(F.Id("claim"), FormulaLogicOperator.Iff,
            FieldBinders(All("A", Subspace(k, l), All("B", Subspace(k, l), Imp(hypotheses, conclusion))))));
    }

    private static Formula PowerSpanFormula() => Disp(All("n", Seq(Mathbb, Grp(F.Id("N"))),
        Eq(Call("powerSpan", F.Id("n")), Call("span", Q(),
            Call("range", Seq(LambdaLower, Sp, Open, F.Id("i"), Colon, Call("Fin", F.Id("n")), Close,
                Mapsto, Sp, new Formula.Power(F.Id("alpha"), Seq(Call("val", F.Id("i")), Plus, D(1)))))))));

    private static Formula CountermodelFormula()
    {
        Formula l = F.Id("Extension"), q = Q();
        return Disp(new Formula.Logic(F.Id("countermodel"), FormulaLogicOperator.Iff,
            new Formula.Aligned([
                Seq(Eq(Dim(q, l), D(7)), Comma, Sp, Eq(new Formula.Power(F.Id("alpha"), D(7)), D(2)), Comma),
                Seq(Eq(Dim(q, PS(6)), D(6)), Comma, Sp, Eq(Dim(q, PS(5)), D(5)), Comma),
                Seq(Lt(PS(5), PS(6)), Comma, Sp, Lt(PS(6), Call("top")), Comma),
                Seq(new Formula.Not(new Formula.Relation(D(1), FormulaRelationOperator.MemberOf, PS(6))), Comma, Sp, new Formula.Not(new Formula.Relation(D(1), FormulaRelationOperator.MemberOf, PS(5))), Comma),
                Seq(Call("intersectionPremise", PS(6), PS(6)), Comma),
                Le(SpanDim(q, PS(5), PS(5)), D(7))
            ])));
    }
