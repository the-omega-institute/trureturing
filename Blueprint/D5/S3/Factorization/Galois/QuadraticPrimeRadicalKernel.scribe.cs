    private static Formula Call(string name, params Formula[] args)
    {
        var xs = new List<Formula> { Operatorname, Grp(F.Id(name)), Open };
        for (var i = 0; i < args.Length; i++)
        {
            if (i > 0) xs.Add(Comma);
            xs.Add(args[i]);
        }
        xs.Add(Close);
        return Seq([.. xs]);
    }

    private static Formula Q() => Seq(Mathbb, Grp(F.Id("Q")));
    private static Formula N() => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula E() => Call("E", F.Id("S"));
    private static Formula FinitePrimeScope() => Seq(
        Forall, Sp, F.Id("S"), Sp, InMacro, Sp, Call("Finset", N()), Comma, Sp,
        Open, Forall, Sp, F.Id("p"), Sp, InMacro, Sp, F.Id("S"), Comma, Sp,
        Call("Prime", F.Id("p")), Close, Sp, Implies, Sp);
    private static Formula FieldFormula() => Disp(Seq(
        Forall, Sp, F.Id("S"), Sp, InMacro, Sp, Call("Finset", N()), Comma, Sp,
        E(), Sp, Eq, Sp, new Formula.Subscript(Operator("adjoin"), Q()),
        Open, OpenBrace, Sqrt, Grp(F.Id("p")), Sp, Mid, Sp,
        F.Id("p"), Sp, InMacro, Sp, F.Id("S"), CloseBrace, Close,
        Sp, Subseteq, Sp, Mathbb, Grp(F.Id("C"))));
    private static Formula Operator(string name) => Seq(Operatorname, Grp(F.Id(name)));
    private static Formula KernelFormula() => Disp(Seq(
        FinitePrimeScope(), Forall, Sp, F.Id("a"), Sp, InMacro, Sp, Q(), Comma, Sp,
        Call("IsSquare", Call("algebraMap", Q(), E(), F.Id("a"))), Sp, Iff, Sp,
        Exists, Sp, F.Id("T"), Sp, InMacro, Sp, Call("Finset", N()), Comma, Sp,
        F.Id("T"), Sp, Subseteq, Sp, F.Id("S"), Sp, Land, Sp,
        Call("IsSquare", Seq(F.Id("a"), Sp, Cdot, Sp,
            new Formula.Subscript(Prod, Seq(F.Id("p"), Sp, InMacro, Sp, F.Id("T"))), F.Id("p")))));
    private static Formula DegreeFormula() => Disp(Seq(
        FinitePrimeScope(), Call("FiniteDimensional", Q(), E()), Sp, Land, Sp,
        OpenBracket, E(), Colon, Q(), CloseBracket, Sp, Eq, Sp,
        new Formula.Power(D(2), Seq(Lvert, Sp, F.Id("S"), Sp, Rvert))));
    private static Formula ProductFormula() => Disp(Seq(
        FinitePrimeScope(), Forall, Sp, F.Id("p"), Sp, InMacro, Sp, N(), Comma, Sp,
        Open, Call("Prime", F.Id("p")), Sp, Land, Sp,
        Neg, Open, F.Id("p"), Sp, InMacro, Sp, F.Id("S"), Close, Close,
        Sp, Implies, Sp, Forall, Sp, F.Id("T"), Sp, InMacro, Sp,
        Call("Finset", N()), Comma, Sp, F.Id("T"), Sp, Subseteq, Sp, F.Id("S"),
        Sp, Implies, Sp, Neg, Call("IsSquare", Seq(F.Id("p"), Sp, Cdot, Sp,
            new Formula.Subscript(Prod, Seq(F.Id("q"), Sp, InMacro, Sp, F.Id("T"))), F.Id("q")))));
