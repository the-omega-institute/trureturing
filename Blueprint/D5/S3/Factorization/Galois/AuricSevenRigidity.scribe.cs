    private static Formula OriginalFormula()
    {
        Formula f = I("F"), d = I("D"), u = I("U"), v = I("V"), gamma = I("gamma");
        Formula conclusion = Some("gamma", d, And(Neq(gamma, Zero()),
            Eq(v, Call("translate", gamma, u))));
        Formula hypotheses = And(Eq(Call("finrank", f, u), D(3)),
            And(Eq(Call("finrank", f, v), D(3)),
            And(Call("LowIntersection", u), Subset(Call("Q", u), Call("Q", v)))));
        return Fields(All("U", Call("Submodule", f, d),
            All("V", Call("Submodule", f, d), Imp(hypotheses, conclusion))));
    }

    private static Formula SharedPlaneFormula()
    {
        Formula f = I("F"), d = I("D"), u = I("U"), v = I("V"), b = I("b");
        Formula hypotheses = And(Eq(Call("finrank", f, u), D(3)),
            And(Call("LowIntersection", u), And(Subset(Call("Q", u), Call("Q", v)),
            And(Member(Call("b", D(0)), u), Member(Call("b", D(1)), u)))));
        return Fields(All("U", Call("Submodule", f, d), All("V", Call("Submodule", f, d),
            All("b", Call("Basis", Call("Fin", D(3)), f, v),
                Imp(hypotheses, Member(Call("b", D(2)), u))))));
    }

    private static Formula Fields(Formula body)
    {
        body = Imp(Eq(Call("finrank", I("F"), I("D")), D(7)), body);
        body = Inst(Call("CharZero", I("F")), body);
        body = Inst(Call("Algebra", I("F"), I("D")), body);
        body = Inst(Call("Field", I("D")), body);
        body = Inst(Call("Field", I("F")), body);
        return All("F", Ty(), All("D", Ty(), body));
    }

    private static Formula Member(Formula a, Formula b) => Seq(a, Sp, InMacro, Sp, b);
    private static Formula Subset(Formula a, Formula b) => Seq(a, Sp, Subseteq, Sp, b);

    private static Formula Call(string name, params Formula[] args) => new Formula.Apply(Qualified(name), [.. args]);
    private static Formula Qualified(string name)
    {
        var items = new System.Collections.Generic.List<Formula> { Operatorname, Grp(I(name.Split('.')[0])) };
        foreach (string part in name.Split('.')[1..])
        {
            items.Add(Dot);
            items.Add(Operatorname);
            items.Add(Grp(I(part)));
        }
        return Seq([.. items]);
    }
    private static Formula I(string name) => F.Id(name);
    private static Formula Ty() => Seq(I("Type"), Star);
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula All(string name, Formula type, Formula body) => Seq(Forall, Sp, Parenthesized(Seq(I(name), Colon, Sp, type)), Comma, Sp, body);
    private static Formula Some(string name, Formula type, Formula body) => Seq(Exists, Sp, Parenthesized(Seq(I(name), Colon, Sp, type)), Comma, Sp, body);
    private static Formula Inst(Formula type, Formula body) => Seq(OpenBracket, type, CloseBracket, Sp, body);
    private static Formula Imp(Formula a, Formula b) => new Formula.Logic(Parenthesized(a), FormulaLogicOperator.Implies, Parenthesized(b));
    private static Formula And(Formula a, Formula b) => new Formula.Logic(Parenthesized(a), FormulaLogicOperator.And, Parenthesized(b));
    private static Formula Eq(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.Equal, b);
    private static Formula Neq(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.NotEqual, b);
    private static Formula Zero() => D(0);
