using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Factorization.Galois;

internal sealed class NormalCorePowerDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S3/Factorization/Galois/NormalCorePower.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Noncommutative algebra for the power-subgroup route to strong completeness.",
        H("NormalCorePower"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("power-subgroup-normal"),
                DeclarationHandle.Create(Prefix + "powerSubgroup_normal"),
                H("Normality without commutativity"),
                StatementSource.FromAuthor(Disp(All("m", N(), C("Normal", P())))),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text("Conjugation carries each mth power to another mth power. The subgroup generated by all such powers is therefore normal in any group."))),
                DescribeRole.Theorem),
            Describe.Lean(
                DescribeId.Create("powersubgroup"),
                DeclarationHandle.Create(Prefix + "powerSubgroup"),
                H("Power-generated subgroup"),
                StatementSource.FromAuthor(Disp(Eqn(P(), C("SubgroupClosure", C("Range", Seq(V("g"), Sp, Mapsto, Sp, Pow(V("g"), V("m")))))))),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text("The subgroup is generated algebraically by all mth powers in an arbitrary group. No commutativity or topology is assumed."))),
                DescribeRole.Definition),
            Describe.Lean(
                DescribeId.Create("pow-mem-powersubgroup"),
                DeclarationHandle.Create(Prefix + "pow_mem_powerSubgroup"),
                H("Each power belongs to the subgroup"),
                StatementSource.FromAuthor(Disp(All("m", N(), All("g", G(), Member(Pow(V("g"), V("m")), P()))))),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text("For every natural m and group element g, the element g to the mth power belongs to the generated subgroup."))),
                DescribeRole.Theorem),
            Describe.Lean(
                DescribeId.Create("powersubgroup-le-iff"),
                DeclarationHandle.Create(Prefix + "powerSubgroup_le_iff"),
                H("Exponent quotient criterion"),
                StatementSource.FromAuthor(Disp(All("m", N(), All("N", C("NormalSubgroup", G()), Seq(Le(P(), V("N")), Sp, Iff, Sp, All("q", C("Quotient", G(), V("N")), Eqn(Pow(V("q"), V("m")), D(1)))))))),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text("For any normal subgroup N, containment of the power subgroup in N is equivalent to every element of G modulo N having mth power one. The criterion also includes m equal to zero."))),
                DescribeRole.Theorem),
            Describe.Lean(
                DescribeId.Create("pow-normalcore-index-mem"),
                DeclarationHandle.Create(Prefix + "pow_normalCore_index_mem"),
                H("Powers in a finite-index normal core"),
                StatementSource.FromAuthor(Disp(All("H", C("Subgroup", G()), Implies(C("FiniteIndex", V("H")), All("g", G(), Member(Pow(V("g"), C("Index", Core())), Core())))))),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text("If H has finite index, its normal core also has finite index. Lagrange in that abstract quotient puts the normal-core-index power of every group element in the core. No normality of H or continuity of this quotient is needed."))),
                DescribeRole.Theorem),
            Describe.Lean(
                DescribeId.Create("powersubgroup-le-normalcore"),
                DeclarationHandle.Create(Prefix + "powerSubgroup_le_normalCore"),
                H("Containment in the normal core"),
                StatementSource.FromAuthor(Disp(All("H", C("Subgroup", G()), Implies(C("FiniteIndex", V("H")), Le(C("powerSubgroup", G(), C("Index", Core())), Core()))))),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text("Every finite-index subgroup H contains the power subgroup at the positive index of its normal core, through the containment of that power subgroup in the core."))),
                DescribeRole.Theorem))));

    private static Formula V(string name) => F.Id(name);
    private static Formula G() => V("G");
    private static Formula N() => Seq(Mathbb, Grp(V("N")));
    private static Formula P() => C("powerSubgroup", G(), V("m"));
    private static Formula Core() => C("NormalCore", V("H"));
    private static Formula Pow(Formula a, Formula b) => new Formula.Power(a, b);
    private static Formula Eqn(Formula a, Formula b) => Seq(a, Sp, Eq, Sp, b);
    private static Formula Le(Formula a, Formula b) => Seq(a, Sp, Leq, Sp, b);
    private static Formula Member(Formula a, Formula b) => Seq(a, Sp, InMacro, Sp, b);
    private static Formula Implies(Formula a, Formula b) => Seq(Grp(a), Sp, Rightarrow, Sp, Grp(b));
    private static Formula All(string n, Formula t, Formula b) =>
        Seq(Forall, Sp, Open, V(n), Colon, Sp, t, Close, Comma, Sp, b);
    private static Formula C(string name, params Formula[] args)
    {
        var parts = new List<Formula> { Operatorname, Grp(V(name)), Open };
        for (var i = 0; i < args.Length; i++)
        {
            if (i > 0) parts.AddRange([Comma, Sp]);
            parts.Add(args[i]);
        }
        parts.Add(Close);
        return Seq([.. parts]);
    }
}
