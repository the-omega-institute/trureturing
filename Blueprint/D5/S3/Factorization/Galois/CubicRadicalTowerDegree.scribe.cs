using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Factorization.Galois;

internal sealed class CubicRadicalTowerDegreeDocument : IScribeDocumentDefinition
{
    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Saturated tests in a field containing the cube roots of unity certify the degree of a finite cubic radical tower.",
        H("Cubic Radical Towers from Base-Field Tests"),
        Blocks(Describe.Lean(
            DescribeId.Create("cubic-radical-tower-degree-of-saturated-noncube-tests"),
            DeclarationHandle.Create(
                "D5/S3/Factorization/Galois/CubicRadicalTowerDegree.cubic_radical_tower_degree_of_saturated_noncube_tests"),
            H("Every cubic radical stage has degree three"),
            StatementSource.FromAuthor(DegreeFormula()),
            AssessedProvenance.FromRepo(),
            Blocks(
                Paragraph(Text(
                    "Let K be a field containing a primitive cube root of unity and let L be "
                        + "an extension field. Fix a natural number J and base elements a_j "
                        + "with specified cube roots beta_j in L for indices one through J. "
                        + "The intermediate field K_m is generated by the first m roots; "
                        + "K_0 is K.")),
                Paragraph(Text(
                    "For each n from zero through J, a predicate P_n on K "
                        + "accepts no cube and is preserved when an "
                        + "accepted element is multiplied by any nonnegative power of "
                        + "any a_i with one less than or equal to i less than or equal to n. "
                        + "For n strictly less than J the test also accepts a_(n+1). These assumptions imply that the degree of K_J over K is 3^J and that any element accepted by P_J still has no cube root in K_J. "
                        + "No additional assumption that the radicands are nonzero is needed: "
                        + "zero is a cube and is excluded by each fresh test.")),
                Paragraph(Text(
                    "Cubic descent proves that a cube root appearing in a later stage "
                        + "would turn a tested element times a power of that stage's "
                        + "radicand into a cube in the preceding field. Preservation of "
                        + "the base-field test excludes this possibility by induction. "
                        + "Consequently each polynomial T^3-a_j is irreducible over the "
                        + "preceding stage, and multiplication of the stage degrees gives "
                        + "the degree formula and the terminal noncube statement. The empty tower has degree one and retains the base-field test.")),
                Paragraph(Text(
                    "Valuations whose integer logarithms are nonzero modulo three can "
                        + "supply these tests when earlier radicands have valuation one. "
                        + "Their required values must be established for the actual "
                        + "radicands. The degree formula alone gives no Frobenius "
                        + "coordinates, cyclotomic intersection, density, or "
                        + "discriminant formula."))),
            DescribeRole.Theorem),
            Describe.Lean(
                DescribeId.Create("finite-valuation-cubic-degree-and-unit-obstruction"),
                DeclarationHandle.Create(
                    "D5/S3/Factorization/Galois/CubicRadicalTowerDegree.finite_valuation_degree_and_unit_noncube"),
                H("Diagonal valuations and a retained noncube unit"),
                StatementSource.WithoutFormula(),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "Let finitely many nonzero radicands over a field have specified cube roots. "
                            + "For each radicand, choose a valuation whose integer logarithm "
                            + "there is not divisible by three and whose value on every other "
                            + "radicand is one.")),
                    Paragraph(Text(
                        "If the base field contains a primitive cube root of unity, the "
                            + "generated radical field has degree three to the number of "
                            + "radicands. A base-field unit that is not a cube and has valuation "
                            + "logarithm zero at all chosen valuations remains a noncube in "
                            + "that generated field."))),
                DescribeRole.Theorem))));

    private static Formula DegreeFormula()
    {
        Formula field = F.Id("K");
        Formula J = F.Id("J");
        Formula tower = new Formula.Subscript(field, J);
        Formula a = F.Id("a");
        Formula x = F.Id("x");
        Formula predicate = new Formula.Apply(new Formula.Subscript(F.Id("P"), J), [a]);
        return Disp(new Formula.Aligned([
            Seq(OpenBracket, tower, Colon, field, CloseBracket,
                Sp, Eq, Sp, new Formula.Power(D(3), J), Comma),
            Seq(predicate, Sp, Rightarrow, Sp, Forall, Sp, x, Sp, InMacro, Sp, tower,
                Comma, Sp, new Formula.Power(x, D(3)), Sp, Neq, Sp, a, Dot),
        ]));
    }
}
