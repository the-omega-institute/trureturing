    private static Formula Call(Formula function, params Formula[] arguments)
    {
        var items = new List<Formula> { Operatorname, Grp(function), Open };
        for (var index = 0; index < arguments.Length; index++)
        {
            if (index > 0)
            {
                items.Add(Comma);
                items.Add(Sp);
            }
            items.Add(arguments[index]);
        }
        items.Add(Close);
        return Seq([.. items]);
    }

    private static Formula Gal(Formula extension, Formula basis) =>
        Call(F.Id("Gal"), extension, basis);

    private static Formula Intersection(Formula left, Formula right) =>
        Call(F.Id("Intersection"), left, right);

    private static Formula FiberProduct(Formula left, Formula right, Formula shared) =>
        Call(F.Id("FiberProduct"), left, right, shared);

    private static Formula FiberProductFormula()
    {
        Formula baseField = F.Id("K");
        Formula left = F.Id("LLeft");
        Formula right = F.Id("LRight");
        Formula shared = Intersection(left, right);
        Formula target = FiberProduct(
            Gal(left, baseField), Gal(right, baseField), Gal(shared, baseField));
        return Disp(Seq(
            Call(F.Id("JointRestriction"), F.Id("sigma")), Sp, InMacro, Sp,
            target, Dot));
    }

    private static Formula LinearDisjointFormula()
    {
        Formula left = F.Id("LLeft");
        Formula right = F.Id("LRight");
        return Disp(Seq(
            Call(F.Id("LinearDisjoint"), left, right), Sp, Iff, Sp,
            Intersection(left, right), Sp, Eq, Sp, F.Id("K"), Dot));
    }

    private static Formula ProductFormula()
    {
        Formula baseField = F.Id("K");
        Formula composite = F.Id("L");
        Formula left = F.Id("LLeft");
        Formula right = F.Id("LRight");
        return Disp(Seq(
            Intersection(left, right), Sp, Eq, Sp, baseField, Sp, Rightarrow,
            RowBreak, Grp(), Gal(composite, baseField), Sp, Sim, Sp,
            Gal(left, baseField), Sp, Times, Sp, Gal(right, baseField), Dot));
    }

    private static Formula DiagonalFormula()
    {
        Formula group = Gal(F.Id("C"), F.Id("R"));
        return Disp(Seq(
            Call(F.Id("SharedField"), F.Id("C"), F.Id("C")), Sp, Neq, Sp,
            F.Id("R"), Sp, Land, Sp, Neg,
            Call(F.Id("Surjective"), Call(F.Id("Diagonal"), group)), Dot));
    }

    private static Formula GenerationFormula()
    {
        Formula baseField = F.Id("R");
        return Disp(Seq(
            Intersection(baseField, baseField), Sp, Eq, Sp, baseField, Sp, Land, Sp,
            Neg, Call(F.Id("Injective"),
                Call(F.Id("JointRestriction"), Gal(F.Id("C"), baseField))), Dot));
    }

    private static Formula FrobeniusFormula()
    {
        Formula prime = F.Id("Q");
        Formula pair = Call(F.Id("RestrictionPair"), Call(F.Id("Frob"), prime));
        Formula shared = Call(F.Id("SharedGaloisGroup"), F.Id("LLeft"), F.Id("LRight"));
        return Disp(Seq(
            Call(F.Id("Unramified"), prime), Sp, Rightarrow, RowBreak, Grp(),
            pair, Sp, InMacro, Sp,
            FiberProduct(F.Id("GalLeft"), F.Id("GalRight"), shared), Dot));
    }

    private static Formula RamifiedFormula()
    {
        Formula prime = F.Id("Q");
        return Disp(Seq(
            Call(F.Id("Ramified"), prime), Sp, Rightarrow, Sp,
            Call(F.Id("mathlibFrobeniusAt"), prime), Sp, Eq, Sp, F.Id("none"), Dot));
    }

    private static Formula CyclotomicRamificationFormula()
    {
        Formula rationals = Seq(Mathbb, Grp(F.Id("Q")));
        Formula integers = Seq(Mathbb, Grp(F.Id("Z")));
        Formula field = Call(F.Id("CyclotomicField"), D(3), rationals);
        Formula ring = Call(F.Id("RingOfIntegers"), field);
        Formula prime = F.Id("P");
        return Disp(Seq(
            Exists, Sp, prime, InMacro, Sp, Call(F.Id("MaxSpec"), ring), Comma, Sp,
            Call(F.Id("RamifiedOver"), prime, integers), Dot));
    }
