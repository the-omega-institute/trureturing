using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Factorization.Galois;

internal sealed class GaloisCompatibleFiberProductDocument : IScribeDocumentDefinition
{
    private const string Prefix =
        "D5/S3/Factorization/Galois/GaloisCompatibleFiberProduct.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Compatible Galois restrictions reconstruct the generated compositum.",
        H("Galois Compatible Fiber Product"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("galois-compatible-fiber-product"),
                DeclarationHandle.Create(Prefix + "galois_compatible_fiber_product"),
                H("The compositum Galois group is the compatible fiber product"),
                StatementSource.FromAuthor(TheoremFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "The ambient field is generated by the two finite subextensions. "
                            + "Restriction identifies its automorphism group with pairs "
                            + "agreeing on their named sharedField.")),
                    Paragraph(Text(
                        "Injectivity uses the fixing subgroup of the supremum. For "
                            + "surjectivity, the proof changes base to the intersection, "
                            + "where Mathlib's trivial-intersection lifting theorem applies.")),
                    Paragraph(Text(
                        "The right extension only needs normality; separability on that side "
                            + "was removed by the assumption audit. The Lean edge-case audit "
                            + "covers trivial maps, equal fields, containment, and failure of "
                            + "ambient generation."))),
                DescribeRole.Theorem))));

    private static Formula Call(Formula function, params Formula[] arguments)
    {
        var items = new List<Formula> { Operatorname, Grp(function), Open };
        for (var index = 0; index < arguments.Length; index++)
        {
            if (index > 0)
            {
                items.Add(Comma);
                items.Add(Sp);
            }
            items.Add(arguments[index]);
        }
        items.Add(Close);
        return Seq([.. items]);
    }

    private static Formula Gal(Formula extension, Formula basis) =>
        Call(F.Id("Gal"), extension, basis);

    private static Formula TheoremFormula()
    {
        Formula baseField = F.Id("K");
        Formula ambient = F.Id("L");
        Formula left = F.Id("LLeft");
        Formula right = F.Id("LRight");
        Formula shared = Call(F.Id("Intersection"), left, right);
        Formula fiberProduct = Call(
            F.Id("FiberProduct"),
            Gal(left, baseField),
            Gal(right, baseField),
            Gal(shared, baseField));
        return Disp(Seq(
            Gal(ambient, baseField), Sp, Sim, Sp, fiberProduct, Dot));
    }
}
