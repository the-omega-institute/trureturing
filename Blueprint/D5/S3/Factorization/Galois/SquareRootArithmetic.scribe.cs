    private static Formula Call(string name, params Formula[] arguments)
    {
        var items = new List<Formula> { Operatorname, Grp(F.Id(name)), Open };
        for (var index = 0; index < arguments.Length; index++)
        {
            if (index > 0) { items.Add(Comma); items.Add(Sp); }
            items.Add(arguments[index]);
        }
        items.Add(Close);
        return Seq([.. items]);
    }
    private static Formula Rationals() => Seq(Mathbb, Grp(F.Id("Q")));
    private static Formula Integers(Formula field) => Seq(Mathcal, Grp(F.Id("O")), Underscore, Grp(field));
    private static Formula Z() => Seq(Mathbb, Grp(F.Id("Z")));
    private static Formula N() => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula All(string name, Formula type, Formula body) =>
        Seq(Forall, Sp, Open, F.Id(name), Colon, Sp, type, Close, Comma, Sp, body);
    private static Formula Arrow(Formula domain, Formula range) => Seq(domain, Sp, To, Sp, range);
    private static Formula Apply(Formula function, Formula argument) => Seq(function, Open, argument, Close);
    private static Formula Square(Formula value) => Seq(value, Caret, Grp(D(2)));
    private static Formula Equal(Formula left, Formula right) => Seq(left, Sp, Eq, Sp, right);
    private static Formula Imply(Formula premise, Formula result) => Seq(Grp(premise), Sp, Implies, Sp, result);
    private static Formula And(params Formula[] clauses)
    {
        var items = new List<Formula>();
        foreach (var clause in clauses)
        {
            if (items.Count > 0) { items.Add(Sp); items.Add(Land); items.Add(Sp); }
            items.Add(Grp(clause));
        }
        return Seq([.. items]);
    }
    private static Formula Instances(params Formula[] classes)
    {
        var items = new List<Formula> { OpenBracket };
        foreach (var item in classes)
        {
            if (items.Count > 1) { items.Add(Comma); items.Add(Sp); }
            items.Add(item);
        }
        items.Add(CloseBracket);
        items.Add(Sp);
        return Seq([.. items]);
    }
    private static Formula OverPrime(Formula primeIdeal, Formula prime) =>
        Call("LiesOver", primeIdeal, Call("span", Seq(OpenBrace, prime, Colon, Sp, Z(), CloseBrace)));
    private static Formula Avoids(Formula prime, Formula radicand) =>
        Seq(Neg, Sp, Grp(Seq(prime, Sp, Mid, Sp, radicand)));

    private static Formula GaloisFormula()
    {
        Formula k = F.Id("K"), l = F.Id("L"), i = F.Id("I");
        Formula d = F.Id("d"), r = F.Id("r"), j = F.Id("j");
        Formula roots = All("j", i, Equal(Square(Apply(r, j)),
            Call("algebraMap", k, l, Apply(d, j))));
        Formula conclusion = Call("IsGalois", k, Call("adjoin", k, Call("range", r)));
        Formula body = Seq(Instances(Call("Field", k), Call("Field", l),
                Call("Algebra", k, l), Call("Finite", i),
                Call("NeZero", Seq(D(2), Colon, Sp, k))),
            All("d", Arrow(i, k), All("r", Arrow(i, l), Imply(roots, conclusion))));
        return Disp(All("K", F.Id("Type"), All("L", F.Id("Type"),
            All("I", F.Id("Type"), body))));
    }
    private static Formula FrobeniusFormula()
    {
        Formula k = F.Id("K"), p = F.Id("p"), d = F.Id("d");
        Formula x = F.Id("x"), q = F.Id("Q"), s = F.Id("s");
        Formula premise = And(Seq(p, Sp, Neq, Sp, D(2)), Avoids(p, d),
            Equal(Square(x), Call("algebraMap", Z(), k, d)),
            Call("IsArithFrobAt", Integers(Rationals()), s, q));
        Formula conclusion = Equal(Apply(s, x), Seq(Call("Jacobi", d, p), Sp, Cdot, Sp, x));
        Formula body = Seq(Instances(Call("Field", k), Call("CharZero", k)),
            All("p", N(), Seq(Instances(Call("Fact", Call("Prime", p))),
                All("d", Z(), All("x", k, All("Q", Call("Ideal", Integers(k)),
                    Seq(Instances(OverPrime(q, p)),
                        All("s", Call("AlgAut", Rationals(), k), Imply(premise, conclusion)))))))));
        return Disp(All("K", F.Id("Type"), body));
    }
    private static Formula UnramifiedFormula()
    {
        Formula k = F.Id("K"), p = F.Id("p"), i = F.Id("I");
        Formula d = F.Id("d"), r = F.Id("r"), j = F.Id("j"), q = F.Id("Q");
        Formula premise = And(
            All("j", i, Equal(Square(Apply(r, j)), Call("algebraMap", Z(), k, Apply(d, j)))),
            Equal(Call("adjoin", Rationals(), Call("range", r)), Call("WholeField", k)),
            Seq(p, Sp, Neq, Sp, D(2)), All("j", i, Avoids(p, Apply(d, j))));
        Formula conclusion = Call("IsUnramifiedAt", Integers(Rationals()), q);
        Formula body = Seq(Instances(Call("Field", k), Call("NumberField", k)),
            All("p", N(), Seq(Instances(Call("Fact", Call("Prime", p))),
                All("I", F.Id("Type"), Seq(Instances(Call("Finite", i)),
                    All("d", Arrow(i, Z()), All("r", Arrow(i, k),
                        All("Q", Call("Ideal", Integers(k)),
                            Seq(Instances(Call("IsPrime", q), OverPrime(q, p)),
                                Imply(premise, conclusion))))))))));
        return Disp(All("K", F.Id("Type"), body));
    }
