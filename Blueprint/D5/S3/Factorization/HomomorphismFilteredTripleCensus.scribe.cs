    private static Formula V(string name) => F.Id(name);
    private static Formula Call(string name, params Formula[] args) =>
        new Formula.Apply(Seq(Operatorname, Grp(V(name))), [.. args]);
    private static Formula Pair(Formula a, Formula b) => Seq(Open, a, Comma, b, Close);
    private static Formula Set(params Formula[] xs)
    {
        var parts = new System.Collections.Generic.List<Formula> { OpenBrace };
        for (var i = 0; i < xs.Length; ++i)
        {
            if (i != 0) parts.Add(Comma);
            parts.Add(xs[i]);
        }
        parts.Add(CloseBrace);
        return Seq([.. parts]);
    }
    private static Formula Sub(string name, byte n) => Seq(V(name), Underscore, Grp(D(n)));
    private static Formula Family() => Call("V", V("f"));
    private static Formula Cycle() => Call("C", V("t"));
    private static Formula Fixed() => Call("F", V("f"), V("t"));
    private static Formula Card(Formula x) => Call("card", x);
    private static Formula Eligible() => Seq(D(3), V("t"), Sp, Eq, Sp, D(0), Sp, Land, Sp,
        Call("f", V("t")), Sp, Neq, Sp, D(0));
    private static Formula Context(bool finite = false) => Seq(Forall, Sp,
        V("G"), Comma, V("A"), Colon, Sp, Call("Type"), Comma, Sp,
        OpenBracket, Call("AddCommGroup", V("G")), CloseBracket, Sp,
        OpenBracket, Call("AddCommGroup", V("A")), CloseBracket, Sp,
        finite ? Seq(OpenBracket, Call("Finite", V("G")), CloseBracket, Sp) : Grp(),
        Forall, Sp, V("f"), Colon, Sp, V("G"), Sp, To, Sp, V("A"), Comma, Sp,
        Call("Additive", V("f")), Sp, Implies, Sp);
    private static Formula FamilyDefinition() => Disp(Seq(Context(),
        Forall, Sp, V("S"), Colon, Sp, Call("Finset", V("G")), Comma, Sp,
        Call("IsFilteredTriple", V("f"), V("S")), Sp, Iff, Sp,
        Card(V("S")), Sp, Eq, Sp, D(3), Sp, Land, Sp,
        Call("InjOn", V("f"), V("S"))));
    private static Formula CycleDefinition() => Disp(Seq(Forall, Sp, V("G"), Colon, Sp,
        Call("Type"), Comma, Sp, OpenBracket, Call("AddCommGroup", V("G")), CloseBracket,
        Sp, Forall, Sp, V("t"), Sp, InMacro, Sp, V("G"), Comma, Sp,
        Cycle(), Sp, Eq, Sp, Set(D(0), V("t"), Seq(D(2), V("t")))));
