            InMacro, Sp, Family(), Comma, Sp, V("c"), Sp, Eq, Sp, Cycle(), Sp, Land),
        Seq(Open, Forall, Sp, V("S"), Sp, InMacro, Sp, Family(), Comma, Sp,
