using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Factorization.PrimePowers;

internal sealed class AffineGcdBehaviorDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S3/Factorization/PrimePowers/AffineGcdBehavior.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Finite positive operation words have gcd-restricted affine actions, and every such modular action is realized.",
        H("Affine actions of a finite addition library"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("affine-word-translation"),
                DeclarationHandle.Create(Prefix + "affine_word_translation"),
                H("Every mixed word retains an affine form"),
                StatementSource.FromAuthor(ForwardFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "Let A be a finite list of positive addends. The named libraryGcd(H,A) "
                            + "is the fold of natural gcd through A, starting at H; in particular "
                            + "an empty list has libraryGcd(H,[]) equal to H. Operation(A) is the "
                            + "sum of positive multipliers and indices in A. Its update multiplies "
                            + "or adds the indexed positive value, and runWord evaluates a list of "
                            + "these operations from left to right on a positive source.")),
                    Paragraph(Text(
                        "The quantifier over words includes the empty list and imposes no common "
                            + "length bound. The slope is a positive natural number. Every addition "
                            + "contributes a multiple of the library gcd, and subsequent positive "
                            + "multiplications preserve that divisibility."))),
                DescribeRole.Theorem),
            Describe.Lean(
                DescribeId.Create("affine-action-realization"),
                DeclarationHandle.Create(Prefix + "affine_action_realization"),
                H("Every permitted affine residue has an original-library word"),
                StatementSource.FromAuthor(ReverseFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "For H at least two, every positive slope a and every natural translation "
                            + "t divisible by libraryGcd(H,A) is realized modulo H. The witnessing "
                            + "word first multiplies by a, then executes a finite list of indexed "
                            + "additions from A. A is allowed to be empty; the list of additions "
                            + "and its length are not constrained in advance.")),
                    Paragraph(Text(
                        "Bézout's identity places the gcd residue in the additive subgroup "
                            + "generated by the library. In the finite group ZMod(H), the positive "
                            + "addition closure has the same carrier. Closure induction extracts "
                            + "one concrete list of original additions, valid for every positive "
                            + "source x."))),
                DescribeRole.Theorem))));

    private static Formula Call(string name, params Formula[] arguments)
    {
        var items = new List<Formula> { Operatorname, Grp(F.Id(name)), Open };
        for (var i = 0; i < arguments.Length; i++)
        {
            if (i > 0)
                items.Add(Seq(Comma, Sp));
            items.Add(arguments[i]);
        }
        items.Add(Close);
        return Seq(items.ToArray());
    }

    private static Formula Par(Formula x) => Seq(Open, x, Close);
    private static Formula Nat() => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula Positive() => Seq(Mathbb, Grp(F.Id("N")), Underscore, Grp(Gt, D(0)));
    private static Formula ListOf(Formula x) => Call("List", x);
    private static Formula All(Formula x, Formula domain, Formula body) =>
        Seq(Forall, Sp, x, Sp, InMacro, Sp, domain, Comma, Sp, body);

    private static Formula ForwardFormula()
    {
        Formula h = F.Id("H");
        Formula library = F.Id("A");
        Formula word = F.Id("w");
        Formula slope = F.Id("a");
        Formula shift = F.Id("t");
        Formula x = F.Id("x");
        Formula output = Seq(Call("runWord", Call("update", library), word, x), Sp,
            Eq, Sp, slope, Sp, x, Sp, Plus, Sp, shift);
        Formula conclusion = Seq(Exists, Sp, slope, Comma, Sp, shift, Sp,
            InMacro, Sp, Nat(), Comma, Sp,
            D(0), Sp, Lt, Sp, slope, Sp, Land, Sp,
            Call("libraryGcd", h, library), Sp, Mid, Sp, shift, Sp, Land, Sp,
            All(x, Positive(), output));
        return Disp(All(h, Nat(), All(library, ListOf(Positive()),
            All(word, ListOf(Call("Operation", library)), conclusion))));
    }

    private static Formula ReverseFormula()
    {
        Formula h = F.Id("H");
        Formula library = F.Id("A");
        Formula slope = F.Id("a");
        Formula shift = F.Id("t");
        Formula indices = F.Id("u");
        Formula x = F.Id("x");
        Formula word = Call("cons", Call("inl", slope), Call("mapInr", indices));
        Formula action = Seq(
            Call("residue", h, Call("runWord", Call("update", library), word, x)),
            Sp, Eq, Sp,
            Call("residue", h, Seq(slope, Sp, x, Sp, Plus, Sp, shift)));
        Formula realizes = Seq(Exists, Sp, indices, Sp, InMacro, Sp,
            ListOf(Call("Fin", Call("length", library))), Comma, Sp,
            All(x, Positive(), action));
        return Disp(All(h, Nat(), All(library, ListOf(Positive()),
            All(slope, Positive(), All(shift, Nat(), Seq(
                Par(Seq(D(2), Sp, Le, Sp, h, Sp, Land, Sp,
                    Call("libraryGcd", h, library), Sp, Mid, Sp, shift)),
                Sp, Rightarrow, Sp, realizes))))));
    }
}
