    private static Formula Call(string name, params Formula[] arguments)
        => Call(F.Id(name), arguments);

    private static Formula Call(Formula function, params Formula[] arguments)
    {
        var items = new List<Formula> { Operatorname, Grp(function), Open };
        for (var i = 0; i < arguments.Length; i++)
        {
            if (i > 0)
                items.Add(Seq(Comma, Sp));
            items.Add(arguments[i]);
        }
        items.Add(Close);
        return Seq(items.ToArray());
    }

    private static Formula Par(Formula x) => Seq(Open, x, Close);
    private static Formula Nat() => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula Int() => Seq(Mathbb, Grp(F.Id("Z")));
    private static Formula Positive() => Seq(Mathbb, Grp(F.Id("N")), Underscore, Grp(Gt, D(0)));
    private static Formula ListOf(Formula x) => Call("List", x);
    private static Formula All(Formula x, Formula domain, Formula body) =>
        Seq(Forall, Sp, x, Sp, InMacro, Sp, domain, Comma, Sp, body);

    private static Formula ForwardFormula()
    {
        Formula h = F.Id("H");
        Formula library = F.Id("A");
        Formula word = F.Id("w");
        Formula slope = F.Id("a");
        Formula shift = F.Id("t");
        Formula x = F.Id("x");
        Formula output = Seq(Seq(Par(Call("runWord", Call("update", library), word, x)), Dot,
            F.Id("val")), Sp,
            Eq, Sp, slope, Sp, x, Sp, Plus, Sp, shift);
        Formula conclusion = Seq(Exists, Sp, slope, Comma, Sp, shift, Sp,
            InMacro, Sp, Nat(), Comma, Sp,
            D(0), Sp, Lt, Sp, slope, Sp, Land, Sp,
            Call("libraryGcd", h, library), Sp, Mid, Sp, shift, Sp, Land, Sp,
            All(x, Positive(), output));
        return Disp(All(h, Nat(), All(library, ListOf(Positive()),
            All(word, ListOf(Call("Operation", library)), conclusion))));
    }

    private static Formula ReverseFormula()
    {
        Formula h = F.Id("H");
        Formula library = F.Id("A");
        Formula slope = F.Id("a");
        Formula shift = F.Id("t");
        Formula indices = F.Id("ws");
        Formula x = F.Id("x");
        Formula word = Call(Seq(F.Id("List"), Dot, F.Id("cons")),
            Call(Seq(F.Id("Sum"), Dot, F.Id("inl")), slope),
            Call(Seq(F.Id("List"), Dot, F.Id("map")),
                Seq(F.Id("Sum"), Dot, F.Id("inr")), indices));
        Formula action = Seq(
            Call("residue", h,
                Seq(Par(Call("runWord", Call("update", library), word, x)),
                    Dot, F.Id("val"))),
            Sp, Eq, Sp,
            Call("residue", h, Seq(slope, Sp, x, Sp, Plus, Sp, shift)));
        Formula realizes = Seq(Exists, Sp, indices, Sp, InMacro, Sp,
            ListOf(Call("Fin", Call("length", library))), Comma, Sp,
            All(x, Positive(), action));
        return Disp(All(h, Nat(), All(library, ListOf(Positive()),
            All(slope, Positive(), All(shift, Nat(), Seq(
                Par(Seq(D(2), Sp, Le, Sp, h, Sp, Land, Sp,
                    Call("libraryGcd", h, library), Sp, Mid, Sp, shift)),
                Sp, Rightarrow, Sp, realizes))))));
    }

    private static Formula CompleteFormula()
    {
        Formula p = F.Id("p"), h = F.Id("h"), e = F.Id("e");
        Formula bigX = F.Id("X"), bigY = F.Id("Y"), a = F.Id("a"), b = F.Id("b");
        Formula m = Seq(p, Caret, Grp(Seq(h, Minus, e)));
        Formula ph = Seq(p, Caret, Grp(h)), pe = Seq(p, Caret, Grp(e));
        Formula modH = Call("ZMod", ph), localCode = Call("LocalCode", p, h, e);
        Formula source(Formula x) => Call("residue", ph, x);
        Formula code(Formula x) => Call("localEncoding", p, h, e, source(x));
        Formula response(Formula x) => Call("depth", p, h, D(0),
            source(Seq(a, Sp, Times, Sp, x, Sp, Plus, Sp, pe, Sp, Times, Sp, b)));
        Formula positive = Positive();
        Formula responseEquality = All(bigX, Int(), All(bigY, Int(), IffFormula(
            Seq(code(bigX), Sp, Eq, Sp, code(bigY)),
            All(a, positive, All(b, Int(), Seq(response(bigX), Sp, Eq, Sp, response(bigY)))))));
        Formula realization = All(F.Id("c"), localCode, Seq(
            Exists, Sp, bigX, Sp, InMacro, Sp, Int(), Comma, Sp,
            Seq(code(bigX), Sp, Eq, Sp, F.Id("c"))));
        Formula hypotheses = Seq(Call("Prime", p), Sp, Land, Sp,
            D(1), Sp, Le, Sp, h, Sp, Land, Sp, e, Sp, Le, Sp, h);
        return Disp(All(p, Nat(), All(h, Nat(), All(e, Nat(), Seq(
            Par(hypotheses), Sp, Rightarrow, Sp,
            Par(Seq(Par(responseEquality), Sp, Land, Sp, Par(realization))))))));
    }

    private static Formula IffFormula(Formula left, Formula right) =>
        new Formula.Logic(Par(left), FormulaLogicOperator.Iff, Par(right));
}
