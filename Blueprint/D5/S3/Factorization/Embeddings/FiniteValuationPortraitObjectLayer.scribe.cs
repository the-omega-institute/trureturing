using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Factorization.Embeddings;

internal sealed class FiniteValuationPortraitObjectLayerDocument
    : IScribeDocumentDefinition
{
    private const string Prefix =
        "D5/S3/Factorization/Embeddings/FiniteValuationPortraitObjectLayer.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Finite valuations recover a principal fractional ideal, leaving a unit ratio.",
        H("Finite-Valuation Portrait Object Layer"),
        Blocks(
            Definition(
                "finite-valuation-portrait",
                "finiteValuationPortrait",
                "The height-one prime valuation portrait"),
            Definition(
                "base-unit-ratio",
                "IsBaseUnitRatio",
                "The quotient is the image of a base-ring unit"),
            Theorem(
                "principal-fractional-ideal-reconstruction",
                "principal_fractional_ideal_reconstruction",
                "The portrait reconstructs the principal fractional ideal",
                ReconstructionFormula(),
                "Mathlib's Dedekind factorization theorem is applied directly to the "
                    + "nonzero principal fractional ideal generated by x."),
            Theorem(
                "reconstruction-nonzero-hypothesis-necessary",
                "reconstruction_nonzero_hypothesis_is_necessary",
                "The reconstruction formula must exclude zero",
                ReconstructionNonzeroNecessityFormula(),
                "At zero, the principal fractional ideal is zero while the totalized "
                    + "all-zero exponent product is one."),
            Theorem(
                "portrait-equality-iff-base-unit-ratio",
                "finite_valuation_portrait_eq_iff_base_unit_ratio",
                "Equal portraits are exactly base-unit ratios",
                UnitKernelFormula(),
                "Prime-valuation faithfulness first identifies the two principal "
                    + "fractional ideals. Equality of singleton spans is then exactly "
                    + "multiplication by a unit of the base Dedekind domain."),
            Theorem(
                "nonzero-ideal-has-prime-valuation-identity-completion",
                "nonzero_ideal_has_prime_valuation_identity_completion",
                "Every nonzero ideal has prime-valuation identity completion",
                IdentityCompletionFormula(),
                "This universal statement reuses the completion predicate from section "
                    + "108 and contrasts with its existential separation witness."),
            Theorem(
                "nonzero-ideal-hypothesis-necessary",
                "nonzero_ideal_hypothesis_is_necessary",
                "Identity completion must exclude the zero ideal",
                NonzeroIdealNecessityFormula(),
                "The imported completion predicate explicitly requires its ideal to be "
                    + "nonzero, so the zero ideal is a concrete counterexample."),
            Theorem(
                "rational-profile-rank-zero-sign",
                "rational_finite_profile_eq_iff_rank_zero_sign",
                "The rational residual is rank zero and a sign",
                RationalConnectionFormula(),
                "The concrete rational portrait from section 178 leaves exactly plus or "
                    + "minus sign, while section 182 supplies the zero unit rank."),
            Theorem(
                "nonzero-hypotheses-necessary",
                "nonzero_hypotheses_are_necessary",
                "Both nonzero hypotheses are necessary",
                NonzeroNecessityFormula(),
                "The totalized count assigns the zero fractional ideal the same all-zero "
                    + "portrait as one, but their quotient is not a base-ring unit."),
            Theorem(
                "composite-readout-not-faithful",
                "composite_readout_is_not_faithful",
                "A composite-modulus readout is not faithful",
                CompositeCounterexampleFormula(),
                "At modulus four, one and two both have value zero although one half is "
                    + "not an integer unit. Prime coordinates are therefore load-bearing."))));

    private static DocumentBlock.Describe Definition(
        string id,
        string declaration,
        string heading) =>
        Describe.Lean(
            DescribeId.Create(id),
            DeclarationHandle.Create(Prefix + declaration),
            H(heading),
            StatementSource.WithoutFormula(),
            AssessedProvenance.FromRepo(),
            Blocks(Paragraph(Text(heading + "."))),
            DescribeRole.Definition);

    private static DocumentBlock.Describe Theorem(
        string id,
        string declaration,
        string heading,
        Formula formula,
        string explanation) =>
        Describe.Lean(
            DescribeId.Create(id),
            DeclarationHandle.Create(Prefix + declaration),
            H(heading),
            StatementSource.FromAuthor(formula),
            AssessedProvenance.FromRepo(),
            Blocks(Paragraph(Text(explanation))),
            DescribeRole.Theorem);

    private static Formula ReconstructionFormula()
    {
        Formula ring = F.Id("R");
        Formula field = F.Id("K");
        Formula element = F.Id("x");
        Formula prime = F.Id("p");
        Formula product = Seq(
            Prod, Underscore,
            Grp(prime, Sp, InMacro, Sp, Call(F.Id("HeightOneSpectrum"), ring)), Sp,
            Superscript(prime, PortraitAt(ring, field, element, prime)));
        return Disp(Seq(
            Forall, Sp, ring, Comma, Sp, field, Colon, Sp, F.Id("Type"), Comma, Sp,
            DedekindFractionField(ring, field), Sp, Rightarrow, Sp,
            Forall, Sp, element, Sp, InMacro, Sp, field, Comma, Sp,
            element, Sp, Neq, Sp, D(0), Sp, Rightarrow, Sp,
            Principal(element), Sp, Eq, Sp, product, Dot));
    }

    private static Formula UnitKernelFormula()
    {
        Formula ring = F.Id("R");
        Formula field = F.Id("K");
        Formula first = F.Id("x");
        Formula second = F.Id("y");
        return Disp(Seq(
            Forall, Sp, ring, Comma, Sp, field, Colon, Sp, F.Id("Type"), Comma, Sp,
            DedekindFractionField(ring, field), Sp, Rightarrow, Sp,
            Forall, Sp, first, Comma, Sp, second, Sp, InMacro, Sp, field, Comma, Sp,
            first, Sp, Neq, Sp, D(0), Sp, Land, Sp,
            second, Sp, Neq, Sp, D(0), Sp, Rightarrow, Sp, Open,
            Portrait(ring, field, first), Sp, Eq, Sp,
            Portrait(ring, field, second), Sp, Iff, Sp,
            Call(F.Id("IsBaseUnitRatio"), ring, field, first, second), Close, Dot));
    }

    private static Formula ReconstructionNonzeroNecessityFormula()
    {
        Formula ring = Integers();
        Formula field = RationalNumbers();
        Formula prime = F.Id("p");
        Formula zero = D(0);
        Formula product = Seq(
            Prod, Underscore,
            Grp(prime, Sp, InMacro, Sp, Call(F.Id("HeightOneSpectrum"), ring)), Sp,
            Superscript(prime, PortraitAt(ring, field, zero, prime)));
        return Disp(Seq(Principal(zero), Sp, Neq, Sp, product, Dot));
    }

    private static Formula IdentityCompletionFormula()
    {
        Formula ring = F.Id("R");
        Formula ideal = F.Id("I");
        return Disp(Seq(
            Forall, Sp, ring, Colon, Sp, F.Id("Type"), Comma, Sp,
            Call(F.Id("CommRing"), ring), Sp, Land, Sp,
            Call(F.Id("IsDedekindDomain"), ring), Sp, Rightarrow, Sp,
            Forall, Sp, ideal, Sp, InMacro, Sp,
            Call(F.Id("NonzeroIdeals"), ring), Comma, Sp,
            Call(F.Id("PrimeValuationIdentityCompletion"), ideal), Dot));
    }

    private static Formula RationalConnectionFormula()
    {
        Formula first = F.Id("x");
        Formula second = F.Id("y");
        Formula profileEquality = Seq(
            Call(F.Id("nu"), RationalNumbers(), first), Sp, Eq, Sp,
            Call(F.Id("nu"), RationalNumbers(), second));
        Formula signAmbiguity = Seq(
            first, Sp, Eq, Sp, second, Sp, Lor, Sp,
            first, Sp, Eq, Sp, Minus, second);
        return Disp(Seq(
            Forall, Sp, first, Comma, Sp, second, Sp, InMacro, Sp,
            RationalNumbers(), Comma, Sp,
            first, Sp, Neq, Sp, D(0), Sp, Land, Sp,
            second, Sp, Neq, Sp, D(0), Sp, Rightarrow, Sp, Open,
            profileEquality, Sp, Iff, Sp,
            Call(F.Id("rank"), RationalNumbers()), Sp, Eq, Sp, D(0), Sp, Land, Sp,
            Open, signAmbiguity, Close, Close, Dot));
    }

    private static Formula NonzeroIdealNecessityFormula() =>
        Disp(Seq(
            Neg, Sp,
            Call(
                F.Id("PrimeValuationIdentityCompletion"),
                Call(F.Id("ZeroIdeal"), Integers())),
            Dot));

    private static Formula NonzeroNecessityFormula()
    {
        Formula zero = D(0);
        Formula one = D(1);
        Formula left = Seq(
            Portrait(Integers(), RationalNumbers(), zero), Sp, Eq, Sp,
            Portrait(Integers(), RationalNumbers(), one), Sp, Land, Sp,
            Neg, Sp,
            Call(F.Id("IsBaseUnitRatio"), Integers(), RationalNumbers(), zero, one));
        Formula right = Seq(
            Portrait(Integers(), RationalNumbers(), one), Sp, Eq, Sp,
            Portrait(Integers(), RationalNumbers(), zero), Sp, Land, Sp,
            Neg, Sp,
            Call(F.Id("IsBaseUnitRatio"), Integers(), RationalNumbers(), one, zero));
        return Disp(Seq(Open, left, Close, Sp, Land, Sp, Open, right, Close, Dot));
    }

    private static Formula CompositeCounterexampleFormula()
    {
        Formula one = D(1);
        Formula two = D(2);
        return Disp(Seq(
            Call(F.Id("v"), D(4), one), Sp, Eq, Sp,
            Call(F.Id("v"), D(4), two), Sp, Land, Sp,
            Neg, Sp, Call(
                F.Id("IsBaseUnitRatio"),
                Integers(),
                RationalNumbers(),
                one,
                two),
            Dot));
    }

    private static Formula Portrait(Formula ring, Formula field, Formula element) =>
        Call(F.Id("nu"), ring, field, element);

    private static Formula PortraitAt(
        Formula ring,
        Formula field,
        Formula element,
        Formula prime) =>
        Call(F.Id("nu"), ring, field, element, prime);

    private static Formula Principal(Formula element) =>
        Seq(Open, element, Close);

    private static Formula Superscript(Formula value, Formula exponent) =>
        Seq(value, Caret, Grp(exponent));

    private static Formula Integers() =>
        Seq(Mathbb, Grp(F.Id("Z")));

    private static Formula RationalNumbers() =>
        Seq(Mathbb, Grp(F.Id("Q")));

    private static Formula DedekindFractionField(Formula ring, Formula field) =>
        Seq(
            Call(F.Id("CommRing"), ring), Sp, Land, Sp,
            Call(F.Id("Field"), field), Sp, Land, Sp,
            Call(F.Id("Algebra"), ring, field), Sp, Land, Sp,
            Call(F.Id("IsFractionRing"), ring, field), Sp, Land, Sp,
            Call(F.Id("IsDedekindDomain"), ring));

    private static Formula Call(Formula name, params Formula[] arguments)
    {
        var items = new List<Formula> { name, Open };
        for (var index = 0; index < arguments.Length; index++)
        {
            if (index > 0)
            {
                items.Add(Comma);
                items.Add(Sp);
            }
            items.Add(arguments[index]);
        }
        items.Add(Close);
        return Seq([.. items]);
    }
}
