using static StrataLint.Scribe.DefinitionDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Factorization.QuadraticIdeals;

internal sealed class GoldenCubicPrimeNormFieldDocument : IScribeDocumentDefinition
{
    private const string Prefix =
        "D5/S3/Factorization/QuadraticIdeals/GoldenCubicPrimeNormField.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "A prime Eisenstein factor gives a cubic without rational roots and a real cyclic "
            + "splitting field of degree three.",
        H("The prime-norm cubic field"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("golden-cubic-prime-norm-no-projective-zero"),
                DeclarationHandle.Create(Prefix + "prime_norm_cubic_no_integer_projective_zero"),
                H("No nonzero integer projective zero"),
                StatementSource.WithoutFormula(),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "Let pi be a nonzero Eisenstein integer whose principal ideal is prime and "
                        + "which is coprime to its conjugate. Put a = pi.re, b = pi.im, "
                        + "A = a squared minus b squared, and D = 2ab minus b squared. For "
                        + "every integer pair (u,v) other than (0,0), the homogeneous cubic "
                        + "A u cubed - 3D u squared v + 3(D-A)u v squared + A v cubed is nonzero. "
                        + "At the prime ideal generated by pi, a zero would equate the valuations "
                        + "of pi squared times (u+v omega) cubed and its conjugate. The two "
                        + "pi factors contribute incompatible residues modulo three."))),
                DescribeRole.Theorem),
            Describe.Lean(
                DescribeId.Create("golden-cubic-prime-norm-field"),
                DeclarationHandle.Create(Prefix + "golden_cubic_prime_norm_field"),
                H("The cubic is irreducible and its splitting field is real cyclic"),
                StatementSource.WithoutFormula(),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "Let pi satisfy the same nonzero, prime-ideal, and conjugate-coprime "
                            + "hypotheses, and let its Eisenstein norm equal a natural number P. "
                            + "With A and D as above, the polynomial over Q with cubic "
                            + "coefficients (A, -3D, 3(D-A), A) is irreducible. Its splitting "
                            + "field has degree three over Q, has cyclic Galois group, and is "
                            + "totally real. The discriminant of the corresponding integer cubic "
                            + "is 81 times P to the fourth power.")),
                    Paragraph(Text(
                        "A rational root would clear denominators to a nonzero integer "
                            + "projective zero. If r is one root of the cubic, every root is r, "
                            + "1/(1-r), or (r-1)/r; hence a single root generates the splitting "
                            + "field. Opposite signs at zero and one give a real root between "
                            + "them, and the two transformed roots are real as well. The "
                            + "discriminant follows by expanding the cubic formula and using "
                            + "the Eisenstein norm identity."))),
                DescribeRole.Theorem))));
}
