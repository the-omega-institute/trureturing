using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Factorization.QuadraticIdeals;

internal sealed class EisensteinOddIdealFactorizationDocument : IScribeDocumentDefinition
{
    private const string Declaration =
        "D5/S3/Factorization/QuadraticIdeals/EisensteinOddIdealFactorization."
        + "eisenstein_odd_ideal_factorization";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Every odd oriented Eisenstein factor has an explicit ideal product indexed by the prime factors of its scalar norm.",
        H("Ideal Factorization of Odd Eisenstein Factors"),
        Blocks(Describe.Lean(
            DescribeId.Create("eisenstein-odd-ideal-factorization"),
            DeclarationHandle.Create(Declaration),
            H("The oriented ideal is the product of its explicit prime-indexed factors"),
            StatementSource.FromAuthor(TheoremFormula()),
            AssessedProvenance.FromRepo(),
            Blocks(
                Paragraph(Text(
                    "For odd b, eta is -2 + b omega, B is b squared plus 2b plus 4, and "
                        + "the factor at p is the ideal generated by eta and p. The quotient "
                        + "of the Eisenstein order by that factor is Z/pZ, so its norm is p.")),
                Paragraph(Text(
                    "Modulo eta, the product of those factors is generated by the prime "
                        + "factorization of B and therefore vanishes. Its absolute ideal norm "
                        + "is B, the same as the norm of the principal ideal of eta. "
                        + "Containment and norm equality yield the ideal identity.")),
                Paragraph(Text(
                    "This statement concerns ideals for every odd b. Primary generators "
                        + "and original-depth exponents require additional results."))),
            DescribeRole.Theorem))));

    private static Formula TheoremFormula()
    {
        Formula b = F.Id("b");
        Formula p = F.Id("p");
        Formula norm = Call("blockNorm", b);
        Formula factor = Call("IdealSup", Call("orientedIdeal", b),
            Call("IdealSpan", p));
        Formula product = Seq(
            new Formula.Subscript(Prod, Seq(p, Sp, InMacro, Sp,
                Call("primeFactors", norm))), Sp,
            new Formula.Power(factor, Call("factorization", norm, p)));

        return Disp(Seq(Forall, Sp, b, Sp, InMacro, Sp, Mathbb, Grp(F.Id("N")),
            Comma, Sp, Call("Odd", b), Sp, Implies, Sp,
            Call("orientedIdeal", b), Sp, Eq, Sp, product, Dot));
    }
}
