using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Factorization.QuadraticIdeals;

internal sealed class NormTwoIdealLocalGlobalGapDocument : IScribeDocumentDefinition
{
    private const string Declaration =
        "D5/S3/Factorization/QuadraticIdeals/NormTwoIdealLocalGlobalGap."
        + "norm_two_ideal_local_global_gap";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "The norm-two ideal is principal after localization at every nonzero prime but is not "
            + "principal globally, giving an explicit positive local-to-global defect.",
        H("A Local-to-Global Principal-Ideal Gap"),
        Blocks(Describe.Lean(
            DescribeId.Create("norm-two-ideal-local-global-principality-gap"),
            DeclarationHandle.Create(Declaration),
            H("The norm-two ideal is locally principal but globally nonprincipal"),
            StatementSource.FromAuthor(TheoremFormula()),
            AssessedProvenance.FromRepo(),
            Blocks(
                Paragraph(Text(
                    "The carrier and ideal are the frozen QuadraticOrder and normTwoIdeal from "
                        + "the adjacent norm-two theorem. Thus the witness is exactly the ideal "
                        + "generated by 2 and 1 + sqrt(-5), not a replacement construction.")),
                Paragraph(Text(
                    "At a prime containing 2, the element 3 lies outside the prime and becomes "
                        + "invertible. The identity (1 + sqrt(-5))(1 - sqrt(-5)) = 3 times 2 "
                        + "then makes the localized ideal principal with generator "
                        + "1 + sqrt(-5). At a prime not containing 2, the image of 2 is a unit, "
                        + "so the localized ideal is the unit ideal.")),
                Paragraph(Text(
                    "If the global ideal had generator x, its element norm would divide both 4 "
                        + "and 6, hence would equal 2 because x cannot be a unit. This would give "
                        + "x.re squared plus 5 times x.im squared equal to 2, which has no integer "
                        + "solution. The local proofs and global obstruction are assembled into "
                        + "the displayed positive defect witness whose underlying ideal is "
                        + "normTwoIdeal. This closes atom generic-residual-1798510a7ffd337203122"
                        + "ce61979bcb8bf790bba93f6b013f118ed868eb5a7c0."))),
            DescribeRole.Theorem))));

    private static Formula TheoremFormula()
    {
        Formula order = Seq(Operatorname, Grp(F.Id("QuadraticOrder")));
        Formula ideal = F.Id("normTwoIdeal");
        Formula prime = F.Id("p");
        Formula witness = F.Id("w");
        Formula idealType = Call("Ideal", order);
        Formula primeLocalization = Call("LocalizationAtPrime", order, prime);
        Formula mappedIdeal = Call("IdealMap", ideal, primeLocalization);
        Formula localClause = Seq(
            Forall, Sp, prime, Colon, Sp, idealType, Comma, Sp,
            Open,
            Call("IsPrime", prime), Sp, Land, Sp, prime, Sp, Neq, Sp, D(0),
            Close, Sp, Rightarrow, Sp,
            Call("IsPrincipal", mappedIdeal));
        Formula globalClause = Seq(Neg, Sp, Call("IsPrincipal", ideal));
        Formula principalPredicate = Call("PrincipalIdealPredicate", order);
        Formula localPredicate = Call("NonzeroPrimeLocalizationPrincipalPredicate", order);
        Formula defectType = Call(
            "positiveHasseDefect",
            principalPredicate,
            localPredicate);
        Formula defectClause = Seq(
            Exists, Sp, witness, Colon, Sp, defectType, Comma, Sp,
            Call("UnderlyingIdeal", witness), Sp, Eq, Sp, ideal);

        return Disp(Seq(
            Open, localClause, Close, Sp, Land, RowBreak, Grp(),
            globalClause, Sp, Land, RowBreak, Grp(),
            Open, defectClause, Close, Dot));
    }
}
