using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Factorization.QuadraticIdeals;

internal sealed class InertEisensteinFrobeniusDocument : IScribeDocumentDefinition
{
    private const string Declaration =
        "D5/S3/Factorization/QuadraticIdeals/InertEisensteinFrobenius."
        + "inert_eisenstein_quotient_frobenius";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Reduction modulo an inert rational prime identifies the Eisenstein quotient "
            + "with a quadratic finite field, where Frobenius acts by conjugation.",
        H("Inert Eisenstein Quotients and Frobenius"),
        Blocks(Describe.Lean(
            DescribeId.Create("inert-eisenstein-quotient-frobenius"),
            DeclarationHandle.Create(Declaration),
            H("An explicit quadratic quotient and its Frobenius action"),
            StatementSource.FromAuthor(TheoremFormula()),
            AssessedProvenance.FromRepo(),
            Blocks(
                Paragraph(Text(
                    "Let E be the Eisenstein order Z[omega], with omega squared plus "
                        + "omega plus one equal to zero. Let ell be a rational prime "
                        + "congruent to two modulo three, and let I be the ideal "
                        + "generated by ell. The ideal I is maximal. The quotient "
                        + "Q = E/I has ell squared elements and characteristic ell.")),
                Paragraph(Text(
                    "Write K for the quadratic algebra over Z/ellZ with a distinguished "
                        + "element satisfying the same relation as omega. There is a "
                        + "ring equivalence e from Q to K which sends the real and "
                        + "imaginary integer coordinates of every z in E to their "
                        + "residues modulo ell. This specifies the equivalence on all "
                        + "classes represented by Eisenstein integers.")),
                Paragraph(Text(
                    "For every z in E, raising its class in Q to the ell-th power "
                        + "gives the class of its quadratic conjugate. This Frobenius "
                        + "identity includes ell equal to two. The statement applies "
                        + "to the actual ideal generated by ell."))),
            DescribeRole.Theorem))));

    private static Formula TheoremFormula()
    {
        Formula ell = F.Id("ell");
        Formula z = F.Id("z");
        Formula e = F.Id("e");
        Formula ideal = F.Id("I");
        Formula quotient = F.Id("Q");
        Formula model = F.Id("K");
        Formula residue = Call("class", z);
        Formula equivResidue = Call("e", residue);
        Formula conditions = Seq(Call("Prime", ell), Sp, Land, Sp,
            Call("mod", ell, D(3)), Sp, Eq, Sp, D(2));
        Formula coordinates = Seq(
            Call("re", equivResidue), Sp, Eq, Sp, Call("mod", Call("re", z), ell),
            Sp, Land, Sp,
            Call("im", equivResidue), Sp, Eq, Sp, Call("mod", Call("im", z), ell));
        return Disp(new Formula.Aligned([
            Seq(Forall, Sp, ell, Sp, InMacro, Sp, F.Id("N"), Comma, Sp,
                conditions, Sp, Rightarrow, Sp,
                Call("Maximal", ideal), Sp, Land, Sp,
                Call("card", quotient), Sp, Eq, Sp, new Formula.Power(ell, D(2)),
                Sp, Land, Sp, Call("CharP", quotient, ell)),
            Seq(Forall, Sp, ell, Sp, InMacro, Sp, F.Id("N"), Comma, Sp,
                conditions, Sp, Rightarrow, Sp,
                Exists, Sp, e, Sp, InMacro, Sp, Call("RingEquiv", quotient, model),
                Comma, Sp, Open,
                Forall, Sp, z, Sp, InMacro, Sp, F.Id("E"), Comma, Sp, coordinates,
                Close, Sp, Land, Sp,
                Open, Forall, Sp, z, Sp, InMacro, Sp, F.Id("E"), Comma, Sp,
                new Formula.Power(residue, ell), Sp, Eq, Sp,
                Call("class", Call("conj", z)), Close),
        ]));
    }
}
