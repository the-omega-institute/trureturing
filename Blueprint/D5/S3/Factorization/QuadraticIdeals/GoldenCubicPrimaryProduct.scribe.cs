using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Factorization.QuadraticIdeals;

internal sealed class GoldenCubicPrimaryProductDocument : IScribeDocumentDefinition
{
    private const string Declaration =
        "D5/S3/Factorization/QuadraticIdeals/GoldenCubicPrimaryProduct."
        + "golden_cubic_primary_product";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "The cubic Lucas block has an exact product of primary Eisenstein generators at its prime factors.",
        H("Primary Factorization of a Cubic Lucas Block"),
        Blocks(Describe.Lean(
            DescribeId.Create("golden-cubic-primary-eisenstein-product"),
            DeclarationHandle.Create(Declaration),
            H("The oriented factor equals the product of its primary prime generators"),
            StatementSource.FromAuthor(TheoremFormula()),
            AssessedProvenance.FromRepo(),
            Blocks(
                Paragraph(Text(
                    "For j at least one, x is the Lucas number at 3 to the j, b is x minus one, "
                        + "B is b squared plus twice b plus four, and eta is -2 + b omega. "
                        + "Writing lambda as 1 + 2 omega identifies eta with omega times "
                        + "the sum of x and lambda. Its norm is B, and eta differs from "
                        + "1 + lambda cubed by a multiple of nine.")),
                Paragraph(Text(
                    "The ideals generated by eta and its conjugate are coprime. For each "
                        + "rational prime factor p of B, the ideal generated by eta and p "
                        + "has norm p. It is prime and is the unique prime ideal containing "
                        + "both eta and p. Its primary generator has norm p, and p is one "
                        + "modulo three.")),
                Paragraph(Text(
                    "The odd-factor ideal decomposition gives the same prime powers as the "
                        + "Fibonacci valuation at the first rank of p. The product of the "
                        + "chosen generators and eta generate the same ideal. Both are one "
                        + "modulo three, so their associated unit is one and the element "
                        + "product is exact."))),
            DescribeRole.Theorem))));

    private static Formula TheoremFormula()
    {
        Formula j = F.Id("j");
        Formula p = F.Id("p");
        Formula q = F.Id("Q");
        Formula x = F.Id("x");
        Formula b = F.Id("b");
        Formula norm = F.Id("B");
        Formula eta = F.Id("eta");
        Formula lambda = LambdaLower;
        Formula pi = new Formula.Subscript(Pi, p);
        Formula eisenstein = Seq(Mathrm, Grp(F.Id("EisensteinOrder")));
        Formula ideal = Call("IdealSup", Call("IdealSpan", eta),
            Call("IdealSpan", p));
        Formula factors = Call("primeFactors", norm);
        Formula depth = Call("padicValNat", p, Call("fib", Call("fibonacciRank", p)));
        Formula product = Seq(new Formula.Subscript(Prod, Seq(p, Sp, InMacro, Sp, factors)),
            Sp, new Formula.Power(pi, depth));
        Formula definitions = Seq(
            x, Sp, Eq, Sp, Call("goldenLucas", new Formula.Power(D(3), j)), Sp, Land, Sp,
            b, Sp, Eq, Sp, Call("toNat", Seq(x, Sp, Minus, Sp, D(1))), Sp, Land, Sp,
            norm, Sp, Eq, Sp, Call("blockNorm", b), Sp, Land, Sp,
            eta, Sp, Eq, Sp, Call("orientedFactor", b), Sp, Land, Sp,
            lambda, Sp, Eq, Sp, D(1), Sp, Plus, Sp, D(2), Omega);
        Formula initial = Seq(
            eta, Sp, Eq, Sp, Omega, Open, x, Sp, Plus, Sp, lambda, Close,
            Sp, Land, Sp, Call("Norm", eta), Sp, Eq, Sp, norm,
            Sp, Land, Sp, D(9), Sp, Mid, Sp,
            eta, Sp, Minus, Sp, Open, D(1), Sp, Plus, Sp,
            new Formula.Power(lambda, D(3)), Close,
            Sp, Land, Sp, Call("IsCoprime", Call("IdealSpan", eta),
                Call("IdealSpan", Call("conjugate", eta))));
        Formula unique = Seq(Forall, Sp, q, Colon, Sp, Call("Ideal", eisenstein),
            Comma, Sp, Open, Call("IsPrime", q), Sp, Land, Sp,
            p, Sp, InMacro, Sp, q, Sp, Land, Sp, eta, Sp, InMacro, Sp, q,
            Close, Sp, Rightarrow, Sp, q, Sp, Eq, Sp, ideal);
        Formula primeData = Seq(
            Forall, Sp, p, Sp, InMacro, Sp, factors, Comma, Sp,
            Call("IsPrime", ideal), Sp, Land, Sp, Open, unique, Close,
            Sp, Land, Sp, Call("IdealSpan", pi), Sp, Eq, Sp, ideal,
            Sp, Land, Sp, Call("Norm", pi), Sp, Eq, Sp, p,
            Sp, Land, Sp, D(3), Sp, Mid, Sp, pi, Sp, Minus, Sp, D(1),
            Sp, Land, Sp, Call("mod", p, D(3)), Sp, Eq, Sp, D(1));
        Formula conclusion = Seq(Exists, Sp, Pi, Colon, Sp,
            Mathbb, Grp(F.Id("N")), Sp, To, Sp, eisenstein,
            Comma, Sp, Open, primeData, Close, Sp, Land, Sp,
            eta, Sp, Eq, Sp, product);

        return Disp(new Formula.Aligned([
            Seq(Forall, Sp, j, Sp, InMacro, Sp, Mathbb, Grp(F.Id("N")),
                Comma, Sp, j, Sp, Geq, Sp, D(1), Sp, Rightarrow, Sp,
                Forall, Sp, x, Sp, InMacro, Sp, Mathbb, Grp(F.Id("Z")), Comma, Sp,
                Forall, Sp, b, Comma, norm, Sp, InMacro, Sp, Mathbb, Grp(F.Id("N")),
                Comma, Sp, Forall, Sp, eta, Comma, lambda, Sp, InMacro, Sp,
                eisenstein, Comma),
            Seq(Open, definitions, Close, Sp, Rightarrow),
            Seq(Open, initial, Close, Sp, Land),
            Seq(Open, conclusion, Close, Dot),
        ]));
    }
}
