using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Zeros.Symmetry;

internal sealed class EdgeTranspositionGroupDocument : IScribeDocumentDefinition
{
    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Edge transpositions generate every permutation on each connected component.",
        H("Edge Transposition Group"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("edge-transpositions-generate-componentwise-symmetric-groups"),
                DeclarationHandle.Create(
                    "D5/S3/Zeros/Symmetry/EdgeTranspositionGroup."
                        + "edge_transposition_group"),
                H("Edge transpositions generate the full component permutation groups"),
                StatementSource.FromAuthor(EdgeTranspositionFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "Let graph be a finite simple graph. For each connected component, "
                            + "the subgroup generated by swaps across its edges is the full "
                            + "permutation group of that component.")),
                    Paragraph(Text(
                        "For a connected graph, a path between two vertices gives a product "
                            + "of edge swaps transporting the first vertex to the second. "
                            + "Thus the generated subgroup acts transitively.")),
                    Paragraph(Text(
                        "Pinned Mathlib's transitive-swap closure theorem then identifies the "
                            + "generated subgroup with the full symmetric group. The same "
                            + "identity supplies a generated permutation transporting any "
                            + "chosen branch to any other branch.")),
                    Paragraph(Text(
                        "Repository and installed-package searches found no existing theorem "
                            + "combining the componentwise, connected-graph, and transport "
                            + "clauses."))),
                DescribeRole.Theorem))));

    private static Formula EdgeTranspositionFormula()
    {
        Formula vertex = F.Id("V");
        Formula graph = F.Id("G");
        Formula component = F.Id("C");
        Formula first = F.Id("a");
        Formula last = F.Id("b");
        Formula permutation = Sigma;
        Formula type = Seq(Operatorname, Grp(F.Id("Type")));
        Formula componentVertices = Call("vertices", component);
        Formula componentGraph = Call("componentGraph", component);
        Formula componentGenerators = EdgeSwaps(
            componentGraph, componentVertices, permutation, first, last);
        Formula graphGenerators = EdgeSwaps(
            graph, vertex, permutation, first, last);
        Formula componentGenerated = Call("closure", componentGenerators);
        Formula graphGenerated = Call("closure", graphGenerators);
        Formula componentGroup = Call("Perm", componentVertices);
        Formula graphGroup = Call("Perm", vertex);

        Formula componentwise = Seq(
            Forall, Sp, component, Colon, Sp, Call("ConnectedComponent", graph), Comma, Sp,
            componentGenerated, Sp, Eq, Sp, componentGroup);
        Formula transport = Seq(
            Forall, Sp, first, Comma, Sp, last, Colon, Sp, vertex, Comma, Sp,
            Exists, Sp, permutation, Colon, Sp, Gamma, Comma, Sp,
            permutation, Open, first, Close, Sp, Eq, Sp, last);
        Formula connectedCase = Seq(
            Call("Connected", graph), Sp, Rightarrow,
            RowBreak, Grp(),
            Operatorname, Grp(F.Id("let")), Sp, Gamma, Sp, Eq, Sp,
            graphGenerated, Semi, Sp,
            Gamma, Sp, Eq, Sp, graphGroup, Sp, Land, Sp, transport);

        return Disp(Seq(
            Forall, Sp, vertex, Colon, Sp, type, Comma, Sp,
            graph, Colon, Sp,
            Call("SimpleGraph", vertex), Comma,
            RowBreak, Grp(),
            Call("Finite", vertex), Sp, Rightarrow,
            RowBreak, Grp(),
            Open, componentwise, Close, Sp, Land,
            RowBreak, Grp(),
            Open, connectedCase, Close, Dot));
    }

    private static Formula EdgeSwaps(
        Formula graph,
        Formula carrier,
        Formula permutation,
        Formula first,
        Formula last)
    {
        Formula membershipCondition = Seq(
            Exists, Sp, first, Comma, Sp, last, Colon, Sp, carrier, Comma, Sp,
            Call("Adj", graph, first, last), Sp, Land, Sp,
            permutation, Sp, Eq, Sp, Call("swap", first, last));
        Formula domainAndCondition = Seq(
            Call("Perm", carrier), Comma, Sp, membershipCondition);
        return new Formula.SetBuilder(permutation, permutation, domainAndCondition);
    }

    private static Formula Call(string name, params Formula[] arguments)
    {
        var items = new List<Formula> { Operatorname, Grp(F.Id(name)), Open };
        for (var index = 0; index < arguments.Length; index++)
        {
            if (index > 0) items.AddRange([Comma, Sp]);
            items.Add(arguments[index]);
        }

        items.Add(Close);
        return Seq([.. items]);
    }
}
