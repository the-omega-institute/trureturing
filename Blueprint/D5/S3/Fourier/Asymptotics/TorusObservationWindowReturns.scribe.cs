    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Vanishing errors preserve bounded returns to every open window meeting a continuous torus observation image.",
        H("Support and Robust Returns of Torus Observations"),
        Blocks(Describe.Lean(
            DescribeId.Create("torus-observation-window-returns"),
            DeclarationHandle.Create("D5/S3/Fourier/Asymptotics/TorusObservationWindowReturns.result"),
            H("Full image support, bounded waiting and positive lower density"),
            StatementSource.FromAuthor(TheoremFormula()),
            AssessedProvenance.FromRepo(
                LibraryNoteRef.Create("D5/L/Fourier/tao2008equidistribution")),
            Blocks(
                Paragraph(Text(
                    "Let I be any finite type, T the complex unit circle, and g an element of T^I. "
                    + "Let G be the closure of the cyclic subgroup generated by g and let mu be "
                    + "its Haar probability measure. The observable h is any continuous real "
                    + "function on G, and e is any real sequence whose difference from h(g^n) "
                    + "tends to zero. Write nu for the pushforward of mu by h. "
                    + "For J=(u,v), let A_J(N) count the integers m with 0 <= m < N and e_m in J.")),
                Paragraph(Text(
                    "The support of nu is exactly h(G). For every open interval J meeting this "
                    + "image, the same integers n_0 >= 1 and M >= 0 give both conclusions: "
                    + "each interval of integers from n to n+M contains a hit whenever n >= n_0, "
                    + "and the lower asymptotic density of the hits is at least 1/(M+1). "
                    + "The last displayed clause states this density bound as an eventual "
                    + "epsilon inequality. The counting ratio lies in [0,1], so this is "
                    + "equivalent to the usual liminf inequality. Counting from 1 instead of "
                    + "0 changes a ratio by at most 1/N and gives the same lower density.")),
                Paragraph(Text(
                    "Compactness makes h(G) closed. An open neighborhood of any point h(z) "
                    + "has a nonempty open preimage, which has positive Haar measure. "
                    + "The complement of h(G) has empty preimage. These two facts identify "
                    + "the support, including atomic pushforward measures.")),
                Paragraph(Text(
                    "Choose z with h(z) in J and a positive margin delta so that the interval "
                    + "from h(z)-2 delta to h(z)+2 delta lies inside J. The inverse image U "
                    + "of the smaller interval with radius delta is nonempty and open. "
                    + "Nonnegative powers are dense in the actual closed subgroup, so every "
                    + "translate x g^k enters U for some k >= 0. The corresponding open "
                    + "preimages cover G. A finite subcover supplies a maximum time M, "
                    + "valid for every starting point. Eventually the perturbation has "
                    + "absolute value less than delta, preserving each selected hit in J.")),
                Paragraph(Text(
                    "Put L=M+1 and divide the integers from n_0 onward into disjoint blocks "
                    + "of length L. Choose one hit per block. The chosen times increase "
                    + "strictly, hence the first floor((N-n_0)/L) complete blocks give "
                    + "that many distinct hits below N when N >= n_0. It follows that "
                    + "N <= n_0 + L(A_J(N)+1). Dividing by N L and letting N grow proves "
                    + "the claimed eventual epsilon inequalities.")),
                Paragraph(Text(
                    "The statement includes empty I, finite-order generators, proper or "
                    + "disconnected subgroups, constant observables, and zero or nonzero "
                    + "vanishing perturbations. It requires neither ambient density nor "
                    + "atom-free thresholds, and assumes no rate of convergence. The "
                    + "waiting bound depends on the generator, observable and window; no "
                    + "bound uniform over these parameters is asserted. The cited torus "
                    + "equidistribution exposition supplies background on orbit closures; "
                    + "the support and finite-cover argument here is a synthesis of "
                    + "standard compact-group and counting methods."))),
            DescribeRole.Theorem))));

    private static Formula TheoremFormula()
    {
        Formula i = F.Id("I"), g = F.Id("g"), group = F.Id("G"), h = F.Id("h");
        Formula e = F.Id("e"), n = F.Id("n"), m = F.Id("m"), size = F.Id("N");
        Formula bound = F.Id("M"), u = F.Id("u"), v = F.Id("v");
        Formula start = new Formula.Subscript(n, F.D(0));
        Formula reals = F.Seq(F.Mathbb, F.Grp(F.Id("R")));
        Formula naturals = F.Seq(F.Mathbb, F.Grp(F.Id("N")));
        Formula torus = F.Seq(F.Mathbb, F.Grp(F.Id("T")));
        Formula window = F.Seq(F.Open, u, F.Comma, v, F.Close);
        Formula density = new Formula.Fraction(F.D(1), F.Seq(bound, F.Plus, F.D(1)));
        Formula count = F.Seq(new Formula.Subscript(F.Id("A"), window), F.Open, size, F.Close);
        Formula support = F.Seq(Call("supp", F.Nu), F.Eq, F.Sp, Call("h", group));
        Formula hit = F.Seq(F.Exists, F.Sp, m, F.InMacro, F.Sp, naturals, F.Colon, F.Sp,
            n, F.Leq, F.Sp, m, F.Leq, F.Sp, n, F.Plus, bound, F.Land, F.Sp,
            new Formula.Subscript(e, m), F.InMacro, F.Sp, window);
        Formula returns = F.Seq(F.Forall, F.Sp, n, F.InMacro, F.Sp, naturals, F.Comma, F.Sp,
            n, F.Geq, F.Sp, start, F.Implies, F.Sp, hit);
        Formula lower = F.Seq(F.Forall, F.Sp, F.Varepsilon, F.Gt, F.D(0), F.Comma, F.Sp,
            F.Exists, F.Sp, new Formula.Subscript(size, F.D(0)), F.InMacro, F.Sp, naturals,
            F.Comma, F.Sp, F.Forall, F.Sp, size, F.InMacro, F.Sp, naturals, F.Comma, F.Sp,
            size, F.Geq, F.Sp, new Formula.Subscript(size, F.D(0)), F.Implies, F.Sp,
            density, F.Minus, F.Varepsilon, F.Leq, F.Sp, new Formula.Fraction(count, size));
        Formula windows = F.Seq(F.Forall, F.Sp, u, F.Comma, v, F.InMacro, F.Sp, reals,
            F.Comma, F.Sp, F.Open, F.Exists, F.Sp, F.Id("z"), F.InMacro, F.Sp, group,
            F.Colon, F.Sp, u, F.Lt, Call("h", F.Id("z")), F.Lt, v, F.Close, F.Implies, F.Sp,
            F.Exists, F.Sp, start, F.Comma, bound, F.InMacro, F.Sp, naturals, F.Colon, F.Sp,
            start, F.Geq, F.D(1), F.Land, F.Sp,
            F.Open, returns, F.Close, F.Land, F.Sp, F.Open, lower, F.Close);
        Formula convergence = F.Seq(F.Lim, F.Underscore, F.Grp(n, F.To, F.Infty), F.Sp,
            F.Open, new Formula.Subscript(e, n), F.Minus,
            Call("h", new Formula.Power(g, n)), F.Close, F.Eq, F.D(0));
        Formula observations = F.Seq(F.Nu, F.Colon, F.Eq, F.Sp, Call("map", h, F.Mu), F.Colon, F.Sp,
            convergence, F.Implies, F.Sp, F.Open, support, F.Land, F.Sp, windows, F.Close);
        Formula body = F.Seq(group, F.Colon, F.Eq, F.Overline, F.Grp(F.Langle, F.Sp, g, F.Rangle),
            F.Comma, F.Sp, F.Mu, F.Colon, F.Eq, F.Sp, Call("HaarProbability", group), F.Colon, F.Sp,
            new Formula.BindMany(FormulaQuantifier.ForAll,
                [new Formula.BoundVariable(FormulaIdentifier.Create("h"), Call("C", group, reals)),
                 new Formula.BoundVariable(FormulaIdentifier.Create("e"), new Formula.Power(reals, naturals))],
                observations));
        return F.Disp(new Formula.BindMany(FormulaQuantifier.ForAll,
            [new Formula.BoundVariable(FormulaIdentifier.Create("I"),
                F.Seq(F.Mathrm, F.Grp(F.Id("FiniteTypes")))),
             new Formula.BoundVariable(FormulaIdentifier.Create("g"), new Formula.Power(torus, i))], body));
    }
