using static StrataLint.Scribe.DefinitionDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Fourier.Asymptotics;

internal sealed class TorusOrbitEquidistributionDocument : IScribeDocumentDefinition
{
    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Every continuous observable on a finite torus orbit closure has its normalized Haar orbit average.",
        H("Haar Equidistribution in the Actual Torus Orbit Closure"),
        Blocks(Describe.Lean(
            DescribeId.Create("torus-orbit-haar-equidistribution"),
            DeclarationHandle.Create("D5/S3/Fourier/Asymptotics/TorusOrbitEquidistribution.result"),
            H("All continuous observables on the closed cyclic subgroup"),
            StatementSource.FromAuthor(TheoremFormula()),
            AssessedProvenance.FromLiterature(
                LibraryNoteRef.Create("D5/L/Fourier/tao2008equidistribution")),
            Blocks(
                Paragraph(Text(
                    "Let I be any finite index type, including the empty type, and let g be any "
                    + "element of the multiplicative torus T^I, where T is the complex unit circle. "
                    + "G is the topological closure of the cyclic subgroup generated by g. "
                    + "The first equality identifies its carrier with the closure of the nonnegative "
                    + "powers. The measure mu_G is Haar measure on G normalized to total mass one.")),
                Paragraph(Text(
                    "The limit holds for every continuous complex-valued function on G. "
                    + "The sum samples exactly g through g^N. At N=0 the sum and its totalized "
                    + "quotient are zero; this convention has no effect on the limit. "
                    + "No irrationality, independence, ambient density or connectedness is required.")),
                Paragraph(Text(
                    "For each integer character, split according to whether its value at g is one. "
                    + "In that case it equals one on all powers and, by continuity, on G. "
                    + "Otherwise the finite geometric sum divided by N tends to zero. "
                    + "Translation invariance of Haar measure forces the same character's integral "
                    + "to vanish. This split retains every integer relation among the coordinates.")),
                Paragraph(Text(
                    "Complex Tietze extension supplies an ambient continuous extension for every "
                    + "observable on G. Restricting the dense multivariate Fourier span therefore "
                    + "gives a dense subspace of C(G,C). The averaging operators have norm at most "
                    + "one and Haar integration is continuous, so the observables satisfying the "
                    + "limit form a closed complex subspace containing that dense span.")),
                Paragraph(Text(
                    "This is the classical character proof of compact-group rotation "
                    + "equidistribution. The cited exposition states the ambient Weyl criterion "
                    + "and geometric-series argument and illustrates a proper subtorus; the "
                    + "restriction and Haar-invariance steps here give the complete orbit-closure "
                    + "form. Finite-order and disconnected groups are included."))),
            DescribeRole.Theorem))));

    private static Formula TheoremFormula()
    {
        Formula i = F.Id("I"), g = F.Id("g"), group = F.Id("G"), n = F.Id("n"), size = F.Id("N");
        Formula complex = F.Seq(F.Mathbb, F.Grp(F.Id("C")));
        Formula naturals = F.Seq(F.Mathbb, F.Grp(F.Id("N")));
        Formula torus = F.Seq(F.Mathbb, F.Grp(F.Id("T")));
        Formula haar = F.Seq(F.Mu, F.Underscore, F.Grp(group));
        Formula powers = F.Seq(F.OpenBrace, new Formula.Power(g, n), F.Mid, F.Sp,
            n, F.InMacro, F.Sp, naturals, F.CloseBrace);
        Formula closedPowers = F.Seq(F.Overline, F.Grp(powers));
        Formula cyclic = F.Seq(F.Overline, F.Grp(F.Langle, F.Sp, g, F.Rangle));
        Formula identity = F.Seq(group, F.Eq, cyclic, F.Eq, closedPowers);
        Formula average = new Formula.Fraction(
            F.Seq(F.Sum, F.Underscore, F.Grp(F.D(0), F.Leq, F.Sp, n, F.Lt, size),
                F.Sp, Call("f", new Formula.Power(g, F.Seq(n, F.Plus, F.D(1))))), size);
        Formula limit = F.Seq(F.Lim, F.Underscore, F.Grp(size, F.To, F.Infty), F.Sp,
            average, F.Eq, F.Int, F.Underscore, F.Grp(group), F.Sp,
            Call("f", F.Id("z")), F.Sp, F.Mathrm, F.Grp(F.Id("d")), haar, F.Open, F.Id("z"), F.Close);
        Formula observable = new Formula.BindMany(FormulaQuantifier.ForAll,
            [new Formula.BoundVariable(FormulaIdentifier.Create("f"), Call("C", group, complex))], limit);
        Formula body = F.Seq(identity, F.Comma, F.Sp,
            haar, F.Eq, Call("HaarProbability", group), F.Colon, F.Sp, observable);
        return F.Disp(new Formula.BindMany(FormulaQuantifier.ForAll,
            [new Formula.BoundVariable(FormulaIdentifier.Create("I"), F.Seq(F.Mathrm, F.Grp(F.Id("FiniteTypes")))),
             new Formula.BoundVariable(FormulaIdentifier.Create("g"), new Formula.Power(torus, i))], body));
    }
}
