    private static Formula Equal(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.Equal, right);

    private static Formula And(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.And, right);

    private static Formula Bits(Formula entropy) =>
        new Formula.Fraction(entropy, Call("log", D(2)));

    private static Formula Rank(Formula characters) =>
        Call("finrank", Call("span", Call("range", characters)));

    private static Formula ProfileLaw(Formula characters, Formula sourceLaw) =>
        Call("profileLaw", characters, sourceLaw);

    private static Formula ProfileEntropy(Formula characters, Formula sourceLaw) =>
        Call("H", ProfileLaw(characters, sourceLaw));

    private static Formula ResidualEntropy(Formula characters, Formula sourceLaw) =>
        Call("conditionalEntropy", sourceLaw, Call("profile", characters));

    private static Formula ProfileEntropyFormula()
    {
        Formula group = F.Id("G");
        Formula characters = F.Id("chi");
        Formula uniform = Call("Uniform", group);
        return Disp(Equal(Bits(ProfileEntropy(characters, uniform)), Rank(characters)));
    }

    private static Formula ConditionalEntropyFormula()
    {
        Formula group = F.Id("G");
        Formula characters = F.Id("chi");
        Formula uniform = Call("Uniform", group);
        Formula sourceBits = new Formula.Log(D(2), Call("card", group));
        Formula residualBits = Bits(ResidualEntropy(characters, uniform));
        Formula remaining = new Formula.Binary(
            sourceBits,
            FormulaBinaryOperator.Subtract,
            Rank(characters));
        return Disp(Equal(residualBits, remaining));
    }

    private static Formula ZeroFamilyFormula()
    {
        Formula group = F.Id("G");
        Formula uniform = Call("Uniform", group);
        Formula characters = Call("zeroFamily", F.Id("I"));
        Formula profileZero = Equal(Bits(ProfileEntropy(characters, uniform)), D(0));
        Formula residualFull = Equal(
            Bits(ResidualEntropy(characters, uniform)),
            new Formula.Log(D(2), Call("card", group)));
        return Disp(And(profileZero, residualFull));
    }

    private static Formula EmptyFamilyFormula()
    {
        Formula group = F.Id("G");
        Formula uniform = Call("Uniform", group);
        Formula characters = Call("emptyFamily", group);
        Formula profileZero = Equal(Bits(ProfileEntropy(characters, uniform)), D(0));
        Formula residualFull = Equal(
            Bits(ResidualEntropy(characters, uniform)),
            new Formula.Log(D(2), Call("card", group)));
        return Disp(And(profileZero, residualFull));
    }

    private static Formula SingletonGroupFormula()
    {
        Formula characters = F.Id("chi");
        Formula uniform = Call("Uniform", F.Id("Unit"));
        Formula profileZero = Equal(Bits(ProfileEntropy(characters, uniform)), D(0));
        Formula residualZero = Equal(Bits(ResidualEntropy(characters, uniform)), D(0));
        return Disp(And(profileZero, residualZero));
    }
}
