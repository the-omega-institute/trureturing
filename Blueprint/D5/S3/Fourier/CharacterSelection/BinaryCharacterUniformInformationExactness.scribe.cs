                DescribeId.Create("binary-character-span"),
                DeclarationHandle.Create(Prefix + "binaryCharacterSpan"),
                H("Binary-character span"),
                StatementSource.WithoutFormula(),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "The named span is the binary-linear subspace generated by the character "
                        + "family."))),
