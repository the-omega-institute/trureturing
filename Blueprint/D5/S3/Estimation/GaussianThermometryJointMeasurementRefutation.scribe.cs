    private static Formula Named(string name)
    {
        var parts = name.Split('.');
        var tokens = new List<Formula>();
        for (var index = 0; index < parts.Length; index++)
        {
            if (index > 0) tokens.Add(Dot);
            tokens.Add(F.Id(parts[index]));
        }
        return Seq(Operatorname, Grp(Seq([.. tokens])));
    }
    private static Formula Call(string name, params Formula[] args) => new Formula.Apply(Named(name), [.. args]);
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula All(string name, Formula type, Formula body) => new Formula.Bind(
        FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), type, body);
    private static Formula Eq(Formula left, Formula right) => new Formula.Relation(left, FormulaRelationOperator.Equal, right);
    private static Formula Iff(Formula left, Formula right) => new Formula.Logic(left, FormulaLogicOperator.Iff, Parenthesized(right));
    private static Formula And(Formula left, Formula right) => new Formula.Logic(Parenthesized(left), FormulaLogicOperator.And, Parenthesized(right));
    private static Formula Imp(Formula a, Formula b) => new Formula.Logic(Parenthesized(a), FormulaLogicOperator.Implies, Parenthesized(b));
    private static Formula Le(Formula left, Formula right) => new Formula.Relation(left, FormulaRelationOperator.LessThanOrEqual, right);
    private static Formula Add(Formula left, Formula right) => new Formula.Binary(left, FormulaBinaryOperator.Add, right);
    private static Formula Mul(Formula left, Formula right) => new Formula.Binary(left, FormulaBinaryOperator.Multiply, right);
    private static Formula Reals() => Seq(Mathbb, Grp(F.Id("R")));
    private static Formula Naturals() => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula Matrix(Formula n) => Call("Matrix", Call("Fin", n), Call("Fin", n), Reals());

    private static Formula Twice(Formula n) => Mul(D(2), n);
    private static Formula FinTwice(Formula n) => Call("Fin", Twice(n));
    private static Formula At(Formula f, Formula x) => new Formula.Apply(f, [x]);
    private static Formula Ite(Formula condition, Formula yes, Formula no) =>
        Call("if", condition, yes, no);
    private static Formula Entry(Formula matrix, Formula i, Formula j) =>
        new Formula.Apply(matrix, [i, j]);
    private static Formula ModeIndex(Formula m, Formula i) => Parenthesized(Seq(
        Call("Fin.mk", Call("Nat.div", Call("Fin.val", i), D(2))), Colon, Call("Fin", m)));
    private static Formula Nu(Formula omega, Formula temperature) =>
        Call("coth", Parenthesized(Seq(omega, Slash, Parenthesized(Twice(temperature)))));
    private static Formula CoordinateMap(Formula m)
    {
        Formula x = F.Id("x");
        Formula even = Eq(new Formula.Modulo(Call("Fin.val", x), D(2)), D(0));
        return Parenthesized(Seq(LambdaLower, Sp, x, Colon, FinTwice(m), Comma,
            Ite(even, Call("Sum.inl", ModeIndex(m, x)), Call("Sum.inr", ModeIndex(m, x)))));
    }
    private static Formula SymplecticForm(Formula m) => Call("Matrix.submatrix",
        new Formula.Negate(Call("Matrix.J", Call("Fin", m), Reals())), CoordinateMap(m), CoordinateMap(m));

    private static Formula ThermalNuDerivFormula()
    {
        Formula denominator = Parenthesized(Mul(D(2), new Formula.Power(F.Id("T"), D(2))));
        Formula prefactor = Seq(F.Id("omega"), Slash, denominator);
        Formula square = new Formula.Power(Nu(F.Id("omega"), F.Id("T")), D(2));
        Formula difference = Parenthesized(Add(square, new Formula.Negate(D(1))));
        Formula equation = Eq(Call("thermalNuDeriv", F.Id("omega"), F.Id("T")), Mul(prefactor, difference));
        return Disp(All("omega", Reals(), All("T", Reals(), equation)));
    }

    private static Formula ThermalCovFormula()
    {
        Formula m = F.Id("m"), ω = F.Id("omega"), T = F.Id("T");
        Formula i = F.Id("i"), j = F.Id("j");
        Formula index = ModeIndex(m, i);
        Formula entry = Ite(new Formula.Relation(i, FormulaRelationOperator.Equal, j),
            Nu(At(ω, index), T), D(0));
        Formula equation = Eq(Entry(Call("thermalCov", ω, T), i, j), entry);
        Formula qj = All("j", FinTwice(m), equation);
        Formula qi = All("i", FinTwice(m), qj);
        Formula qT = All("T", Reals(), qi);
        Formula qw = All("omega", new Formula.TypeArrow(Call("Fin", m), Reals()), qT);
        return Disp(All("m", Naturals(), qw));
    }

    private static Formula ThermalCovDerivFormula()
    {
        Formula m = F.Id("m"), ω = F.Id("omega"), T = F.Id("T");
        Formula i = F.Id("i"), j = F.Id("j");
        Formula index = ModeIndex(m, i);
        Formula entry = Ite(new Formula.Relation(i, FormulaRelationOperator.Equal, j),
            Call("thermalNuDeriv", At(ω, index), T), D(0));
        Formula equation = Eq(Entry(Call("thermalCovDeriv", ω, T), i, j), entry);
        Formula qj = All("j", FinTwice(m), equation);
        Formula qi = All("i", FinTwice(m), qj);
        Formula qT = All("T", Reals(), qi);
        Formula qw = All("omega", new Formula.TypeArrow(Call("Fin", m), Reals()), qT);
        return Disp(All("m", Naturals(), qw));
    }

    private static Formula PhysicalFormula()
    {
        Formula m = F.Id("m"), σM = F.Id("sigmaM");
        Formula omega = Call("Matrix.map", SymplecticForm(m), Named("Complex.ofReal"));
        Formula psd = Call("PosSemidef", Add(Call("Matrix.map", σM, Named("Complex.ofReal")), Call("SMul.smul", Named("Complex.I"), omega)));
        Formula body = Iff(Call("IsGaussianMeasurementCov", σM),
            And(Call("IsSymm", σM), psd));
        return Disp(All("m", Naturals(), All("sigmaM", Matrix(Twice(m)), body)));
    }

    private static Formula FisherFormula()
    {
        Formula sum = Add(F.Id("sigma"), F.Id("sigmaM"));
        Formula squared = new Formula.Power(
            Mul(Call("inv", sum), F.Id("d")), D(2));
        Formula rhs = Mul(Seq(D(1), Slash, D(2)), Call("trace", squared));
        Formula equation = Eq(Call("fisherC", F.Id("sigma"), F.Id("d"), F.Id("sigmaM")), rhs);
        return Disp(All("n", Naturals(),
            All("sigma", Matrix(F.Id("n")),
                All("d", Matrix(F.Id("n")),
                    All("sigmaM", Matrix(F.Id("n")), equation)))));
    }

    private static Formula LocalCovFormula()
    {
        Formula m = F.Id("m"), M = F.Id("M"), i = F.Id("i"), j = F.Id("j");
        Formula subindex(Formula x) => Parenthesized(Seq(
            Call("Fin.mk", Call("Nat.mod", Call("Fin.val", x), D(2))), Colon, Call("Fin", D(2))));
        Formula value = Entry(At(M, ModeIndex(m, i)), subindex(i), subindex(j));
        Formula equation = Eq(Entry(Call("localCov", M), i, j),
            Ite(Eq(ModeIndex(m, i), ModeIndex(m, j)), value, D(0)));
        return Disp(All("m", Naturals(), All("M", new Formula.TypeArrow(Call("Fin", m), Matrix(D(2))),
            All("i", FinTwice(m), All("j", FinTwice(m), equation)))));
    }

    private static Formula LocalFisherFormula()
    {
        Formula m = F.Id("m"), ω = F.Id("omega"), T = F.Id("T"), M = F.Id("M"), f = F.Id("f");
        Formula physical = All("k", Call("Fin", m), Call("IsGaussianMeasurementCov", At(M, F.Id("k"))));
        Formula value = Call("fisherC", Call("thermalCov", ω, T), Call("thermalCovDeriv", ω, T), Call("localCov", M));
        Formula members = new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create("M"),
            new Formula.TypeArrow(Call("Fin", m), Matrix(D(2))), And(physical, Eq(f, value)));
        Formula set = Call("Set.setOf", Parenthesized(Seq(LambdaLower, Sp, f, Colon, Reals(), Comma, members)));
        return Disp(All("m", Naturals(), All("omega", new Formula.TypeArrow(Call("Fin", m), Reals()),
            All("T", Reals(), Eq(Call("localFisher", ω, T), Call("sSup", set))))));
    }

    private static Formula ClaimFormula()
    {
        Formula m = F.Id("m"), ω = F.Id("omega"), T = F.Id("T"), σM = F.Id("sigmaM"), k = F.Id("k");
        Formula body = Le(Call("fisherC", Call("thermalCov", ω, T), Call("thermalCovDeriv", ω, T), σM),
            Call("localFisher", ω, T));
        body = Imp(Call("IsGaussianMeasurementCov", σM), body);
        body = All("sigmaM", Matrix(Twice(m)), body);
        body = Imp(new Formula.Relation(D(0), FormulaRelationOperator.LessThan, T), body);
        Formula positiveFrequencies = All("k", Call("Fin", m),
            new Formula.Relation(D(0), FormulaRelationOperator.LessThan, At(ω, k)));
        body = Imp(positiveFrequencies, body);
        body = All("T", Reals(), body);
        body = All("omega", new Formula.TypeArrow(Call("Fin", m), Reals()), body);
        body = All("m", Naturals(), body);
        return Disp(Iff(F.Id("claim"), body));
    }
