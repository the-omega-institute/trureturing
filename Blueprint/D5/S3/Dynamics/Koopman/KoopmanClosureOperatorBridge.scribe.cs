using static StrataLint.Scribe.DefinitionDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Dynamics.Koopman;

internal sealed class KoopmanClosureOperatorBridgeDocument
    : IScribeDocumentDefinition
{
    private const string Prefix =
        "D5/S3/Dynamics/Koopman/KoopmanClosureOperatorBridge.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Existing observable Koopman generators are exactly finite iterates of the first-class discrete Koopman operator.",
        H("Koopman Closure Operator Bridge"),
        Blocks(
            Def("generators", "operatorKoopmanGenerators", "Operator-generated Koopman observables",
                "The generator set contains finite Koopman iterates of observables constant on the source relation fibers."),
            Thm("equality", "operatorKoopmanGenerators_eq_existing", "Operator and existing generators coincide",
                "The first-class iterate notation is definitionally the same pullback family already used by the repository closure."),
            Thm("closure", "koopmanClosure_eq_adjoin_operatorIterates", "Existing closure is the operator-iterate adjoin",
                "The frozen Koopman closure is exactly the star algebra generated by finite first-class operator iterates."),
            Thm("source", "sourceObservable_mem_operatorKoopmanGenerators", "Source observables enter at depth zero",
                "Every source-fiber observable belongs to the operator generator set without applying an update."),
            Thm("successor", "koopmanIterate_succ_mem_operatorKoopmanGenerators", "Further pullback advances generator depth",
                "Applying any finite positive number of Koopman pulls remains inside the operator generator family.")),
        [
            DocumentEdge.Dependency.Create(GidRef.Create(
                "D5/S3/Dynamics/Koopman/DiscreteKoopmanOperator")),
            DocumentEdge.Dependency.Create(GidRef.Create(
                "D5/S3/QuantumStates/ObservableAlgebraClosureDuality")),
        ]));

    private static DocumentBlock.Describe Def(string id, string declaration, string heading, string paragraph) =>
        Describe.Lean(DescribeId.Create(id), DeclarationHandle.Create(Prefix + declaration), H(heading),
            StatementSource.WithoutFormula(), AssessedProvenance.FromRepo(),
            Blocks(Paragraph(Text(paragraph))), DescribeRole.Definition);

    private static DocumentBlock.Describe Thm(string id, string declaration, string heading, string paragraph) =>
        Describe.Lean(DescribeId.Create(id), DeclarationHandle.Create(Prefix + declaration), H(heading),
            StatementSource.WithoutFormula(), AssessedProvenance.FromRepo(),
            Blocks(Paragraph(Text(paragraph))), DescribeRole.Theorem);
}
