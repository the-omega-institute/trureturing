    private static Formula ResponsesFormula()
    {
        Formula identities = All("β", Arrow(FinOf("m"), Reals()),
            Imp(Equal(SumOver("b", FinOf("m"), Smul(Typed(At(X("β"), X("b")), Complexes()), At(X("M"), X("b")))), D(0)),
                Equal(SumOver("b", FinOf("m"), Mul(At(X("β"), X("b")), At(X("r"), X("b")))), D(0))));
        Formula body = SetOf("r", Arrow(FinOf("m"), Reals()), And(
            All("b", FinOf("m"), LE(D(0), At(X("r"), X("b")))),
            And(Equal(SumOver("b", FinOf("m"), At(X("r"), X("b"))), D(1)), identities)));
        return MeasurementBinders(Equal(LocalCall("responsePolytope", X("M")), body));
    }

    private static Formula TableFormula()
    {
        Formula preparationSum = SumIn("a", X("s"),
            Smul(Typed(At(X("α"), X("a")), Complexes()), At(X("ρ"), X("a"))));
        Formula weightSum = SumIn("a", X("s"),
            Mul(At(X("α"), X("a")), At(X("μ"), X("a"), X("l"))));
        Formula identity = All("l", X("Λ"), All("s", At(Qualified("Finset"), X("ι")),
            All("α", Arrow(X("ι"), Reals()), Imp(Equal(preparationSum, D(0)), Equal(weightSum, D(0))))));
        Formula positivity = All("a", X("ι"), All("l", X("Λ"),
            LE(D(0), At(X("μ"), X("a"), X("l")))));
        Formula normalization = All("a", X("ι"), At(Qualified("HasSum"), At(X("μ"), X("a")), D(1)));
        Formula responses = All("l", X("Λ"),
            Member(At(X("ξ"), X("l")), LocalCall("responsePolytope", X("M"))));
        Formula reconstruction = All("a", X("ι"), All("b", FinOf("m"), At(Qualified("HasSum"),
            LambdaOf("l", X("Λ"), Mul(At(X("ξ"), X("l"), X("b")), At(X("μ"), X("a"), X("l")))),
            At(X("p"), X("a"), X("b")))));
        Formula model = Some("Λ", Qualified("Type"), Some("μ", Arrow(X("ι"), Arrow(X("Λ"), Reals())),
            Some("ξ", Arrow(X("Λ"), Arrow(FinOf("m"), Reals())),
                And(positivity, And(normalization, And(responses, And(identity, reconstruction)))))));
        return All("d", Naturals(), All("m", Naturals(), All("ι", Qualified("Type"),
            All("ρ", Arrow(X("ι"), Mat()), All("M", Arrow(FinOf("m"), Mat()),
                All("p", Arrow(X("ι"), Arrow(FinOf("m"), Reals())),
                    IffOf(LocalCall("NoncontextualTable", X("ρ"), X("M"), X("p")), model)))))));
    }

    private static Formula ClassicalFormula()
    {
        Formula states = Seq(OpenBrace, X("ρ"), Colon, Sp, Mat(), Sp,
            Slash, Slash, Sp, Density(X("ρ")), CloseBrace);
        Formula preparations = LambdaOf("ρ", states, At(Qualified("val"), X("ρ")));
        Formula probabilities = LambdaOf("ρ", states, LambdaOf("b", FinOf("m"),
            Born(At(Qualified("val"), X("ρ")), At(X("M"), X("b")))));
        return MeasurementBinders(IffOf(LocalCall("Classical", X("M")),
            LocalCall("NoncontextualTable", preparations, X("M"), probabilities)));
    }

    private static Formula ClaimBody()
    {
        Formula score = SumOver("a", FinOf("n"), SumOver("b", FinOf("m"),
            Mul(At(X("w"), X("a"), X("b")), At(X("p"), X("a"), X("b")))));
        Formula quantumScore = SumOver("a", FinOf("n"), SumOver("b", FinOf("m"),
            Mul(At(X("w"), X("a"), X("b")), Born(At(X("ρ"), X("a")), At(X("M"), X("b"))))));
        Formula conclusion = Some("n", Naturals(), Some("ρ", Arrow(FinOf("n"), Mat()),
            Some("w", Arrow(FinOf("n"), Arrow(FinOf("m"), Reals())), Some("c", Reals(),
                And(All("a", FinOf("n"), Density(At(X("ρ"), X("a")))),
                    And(All("p", Arrow(FinOf("n"), Arrow(FinOf("m"), Reals())),
                        Imp(LocalCall("NoncontextualTable", X("ρ"), X("M"), X("p")), LE(score, X("c")))),
                        Less(X("c"), quantumScore)))))));
        return All("d", Naturals(), Imp(Less(D(0), X("d")), All("m", Naturals(), Imp(Less(D(0), X("m")),
            All("M", Arrow(FinOf("m"), Mat()), Imp(
                At(Qualified("D5", "S3", "Quantum", "QuantumChannels", "ConcealmentKernelNecessityRefutation", "IsPOVM"), X("M")),
                Imp(new Formula.Not(Parenthesized(LocalCall("Classical", X("M")))), conclusion)))))));
    }

    private static Formula X(string name) => name switch
    {
        "ρ" => Rho, "ι" => Iota, "μ" => Mu, "ξ" => Xi, "Λ" => Lambda,
        "α" => Alpha, "β" => Beta, _ => F.Id(name),
    };
    private static Formula Qualified(params string[] parts)
    {
        var items = new System.Collections.Generic.List<Formula>();
        foreach (var part in parts)
        {
            if (items.Count > 0) items.Add(Dot);
            items.Add(F.Id(part));
        }
        return Seq(Operatorname, Grp(Seq([.. items])));
    }
    private static Formula Local(string name) => Qualified("D5", "S3", "QuantumContext", "FinitePreparationCertification", name);
    private static Formula LocalCall(string name, params Formula[] arguments) => At(Local(name), arguments);
    private static Formula At(Formula function, params Formula[] arguments) => new Formula.Apply(function, [.. arguments]);
    private static Formula Parenthesized(Formula body) => Seq(Left, Open, body, Right, Close);
    private static Formula Typed(Formula value, Formula type) => Parenthesized(Seq(value, Colon, Sp, type));
    private static Formula Naturals() => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula Reals() => Seq(Mathbb, Grp(F.Id("R")));
    private static Formula Complexes() => Seq(Mathbb, Grp(F.Id("C")));
    private static Formula FinOf(string size) => At(Qualified("Fin"), X(size));
    private static Formula Mat() => At(Qualified("Matrix"), FinOf("d"), FinOf("d"), Complexes());
    private static Formula Arrow(Formula domain, Formula codomain) => new Formula.TypeArrow(Parenthesized(domain), Parenthesized(codomain));
    private static Formula SetOf(string name, Formula type, Formula body) => Seq(OpenBrace, X(name), Colon, Sp, type, Sp, Mid, Sp, body, CloseBrace);
    private static Formula All(string name, Formula type, Formula body) => Seq(Forall, Sp, Typed(X(name), type), Comma, Sp, Parenthesized(body));
    private static Formula Some(string name, Formula type, Formula body) => Seq(Exists, Sp, Typed(X(name), type), Comma, Sp, Parenthesized(body));
    private static Formula LambdaOf(string name, Formula type, Formula body) => Seq(LambdaLower, Sp, Typed(X(name), type), Sp, Mapsto, Sp, Parenthesized(body));
    private static Formula And(Formula left, Formula right) => new Formula.Logic(Parenthesized(left), FormulaLogicOperator.And, Parenthesized(right));
    private static Formula Imp(Formula left, Formula right) => new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Implies, Parenthesized(right));
    private static Formula IffOf(Formula left, Formula right) => new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Iff, Parenthesized(right));
    private static Formula Equal(Formula left, Formula right) => new Formula.Relation(left, FormulaRelationOperator.Equal, right);
    private static Formula LE(Formula left, Formula right) => new Formula.Relation(left, FormulaRelationOperator.LessThanOrEqual, right);
    private static Formula Less(Formula left, Formula right) => new Formula.Relation(left, FormulaRelationOperator.LessThan, right);
    private static Formula Member(Formula left, Formula right) => new Formula.Relation(left, FormulaRelationOperator.MemberOf, right);
    private static Formula Mul(Formula left, Formula right) => new Formula.Binary(Parenthesized(left), FormulaBinaryOperator.Multiply, Parenthesized(right));
    private static Formula Smul(Formula scalar, Formula value) => Seq(Parenthesized(scalar), Sp, Cdot, Sp, Parenthesized(value));
    private static Formula SumOver(string name, Formula type, Formula body) => Seq(new Formula.Subscript(Sum, Seq(X(name), Colon, Sp, type)), Sp, Parenthesized(body));
    private static Formula SumIn(string name, Formula set, Formula body) => Seq(new Formula.Subscript(Sum, Member(X(name), set)), Sp, Parenthesized(body));
    private static Formula Density(Formula matrix) => At(Qualified("D5", "S3", "QuantumChannels", "CoPRelativeQuantumnessRefutation", "IsDensity"), matrix);
    private static Formula Born(Formula state, Formula effect) => At(Qualified("Complex", "re"),
        At(Qualified("D5", "S3", "Quantum", "FiniteDimensional", "bornProbability"), state, effect));
    private static Formula MeasurementBinders(Formula body) => All("d", Naturals(), All("m", Naturals(), All("M", Arrow(FinOf("m"), Mat()), body)));
}
