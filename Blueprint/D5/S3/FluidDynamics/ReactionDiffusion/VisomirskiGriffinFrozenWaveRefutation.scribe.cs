    private static DocumentBlock Node(string name, string title, Formula formula, string prose,
        DescribeRole role, bool literature = false) =>
        Describe.Lean(DescribeId.Create("visomirski-griffin-" + name.ToLowerInvariant()),
            DeclarationHandle.Create(Prefix + name), H(title), StatementSource.FromAuthor(Disp(formula)),
            literature ? AssessedProvenance.FromLiterature(Source) : AssessedProvenance.FromRepo(Source),
            Blocks(Paragraph(Text(prose))), role);

    private static Formula Sites() => Call("Fin", Mul(D(2), A("n")));
    private static Formula U() => Ty(Sites(), R(), R(), R());
    private static Formula V() => Ty(Sites(), R(), R());
    private static Formula CastN() => Parenthesized(Seq(A("n"), Colon, Sp, R()));
    private static Formula Denom() => Mul(D(2), CastN());
    private static Formula Equilibrium() => Call("equilibrium", A("n"));
    private static Formula Species(Formula body) => All("i", Sites(), body);
    private static Formula UV(Formula u, Formula t, Formula x) => Apply(u, A("i"), t, x);
    private static Formula Component(Formula u) => Apply(u, A("i"));
    private static Formula Vec(Formula u, Formula t, Formula x) =>
        Lam("j", Sites(), Apply(u, A("j"), t, x));
    private static Formula RealData(Formula x) => Call("initialData", A("n"), A("i"), x);
    private static Formula Classical(Formula u, Formula a, Formula d) => Call("ClassicalSolution", A("n"), a, d, u);
    private static Formula Distance(Formula f, Formula g) => Call("distanceSq", f, g);
    private static Formula ConstantEq() => Call("Function.const", R(), Equilibrium());
    private static Formula MatrixFormula()
    {
        var n = A("n"); var a = A("a"); var i = A("i"); var j = A("j");
        var one = Call("Fin.mk", Call("Nat.mod", D(1), Mul(D(2), n)));
        return All("n", N(), All("a", R(), All("i", Sites(), All("j", Sites(),
            Eq(Call("biasedMatrix", n, a, i, j), Call("ite", Eq(j, Call("Fin.sub", i, one)), Add(D(1), a),
                Call("ite", Eq(j, Call("Fin.add", i, one)), Minus(D(1)), D(0))))))));
    }
    private static Formula ReactionFormula()
    {
        var z = A("z"); var mat = Call("biasedMatrix", A("n"), A("a")); var vec = Call("Matrix.mulVec", mat, z);
        return All("n", N(), All("a", R(), All("z", Ty(Sites(), R()), All("i", Sites(),
            Eq(Call("reaction", A("n"), A("a"), z, A("i")),
                Mul(Apply(z, A("i")), Sub(Apply(vec, A("i")), Call("dotProduct", z, vec))))))));
    }
    private static Formula InitialFormula() => All("n", N(), Species(All("x", R(), Eq(
        RealData(A("x")), Call("ite", Eq(Call("Nat.mod", Call("val", A("i")), D(2)), D(0)),
            Div(Add(D(1), Call("Real.sin", A("x"))), Denom()), Div(Sub(D(1), Call("Real.sin", A("x"))), Denom()))))));
    private static Formula EquilibriumFormula() => All("n", N(), Eq(Equilibrium(), Div(D(1), Denom())));
    private static Formula ClassicalFormula()
    {
        var u = A("u"); var t = A("t"); var x = A("x"); var w = Component(u);
        var td = Lam("t", R(), Lam("x", R(), Dt(w, t, x)));
        var xd = Lam("t", R(), Lam("x", R(), Dx(w, t, x)));
        var xxd = Lam("t", R(), Lam("x", R(), Dxx(w, t, x)));
        var clauses = Ands(
            Species(Cont(w, false)), Species(NonnegTime(Call("Function.Periodic", Apply(w, t), Period()))),
            Species(PosTime(All("x", R(), Call("HasDerivAt", Lam("r", R(), Value(w, A("r"), x)), Dt(w, t, x), t)))),
            Species(PosTime(All("x", R(), Call("HasDerivAt", Apply(w, t), Dx(w, t, x), x)))),
            Species(PosTime(All("x", R(), Call("HasDerivAt", Call("deriv", Apply(w, t)), Dxx(w, t, x), x)))),
            Species(Cont(td, true)), Species(Cont(xd, true)), Species(Cont(xxd, true)),
            Species(PosTime(All("x", R(), Eq(Dt(w, t, x), Add(Call("reaction", A("n"), A("a"), Vec(u, t, x), A("i")),
                Mul(A("D"), Dxx(w, t, x))))))),
            Species(All("x", R(), Eq(UV(u, D(0), x), RealData(x)))));
        return All("n", N(), All("a", R(), All("D", R(), All("u", U(), Iff(Classical(u, A("a"), A("D")), clauses)))));
    }
    private static Formula DistanceFormula() => All("f", Fns(), All("g", Fns(),
        Eq(Distance(A("f"), A("g")), Interval(Pow(Sub(Apply(A("f"), A("x")), Apply(A("g"), A("x"))), 2)))));
    private static Formula HomogenizesFormula() => All("n", N(), All("u", U(), Iff(Call("Homogenizes", A("n"), A("u")),
        Species(LimitZero(Lam("t", R(), Distance(Apply(A("u"), A("i"), A("t")), ConstantEq())))))));
    private static Formula FrozenFormula()
    {
        var u = A("u"); var v = A("v");
        return All("n", N(), All("u", U(), All("v", V(), Iff(Call("FrozenWaveLimit", A("n"), u, v), Ands(
            Species(Call("Continuous", Apply(v, A("i")))), Species(Call("Function.Periodic", Apply(v, A("i")), Period())),
            Some("i", Sites(), Some("x", R(), Ne(Apply(v, A("i"), A("x")), Equilibrium()))),
            Species(LimitZero(Lam("t", R(), Distance(Apply(u, A("i"), A("t")), Apply(v, A("i")))))))))));
    }
    private static Formula ClaimFormula() => Iff(Named("claim"), All("n", N(), Imp(Leq(D(2), A("n")),
        Some("u", U(), Some("v", V(), Conj(Classical(A("u"), Minus(Div(D(1), D(2))), Div(D(1), D(1,0,0))),
            Call("FrozenWaveLimit", A("n"), A("u"), A("v"))))))));

    private static Formula R() => Seq(Mathbb, Grp(F.Id("R")));
    private static Formula N() => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula A(string name) => F.Id(name);
    private static Formula Named(string name)
    {
        var items = new List<Formula>();
        foreach (var part in name.Split('.'))
        {
            if (items.Count > 0) items.Add(Dot);
            items.Add(F.Id(part));
        }
        return Seq(Operatorname, Grp(Seq([.. items])));
    }
    private static Formula Call(string name, params Formula[] args) =>
        new Formula.Apply(Named(name), [.. args]);
    private static Formula Apply(Formula f, params Formula[] args) => new Formula.Apply(f, [.. args]);
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula Eq(Formula l, Formula r) => new Formula.Relation(l, FormulaRelationOperator.Equal, r);
    private static Formula Ne(Formula l, Formula r) => new Formula.Relation(l, FormulaRelationOperator.NotEqual, r);
    private static Formula Leq(Formula l, Formula r) => new Formula.Relation(l, FormulaRelationOperator.LessThanOrEqual, r);
    private static Formula Lt(Formula l, Formula r) => new Formula.Relation(l, FormulaRelationOperator.LessThan, r);
    private static Formula Add(Formula l, Formula r) => new Formula.Binary(l, FormulaBinaryOperator.Add, r);
    private static Formula Sub(Formula l, Formula r) => new Formula.Binary(l, FormulaBinaryOperator.Subtract, r);
    private static Formula Mul(Formula l, Formula r) => new Formula.Binary(l, FormulaBinaryOperator.Multiply, r);
    private static Formula Div(Formula l, Formula r) => new Formula.Fraction(l, r);
    private static Formula Pow(Formula b, byte p) => new Formula.Power(b, D(p));
    private static Formula Minus(Formula f) => new Formula.Negate(f);
    private static Formula All(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), type, body);
    private static Formula Some(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create(name), type, body);
    private static Formula Imp(Formula p, Formula q) =>
        new Formula.Logic(Parenthesized(p), FormulaLogicOperator.Implies, Parenthesized(q));
    private static Formula Conj(Formula p, Formula q) =>
        new Formula.Logic(Parenthesized(p), FormulaLogicOperator.And, Parenthesized(q));
    private static Formula Iff(Formula p, Formula q) =>
        new Formula.Logic(Parenthesized(p), FormulaLogicOperator.Iff, Parenthesized(q));
    private static Formula Ands(params Formula[] ps) => ps.Aggregate(Conj);
    private static Formula Ty(params Formula[] types) => types.Length == 1 ? types[0] :
        new Formula.TypeArrow(types[0], Ty(types.Skip(1).ToArray()));
    private static Formula Lam(string name, Formula type, Formula body) =>
        Parenthesized(Seq(Named("fun"), Sp, A(name), Colon, Sp, type, Sp, Mapsto, Sp, body));
    private static Formula Fns() => Ty(R(), R());
    private static Formula PiR() => Named("Real.pi");
    private static Formula Period() => Mul(D(2), PiR());
    private static Formula Interval(Formula body) =>
        Seq(Int, Underscore, Grp(Minus(PiR())), Caret, Grp(PiR()), Sp, body, Sp, A("dx"));
    private static Formula Value(Formula w, Formula t, Formula x) => Apply(w, t, x);
    private static Formula Dt(Formula w, Formula t, Formula x) =>
        Call("deriv", Lam("r", R(), Value(w, A("r"), x)), t);
    private static Formula Dx(Formula w, Formula t, Formula x) => Call("deriv", Apply(w, t), x);
    private static Formula Dxx(Formula w, Formula t, Formula x) =>
        Call("deriv", Call("deriv", Apply(w, t)), x);
    private static Formula Uncurry(Formula w) => Call("Function.uncurry", w);
    private static Formula Product(Formula l, Formula r) => Seq(l, Sp, Times, Sp, r);
    private static Formula Strip(bool positive) => Product(Call(positive ? "Set.Ioi" : "Set.Ici", D(0)), Named("Set.univ"));
    private static Formula Cont(Formula w, bool positive) => Call("ContinuousOn", Uncurry(w), Strip(positive));
    private static Formula PosTime(Formula body) => All("t", R(), Imp(Lt(D(0), A("t")), body));
    private static Formula NonnegTime(Formula body) => All("t", R(), Imp(Leq(D(0), A("t")), body));
    private static Formula LimitZero(Formula f) => Call("Tendsto", f, Named("Filter.atTop"), Call("nhds", D(0)));
}
