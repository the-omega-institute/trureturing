using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Quantum.Entanglement.AbsolutePPT;

internal sealed class NonnegativeKernelCofactorDocument : IScribeDocumentDefinition
{
    private const string Root = "D5/S3/Quantum/Entanglement/AbsolutePPT/NonnegativeKernelCofactor.";
    private static Formula N => Seq(Mathbb, Grp(F.Id("N")));

    private static Formula TypeName(string name) => Seq(Operatorname, Grp(F.Id(name)));
    private static Formula NamedCall(string name, params Formula[] arguments) =>
        new Formula.Apply(F.Id(name), [.. arguments]);
    private static Formula Arrow(Formula left, Formula right) => Seq(left, Sp, To, Sp, right);
    private static Formula Fin(Formula n) => Seq(TypeName("Fin"), Open, n, Close);
    private static Formula Matrix(Formula rows, Formula columns) =>
        Seq(TypeName("Matrix"), Open, rows, Comma, Sp, columns, Comma, Sp, Seq(Mathbb, Grp(F.Id("R"))), Close);
    private static Formula Embedding(Formula source, Formula target) =>
        Seq(TypeName("Embedding"), Open, source, Sp, To, Sp, target, Close);
    private static Formula LiftCofStatement()
    {
        var real = Seq(Mathbb, Grp(F.Id("R")));
        var result = Arrow(F.Id("J"), real);
        var columns = Embedding(Fin(Seq(F.Id("k"), Plus, D(1))), F.Id("J"));
        var rowEmbedding = Seq(OpenBrace, F.Id("k"), Sp, Colon, Sp, N, CloseBrace, Sp,
            Embedding(Fin(F.Id("k")), Fin(F.Id("m"))));
        var domain = Arrow(Matrix(Fin(F.Id("m")), F.Id("J")),
            Arrow(rowEmbedding, Arrow(columns, result)));
        return Disp(Seq(TypeName("liftCof"), Sp, Colon, Sp,
            OpenBrace, F.Id("J"), Sp, Colon, Sp, TypeName("Type"), CloseBrace, Sp,
            OpenBracket, TypeName("Fintype"), Sp, F.Id("J"), CloseBracket, Sp,
            OpenBrace, F.Id("m"), Sp, Colon, Sp, N, CloseBrace, Sp, domain));
    }

    private static Formula CofactorCandidatesStatement()
    {
        var real = Seq(Mathbb, Grp(F.Id("R")));
        var result = Seq(TypeName("Set"), Sp, Open, Arrow(F.Id("J"), real), Close);
        var domain = Arrow(Matrix(Fin(F.Id("m")), F.Id("J")), result);
        return Disp(Seq(TypeName("cofactorCandidates"), Sp, Colon, Sp,
            OpenBrace, F.Id("J"), Sp, Colon, Sp, TypeName("Type"), CloseBrace, Sp,
            OpenBracket, TypeName("Fintype"), Sp, F.Id("J"), CloseBracket, Sp,
            OpenBrace, F.Id("m"), Sp, Colon, Sp, N, CloseBrace, Sp, domain));
    }

    private static Formula CircuitCompleteStatement() => Disp(Seq(
        NamedCall("Circuit", F.Id("B"), F.Id("v")), Sp, Rightarrow, Sp,
        Exists, Sp, F.Id("k"), Sp, Colon, Sp, N, Sp, Comma, Sp,
        F.Id("cofactorRepresentative")));

    private static Formula ConeCharacterizationStatement() => Disp(Seq(
        NamedCall("InKernel", F.Id("B"), F.Id("x")), Sp, Iff, Sp,
        F.Id("x"), Sp, InMacro, Sp,
        NamedCall("hull", NamedCall("cofactorCandidates", F.Id("B")))));

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Every finite real nonnegative kernel is generated by oriented cofactor vectors from row minors of the appropriate support size.",
        H("Cofactor completeness of nonnegative kernels"),
        Blocks(
            Describe.Lean(DescribeId.Create("nonnegative-kernel-lift-cofactor"),
                DeclarationHandle.Create(Root + "liftCof"),
                H("Zero extension of signed cofactors"),
                StatementSource.FromAuthor(LiftCofStatement()), AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text("Choose k rows and k+1 columns by embeddings. Take the signed cofactors of that rectangular submatrix and extend them by zero to the ambient coordinate type. Cofactor j is exactly (-1) to the natural value of j times the determinant after deleting column j with succAbove. No order on the ambient finite coordinate type is required."))),
                DescribeRole.Definition),
            Describe.Lean(DescribeId.Create("nonnegative-kernel-cofactor-candidates"),
                DeclarationHandle.Create(Root + "cofactorCandidates"),
                H("Qualifying cofactor vectors"),
                StatementSource.FromAuthor(CofactorCandidatesStatement()), AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text("For each k at most the number of original rows, select k rows, k+1 columns and one of the two signs. Retain exactly the nonzero zero-extended vectors that are nonnegative and satisfy every original row equation. The full-kernel filter is essential when fewer rows are selected. The parameter families are finite, but this theorem does not enumerate or count their distinct rays."))),
                DescribeRole.Definition),
            Describe.Lean(DescribeId.Create("nonnegative-kernel-circuit-cofactor-complete"),
                DeclarationHandle.Create(Root + "circuit_cofactor_complete"),
                H("Every circuit has a cofactor representative"),
                StatementSource.FromAuthor(CircuitCompleteStatement()), AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text("The compiled declaration retains arbitrary finite J with its Fintype instance, arbitrary m, the full real matrix B and vector v, the Circuit witness, and every existential witness and conjunct in the result: row and column embeddings, orientation, positive scale, support equality, nonzero cofactor, all original row equations, nonzero zero-extended vector, and exact proportionality. A circuit with support size k+1 is a strictly positive multiple of an oriented cofactor vector with the same support. Deleting one supported column leaves independent columns. The restricted matrix has rank k: those deleted columns give the lower bound, while its strictly positive kernel vector and rank-nullity give the upper bound. A basis selected from its rows yields a nonzero k by k minor. Apply CofactorKernel.kernel_cross_identity to the strictly positive restricted vector. Its positive coordinate sum and the nonzero cofactor force a nonzero augmented determinant, determine one of the two orientations, and give positive proportionality at every coordinate. This is the classical finite-dimensional elementary-vector/cofactor argument. Zero extension reconstructs the original vector. Dividing the full original row equations by the positive factor proves full kernel membership of the cofactor representative.")),
                    Paragraph(Text("No nonempty ambient coordinate type, positive row count, full row rank or sign restriction on matrix entries is assumed. A circuit itself has nonempty support. For support one, k is zero and the empty minor has determinant one. With no rows or an all-zero matrix, singleton circuits are included. Dependent and zero rows require no padding."))),
                DescribeRole.Theorem),
            Describe.Lean(DescribeId.Create("nonnegative-kernel-cofactor-cone-characterization"),
                DeclarationHandle.Create(Root + "nonnegKernel_iff_mem_hull_cofactorCandidates"),
                H("Exact cone characterization"),
                StatementSource.FromAuthor(ConeCharacterizationStatement()), AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text("A vector is a nonnegative solution of all original equations if and only if it belongs to the pointed conic hull of qualifying cofactor vectors. The forward implication consumes the existing circuit decomposition and replaces each circuit by its positive multiple of a qualifying cofactor vector. The reverse implication uses closure of the full nonnegative kernel under addition and nonnegative scaling. Zero belongs to the hull even when the coordinate type and candidate set are empty. No second support-descent argument is used."))),
                DescribeRole.Theorem),
            Paragraph(Text("For three equations, the theorem includes row selections of sizes zero through three and supports of sizes one through four. Using only cofactors of all three rows can miss degenerate circuits. To certify a particular finite list, every qualifying candidate must be shown positively proportional to an entry of that list, with column and row reorderings accounted for under this sign convention. No completeness or count certificate for a list of 187 rays is asserted here, and no final APPT purity claim follows without that additional consumer and the exact slack and spectrum reconstruction.")))));
}
