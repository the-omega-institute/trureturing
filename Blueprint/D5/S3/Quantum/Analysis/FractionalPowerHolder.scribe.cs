using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Quantum.Analysis;

internal sealed class FractionalPowerHolderDocument : IScribeDocumentDefinition
{
    private static readonly Formula A = F.Id("A"), Aa = F.Id("a"), B = F.Id("b"), P = F.Id("p");
    private static readonly LibraryNoteRef Source = LibraryNoteRef.Create("D5/L/HilbertOperators/kittanehkosaki1987powers");

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Fractional powers are uniformly Holder continuous on the positive cone.",
        H("Noncommuting fractional powers without a spectral gap"),
        Blocks(
            Describe.Lean(DescribeId.Create("positive-fractional-power-holder"),
                DeclarationHandle.Create("D5/S3/Quantum/Analysis/FractionalPowerHolder.norm_rpow_sub_rpow_le"),
                H("Dimension-free positive-cone estimate"),
                StatementSource.FromAuthor(All([
                    new(FormulaIdentifier.Create("A"), F.Id("OrderedUnitalComplexCStarAlgebra")),
                    new(FormulaIdentifier.Create("a"), A),
                    new(FormulaIdentifier.Create("b"), A),
                    new(FormulaIdentifier.Create("p"), F.Id("Real"))],
                    Imp(Conj(Le(D(0), Aa), Conj(Le(D(0), B),
                        Conj(Lt(D(0), P), Le(P, D(1))))),
                        Le(Call("norm", Call("subtract", Call("rpow", Aa, P), Call("rpow", B, P))),
                            Call("rpow", Call("norm", Call("subtract", Aa, B)), P))))),
                AssessedProvenance.FromLiterature(Source),
                Blocks(
                    Paragraph(Text("For every ordered unital complex C-star algebra, positive a and b, "
                        + "and real exponent 0<p<=1, the norm of a^p-b^p is at most the pth power "
                        + "of the norm of a-b. The order is the C-star positive-cone order. "
                        + "The inputs need not commute or be invertible. The algebra may be trivial "
                        + "and no dimension or positive lower spectral bound enters the estimate.")),
                    Paragraph(Text("Set delta=norm(a-b). Self-adjoint norm bounds give a<=b+delta I "
                        + "and b<=a+delta I. Operator monotonicity compares their pth powers. For "
                        + "each positive x and t>=0, scalar subadditivity on the spectrum of x and "
                        + "continuous functional calculus give (x+t I)^p<=x^p+t^p I. This step "
                        + "takes place in the commutative algebra generated by x and the identity. "
                        + "The two comparisons bound a^p-b^p between plus and minus delta^p I, "
                        + "so its norm is at most delta^p. Continuity of the scalar power at zero "
                        + "retains zero spectral values.")),
                    Paragraph(Text("Kittaneh and Kosaki, Theorem 2.3, prove the corresponding "
                        + "operator-norm inequality for operator-monotone functions continuous at "
                        + "zero and vanishing there, on arbitrary Hilbert spaces. Fractional powers are a classical "
                        + "special case. The present statement uses an abstract unital C-star "
                        + "algebra and proves the estimate from the pinned functional-calculus "
                        + "and operator-monotonicity results. No mathematical novelty is claimed."))),
                DescribeRole.Theorem),
            Paragraph(Text("Let rho be a positive trace-class operator of trace one on an arbitrary "
                + "complex Hilbert space. Let P project onto finitely many vectors of a full "
                + "Hilbert basis, and let q be the discarded diagonal mass. The existing "
                + "TraceClassCompression.norm_sub_compress_le gives trace-norm error at most "
                + "2 sqrt(q), and opNorm_le_traceNorm bounds the operator norm by that trace "
                + "norm. Applying the positive-cone estimate in the bounded-operator C-star "
                + "algebra, followed by scalar monotonicity, gives "
                + "norm(rho^p-(P rho P)^p)<=(2 sqrt(q))^p for 0<p<=1.")),
            Paragraph(Text("These powers are bounded operators on the original Hilbert space. "
                + "The power rho^p need not be trace class when p<1. The compressed power "
                + "is (P rho P)^p and no equality with P rho^p P is asserted. At p=1/2 the "
                + "bound is sqrt(2) q^(1/4). Empty finite spans and zero discarded mass "
                + "remain allowed. This is a consequence of the two cited trace-class "
                + "estimates and the positive-cone theorem above.")))));

    private static Formula All(Formula.BoundVariable[] variables, Formula body) =>
        new Formula.BindMany(FormulaQuantifier.ForAll, [.. variables], body);
    private static Formula Conj(Formula a, Formula b) => new Formula.Logic(a, FormulaLogicOperator.And, b);
    private static Formula Imp(Formula a, Formula b) => new Formula.Logic(a, FormulaLogicOperator.Implies, b);
    private static Formula Le(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThanOrEqual, b);
    private static Formula Lt(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThan, b);
}
