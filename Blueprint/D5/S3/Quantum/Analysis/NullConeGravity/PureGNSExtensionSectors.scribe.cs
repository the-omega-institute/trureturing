using static StrataLint.Scribe.DefinitionDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Quantum.Analysis.NullConeGravity;

internal sealed class PureGNSExtensionSectorsDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S3/Quantum/Analysis/NullConeGravity/PureGNSExtensionSectors.";

    private static readonly LibraryNoteRef NullCone =
        LibraryNoteRef.Create("D5/L/HilbertOperators/chandrasekaran2026nullcone");

    private static readonly LibraryNoteRef InfiniteProducts =
        LibraryNoteRef.Create("D5/L/HilbertOperators/guichardet1966infiniteproducts");

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "The distance of two pure matrix states and the tail-product classification of qubit product representations.",
        H("Pure vector states and product GNS sectors"),
        Blocks(
            Paragraph(Text("The difference of the two ray projections obeys a cubic matrix identity. "
                + "Its positive square root gives the trace norm. On the qubit observable algebra, finite products of local observables factor in each reference vacuum. The vacua "
                + "define cyclic pure states. Finite rotations yield a common realization under summability, "
                + "and finite products of vacuum projections force every intertwiner to vanish under divergence. Applying the classification to matched null-cone clock cuts requires a common model "
                + "of the clock-cut algebras and their embeddings.")),
            Result("pure-matrix-trace-norm", "pure_matrix_traceNorm", "Trace norm of a ray-projection difference",
                "For unit vectors ψ and φ, the trace norm of their ray-projection difference is 2√(1 − |⟨ψ,φ⟩|²)."),
            Definition("pure-matrix-vector-state", "matrixVectorState", "Matrix vector functional",
                "The functional of a vector ψ pairs the matrix argument with the ray density of ψ by the trace."),
            Result("pure-matrix-vector-state-evaluation", "matrixVectorState_apply", "Matrix vector evaluation",
                "The trace-pairing functional evaluates at A as the inner product ⟨ψ,Aψ⟩."),
            Result("pure-matrix-vector-state-distance", "pure_matrix_vectorState_norm", "Norm distance between matrix vector states",
                "On the full matrix algebra with the operator norm, the distance of the vector states of unit ψ and φ "
                + "is 2√(1 − |⟨ψ,φ⟩|²)."),
            Definition("gns-unitary-equivalence", "GNSEquivalent", "Unitary equivalence of GNS representations",
                "The two completed GNS representations admit a surjective linear isometry that intertwines every observable."),
            Definition("gns-disjointness", "GNSDisjoint", "Disjoint GNS representations",
                "Every bounded linear operator intertwining the two completed GNS representations is zero."),
            Definition("first-qubit-product-state", "firstProductState", "First qubit product state",
                "The first component of the common observable algebra acts on the first vacuum, defining its normalized vector state."),
            Definition("second-qubit-product-state", "secondProductState", "Second qubit product state",
                "The second component of the common observable algebra acts on the second vacuum, defining its normalized vector state."),
            Result("pure-qubit-product-states", "pure_product_states", "Purity of the qubit product states",
                "Both product states are pure on the common norm-closed algebra generated by the paired local matrix actions."),
            Result("qubit-product-gns-dichotomy", "pure_product_gns_dichotomy", "Tail-product dichotomy",
                "The product GNS representations are unitarily equivalent exactly when the overlap deficits sum finitely. "
                + "They are disjoint exactly when the limit of the finite products is zero for every starting site.",
                AssessedProvenance.FromLiterature(InfiniteProducts)),
            Result("qubit-product-state-distance", "pure_product_state_norm", "Norm distance of product states",
                "The operator norm of the difference of the product state functionals is 2√(1 − p²), "
                + "where p is the full overlap product. The finite tests attain the corresponding finite-product distances."),
            Definition("even-diagonal-observable-algebra", "evenDiagonalAlgebra", "Even-site diagonal observables",
                "The incoming algebra is the norm-closed star subalgebra generated by diagonal observables at even sites."),
            Result("equivalent-sectors-one-orthogonal-site", "one_orthogonal_site_equivalent", "Equivalent sectors with one orthogonal site",
                "The first and second states are distinct and agree on the even-site diagonal algebra. "
                + "The overlap vanishes at site one and equals one elsewhere. The full product is zero, and the GNS representations are equivalent."),
            Result("disjoint-sectors-odd-orthogonal-sites", "odd_orthogonal_sites_disjoint", "Disjoint sectors with odd-site orthogonality",
                "The first and second states are distinct and agree on the even-site diagonal algebra. "
                + "The overlap is one at each even site and zero at each odd site, and the GNS representations are disjoint."))));

    private static DocumentBlock Definition(string id, string declaration, string title, string statement) =>
        Describe.Lean(DescribeId.Create(id), DeclarationHandle.Create(Prefix + declaration),
            H(title), StatementSource.WithoutFormula(), AssessedProvenance.FromRepo(NullCone),
            Blocks(Paragraph(Text(statement))), DescribeRole.Definition);

    private static DocumentBlock Result(string id, string declaration, string title, string statement,
        AssessedProvenance? provenance = null) =>
        Describe.Lean(DescribeId.Create(id), DeclarationHandle.Create(Prefix + declaration),
            H(title), StatementSource.WithoutFormula(), provenance ?? AssessedProvenance.FromRepo(NullCone),
            Blocks(Paragraph(Text(statement))), DescribeRole.Theorem);
}
