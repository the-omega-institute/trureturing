    private static Formula X(string name) => F.Id(name);

    private static Formula Qualified(params string[] parts)
    {
        var items = new List<Formula>();
        foreach (var part in parts)
        {
            if (items.Count > 0)
                items.Add(Dot);
            items.Add(F.Id(part));
        }
        return Seq(Operatorname, Sp, Grp(Seq([.. items])));
    }

    private static Formula At(Formula function, params Formula[] arguments) =>
        new Formula.Apply(function, [.. arguments]);

    private static Formula Call(string name, params Formula[] arguments) =>
        new Formula.FunctionCall(FormulaIdentifier.Create(name), [.. arguments]);

    private static Formula All(string name, Formula type, Formula body) =>
        Seq(Forall, Sp, Parenthesized(Seq(X(name), Sp, Colon, Sp, type)), Comma, Sp,
            Parenthesized(body));

    private static Formula LambdaOf(string name, Formula type, Formula body) =>
        Seq(LambdaLower, Sp, Parenthesized(Seq(X(name), Sp, Colon, Sp, type)), Sp,
            Mapsto, Sp, Parenthesized(body));

    private static Formula Imp(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Implies, Parenthesized(right));

    private static Formula Equal(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.Equal, right);

    private static Formula LessEqual(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.LessThanOrEqual, right);

    private static Formula Add(Formula left, Formula right) =>
        new Formula.Binary(Parenthesized(left), FormulaBinaryOperator.Add, Parenthesized(right));

    private static Formula Subtract(Formula left, Formula right) =>
        new Formula.Binary(Parenthesized(left), FormulaBinaryOperator.Subtract, Parenthesized(right));

    private static Formula Pow(Formula value, Formula exponent) =>
        new Formula.Power(Parenthesized(value), exponent);

    private static Formula Inverse(Formula value) => Pow(value, new Formula.Negate(D(1)));

    private static Formula Smul(Formula scalar, Formula value) =>
        Seq(Parenthesized(scalar), Sp, Cdot, Sp, Parenthesized(value));

    private static Formula Typed(Formula value, Formula type) =>
        Parenthesized(Seq(value, Colon, Sp, type));

    private static Formula Cast(Formula value, Formula type) => Typed(value, type);

    private static Formula NatDiv(Formula left, Formula right) =>
        At(Qualified("Nat", "div"), left, right);

    private static Formula MatrixType(Formula n) =>
        Call("Matrix", VectorType(n), VectorType(n), Complex());

    private static Formula VectorType(Formula n) =>
        new Formula.TypeArrow(Parenthesized(Fin(n)), Parenthesized(Fin(D(2))));

    private static Formula Fin(Formula n) => Call("Fin", n);

    private static Formula Identity(Formula n) => Typed(D(1), MatrixType(n));

    private static Formula Naturals() => Seq(Mathbb, Grp(F.Id("N")));

    private static Formula Integers() => new Formula.Integers();

    private static Formula Reals() => Seq(Mathbb, Grp(F.Id("R")));

    private static Formula Complex() => Seq(Mathbb, Grp(F.Id("C")));

    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
