                            + "These are all the edges. Every vertex is connected to c, and there are 9 + 7 = 16 edges on 17 vertices, so the graph is a tree. "
                            + "The degrees are 9 at c, 2 at each xᵢ and 1 at u, v and each yᵢ.")),
                    Paragraph(Text(
