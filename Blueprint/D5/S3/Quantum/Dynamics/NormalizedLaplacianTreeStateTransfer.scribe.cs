    private static DocumentBlock Node(string declaration, string title, Formula formula, string prose) =>
        Describe.Lean(DescribeId.Create("normalized-laplacian-tree-" + declaration.ToLowerInvariant()),
            DeclarationHandle.Create(Prefix + declaration), H(title),
            StatementSource.FromAuthor(Disp(formula)), AssessedProvenance.FromLiterature(Source),
            Blocks(Paragraph(Text(prose))), DescribeRole.Definition);

    private static Formula NormalizedLaplacianFormula()
    {
        Formula degree = At(Qualified("SimpleGraph", "degree"), X("G"), X("i"));
        Formula realDegree = Typed(At(Qualified("Nat", "cast"), degree), Reals());
        Formula root = At(Qualified("Complex", "ofReal"), At(Qualified("Real", "sqrt"), realDegree));
        Formula diagonal = At(Qualified("Matrix", "diagonal"),
            LambdaOf("i", FinOf(X("n")), At(Qualified("Inv", "inv"), Typed(root, Complexes()))));
        Formula laplacian = At(Qualified("SimpleGraph", "lapMatrix"), Complexes(), X("G"));
        return GraphBinders(Equal(Typed(LocalCall("normalizedLaplacian", X("G")), MatrixType()),
            Multiply(Multiply(diagonal, laplacian), diagonal)));
    }

    private static Formula WalkFormula() => GraphBinders(All("t", Reals(),
        Equal(Typed(LocalCall("walk", X("G"), X("t")), MatrixType()),
            At(Qualified("NormedSpace", "exp"),
                Smul(Multiply(Qualified("Complex", "I"), At(Qualified("Complex", "ofReal"), X("t"))),
                    LocalCall("normalizedLaplacian", X("G")))))));

    private static Formula PSTFormula()
    {
        Formula evolution = At(Qualified("Matrix", "mulVec"), LocalCall("walk", X("G"), Tau),
            At(Qualified("Pi", "single"), X("a"), Typed(D(1), Complexes())));
        Formula target = Smul(X("c"), At(Qualified("Pi", "single"), X("b"), Typed(D(1), Complexes())));
        Formula transfer = Some("τ", Reals(), Some("c", Complexes(),
            Conjunction(Equal(new Formula.Norm(X("c")), Typed(D(1), Reals())), Equal(evolution, target))));
        return GraphBinders(All("a", FinOf(X("n")), All("b", FinOf(X("n")),
            Equivalence(LocalCall("PST", X("G"), X("a"), X("b")), transfer))));
    }

    private static Formula ClaimFormula()
    {
        Formula exclusion = All("a", FinOf(X("n")), All("b", FinOf(X("n")),
            Arrow(NotEqual(X("a"), X("b")),
                new Formula.Not(Parenthesized(LocalCall("PST", X("G"), X("a"), X("b")))))));
        Formula trees = All("G", At(Qualified("SimpleGraph"), FinOf(X("n"))), InstanceBinder(
            Arrow(At(Qualified("SimpleGraph", "IsTree"), X("G")), exclusion)));
        return Equivalence(Local("claim"), All("n", Naturals(), Arrow(LE(D(4), X("n")), trees)));
    }

    private static Formula GraphBinders(Formula body) => All("n", Naturals(),
        All("G", At(Qualified("SimpleGraph"), FinOf(X("n"))), InstanceBinder(body)));
    private static Formula InstanceBinder(Formula body) => Seq(OpenBracket,
        At(Qualified("DecidableRel"), At(Qualified("SimpleGraph", "Adj"), X("G"))),
        CloseBracket, Comma, Sp, Parenthesized(body));
    private static Formula MatrixType() => At(Qualified("Matrix"), FinOf(X("n")), FinOf(X("n")), Complexes());
    private static Formula Local(string name) => Qualified("D5", "S3", "Quantum", "Dynamics",
        "NormalizedLaplacianTreeStateTransfer", name);
    private static Formula LocalCall(string name, params Formula[] args) => At(Local(name), args);
    private static Formula X(string name) => name == "τ" ? Tau : F.Id(name);
    private static Formula Qualified(params string[] parts)
    {
        var items = new System.Collections.Generic.List<Formula>();
        foreach (var part in parts)
        {
            if (items.Count > 0) items.Add(Dot);
            items.Add(F.Id(part));
        }
        return Seq(Operatorname, Grp(Seq([.. items])));
    }
    private static Formula At(Formula function, params Formula[] args) => new Formula.Apply(function, [.. args]);
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula Typed(Formula value, Formula type) => Parenthesized(Seq(value, Colon, Sp, type));
    private static Formula Naturals() => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula Reals() => Seq(Mathbb, Grp(F.Id("R")));
    private static Formula Complexes() => Seq(Mathbb, Grp(F.Id("C")));
    private static Formula FinOf(Formula n) => At(Qualified("Fin"), n);
    private static Formula All(string name, Formula type, Formula body) =>
        Seq(Forall, Sp, Typed(X(name), type), Comma, Sp, Parenthesized(body));
    private static Formula Some(string name, Formula type, Formula body) =>
        Seq(Exists, Sp, Typed(X(name), type), Comma, Sp, Parenthesized(body));
    private static Formula LambdaOf(string name, Formula type, Formula body) =>
        Seq(LambdaLower, Sp, Typed(X(name), type), Sp, Mapsto, Sp, Parenthesized(body));
    private static Formula Smul(Formula scalar, Formula vector) =>
        Seq(Parenthesized(scalar), Sp, Cdot, Sp, Parenthesized(vector));
    private static Formula Arrow(Formula domain, Formula codomain) =>
        new Formula.TypeArrow(Parenthesized(domain), Parenthesized(codomain));
    private static Formula LE(Formula left, Formula right) => new Formula.Relation(left, FormulaRelationOperator.LessThanOrEqual, right);
    private static Formula Conjunction(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.And, Parenthesized(right));
    private static Formula Equivalence(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Iff, Parenthesized(right));
}
