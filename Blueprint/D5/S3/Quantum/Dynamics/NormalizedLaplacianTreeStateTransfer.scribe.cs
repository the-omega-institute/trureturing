        H("Normalized-Laplacian perfect state transfer on a tree"),
        Blocks(
            Node("normalizedLaplacian", "The normalized Laplacian", NormalizedLaplacianFormula(),
                "For a finite simple graph G, the combinatorial Laplacian is its degree matrix minus its adjacency matrix. "
                    + "Multiplication on both sides by the diagonal inverse square roots of the degrees gives the normalized Laplacian. "
                    + "This is the source's definition preceding equation (1), expressed as a complex matrix. "
                    + "The natural-valued degree is cast to a real number before taking its square root; the square root is then cast to a complex number before inversion. "
                    + "The displayed definition extends to every finite simple graph, with inverse zero at an isolated vertex; the source assumes connected graphs on at least two vertices."),
            Node("walk", "The positive-sign continuous quantum walk", WalkFormula(),
                "Equation (1) defines the walk generated by the normalized Laplacian with the positive sign in the exponential. "
