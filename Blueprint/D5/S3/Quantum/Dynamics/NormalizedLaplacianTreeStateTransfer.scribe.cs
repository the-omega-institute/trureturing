                    + "The definition itself does not require a and b to be distinct or τ to be positive."),
            Node("claim", "The conjecture for trees with at least four vertices", ClaimFormula(),
                "The Discussion conjectures that no tree except the paths on two and three vertices admits normalized-Laplacian perfect state transfer. "
                    + "The statement excludes transfer between every pair of distinct vertices in every tree on n vertices, for every natural n at least four. "
                    + "The only trees on two and three vertices are those paths. A tree with a single vertex has no pair of distinct vertices."),
            Describe.Lean(
