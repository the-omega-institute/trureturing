                            + "The vector eᵤ − eᵥ is an eigenvector of L with eigenvalue 1. "
                            + "Four symmetric eigenvectors are specified by their values at (u,v; c; xᵢ; yᵢ), constant over the seven arms: "
                            + "w₀ = (1,1; 3; √2; 1), w₂ = (1,1; −3; √2; −1), "
                            + "w₂⁄₃ = (1,1; 1; −√2/7; −3/7) and w₄⁄₃ = (1,1; −1; −√2/7; 3/7). "
