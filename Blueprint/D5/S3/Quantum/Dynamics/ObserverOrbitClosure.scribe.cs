using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Quantum.Dynamics;

internal sealed class ObserverOrbitClosureDocument : IScribeDocumentDefinition
{
    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Power-orbit spans form the least invariant observer closure.",
        H("Observer Power-Orbit Closure"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("observer-orbit-closure-is-least-invariant"),
                DeclarationHandle.Create(
                    "D5/S3/Quantum/Dynamics/ObserverOrbitClosure."
                        + "observer_closure_is_least_invariant"),
                H("Observer orbit closure is the least invariant closure"),
                StatementSource.FromAuthor(ObserverClosureFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "Let V be a finite-dimensional real Hilbert space, K a linear "
                            + "endomorphism, and W a visible subspace. The observer closure is "
                            + "constructed as the supremum of the images of W under every "
                            + "nonnegative power of K, exactly the submodule generated by the "
                            + "source power orbit.")),
                    Paragraph(Text(
                        "The zero power proves extensivity, and monotonicity follows from "
                            + "monotonicity of submodule images. Mapping the supremum by K shifts "
                            + "each power image to its successor, which proves invariance.")),
                    Paragraph(Text(
                        "Induction on the power shows that every invariant subspace containing W "
                            + "contains every orbit image and hence their supremum. This leastness "
                            + "gives idempotence when applied to the already invariant closure. "
                            + "Mathlib's invariant-submodule map characterization is used "
                            + "directly."))),
                DescribeRole.Theorem))));

    private static Formula Call(string name, params Formula[] arguments)
    {
        var items = new List<Formula> { Operatorname, Grp(F.Id(name)), Open };
        for (var index = 0; index < arguments.Length; index++)
        {
            if (index > 0)
            {
                items.Add(Comma);
                items.Add(Sp);
            }
            items.Add(arguments[index]);
        }
        items.Add(Close);
        return Seq([.. items]);
    }

    private static Formula ObserverClosureFormula()
    {
        Formula space = F.Id("V");
        Formula evolution = F.Id("K");
        Formula visible = F.Id("W");
        Formula left = F.Id("A");
        Formula right = F.Id("B");
        Formula candidate = F.Id("U");
        Formula Closure(Formula subspace) => Call("Cl", evolution, subspace);
        Formula Invariant(Formula subspace) => Call("Invariant", evolution, subspace);

        Formula extensive = Seq(visible, Sp, Subseteq, Sp, Closure(visible));
        Formula monotone = Seq(
            Open, Forall, Sp, left, Comma, Sp, right, Comma, Esc,
            left, Sp, Subseteq, Sp, right, Sp, Rightarrow, Sp,
            Closure(left), Sp, Subseteq, Sp, Closure(right), Close);
        Formula idempotent = Seq(
            Closure(Closure(visible)), Sp, Eq, Sp, Closure(visible));
        Formula invariant = Invariant(Closure(visible));
        Formula least = Seq(
            Forall, Sp, candidate, Comma, Esc,
            Open, visible, Sp, Subseteq, Sp, candidate, Sp, Land, Sp,
            Invariant(candidate), Close, Sp, Rightarrow, Sp,
            Closure(visible), Sp, Subseteq, Sp, candidate);

        return Disp(Seq(
            Forall, Sp, space, Colon, Sp,
            Operatorname, Grp(F.Id("FiniteDimensionalRealHilbertSpace")),
            Comma, Esc,
            Forall, Sp, evolution, Colon, Sp, Call("End", space),
            Comma, Esc,
            Forall, Sp, visible, Colon, Sp, Call("Submodule", space),
            Comma, Esc,
            extensive, Sp, Land, Sp,
            monotone, Sp, Land, Sp,
            idempotent, Sp, Land, Sp,
            invariant, Sp, Land, Sp,
            least, Dot));
    }
}
