    private static Formula Call(string name, params Formula[] arguments)
    {
        var items = new List<Formula> { Operatorname, Grp(F.Id(name)), Open };
        for (var index = 0; index < arguments.Length; index++)
        {
            if (index > 0)
            {
                items.Add(Comma);
                items.Add(Sp);
            }
            items.Add(arguments[index]);
        }
        items.Add(Close);
        return Seq([.. items]);
    }

    private static Formula TheoremFormula()
    {
        Formula state = F.Id("Y");
        Formula output = F.Id("O");
        Formula update = Tau;
        Formula readout = F.Id("q");
        Formula depth = F.Id("m");
        Formula function = F.Id("f");
        Formula point = F.Id("y");
        Formula word = Call("futureReadoutWord", update, readout, depth);
        Formula algebra = Call("finiteKoopmanClosure", update, readout, depth);
        Formula range = Call("range", word);
        Formula equivalence = Call(
            "finiteWordObservableAlgebraEquiv", update, readout, depth);

        return Disp(Seq(
            Begin, Grp(F.Id("gathered")),
            Forall, Sp, state, Comma, Sp, output, Colon, Sp,
            Operatorname, Grp(F.Id("Type")), Comma, Sp,
            OpenBracket, Operatorname, Grp(F.Id("Fintype")), Open, state, Close,
            CloseBracket, Comma, RowBreak, Grp(),
            update, Colon, Sp, state, Sp, To, Sp, state, Comma, Sp,
            readout, Colon, Sp, state, Sp, To, Sp, output, Comma, Sp,
            Call("Surjective", readout), Comma, Sp, depth, InMacro, Sp,
            Mathbb, Grp(F.Id("N")), Comma, RowBreak, Grp(),
            algebra, Sp, Eq, Sp,
            Call("fiberStarAlgebra", Call("ker", word)),
            Sp, Land, RowBreak, Grp(),
            Open, Forall, Sp, function, InMacro, Sp, algebra, Comma, Sp,
            point, InMacro, Sp, state, Comma, Sp,
            equivalence, Open, function, Close, Open, word, Open, point, Close, Close,
            Sp, Eq, Sp, function, Open, point, Close, Close,
            Sp, Land, RowBreak, Grp(),
            Call("finrank", algebra), Sp, Eq, Sp,
            Lvert, range, Rvert, Dot,
            End, Grp(F.Id("gathered"))));
    }
}
