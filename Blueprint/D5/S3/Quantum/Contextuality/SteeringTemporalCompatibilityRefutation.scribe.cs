    private static DocumentBlock Node(string name, string title, Formula formula, string prose,
        params DocumentBlock[] details) =>
        Describe.Lean(
            DescribeId.Create("song-steering-" + name.ToLowerInvariant()),
            DeclarationHandle.Create(Prefix + name),
            H(title),
            StatementSource.FromAuthor(Disp(formula)),
            AssessedProvenance.FromLiterature(Source),
            Blocks([Paragraph(Text(prose)), .. details]),
            DescribeRole.Definition);

    private static Formula X(string name) => F.Id(name);
    private static Formula Named(string name) => Seq(Operatorname, Grp(X(name)));
    private static Formula Qualified(params string[] parts)
    {
        var items = new List<Formula>();
        foreach (var part in parts)
        {
            if (items.Count > 0) items.Add(Dot);
            items.Add(X(part));
        }
        return Seq(Operatorname, Grp(Seq([.. items])));
    }

    private static Formula Call(string name, params Formula[] arguments) =>
        new Formula.Apply(Named(name), [.. arguments]);
    private static Formula QCall(string[] name, params Formula[] arguments) =>
        new Formula.Apply(Qualified(name), [.. arguments]);
    private static Formula App(Formula function, params Formula[] arguments) =>
        new Formula.Apply(function, [.. arguments]);
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula Typed(Formula value, Formula type) => Parenthesized(Seq(value, Colon, Sp, type));
    private static Formula All(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), type, Parenthesized(body));
    private static Formula Exists(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create(name), type, Parenthesized(body));
    private static Formula Lambda(string name, Formula type, Formula body) =>
        Seq(LambdaLower, Sp, Typed(X(name), type), Sp, Mapsto, Sp, Parenthesized(body));
    private static Formula SumOver(string name, Formula type, Formula body) =>
        Seq(new Formula.Subscript(Sum, Typed(X(name), type)), Sp, Parenthesized(body));
    private static Formula Equal(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.Equal, right);
    private static Formula And(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.And, Parenthesized(right));
    private static Formula Or(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Or, Parenthesized(right));
    private static Formula Implies(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Implies, Parenthesized(right));
    private static Formula Iff(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Iff, Parenthesized(right));
    private static Formula Add(Formula left, Formula right) =>
        new Formula.Binary(left, FormulaBinaryOperator.Add, right);
    private static Formula Multiply(Formula left, Formula right) =>
        new Formula.Binary(left, FormulaBinaryOperator.Multiply, right);
    private static Formula Neg(Formula value) => new Formula.Not(value);
    private static Formula Fraction(Formula numerator, Formula denominator) =>
        new Formula.Fraction(numerator, denominator);

    private static Formula Nats() => Seq(Mathbb, Grp(X("N")));
    private static Formula Complexes() => Seq(Mathbb, Grp(X("C")));
    private static Formula Bool() => X("Bool");
    private static Formula Fin2() => Call("Fin", D(2));
    private static Formula PairIndex() => Call("Prod", Fin2(), Fin2());
    private static Formula QubitMatrix() => Call("Matrix", Fin2(), Fin2(), Complexes());
    private static Formula BipartiteMatrix() => Call("Matrix", PairIndex(), PairIndex(), Complexes());
    private static Formula Arrow(Formula domain, Formula codomain) =>
        Parenthesized(new Formula.TypeArrow(domain, codomain));
    private static Formula MeasurementFamily(Formula n) =>
        Arrow(FinOf(n), Arrow(Bool(), QubitMatrix()));
    private static Formula FinOf(Formula n) => Call("Fin", n);
    private static Formula One() => D(1);
    private static Formula Tensor(Formula left, Formula right) => Call("kronecker", left, right);
    private static Formula MatrixProduct(Formula left, Formula right) => Multiply(left, right);
    private static Formula MatrixSubmatrix(Formula matrix) =>
        Call("submatrix", matrix, Qualified("Prod", "swap"), Qualified("Prod", "swap"));
    private static Formula Density(Formula matrix) => Call("IsDensity", matrix);

    private static Formula DensityFormula()
    {
        Formula r = X("R");
        return All("R", BipartiteMatrix(), Iff(Density(r),
            And(Call("PosSemidef", r), Equal(Call("trace", r), One()))));
    }

    private static Formula TemporalKernelFormula()
    {
        Formula r = X("R");
        Formula swap = Call("swap", D(2));
        Formula halfIdentity = Multiply(Fraction(D(1), D(2)), One());
        Formula a = Tensor(Call("partialTraceRight", r), halfIdentity);
        return All("R", BipartiteMatrix(), Equal(Call("temporalKernel", r),
            Add(MatrixProduct(a, swap), MatrixProduct(swap, a))));
    }

    private static Formula TemporalForwardFormula()
    {
        Formula r = X("R");
        Formula channel = Call("QuantumChannel", Fin2(), Fin2());
        Formula action = QCall(["CStarMatrix", "ofMatrix", "symm"],
            Call("referenceAction", X("E"),
                QCall(["CStarMatrix", "ofMatrix"], Call("temporalKernel", r))));
        Formula body = Exists("E", channel, Equal(r, action));
        return All("R", BipartiteMatrix(), Iff(Call("TemporalForward", r), body));
    }

    private static Formula TemporalReverseFormula()
    {
        Formula r = X("R");
        return All("R", BipartiteMatrix(), Iff(Call("TemporalReverse", r),
            Call("TemporalForward", MatrixSubmatrix(r))));
    }

    private static Formula AtemporalFormula()
    {
        Formula r = X("R");
        return All("R", BipartiteMatrix(), Iff(Call("Atemporal", r),
            And(Neg(Call("TemporalForward", r)), Neg(Call("TemporalReverse", r)))));
    }

    private static Formula BinaryProjectiveFormula()
    {
        Formula n = X("n"), p = X("P");
        Formula projection = All("x", FinOf(n), All("b", Bool(),
            Call("IsStarProjection", App(App(p, X("x")), X("b")))));
        Formula complement = All("x", FinOf(n),
            Equal(Add(App(App(p, X("x")), X("false")), App(App(p, X("x")), X("true"))), One()));
        return All("n", Nats(), All("P", MeasurementFamily(n),
            Iff(Call("BinaryProjective", p), And(projection, complement))));
    }

    private static Formula AssemblageFormula()
    {
        Formula n = X("n"), r = X("R"), p = X("P");
        Formula x = X("x"), b = X("b");
        Formula body = Lambda("x", FinOf(n), Lambda("b", Bool(),
            Call("partialTraceRight", MatrixProduct(
                Tensor(One(), App(App(p, x), b)), r))));
        return All("n", Nats(), All("R", BipartiteMatrix(), All("P", MeasurementFamily(n),
            Equal(Call("assemblage", r, p), body))));
    }

    private static Formula HasLHSFormula()
    {
        Formula n = X("n"), sigma = X("sigma"), h = X("H");
        Formula responseType = Arrow(FinOf(n), Bool());
        Formula hiddenType = Arrow(responseType, QubitMatrix());
        Formula positivity = All("lam", responseType,
            Call("PosSemidef", App(h, X("lam"))));
        Formula model = All("x", FinOf(n), All("b", Bool(),
            Equal(
                SumOver("lam", responseType,
                    Call("ite", Equal(App(X("lam"), X("x")), X("b")),
                        App(h, X("lam")), D(0))),
                App(App(sigma, X("x")), X("b")))));
        return All("n", Nats(), All("sigma", MeasurementFamily(n),
            Iff(Call("HasLHS", sigma), Exists("H", hiddenType, And(positivity, model)))));
    }

    private static Formula SteerableBAFormula()
    {
        Formula r = X("R"), n = X("n"), p = X("P");
        Formula witness = And(Call("BinaryProjective", p),
            Neg(Call("HasLHS", Call("assemblage", r, p))));
        return All("R", BipartiteMatrix(), Iff(Call("SteerableBA", r),
            Exists("n", Nats(), Exists("P", MeasurementFamily(n), witness))));
    }

    private static Formula SteerableABFormula()
    {
        Formula r = X("R");
        return All("R", BipartiteMatrix(), Iff(Call("SteerableAB", r),
            Call("SteerableBA", MatrixSubmatrix(r))));
    }

    private static Formula ClaimFormula()
    {
        Formula r = X("R");
        Formula direction = Or(Call("SteerableBA", r), Call("SteerableAB", r));
        return Iff(X("claim"), All("R", BipartiteMatrix(),
            Implies(Density(r), Implies(direction, Call("Atemporal", r)))));
    }
}
