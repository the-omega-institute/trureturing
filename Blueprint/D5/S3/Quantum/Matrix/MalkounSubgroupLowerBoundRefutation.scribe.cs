    private static DocumentBlock Entry(string id, string name, string title, Formula formula,
        string prose, AssessedProvenance provenance, DescribeRole role = DescribeRole.Definition) =>
        Describe.Lean(DescribeId.Create(id), DeclarationHandle.Create(Prefix + name), H(title),
            StatementSource.FromAuthor(formula), provenance, Blocks(Paragraph(Text(prose))), role,
            name == "result" ? new OpenProblemResolutionClaim(
                ProblemSlugRef.Create("malkoun-2023-subgroup-permanent-lower-bound"),
                ResolutionKind.Refuted) : null);

    private static Formula CrossSumFormula()
    {
        Formula n = V("n"), g = V("G"), k = V("K"), h = V("H"), i = V("i");
        Formula term = App(h, App(V("sigma"), i), App(V("tau"), i));
        return Disp(All("n", Nat(), All("G", Subgroup(n), All("K", Subgroup(n),
            All("H", Matrix(n), Equal(Call("crossSum", g, k, h),
                SumOver("sigma", g, SumOver("tau", k, Product("i", Fin(n), term)))))))));
    }

    private static Formula ClaimFormula() => Disp(Iff(V("claim"), ClaimBody()));

    private static Formula ClaimBody()
    {
        Formula n = V("n"), g = V("G"), k = V("K"), h = V("H"), c = V("c"), i = V("i");
        Formula diagonal = Product("i", Fin(n), Call("Complex.re", App(h, i, i)));
        Formula bound = Leq(Mul(c, diagonal), Call("Complex.re", Call("crossSum", g, k, h)));
        Formula matrices = All("H", Matrix(n), Imp(Call("Matrix.IsHermitian", h),
            Imp(Call("Matrix.PosSemidef", h), bound)));
        return All("n", Nat(), All("G", Subgroup(n),
            All("K", Subgroup(n), ExistsIn("c", Real(), And(Lt(D(0), c), matrices)))));
    }

    private static Formula DiagonalFormula()
    {
        Formula n = V("n"), h = V("H"), i = V("i");
        return Disp(All("n", Nat(), All("H", Matrix(n), Imp(Call("Matrix.IsHermitian", h),
            Equal(Product("i", Fin(n), App(h, i, i)), Call("Complex.ofReal",
                Product("i", Fin(n), Call("Complex.re", App(h, i, i)))))))));
    }

    private static Formula V(string name) => F.Id(name);
    private static Formula Nat() => Seq(Mathbb, Grp(V("N")));
    private static Formula Real() => Seq(Mathbb, Grp(V("R")));
    private static Formula Complex() => Seq(Mathbb, Grp(V("C")));
    private static Formula Fin(Formula n) => Call("Fin", n);
    private static Formula Matrix(Formula n) => Call("Matrix", Fin(n), Fin(n), Complex());
    private static Formula Subgroup(Formula n) => Call("Subgroup", Call("Equiv.Perm", Fin(n)));
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula App(Formula function, params Formula[] args) => new Formula.Apply(function, [.. args]);
    private static Formula Call(string name, params Formula[] args) => App(
        Seq(Operatorname, Grp(Seq(name.Split('.').Select((part, index) =>
            index == 0 ? V(part) : Seq(Dot, V(part))).ToArray()))), args);
    private static Formula All(string name, Formula type, Formula body) =>
        Seq(Forall, Sp, Parenthesized(Seq(V(name), Colon, Sp, type)), Comma, Sp, body);
    private static Formula ExistsIn(string name, Formula type, Formula body) =>
        Seq(Exists, Sp, Parenthesized(Seq(V(name), Colon, Sp, type)), Comma, Sp, body);
    private static Formula SumOver(string name, Formula type, Formula body) =>
        Seq(new Formula.Subscript(F.Sum, Seq(V(name), Colon, Sp, type)), Sp, body);
    private static Formula Product(string name, Formula type, Formula body) =>
        Seq(new Formula.Subscript(F.Prod, Seq(V(name), Colon, Sp, type)), Sp, body);
    private static Formula And(Formula a, Formula b) => new Formula.Logic(Parenthesized(a), FormulaLogicOperator.And, Parenthesized(b));
    private static Formula Imp(Formula a, Formula b) => new Formula.Logic(Parenthesized(a), FormulaLogicOperator.Implies, Parenthesized(b));
    private static Formula Iff(Formula a, Formula b) => new Formula.Logic(Parenthesized(a), FormulaLogicOperator.Iff, Parenthesized(b));
    private static Formula Equal(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.Equal, b);
    private static Formula Leq(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThanOrEqual, b);
    private static Formula Lt(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThan, b);
    private static Formula Mul(Formula a, Formula b) => new Formula.Binary(a, FormulaBinaryOperator.Multiply, b);
}
