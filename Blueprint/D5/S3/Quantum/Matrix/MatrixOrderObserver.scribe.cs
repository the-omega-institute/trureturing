using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Quantum.Matrix;

internal sealed class MatrixOrderObserverDocument : IScribeDocumentDefinition
{
    private const string DeclarationPrefix =
        "D5/S3/Quantum/Matrix/MatrixOrderObserver.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "A finite matrix-order observer may expose a unital self-adjoint question space "
            + "without exposing the multiplication algebra generated by those questions.",
        H("Matrix-Order Observers"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("matrix-order-observer-data"),
                DeclarationHandle.Create(DeclarationPrefix + "ObserverData"),
                H("Finite matrix-order observer data"),
                StatementSource.WithoutFormula(),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "The ambient finite complex matrix algebra canonically supplies every "
                            + "amplified positive cone and the identity order unit. A positive "
                            + "trace-one density state and the existing MatrixOperatorSystem "
                            + "supply the state and accessible question space.")),
                    Paragraph(Text(
                        "The remaining data are a completely positive coarse-graining map whose "
                            + "self-adjoint range is visible, completely positive trace-"
                            + "nonincreasing instrument branches, global dynamics, a ledger of "
                            + "outcomes, paths, and environment copies, and a same-address "
                            + "evaluation of the observer's own rule.")),
                    Paragraph(Text(
                        "The source does not define the carriers for paths, environment copies, "
                            + "addresses, rules, or evaluation values. They remain explicit type "
                            + "parameters, so no unlicensed algebraic law is added."))),
                DescribeRole.Definition),
            Describe.Lean(
                DescribeId.Create("matrix-order-observers-need-not-be-multiplicatively-closed"),
                DeclarationHandle.Create(
                    DeclarationPrefix
                        + "exists_matrix_order_observer_not_multiplicatively_closed"),
                H("A matrix-order observer need not be multiplicatively closed"),
                StatementSource.FromAuthor(ExistenceFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "Take the complex span of the identity and the Pauli X and Z matrices. "
                            + "Its Hermitian part consists exactly of the self-adjoint matrices "
                            + "whose two off-diagonal entries are equal. The remaining observer "
                            + "components have explicit finite witnesses.")),
                    Paragraph(Text(
                        "The Pauli X and Z matrices are both visible and self-adjoint. Their "
                            + "product XZ has entry zero-one equal to minus one and entry one-zero "
                            + "equal to one. Every visible matrix has equal off-diagonal entries, "
                            + "so XZ lies outside the complex operator system.")),
                    Paragraph(Text(
                        "For the opposite calculation, X commutes with itself and X squared is "
                            + "the identity, which is visible. This breaks the noncommutativity "
                            + "premise and makes product nonvisibility false for that pair."))),
                DescribeRole.Theorem))));

    private static Formula ExistenceFormula()
    {
        Formula observerType = Call(
            "ObserverData",
            Call("Fin", D(2)),
            F.Id("Unit"),
            F.Id("Unit"),
            F.Id("Unit"),
            F.Id("Unit"),
            F.Id("Unit"),
            F.Id("Unit"));
        Formula visibleSystem = Seq(F.Id("O"), Dot, F.Id("visibleSystem"));

        return Disp(Seq(
            Exists, Sp, F.Id("O"), Colon, Sp, observerType, Comma, RowBreak,
            Neg, Operatorname, Grp(F.Id("MultiplicativelyClosed")),
            Open, visibleSystem, Close, Dot));
    }
}
