        Seq(Bang, Bang, OpenBracket, D(0), Comma, Sp, new Formula.Fraction(D(1), F.Id("y")),
            Semi, Sp, F.Id("y"), Comma, Sp, D(0), CloseBracket))));
    private static Formula LocalBlockFormula()
    {
        var n = F.Id("n"); var i = F.Id("i"); var b = F.Id("B");
        var row = F.Id("row"); var col = F.Id("col");
        var iv = Val(i); var next = Add(iv, D(1));
        Formula Match(Formula r, Formula c) => And(Equal(Val(row), r), Equal(Val(col), c));
        Formula If(Formula test, Formula yes, Formula no) =>
            Seq(Named("if"), Sp, Parenthesized(test), Sp, Named("then"), Sp, yes, Sp, Named("else"), Sp, no);
        var body = If(Match(iv, iv), At(b, D(0), D(0)),
            If(Match(iv, next), At(b, D(0), D(1)),
                If(Match(next, iv), At(b, D(1), D(0)),
                    If(Match(next, next), At(b, D(1), D(1)), If(Equal(row, col), D(1), D(0))))));
        return Disp(All("n", NatType(), All("i", Fin(Subtract(n, D(1))), All("B", MatrixType(D(2)),
            Equal(Call("localBlock", i, b), Seq(Named("fun"), Sp, row, Colon, Sp, Fin(n), Sp,
                col, Colon, Sp, Fin(n), Sp, Mapsto, Sp, body))))));
    }
    private static Formula GeneratorFormula()
    {
        var k = F.Id("k"); var n = F.Id("n"); var a = F.Id("a"); var b = F.Id("b");
        var y = F.Id("y"); var i = F.Id("i"); var alpha = F.Id("alpha");
        var g = F.Id("g");
        var body = Seq(Named("fun"), Sp, g, Colon, Sp, GeneratorType(k, n), Sp, Mapsto, Sp,
            Named("match"), Sp, g, Sp, Named("with"), Sp,
            Bar, Sp, Call("Sum.inl", i), Sp, Mapsto, Sp, Call("localBlock", i, Call("sBlock", a, b)), Sp,
            Bar, Sp, Call("Sum.inr", Pair(i, alpha)), Sp, Mapsto, Sp,
            Call("localBlock", i, Call("rhoBlock", At(y, alpha))));
        return Disp(AtKN(All("a", ComplexType(), All("b", ComplexType(),
            All("y", new Formula.TypeArrow(Fin(k), ComplexType()),
                Equal(Call("generatorMatrix", a, b, y), body))))));
    }

    private static Formula IsZetaFormula()
    {
        var k = F.Id("k"); var n = F.Id("n"); var a = F.Id("a"); var b = F.Id("b");
        var y = F.Id("y"); var f = F.Id("f"); var g = F.Id("g");
        var matrix = Parenthesized(Seq(At(f, Call("PresentedGroup.of", g)), Colon, Sp, MatrixType(n)));
        return Disp(AtKN(All("a", ComplexType(), All("b", ComplexType(),
            All("y", new Formula.TypeArrow(Fin(k), ComplexType()), All("f", HomType(k, n),
                Equal(Call("IsZetaEight", a, b, y, f), Parenthesized(All("g", GeneratorType(k, n),
                    Equal(matrix, Call("generatorMatrix", a, b, y, g)))))))))));
    }
    private static Formula ClaimBody()
    {
        var k = F.Id("k"); var n = F.Id("n"); var a = F.Id("a"); var b = F.Id("b");
        var y = F.Id("y"); var f = F.Id("f"); var alpha = F.Id("alpha");
        var existence = Some("f", HomType(k, n), Call("IsZetaEight", a, b, y, f));
        var faithful = All("f", HomType(k, n), Imp(Call("IsZetaEight", a, b, y, f), Call("Function.Injective", f)));
        var nonzero = All("alpha", Fin(k), NotEqual(At(y, alpha), D(0)));
        return AtKN(Imp(Leq(D(1), k), Imp(Leq(D(3), n), All("a", ComplexType(), All("b", ComplexType(),
            All("y", new Formula.TypeArrow(Fin(k), ComplexType()), Imp(NotEqual(a, D(0)), Imp(NotEqual(a, D(1)),
                Imp(NotEqual(a, Seq(Minus, D(1))), Imp(NotEqual(b, D(0)), Imp(nonzero, And(existence, faithful))))))))))));
    }
