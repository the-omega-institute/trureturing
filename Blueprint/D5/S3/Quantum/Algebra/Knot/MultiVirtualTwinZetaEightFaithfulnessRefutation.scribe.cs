    private static Formula SBlockFormula()
    {
        var a = F.Id("a"); var b = F.Id("b");
        var entries = Seq(Bang, Bang, OpenBracket, Minus, a, Comma, Sp,
            new Formula.Fraction(Seq(Minus, Parenthesized(Subtract(new Formula.Power(a, D(2)), D(1)))), b),
            Semi, Sp, b, Comma, Sp, a, CloseBracket);
        return Disp(All("a", ComplexType(), All("b", ComplexType(), Equal(Call("sBlock", a, b), entries))));
    }
