    private static Formula Named(string name)
    {
        var parts = name.Split('.');
        var items = new List<Formula>();
        for (var i = 0; i < parts.Length; i++)
        {
            if (i > 0) items.Add(Dot);
            items.Add(Operatorname);
            items.Add(Grp(F.Id(parts[i])));
        }
        return Seq([.. items]);
    }
    private static Formula Call(string name, params Formula[] args) => new Formula.Apply(Named(name), [.. args]);
    private static Formula At(Formula value, params Formula[] args) => new Formula.Apply(value, [.. args]);
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula All(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), type, body);
    private static Formula Some(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create(name), type, body);
    private static Formula And(Formula a, Formula b) => new Formula.Logic(a, FormulaLogicOperator.And, b);
    private static Formula Or(Formula a, Formula b) => new Formula.Logic(a, FormulaLogicOperator.Or, b);
    private static Formula Imp(Formula a, Formula b) => new Formula.Logic(a, FormulaLogicOperator.Implies, b);
    private static Formula Leq(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThanOrEqual, b);
    private static Formula Less(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThan, b);
    private static Formula Pair(Formula a, Formula b) => Parenthesized(Seq(a, Comma, Sp, b));
    private static Formula NatType() => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula ComplexType() => Seq(Mathbb, Grp(F.Id("C")));
    private static Formula Fin(Formula n) => Call("Fin", n);
    private static Formula MatrixType(Formula n) => Call("Matrix", Fin(n), Fin(n), ComplexType());
    private static Formula GeneratorType(Formula k, Formula n) =>
        Call("Sum", Fin(Subtract(n, D(1))), Call("Prod", Fin(Subtract(n, D(1))), Fin(k)));
    private static Formula FreeType(Formula k, Formula n) => Call("FreeGroup", GeneratorType(k, n));
    private static Formula HomType(Formula k, Formula n) => Call("MonoidHom", Call("MultiVirtualTwin", k, n),
