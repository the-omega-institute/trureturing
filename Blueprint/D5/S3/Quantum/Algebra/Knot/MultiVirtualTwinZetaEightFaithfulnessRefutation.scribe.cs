    private static Formula S(Formula i) => Call("FreeGroup.of", Call("Sum.inl", i));
    private static Formula R(Formula i, Formula alpha) => Call("FreeGroup.of", Call("Sum.inr", Pair(i, alpha)));
    private static Formula Val(Formula i) => Call("val", i);
    private static Formula Distant(Formula i, Formula j) =>
        Or(Leq(Add(Val(i), D(2)), Val(j)), Leq(Add(Val(j), D(2)), Val(i)));
    private static Formula Triple(Formula a, Formula b, Formula c) => Multiply(Multiply(a, b), c);
    private static Formula AtKN(Formula body) => All("k", NatType(), All("n", NatType(), body));

    private static Formula EquationsFormula()
    {
        var k = F.Id("k"); var n = F.Id("n"); var p = F.Id("p");
        var i = F.Id("i"); var j = F.Id("j"); var alpha = F.Id("alpha"); var beta = F.Id("beta");
        var index = Fin(Subtract(n, D(1))); var color = Fin(k);
        Formula I(Formula body) => Some("i", index, body);
        Formula IJ(Formula body) => I(Some("j", index, body));
        Formula A(Formula body) => Some("alpha", color, body);
        Formula AB(Formula body) => A(Some("beta", color, body));
        Formula Equation(Formula l, Formula r) => Equal(p, Pair(l, r));
        var adjacent = Equal(Add(Val(i), D(1)), Val(j));
        var ordered = Less(Val(alpha), Val(beta));
        Formula[] families = [
            I(Equation(new Formula.Power(S(i), D(2)), D(1))),
            IJ(And(Distant(i, j), Equation(Multiply(S(i), S(j)), Multiply(S(j), S(i))))),
            I(A(Equation(new Formula.Power(R(i, alpha), D(2)), D(1)))),
            IJ(AB(And(Distant(i, j), Equation(Multiply(R(i, alpha), R(j, beta)), Multiply(R(j, beta), R(i, alpha)))))),
            IJ(A(And(Distant(i, j), Equation(Multiply(R(i, alpha), S(j)), Multiply(S(j), R(i, alpha)))))),
            IJ(A(And(adjacent, Equation(Triple(R(i, alpha), R(j, alpha), R(i, alpha)), Triple(R(j, alpha), R(i, alpha), R(j, alpha)))))),
            IJ(AB(And(adjacent, And(ordered, Equation(Triple(R(i, alpha), R(j, beta), R(i, beta)), Triple(R(j, beta), R(i, beta), R(j, alpha))))))),
            IJ(AB(And(adjacent, And(ordered, Equation(Triple(R(i, alpha), R(j, alpha), R(i, beta)), Triple(R(j, beta), R(i, alpha), R(j, alpha))))))),
            IJ(A(And(adjacent, Equation(Triple(R(i, alpha), R(j, alpha), S(i)), Triple(S(j), R(i, alpha), R(j, alpha))))))
        ];
        Formula body = families[^1];
        for (var t = families.Length - 2; t >= 0; t--) body = Or(families[t], body);
        var pairType = Call("Prod", FreeType(k, n), FreeType(k, n));
        var set = Seq(OpenBrace, p, Colon, Sp, pairType, Sp, Bar, Sp, body, CloseBrace);
        return Disp(AtKN(Equal(Call("Equations", k, n), set)));
    }

    private static Formula RelatorsFormula()
    {
        var k = F.Id("k"); var n = F.Id("n"); var w = F.Id("w"); var p = F.Id("p");
        var left = Seq(p, Dot, D(1)); var right = Seq(p, Dot, D(2));
        var body = Some("p", Call("Prod", FreeType(k, n), FreeType(k, n)),
            And(new Formula.Relation(p, FormulaRelationOperator.MemberOf, Call("Equations", k, n)),
                Equal(w, Multiply(left, new Formula.Power(right, Seq(Minus, D(1)))))));
        return Disp(AtKN(Equal(Call("relators", k, n),
            Seq(OpenBrace, w, Colon, Sp, FreeType(k, n), Sp, Bar, Sp, body, CloseBrace))));
    }
