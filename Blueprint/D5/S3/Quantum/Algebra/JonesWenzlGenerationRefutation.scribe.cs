    private static Formula RelationFormula()
    {
        Formula i = X("i"), j = X("j"), x = X("x"), y = X("y");
        Formula adjacent = Or(Equal(Add(Value(i), D(1)), Value(j)), Equal(Add(Value(j), D(1)), Value(i)));
        Formula distant = Or(Less(Add(Value(i), D(1)), Value(j)), Less(Add(Value(j), D(1)), Value(i)));
        Formula square = Some("i", Index(), And(Equal(x, Multiply(Free(i), Free(i))), Equal(y, Smul(X("ν"), Free(i)))));
        Formula triple = Some("i", Index(), Some("j", Index(), And(adjacent,
            And(Equal(x, Multiply(Multiply(Free(i), Free(j)), Free(i))), Equal(y, Free(i))))));
        Formula commute = Some("i", Index(), Some("j", Index(), And(distant,
            And(Equal(x, Multiply(Free(i), Free(j))), Equal(y, Multiply(Free(j), Free(i)))))));
        return AlgebraBinders(All("x", FreeType(), All("y", FreeType(),
            Equal(LocalCall("rel", X("n"), X("ν"), x, y), Parenthesized(Or(square, Or(triple, commute)))))));
    }

    private static Formula AlgebraFormula() => AlgebraBinders(Equal(
        Typed(LocalCall("TL", X("n"), X("ν")), Qualified("Type")),
        At(Qualified("RingQuot"), LocalCall("rel", X("n"), X("ν")))));

    private static Formula GeneratorFormula()
    {
        Formula condition = And(LE(D(1), X("i")), Less(X("i"), X("n")));
        Formula index = Typed(Seq(Langle, Sp, Subtract(X("i"), D(1)), Comma, Sp,
            new Formula.Placeholder(), Rangle), Index());
        Formula image = At(At(Qualified("RingQuot", "mkAlgHom"), Complexes(),
            LocalCall("rel", X("n"), X("ν"))), Free(index));
        Formula generator = Typed(LocalCall("gen", X("n"), X("ν"), X("i")), TL(X("n"), X("ν")));
        return AlgebraBinders(All("i", Naturals(), And(Arrow(condition, Equal(generator, image)),
            Arrow(new Formula.Not(Parenthesized(condition)), Equal(generator, Typed(D(0), TL(X("n"), X("ν"))))))));
    }

    private static Formula QuantumIntegerFormula() => All("q", Complexes(), All("k", Naturals(),
        Equal(Typed(LocalCall("qint", X("q"), X("k")), Complexes()),
            At(Qualified("Finset", "sum"), At(Qualified("Finset", "range"), X("k")),
                LambdaOf("j", Naturals(), new Formula.Power(X("q"),
                    Subtract(Subtract(Cast(X("k"), Integers()), Typed(D(1), Integers())),
                        Multiply(Typed(D(2), Integers()), Cast(X("j"), Integers())))))))));

    private static Formula OrderFormula()
    {
        Formula order = At(Qualified("orderOf"), new Formula.Power(X("q"), D(2)));
        Formula infinity = Qualified("Top", "top");
        return All("q", Complexes(), Equal(Typed(LocalCall("pbar", X("q")), ENat()),
            If(Or(Equal(X("q"), Typed(D(1), Complexes())), Equal(X("q"), new Formula.Negate(Typed(D(1), Complexes())))),
                Typed(infinity, ENat()), If(Equal(order, Typed(D(0), Naturals())),
                    Typed(infinity, ENat()), Cast(order, ENat())))));
    }

    private static Formula ProjectorFormula()
    {
        Formula algebra = TL(X("n"), Parameter());
        Formula step = LambdaOf("k", Naturals(), LambdaOf("p", algebra,
            Add(X("p"), Smul(new Formula.Fraction(LocalCall("qint", X("q"), X("k")),
                LocalCall("qint", X("q"), Add(X("k"), D(1)))),
                Multiply(Multiply(X("p"), LocalCall("gen", X("n"), Parameter(), Add(X("a"), X("k")))), X("p"))))));
        Formula recursion = At(Qualified("Nat", "rec"),
            At(Qualified("Function", "const"), Naturals(), algebra), Typed(D(1), algebra), step, X("s"));
        return All("q", Complexes(), All("n", Naturals(), All("a", Naturals(), All("s", Naturals(),
            Equal(Typed(LocalCall("jw", X("q"), X("n"), X("a"), X("s")), algebra), recursion)))));
    }

    private static Formula CompositeFormula()
    {
        Formula size = At(Qualified("List", "getD"), X("σ"), X("i"), D(0));
        Formula boxes = At(Qualified("List", "map"), LambdaOf("i", Naturals(),
            LocalCall("jw", X("q"), ListSum(X("σ")), ListSum(At(Qualified("List", "take"), X("i"), X("σ"))), size)),
            At(Qualified("List", "range"), Length()));
        return ListBinders(Equal(Typed(Projector(), CornerAmbient()), At(Qualified("List", "prod"), boxes)));
    }

    private static Formula BoundaryFormula() => ListBinders(All("i", Naturals(),
        Equal(Typed(LocalCall("jwGen", X("q"), X("σ"), X("i")), CornerAmbient()),
            Multiply(Multiply(Projector(), LocalCall("gen", ListSum(X("σ")), Parameter(),
                ListSum(At(Qualified("List", "take"), X("i"), X("σ"))))), Projector()))));

    private static Formula ClaimProposition()
    {
        Formula positive = All("s", Naturals(), Arrow(Member(X("s"), X("σ")), Less(D(0), X("s"))));
        Formula admissible = All("s", Naturals(), Arrow(Member(X("s"), X("σ")),
            Less(Cast(X("s"), ENat()), LocalCall("pbar", X("q")))));
        Formula generators = Seq(OpenBrace, Typed(X("u"), CornerAmbient()), Sp, Mid, Sp,
            Some("i", Naturals(), And(LE(D(1), X("i")), And(Less(X("i"), Length()),
                Equal(X("u"), LocalCall("jwGen", X("q"), X("σ"), X("i")))))), CloseBrace);
        Formula generated = At(Qualified("Algebra", "adjoin"), Complexes(),
            At(Qualified("insert"), Projector(), generators));
        return All("q", Complexes(), Arrow(NotEqual(X("q"), Typed(D(0), Complexes())),
            All("σ", ListOfNaturals(), Arrow(positive, Arrow(admissible, All("t", CornerAmbient(),
                Member(Multiply(Multiply(Projector(), X("t")), Projector()), generated)))))));
    }

    private static Formula X(string name) => name switch { "ν" => Nu, "σ" => SigmaLower, _ => F.Id(name) };
    private static Formula Qualified(params string[] parts)
    {
        var items = new System.Collections.Generic.List<Formula>();
        foreach (var part in parts)
        {
            if (items.Count > 0) items.Add(Dot);
            items.Add(part == "ι" ? Iota : F.Id(part));
        }
        return Seq(Operatorname, Grp(Seq([.. items])));
    }
