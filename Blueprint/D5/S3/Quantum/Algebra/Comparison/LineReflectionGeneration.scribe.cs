                Blocks(
                    Paragraph(Text("Let F be a finite-dimensional real inner product space of dimension n, and for a nonzero vector v let the line reflection be the orthogonal reflection in the line span(R, {v}): it fixes v and acts as minus the identity on the orthogonal complement of v. In the display, LinearIsometryEquiv(R, F, F) is the group of linear isometries of F onto itself, closure(S) is the subgroup generated by a set S of isometries, r is the generic element of the generating set, finrank(R, F) = n is the dimension, and det(g) is the determinant of the underlying linear map of g. The statement is: an isometry g is a finite product of line reflections and their inverses if and only if n is even or det(g) = 1. Thus the line reflections generate the whole orthogonal group in even dimension and exactly the isometries of determinant one in odd dimension. The dimensions zero and one are included; in dimension one every line reflection is the identity, and in dimension zero the group is trivial.")),
                    Paragraph(Text("The reflection in the hyperplane orthogonal to a nonzero vector v is minus the line reflection in span(R, {v}), and it has determinant -1. By the Cartan-Dieudonne theorem every isometry g is a product of k hyperplane reflections, so g = (-1)^k h with h a product of k line reflections and det(g) = (-1)^k. If det(g) = 1 then k is even and g = h lies in the generated subgroup. In even dimension the isometry -1 is the reflection in the zero subspace and has determinant (-1)^n = 1, so it lies in the generated subgroup, and therefore so does every g = (-1)^k h. In odd dimension the orthogonal complement of a line has even dimension n - 1, so every line reflection has determinant (-1)^(n-1) = 1; the determinant is multiplicative, hence every element of the generated subgroup has determinant one.")),
                    Paragraph(Text("Both conditions are needed. The hypothesis v nonzero matters, because the reflection in the zero line is -1, which would make every isometry a product of generators in every dimension. The parity of the dimension cannot be dropped: in odd dimension the isometry -1 has determinant -1 and is not a product of line reflections. The generation of the orthogonal group by hyperplane reflections is the classical Cartan-Dieudonne theorem; the parity refinement for line reflections is a standard consequence of it."))),
                DescribeRole.Theorem))));

    private static Formula Call(string name, params Formula[] arguments) =>
        new Formula.FunctionCall(FormulaIdentifier.Create(name), [.. arguments]);
    private static Formula Rel(Formula x, FormulaRelationOperator op, Formula y) => new Formula.Relation(x, op, y);
    private static Formula Equal(Formula x, Formula y) => Rel(x, FormulaRelationOperator.Equal, y);
    private static Formula Logic(Formula x, FormulaLogicOperator op, Formula y) => new Formula.Logic(x, op, y);
    private static Formula ForAll(string name, Formula domain, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), domain, body);
    private static Formula Exists(string name, Formula domain, Formula body) =>
        new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create(name), domain, body);
    private static Formula TypeStar => Seq(Operatorname, Grp(F.Id("Type")), Star);
    private static Formula Real => Seq(Mathbb, Grp(F.Id("R")));

    private static Formula ClosureFormula()
    {
        Formula space = F.Id("F"), g = F.Id("g"), r = F.Id("r"), v = F.Id("v");
        Formula isometries = Call("LinearIsometryEquiv", Real, space, space);
        Formula lineReflection = Call("reflection", Call("span", Real, new Formula.SetLiteral([v])));
        Formula generator = Exists("v", space,
            Logic(Rel(v, FormulaRelationOperator.NotEqual, D(0)), FormulaLogicOperator.And,
                Equal(r, lineReflection)));
        Formula generators = Seq(OpenBrace, r, Sp, InMacro, Sp, isometries, Sp, Mid, Sp, generator, CloseBrace);
        Formula body = ForAll("g", isometries,
            Logic(Rel(g, FormulaRelationOperator.MemberOf, Call("closure", generators)), FormulaLogicOperator.Iff,
                Logic(Call("Even", Call("finrank", Real, space)), FormulaLogicOperator.Or,
                    Equal(Call("det", g), D(1)))));
        return Disp(ForAll("F", TypeStar, Seq(
            OpenBracket, Call("NormedAddCommGroup", space), CloseBracket, Sp,
            OpenBracket, Call("InnerProductSpace", Real, space), CloseBracket, Sp,
            OpenBracket, Call("FiniteDimensional", Real, space), CloseBracket, Sp,
            body)));
    }
}
