using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Quantum.Algebra;

internal sealed class FourDimensionalSingletBranchingDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S3/Quantum/Algebra/FourDimensionalSingletBranching.";
    private static readonly LibraryNoteRef Source =
        LibraryNoteRef.Create("D5/L/Eigenstructure/grootnibbelink2020tension");

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "No finite group has a four-dimensional complex representation with trivial determinant and no trivial singlet whose restriction to every cyclic subgroup contains the trivial singlet. This proves the finite-group conjecture of S. Groot Nibbelink, O. Loukas, A. Mutter, E. Parr and P. K. S. Vaudrevange (arXiv:1710.09237), which the authors checked by computer for the 1,594 finite groups arising from the CARAT classification and for all finite groups of order at most 500; the two collections overlap.",
        H("Four-dimensional determinant-one representations and cyclic singlets"),
        Blocks(
            Node("claim", "The finite group conjecture", ClaimFormula(),
                "For every finite group H and every representation D of H by 4 x 4 complex matrices (a monoid homomorphism from H to the complex 4 x 4 matrices): if (i) every D(h) has determinant 1 and (ii) the only vector fixed by every D(h) is 0 (D contains no trivial singlet), then (iii) fails, that is, some cyclic subgroup K of H fixes no nonzero vector (the branching of D to K contains no trivial singlet).",
                "claim", DescribeRole.Definition, AssessedProvenance.FromLiterature(Source)),
            Node("result", "Proof of the conjecture", Disp(F.Id("claim")),
                "Suppose (i), (ii) and (iii). For the cyclic subgroup generated by h, (iii) gives a nonzero vector fixed by D(h), so det(1 - D(h)) = 0 for every h. For a 4 x 4 matrix A of determinant 1 the adjugate is the inverse, and expanding the determinant gives det(1 - A) = 2 - tr A - tr A^(-1) + e_2(A) with e_2(A) = ((tr A)^2 - tr(A^2))/2. The sum S of D(h) over H satisfies D(g) S = S, so its columns are fixed vectors and S = 0 by (ii); hence the traces of D(h) and of D(h)^(-1) = D(h^(-1)) sum to 0. Let T be the sum of the Kronecker squares D(h) x D(h) and W the swap of the two tensor factors. Then T^2 = |H| T, W^2 = 1 and W commutes with T, so Q = T(1 - W)/(2|H|) is idempotent; its trace is the rank of Q, a natural number r, and it equals the average of e_2(D(h)) because tr((A x A) W) = tr(A^2). Summing, the sum of det(1 - D(h)) over H is |H|(2 + r), which is not 0, a contradiction.",
                "result", DescribeRole.Theorem, AssessedProvenance.FromRepo(Source),
                new OpenProblemResolutionClaim(
                    ProblemSlugRef.Create("groot-nibbelink-2020-four-dimensional-singlet-branching"),
                    ResolutionKind.Proved))),
        []));

    private static DocumentBlock Node(
        string id, string title, Formula formula, string prose,
        string declaration, DescribeRole role, AssessedProvenance provenance,
        OpenProblemResolutionClaim? resolution = null) =>
        Describe.Lean(
            DescribeId.Create("singlet-" + id), DeclarationHandle.Create(Prefix + declaration),
            H(title), StatementSource.FromAuthor(formula), provenance,
            Blocks(Paragraph(Text(prose))), role, resolution);

    private static Formula Named(Formula name) => Seq(Operatorname, Grp(name));
    private static Formula Call(Formula name, params Formula[] arguments) =>
        new Formula.Apply(Named(name), [.. arguments]);
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula Rel(Formula left, FormulaRelationOperator op, Formula right) =>
        new Formula.Relation(left, op, right);
    private static Formula Equal(Formula left, Formula right) =>
        Rel(left, FormulaRelationOperator.Equal, right);
    private static Formula Iff(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.Iff, Parenthesized(right));
    private static Formula Implies(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Implies, right);
    private static Formula And(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.And, Parenthesized(right));
    private static Formula AllIn(Formula variable, Formula domain, Formula body) =>
        Seq(Forall, Sp, variable, Sp, InMacro, Sp, domain, Comma, Sp, body);
    private static Formula AllOf(Formula variable, Formula type, Formula body) =>
        Seq(Forall, Sp, variable, Sp, Colon, Sp, type, Comma, Sp, body);
    private static Formula Complexes() => Seq(Mathbb, Grp(F.Id("C")));
    private static Formula FinOf(byte n) => Call(F.Id("Fin"), D(n));
    private static Formula VectorSpace() => Seq(Complexes(), Caret, Grp(D(4)));
    private static Formula Act(Formula h, Formula v) =>
        Seq(new Formula.Apply(F.Id("D"), [h]), Sp, v);

    private static Formula ClaimFormula()
    {
        Formula h = F.Id("h"), k = F.Id("k"), v = F.Id("v"), group = F.Id("H"), cyc = F.Id("K"),
            rep = F.Id("D");
        Formula groupDomain = Seq(Named(F.Id("FiniteGroup")));
        Formula repType = Call(F.Id("MonoidHom"), group,
            Call(F.Id("Matrix"), FinOf(4), FinOf(4), Complexes()));
        Formula detOne = AllIn(h, group,
            Equal(Call(F.Id("det"), new Formula.Apply(rep, [h])), D(1)));
        Formula noSinglet = AllOf(v, VectorSpace(),
            Implies(AllIn(h, group, Equal(Act(h, v), v)), Equal(v, D(0))));
        Formula cyclicSinglet = AllOf(cyc, Call(F.Id("Subgroup"), group),
            Implies(Call(F.Id("IsCyclic"), cyc),
                Seq(Exists, Sp, v, Sp, InMacro, Sp, VectorSpace(), Comma, Sp,
                    And(Rel(v, FormulaRelationOperator.NotEqual, D(0)),
                        AllIn(k, cyc, Equal(Act(k, v), v))))));
        Formula conclusion = new Formula.Not(Parenthesized(cyclicSinglet));
        Formula body = AllIn(group, groupDomain,
            AllOf(rep, repType,
                Implies(detOne, Implies(noSinglet, conclusion))));
        return Disp(Iff(F.Id("claim"), body));
    }
}
