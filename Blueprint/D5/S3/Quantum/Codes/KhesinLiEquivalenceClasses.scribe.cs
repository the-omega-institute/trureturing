    private static Formula X(string name) => F.Id(name);
    private static Formula Named(string name) => Seq(Operatorname, Grp(X(name)));
    private static Formula Q(string owner, string name) => Seq(Named(owner), Dot, Named(name));
    private static Formula Call(string name, params Formula[] args) => new Formula.Apply(Named(name), [.. args]);
    private static Formula App(Formula function, params Formula[] args) => new Formula.Apply(function, [.. args]);
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula All(string name, Formula domain, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), domain, body);
    private static Formula Ex(string name, Formula domain, Formula body) =>
        new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create(name), domain, body);
    private static Formula And(Formula a, Formula b) =>
        new Formula.Logic(Parenthesized(a), FormulaLogicOperator.And, Parenthesized(b));
    private static Formula ImpliesF(Formula a, Formula b) =>
        new Formula.Logic(Parenthesized(a), FormulaLogicOperator.Implies, Parenthesized(b));
    private static Formula Iff(Formula a, Formula b) =>
        new Formula.Logic(Parenthesized(a), FormulaLogicOperator.Iff, Parenthesized(b));
    private static Formula EqualF(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.Equal, b);
    private static Formula Less(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThan, b);
    private static Formula NotF(Formula a) => new Formula.Not(Parenthesized(a));
    private static Formula Adj(Formula g, Formula a, Formula b) => App(Q("SimpleGraph", "Adj"), g, a, b);
    private static Formula Inl(Formula x) => App(Q("Sum", "inl"), x);
    private static Formula Inr(Formula x) => App(Q("Sum", "inr"), x);
    private static Formula FinType(string n) => Call("Fin", X(n));
    private static Formula Vertices() => Call("Sum", FinType("k"), FinType("n"));
    private static Formula Graph() => Call("SimpleGraph", Vertices());
    private static Formula Naturals() => Seq(Mathbb, Grp(X("N")));
    private static Formula KN(Formula body) => All("k", Naturals(), All("n", Naturals(), body));
    private static Formula LambdaXY(Formula body) => Seq(Named("fun"), Sp,
        Parenthesized(Seq(X("x"), Sp, X("y"), Colon, Sp, Vertices())), Sp, Mapsto, Sp, Parenthesized(body));
    private static Formula Complement(Formula g, Formula v) => App(Q("SimpleGraph", "fromRel"),
        LambdaXY(Call("Xor", Adj(g, X("x"), X("y")), And(Adj(g, v, X("x")), Adj(g, v, X("y"))))));

    private static Formula RowFormula()
    {
        Formula g = X("G"), a = X("a"), o = X("o"), i = X("i"), j = X("j");
        Formula row = Seq(Named("if"), Sp, EqualF(a, i), Sp, Named("then"), Sp,
            Call("Xor", Adj(g, Inl(i), Inr(o)), Adj(g, Inl(j), Inr(o))),
            Sp, Named("else"), Sp, Adj(g, X("x"), X("y")));
        Formula branches = new Formula.Aligned([
            Seq(Bar, Inl(a), Comma, Inr(o), Sp, Mapsto, Sp, row),
            Seq(Bar, Inr(o), Comma, Inl(a), Sp, Mapsto, Sp, row),
            Seq(Bar, X("x"), Comma, X("y"), Sp, Mapsto, Sp, Adj(g, X("x"), X("y")))]);
        Formula match = Seq(Named("match"), Sp, X("x"), Comma, X("y"), Sp, Named("with"), Sp, branches);
        return Disp(KN(All("G", Graph(), All("i", FinType("k"), All("j", FinType("k"),
            EqualF(Call("addInputRow", g, i, j), App(Q("SimpleGraph", "fromRel"), LambdaXY(match))))))));
    }

    private static Formula StepFormula(bool renormalize)
    {
        Formula g = X("G"), i = X("i"), j = X("j");
        string relation = renormalize ? "RenormStep" : "Step";
        Formula Perm(string side, string sigma) => App(Q("Equiv", "sumCongr"),
            side == "output" ? App(Q("Equiv", "refl"), FinType("k")) : X(sigma),
            side == "input" ? App(Q("Equiv", "refl"), FinType("n")) : X(sigma));
        Formula Mapped(Formula permutation) => App(Q("SimpleGraph", "map"),
            App(Q("Equiv", "toEmbedding"), permutation), g);
        var rows = new System.Collections.Generic.List<Formula>();
        if (!renormalize)
            rows.Add(All("v", Vertices(), Call(relation, g, Complement(g, X("v")))));
        rows.Add(All("sigma", App(Q("Equiv", "Perm"), FinType("n")),
            Call(relation, g, Mapped(Perm("output", "sigma")))));
        rows.Add(All("tau", App(Q("Equiv", "Perm"), FinType("k")),
            Call(relation, g, Mapped(Perm("input", "tau")))));
        rows.Add(All("i", FinType("k"), All("j", FinType("k"),
            ImpliesF(NotF(EqualF(i, j)), Call(relation, g, Call("addInputRow", g, i, j))))));
        Formula pair = App(Q("Sym2", "mk"), Inl(i), Inl(j));
        rows.Add(All("i", FinType("k"), All("j", FinType("k"),
            Call(relation, g, App(Q("SimpleGraph", "deleteEdges"), g, new Formula.SetLiteral([pair]))))));
        return Disp(KN(All("G", Graph(), new Formula.Aligned([.. rows]))));
    }

    private static Formula NormalizedFormula()
    {
        Formula g = X("G"), i = X("i"), j = X("j"), l = X("l");
        Formula noInputs = All("i", FinType("k"), All("j", FinType("k"), NotF(Adj(g, Inl(i), Inl(j)))));
        Formula pivots = All("i", FinType("k"), All("j", FinType("n"),
            ImpliesF(Less(Call("val", j), X("k")), Iff(Adj(g, Inl(i), Inr(j)), EqualF(Call("val", j), Call("val", i))))));
        Formula noPivots = All("j", FinType("n"), All("l", FinType("n"),
            ImpliesF(Less(Call("val", j), X("k")), ImpliesF(Less(Call("val", l), X("k")), NotF(Adj(g, Inr(j), Inr(l)))))));
        return Disp(KN(All("G", Graph(), Iff(Call("Normalized", g), And(noInputs, And(pivots, noPivots))))));
    }

    private static Formula NormalizedStepFormula() => Disp(KN(All("G", Graph(), All("H", Graph(),
        Iff(Call("NormalizedStep", X("G"), X("H")), And(Call("Normalized", X("G")),
            And(Call("Normalized", X("H")), Ex("Z", Graph(),
                And(Call("Step", X("G"), X("Z")), App(Q("Relation", "ReflTransGen"), Named("RenormStep"), X("Z"), X("H")))))))))));

    private static Formula ClassSizeFormula()
    {
        Formula members = Seq(OpenBrace, X("H"), Colon, Sp, Graph(), Sp, Slash, Slash, Sp,
            And(Call("Normalized", X("H")), App(Q("Relation", "EqvGen"), Named("NormalizedStep"), X("G"), X("H"))), CloseBrace);
        return Disp(KN(All("G", Graph(), EqualF(Call("classSize", X("G")), App(Q("Nat", "card"), members)))));
    }

    private static Formula ClaimBody()
    {
        Formula connectedClass = All("H", Graph(), ImpliesF(Call("Normalized", X("H")),
            ImpliesF(App(Q("Relation", "EqvGen"), Named("NormalizedStep"), X("G"), X("H")), App(Q("SimpleGraph", "Connected"), X("H")))));
        Formula divisibility = new Formula.Relation(new Formula.Power(D(3), X("k")),
            FormulaRelationOperator.Divides, Call("classSize", X("G")));
        return KN(ImpliesF(Less(D(0), X("k")), ImpliesF(Less(X("k"), X("n")),
            All("G", Graph(), ImpliesF(Call("Normalized", X("G")), ImpliesF(connectedClass, divisibility))))));
    }
