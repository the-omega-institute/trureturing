    private static Formula X(string name) => name switch
    {
        "σ" => SigmaLower,
        "τ" => Tau,
        _ => F.Id(name)
    };
    private static Formula Qualified(params string[] parts)
    {
        var items = new System.Collections.Generic.List<Formula>();
        foreach (var part in parts)
        {
            if (items.Count > 0) items.Add(Dot);
            items.Add(F.Id(part));
        }
        return Seq(Operatorname, Grp(Seq([.. items])));
    }
    private static Formula Local(string name) =>
        Qualified("D5", "S3", "Quantum", "Codes", "KhesinLiBipartiteEncoderEquivalence", name);
    private static Formula Encoder(string name) =>
        Qualified("D5", "S3", "Quantum", "Codes", "KhesinLiEquivalenceClasses", name);
    private static Formula At(Formula function, params Formula[] args) => new Formula.Apply(function, [.. args]);
    private static Formula Parenthesized(Formula value) => new Formula.LatexSequence([Open, value, Close]);
    private static Formula Typed(Formula value, Formula type) => Parenthesized(Seq(value, Colon, Sp, type));
    private static Formula Naturals() => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula FinOf(string size) => At(Qualified("Fin"), X(size));
    private static Formula Vertices() => At(Qualified("Sum"), FinOf("k"), FinOf("n"));
    private static Formula Graphs() => At(Qualified("SimpleGraph"), Vertices());
    private static Formula All(string name, Formula type, Formula body) =>
        Seq(Forall, Sp, Typed(X(name), type), Comma, Sp, Parenthesized(body));
    private static Formula Some(string name, Formula type, Formula body) =>
        Seq(Exists, Sp, Typed(X(name), type), Comma, Sp, Parenthesized(body));
    private static Formula LambdaOf(string name, Formula type, Formula body) =>
        Seq(LambdaLower, Sp, Typed(X(name), type), Sp, Mapsto, Sp, Parenthesized(body));
    private static Formula Arrow(Formula premise, Formula conclusion) =>
        new Formula.TypeArrow(Parenthesized(premise), Parenthesized(conclusion));
    private static Formula And(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.And, Parenthesized(right));
    private static Formula Or(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Or, Parenthesized(right));
    private static Formula Equivalence(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Iff, Parenthesized(right));
    private static Formula KN(Formula body) => All("k", Naturals(), All("n", Naturals(), body));
    private static Formula GH(Formula body) => All("G", Graphs(), All("H", Graphs(), body));
    private static Formula Mapped(Formula inputs, Formula outputs) =>
        At(Qualified("SimpleGraph", "map"),
            At(Qualified("DFunLike", "coe"), At(Qualified("Equiv", "toEmbedding"),
                At(Qualified("Equiv", "sumCongr"), inputs, outputs))), X("G"));

    private static Formula BipartiteStepFormula()
    {
        Formula outputs = Some("σ", At(Qualified("Equiv", "Perm"), FinOf("n")),
            Equal(X("H"), Mapped(At(Qualified("Equiv", "refl"), FinOf("k")), X("σ"))));
        Formula inputs = Some("τ", At(Qualified("Equiv", "Perm"), FinOf("k")),
            Equal(X("H"), Mapped(X("τ"), At(Qualified("Equiv", "refl"), FinOf("n")))));
        Formula rows = Some("i", FinOf("k"), Some("j", FinOf("k"),
            And(NotEqual(X("i"), X("j")), Equal(X("H"), At(Encoder("addInputRow"), X("G"), X("i"), X("j"))))));
        return KN(GH(Equivalence(At(Local("BipartiteStep"), X("G"), X("H")), Or(outputs, Or(inputs, rows)))));
    }

    private static Formula Bipartite(Formula graph)
    {
        Formula Side(string side) => At(Qualified("Set", "ofPred"), LambdaOf("v", Vertices(),
            Equal(At(Qualified("Sum", side), X("v")), Qualified("Bool", "true"))));
        return At(Qualified("SimpleGraph", "IsBipartiteWith"), graph, Side("isLeft"), Side("isRight"));
    }

    private static Formula ClaimBody() => KN(GH(Arrow(Bipartite(X("G")), Arrow(Bipartite(X("H")),
