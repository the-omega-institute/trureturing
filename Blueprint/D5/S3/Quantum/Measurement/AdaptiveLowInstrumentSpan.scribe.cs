using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Quantum.Measurement;

internal sealed class AdaptiveLowInstrumentSpanDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S3/Quantum/Measurement/AdaptiveLowInstrumentSpan.";
    private static readonly Formula A = F.Id("A"), J = F.Id("J"), Hh = F.Id("H");
    private static readonly Formula W = F.Id("W"), L = F.Id("l"), X = F.Id("X");
    private static readonly Formula Ev = F.Id("e"), R = F.Id("R"), Alg = F.Id("D");
    private static readonly Formula C = Seq(Mathbb, Grp(F.Id("C")));
    private static readonly Formula Type = Call("Type");
    private static readonly Formula Joint = Seq(A, Times, Sp, Hh);

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Finite adaptive events generated by one forward unitary and arbitrary low instruments "
            + "span the least invariant unital star algebra.",
        H("Actual Adaptive Low-Instrument Effects"),
        Blocks(
            Node("instrument", "Normalized finite instruments", InstrumentFormula(),
                "The outcome index is retained. The Kraus index within an outcome is hidden and summed. "
                    + "Different outcomes can select different subsequent protocols. Zero Kraus "
                    + "operators allow different finite Kraus multiplicities to be padded to a common size.",
                "LowInstrument", DescribeRole.Definition),
            Node("event", "Finite adaptive events", EventFormula(),
                "An event is a finite tree with accepting or rejecting Boolean leaves, a forward tick, "
                    + "and a normalized low instrument with an outcome-dependent continuation. Selecting "
                    + "the accepting leaves specifies a union of mutually exclusive complete histories. "
                    + "Selecting every descendant of a node specifies an intermediate event.",
                "Event", DescribeRole.Definition),
            Node("tensor", "The actual low tensor action", TensorFormula(),
                "The low embedding tensors a low matrix with the high identity. It preserves the "
                    + "unit, addition, multiplication, complex scalars and adjoints.",
                "tensorLow", DescribeRole.Definition),
            Node("effect", "Heisenberg event effects", RecursionFormula(false),
                "An accepted leaf has effect identity and a rejected leaf has effect zero. A tick "
                    + "pulls back the next effect by W. An instrument sums its Kraus pullbacks, using "
                    + "the continuation selected by each recorded outcome.",
                "effect", DescribeRole.Definition),
            Node("state", "Accepted Schrödinger substates", RecursionFormula(true),
                "The event map returns the input at an accepted leaf and zero at a rejected leaf. "
                    + "A tick evolves the input by W before continuing. An instrument continues "
                    + "on each Kraus substate and sums the accepted outputs. Inputs may have "
                    + "arbitrary low-high correlations.",
                "eventState", DescribeRole.Definition),
            Node("span", "The actual complex effect span", SpanFormula(),
                "The span is taken over the effects of actual finite events. Linear combinations "
                    + "of effects are algebraic observables and need not themselves be executable events.",
                "effectSpan", DescribeRole.Definition),
            Node("result", "Trace duality, effect bounds and the least invariant algebra", TheoremFormula(),
                "A scaled low filter can be completed by the positive square root of its defect "
                    + "to a normalized two-outcome instrument. Selecting the filter outcome and "
                    + "polarizing gives every low cross-sandwich of the actual effect span. Its "
                    + "two-sided idealizer therefore contains the low algebra. Forward prefixing "
                    + "preserves the span; finite-dimensional injectivity makes this preservation "
                    + "surjective. The idealizer is invariant, and event recursion puts every effect "
                    + "back in it. This proves equality and minimality. Inverse conjugation occurs "
                    + "only in the finite-dimensional proof; the event tree permits only forward ticks.",
                "actual_adaptive_span", DescribeRole.Theorem))));

    private static Formula Call(string name, params Formula[] args)
    {
        var items = new List<Formula> { Operatorname, Grp(F.Id(name)), Open };
        for (var k = 0; k < args.Length; k++)
        {
            if (k > 0) items.AddRange([Comma, Sp]);
            items.Add(args[k]);
        }
        items.Add(Close);
        return Seq([.. items]);
    }

    private static Formula M(Formula t) => Call("CStarMatrix", t, t, C);
    private static Formula StarOf(Formula x) => Call("star", x);
    private static Formula Mul(Formula x, Formula y) => new Formula.Binary(x, FormulaBinaryOperator.Multiply, y);
    private static Formula EqOf(Formula x, Formula y) => new Formula.Relation(x, FormulaRelationOperator.Equal, y);
    private static Formula Mem(Formula x, Formula y) => new Formula.Relation(x, FormulaRelationOperator.MemberOf, y);
    private static Formula AndOf(Formula x, Formula y) => new Formula.Logic(x, FormulaLogicOperator.And, y);
    private static Formula ImpliesOf(Formula x, Formula y) => new Formula.Logic(x, FormulaLogicOperator.Implies, y);
    private static Formula For(string name, Formula type, Formula body) => new Formula.BindMany(
        FormulaQuantifier.ForAll, [new Formula.BoundVariable(FormulaIdentifier.Create(name), type)], body);
    private static Formula Ex(string name, Formula type, Formula body) => new Formula.BindMany(
        FormulaQuantifier.Exists, [new Formula.BoundVariable(FormulaIdentifier.Create(name), type)], body);
    private static Formula Instances(Formula t, bool nonempty = false) => Seq(
        OpenBracket, Call("Fintype", t), CloseBracket, Sp,
        OpenBracket, Call("DecidableEq", t), CloseBracket, Sp,
        nonempty ? Seq(OpenBracket, Call("Nonempty", t), CloseBracket) : Grp());
    private static Formula Types(Formula body, bool nonempty = false) => For("A", Type,
        For("H", Type, Seq(Instances(A, nonempty), Sp, Instances(Hh, nonempty), Sp, body)));
    private static Formula E(Formula low, Formula gate, Formula e) => Call("effect", low, gate, e);
    private static Formula S(Formula low, Formula gate) => Call("effectSpan", low, gate);
    private static Formula Low => Call("tensorLow", Hh);

    private static Formula InstrumentFormula()
    {
        Formula n = F.Id("n"), m = F.Id("m"), k = F.Id("K");
        Formula y = F.Id("y"), r = F.Id("r");
        Formula kt = Call("K", y, r);
        return Disp(For("A", Type, Seq(Instances(A), Sp,
            Call("LowInstrument", A), Eq, OpenBrace,
            n, Colon, Call("Nat"), Comma, m, Colon, Call("Nat"), Comma,
            k, Colon, Call("Fin", n), To, Call("Fin", m), To, M(A), Mid,
            Sum, Underscore, Grp(y, Colon, Call("Fin", n)), Sp,
            Sum, Underscore, Grp(r, Colon, Call("Fin", m)), Sp,
            Mul(StarOf(kt), kt), Eq, Call("identity", A), CloseBrace)));
    }

    private static Formula EventFormula() => Disp(For("A", Type, Seq(Instances(A), Sp,
        Call("Event", A), Eq, Call("inductive",
            For("b", Call("Bool"), Seq(Call("stop", F.Id("b")), Colon, Call("Event", A))),
            For("next", Call("Event", A), Seq(Call("tick", F.Id("next")), Colon, Call("Event", A))),
            For("I", Call("LowInstrument", A), For("next",
                Seq(Call("Fin", Call("outcomes", F.Id("I"))), To, Call("Event", A)),
                Seq(Call("observe", F.Id("I"), F.Id("next")), Colon, Call("Event", A))))))));

    private static Formula TensorFormula() => Disp(Types(For("K", M(A),
        EqOf(Call("tensorLow", Hh, F.Id("K")),
            Call("kronecker", F.Id("K"), Call("identity", Hh))))));

    private static Formula RecursionFormula(bool state)
    {
        Formula rho = F.Id("rho");
        Formula b = F.Id("b"), i = F.Id("I"), y = F.Id("y"), r = F.Id("r");
        Formula next = F.Id("next"), k = Call("kraus", i, y, r);
        Formula lk = Call("apply", L, k);
        Formula applied = state ? Call("eventState", L, W, Ev, rho) : E(L, W, Ev);
        Formula child = Call("apply", next, y);
        Formula branch = state
            ? Call("eventState", L, W, child, Mul(Mul(lk, rho), StarOf(lk)))
            : Mul(Mul(StarOf(lk), E(L, W, child)), lk);
        Formula cases = Call("cases", Ev,
            Seq(Call("stop", Seq(b, Colon, Call("Bool"))), Mapsto,
                Call("if", b, state ? rho : Call("identity", J), D(0))),
            Seq(Call("tick", Seq(X, Colon, Call("Event", A))), Mapsto,
                state ? Call("eventState", L, W, X, Mul(Mul(W, rho), StarOf(W)))
                    : Mul(Mul(StarOf(W), E(L, W, X)), W)),
            Seq(Call("observe", Seq(i, Colon, Call("LowInstrument", A)),
                Seq(next, Colon, Call("Fin", Call("outcomes", i)), To, Call("Event", A))), Mapsto,
                Sum, Underscore, Grp(y, Colon, Call("Fin", Call("outcomes", i))), Sp,
                Sum, Underscore, Grp(r, Colon, Call("Fin", Call("multiplicity", i))), Sp, branch));
        Formula body = EqOf(applied, cases);
        if (state) body = For("rho", M(J), body);
        return Disp(For("A", Type, For("J", Type, Seq(Instances(A), Sp, Instances(J), Sp,
            For("l", Call("StarAlgHom", C, M(A), M(J)), For("W", M(J),
                For("e", Call("Event", A), body)))))));
    }

    private static Formula SpanFormula()
    {
        Formula range = Call("range", Call("effect", L, W));
        Formula body = EqOf(S(L, W), Call("complexSpan", range));
        return Disp(For("A", Type, For("J", Type,
            Seq(Instances(A), Sp, Instances(J), Sp,
                For("l", Call("StarAlgHom", C, M(A), M(J)), For("W", M(J), body))))));
    }

    private static Formula TheoremFormula()
    {
        Formula rho = F.Id("rho"), k = F.Id("K");
        Formula eff = E(Low, W, Ev);
        Formula duality = For("e", Call("Event", A), For("rho", M(Joint),
            EqOf(Call("trace", Call("eventState", Low, W, Ev, rho)), Call("trace", Mul(eff, rho)))));
        Formula bounds = For("e", Call("Event", A), Seq(D(0), Leq, eff, Land, eff, Leq, Call("identity", Joint)));
        Formula lowIn = For("K", M(A), Mem(Call("tensorLow", Hh, k), Alg));
        Formula invariant = For("X", M(Joint), new Formula.Logic(Mem(X, Alg), FormulaLogicOperator.Iff,
            Mem(Mul(Mul(StarOf(W), X), W), Alg)));
        Formula minimal = For("R", Call("StarSubalgebra", C, M(Joint)), ImpliesOf(
            AndOf(For("K", M(A), Mem(Call("tensorLow", Hh, k), R)),
                For("X", M(Joint), ImpliesOf(Mem(X, R), Mem(Mul(Mul(StarOf(W), X), W), R)))),
            new Formula.Relation(Alg, FormulaRelationOperator.SubsetOf, R)));
        Formula algebra = Ex("D", Call("StarSubalgebra", C, M(Joint)),
            AndOf(EqOf(Call("complexSpace", Alg), S(Low, W)),
                AndOf(lowIn, AndOf(invariant, minimal))));
        Formula unitary = AndOf(EqOf(Mul(StarOf(W), W), Call("identity", Joint)),
            EqOf(Mul(W, StarOf(W)), Call("identity", Joint)));
        return Disp(Types(For("W", M(Joint), ImpliesOf(unitary,
            AndOf(duality, AndOf(bounds, algebra)))), true));
    }

    private static DocumentBlock Node(string id, string title, Formula formula,
        string prose, string declaration, DescribeRole role) => Describe.Lean(
        DescribeId.Create("adaptive-low-instrument-" + id), DeclarationHandle.Create(Prefix + declaration),
        H(title), StatementSource.FromAuthor(formula), AssessedProvenance.FromRepo(),
        Blocks(Paragraph(Text(prose))), role);
}
