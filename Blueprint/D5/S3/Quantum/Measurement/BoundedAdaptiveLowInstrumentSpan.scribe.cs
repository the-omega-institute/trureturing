using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Quantum.Measurement;

internal sealed class BoundedAdaptiveLowInstrumentSpanDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S3/Quantum/Measurement/BoundedAdaptiveLowInstrumentSpan.";
    private static readonly Formula A = F.Id("A"), Hh = F.Id("H");
    private static readonly Formula W = F.Id("W"), N = F.Id("N"), X = F.Id("X");
    private static readonly Formula C = Seq(Mathbb, Grp(F.Id("C")));
    private static readonly Formula Joint = Seq(A, Times, Sp, Hh);

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "The complex spans of finite adaptive event effects with bounded forward calls "
            + "satisfy an exact recurrence under free low instruments.",
        H("Bounded Adaptive Low-Instrument Effects"),
        Blocks(
            Node("calls", "Worst recorded-branch call count", CallsFormula(),
                "A stopped event uses no calls. A tick adds one call. An instrument takes the "
                    + "maximum over its recorded outcomes, with empty maximum zero. Instruments "
                    + "are free. The hidden Kraus index is summed in the effect and never selects "
                    + "a continuation or enters the call maximum.",
                "worstBranchCalls", DescribeRole.Definition),
            Node("span", "Actual effects within a budget", SpanFormula(),
                "The generators are effects of actual finite event trees with at most N ticks "
                    + "on every recorded branch. The low action tensors a low matrix with the high "
                    + "identity. Complex linear combinations need not themselves be executable "
                    + "events. The budget counts ticks and places no bound on the number of free "
                    + "instruments, records or linear-combination coefficients.",
                "boundedEffectSpan", DescribeRole.Definition),
            Node("recurrence", "The exact next-call span", RecurrenceFormula(),
                "For every natural budget and finite nonempty low and high index types, the "
                    + "next span is generated by the current span and its low sandwiches after one "
                    + "forward pullback. A low matrix can be scaled to a contraction and completed "
                    + "by the positive square root of its defect to a two-outcome instrument. "
                    + "Continuing on the first outcome and rejecting on the second preserves the "
                    + "call count. Cancelling the nonzero scale in the complex span gives low "
                    + "sandwich stability. Tree induction handles all finite free prefixes and "
                    + "sums each hidden Kraus index with the same recorded-outcome continuation. "
                    + "Conversely, for a tail that is an actual event, prefixing one tick and such a "
                    + "filter realizes its sandwich up to a nonzero scalar. Complex linearity then "
                    + "places the sandwich of every element of the current span in the next span. "
                    + "The joint matrix W is arbitrary "
                    + "in this algebraic identity. A physical clock application requires a unitary "
                    + "W; positivity and normalization are supplied by the unitary event theory. "
                    + "The recurrence asserts neither general multiplicative closure, a saturation "
                    + "budget nor a uniform probability gap.",
                "actual_bounded_effect_span_recurrence", DescribeRole.Theorem))));

    private static Formula Call(string name, params Formula[] args)
    {
        var items = new List<Formula> { Operatorname, Grp(F.Id(name)), Open };
        for (var k = 0; k < args.Length; k++)
        {
            if (k > 0) items.AddRange([Comma, Sp]);
            items.Add(args[k]);
        }
        items.Add(Close);
        return Seq([.. items]);
    }

    private static Formula M(Formula t) => Call("CStarMatrix", t, t, C);
    private static Formula StarOf(Formula x) => Call("star", x);
    private static Formula Mul(Formula x, Formula y) => new Formula.Binary(x, FormulaBinaryOperator.Multiply, y);
    private static Formula AddOf(Formula x, Formula y) => new Formula.Binary(x, FormulaBinaryOperator.Add, y);
    private static Formula EqOf(Formula x, Formula y) => new Formula.Relation(x, FormulaRelationOperator.Equal, y);
    private static Formula Mem(Formula x, Formula y) => new Formula.Relation(x, FormulaRelationOperator.MemberOf, y);
    private static Formula LeOf(Formula x, Formula y) => new Formula.Relation(x, FormulaRelationOperator.LessThanOrEqual, y);
    private static Formula AndOf(Formula x, Formula y) => new Formula.Logic(x, FormulaLogicOperator.And, y);
    private static Formula For(string name, Formula type, Formula body) => new Formula.BindMany(
        FormulaQuantifier.ForAll, [new Formula.BoundVariable(FormulaIdentifier.Create(name), type)], body);
    private static Formula Ex(string name, Formula type, Formula body) => new Formula.BindMany(
        FormulaQuantifier.Exists, [new Formula.BoundVariable(FormulaIdentifier.Create(name), type)], body);
    private static Formula Instances(Formula t, bool nonempty = false) => Seq(
        OpenBracket, Call("Fintype", t), CloseBracket, Sp,
        OpenBracket, Call("DecidableEq", t), CloseBracket, Sp,
        nonempty ? Seq(OpenBracket, Call("Nonempty", t), CloseBracket) : Grp());
    private static Formula Types(Formula body, bool nonempty = false) => For("A", Call("Type"),
        For("H", Call("Type"), Seq(Instances(A, nonempty), Sp, Instances(Hh, nonempty), Sp, body)));
    private static Formula Calls(Formula e) => Call("worstBranchCalls", e);
    private static Formula SpanAt(Formula n) => Call("boundedEffectSpan", W, n);
    private static Formula Low(Formula k) => Call("tensorLow", Hh, k);
    private static Formula Effect(Formula e) => Call("effect", Call("tensorLow", Hh), W, e);

    private static Formula CallsFormula()
    {
        Formula e = F.Id("e"), b = F.Id("b"), next = F.Id("next");
        Formula i = F.Id("I"), y = F.Id("y");
        Formula outcomes = Call("Fin", Call("outcomes", i));
        Formula cases = Call("cases", e,
            Seq(Call("stop", Seq(b, Colon, Call("Bool"))), Mapsto, D(0)),
            Seq(Call("tick", Seq(next, Colon, Call("Event", A))), Mapsto, AddOf(D(1), Calls(next))),
            Seq(Call("observe", Seq(i, Colon, Call("LowInstrument", A)),
                Seq(next, Colon, outcomes, To, Call("Event", A))), Mapsto,
                Call("FinsetSup", Call("univ", outcomes),
                    Seq(y, Colon, outcomes, Mapsto, Calls(Call("apply", next, y))))));
        return Disp(For("A", Call("Type"), Seq(Instances(A), Sp,
            For("e", Call("Event", A), EqOf(Calls(e), cases)))));
    }

    private static Formula SpanFormula()
    {
        Formula e = F.Id("e");
        Formula generators = Seq(OpenBrace, X, Colon, M(Joint), Mid,
            Ex("e", Call("Event", A), AndOf(LeOf(Calls(e), N), EqOf(X, Effect(e)))), CloseBrace);
        return Disp(Types(For("W", M(Joint), For("N", Call("Nat"),
            EqOf(SpanAt(N), Call("complexSpan", generators))))));
    }

    private static Formula RecurrenceFormula()
    {
        Formula k = F.Id("K"), y = F.Id("Y");
        Formula sandwich = Mul(Mul(StarOf(Low(k)), Grp(Mul(Mul(StarOf(W), X), W))), Low(k));
        Formula added = Seq(OpenBrace, y, Colon, M(Joint), Mid,
            Ex("K", M(A), Ex("X", M(Joint), AndOf(Mem(X, SpanAt(N)), EqOf(y, sandwich)))), CloseBrace);
        Formula rhs = Call("complexSpan", Seq(Call("carrier", SpanAt(N)), Cup, Sp, added));
        return Disp(Types(For("W", M(Joint), For("N", Call("Nat"),
            EqOf(SpanAt(AddOf(N, D(1))), rhs))), true));
    }

    private static DocumentBlock Node(string id, string title, Formula formula,
        string prose, string declaration, DescribeRole role) => Describe.Lean(
        DescribeId.Create("bounded-adaptive-low-instrument-" + id), DeclarationHandle.Create(Prefix + declaration),
        H(title), StatementSource.FromAuthor(formula), AssessedProvenance.FromRepo(),
        Blocks(Paragraph(Text(prose))), role);
}
