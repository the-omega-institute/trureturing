    private static Formula Named(Formula name) => Seq(Operatorname,Grp(name));
    private static Formula Call(string name, params Formula[] args) => Call(Seq([.. name.Split('.').SelectMany((part,index) => index == 0 ? new Formula[]{F.Id(part)} : new Formula[]{Dot,F.Id(part)})]),args);
    private static Formula Call(Formula name, params Formula[] args) => args.Length == 0 ? Named(name) : new Formula.Apply(Named(name),[.. args]);
    private static Formula Parenthesized(Formula x) => Seq(Open,x,Close);
    private static Formula Equal(Formula a, Formula b) => new Formula.Relation(a,FormulaRelationOperator.Equal,b);
    private static Formula Relation(Formula a, FormulaRelationOperator op, Formula b) => new Formula.Relation(a,op,b);
    private static Formula Iff(Formula a, Formula b) => new Formula.Logic(a,FormulaLogicOperator.Iff,Parenthesized(b));
    private static Formula Imp(Formula a, Formula b) => new Formula.Logic(Parenthesized(a),FormulaLogicOperator.Implies,b);
    private static Formula And(Formula a, Formula b) => new Formula.Logic(Parenthesized(a),FormulaLogicOperator.And,Parenthesized(b));
    private static Formula Or(Formula a, Formula b) => new Formula.Logic(Parenthesized(a),FormulaLogicOperator.Or,Parenthesized(b));
    private static Formula Add(Formula a, Formula b) => new Formula.Binary(a,FormulaBinaryOperator.Add,b);
    private static Formula Sub(Formula a, Formula b) => new Formula.Binary(a,FormulaBinaryOperator.Subtract,b);
    private static Formula Mul(Formula a, Formula b) => new Formula.Binary(a,FormulaBinaryOperator.Multiply,b);
    private static Formula Negate(Formula a) => new Formula.Negate(a);
    private static Formula Arrow(Formula a, Formula b) => Seq(Parenthesized(a),Sp,To,Sp,b);
    private static Formula All(Formula a, Formula type, Formula body) => Seq(Forall,Sp,a,Colon,Sp,type,Comma,Sp,body);
    private static Formula Some(Formula a, Formula type, Formula body) => Seq(Exists,Sp,a,Colon,Sp,type,Comma,Sp,body);
    private static Formula NM(Formula body) => All(n,N,All(m,N,body));
    private static Formula Fin(Formula a) => Call("Fin",a);
    private static Formula Index(Formula a) => Call("QubitIndex",a);
    private static Formula State(Formula a) => Call("State",a);
    private static Formula Op(Formula a) => Call("Operator",a);
    private static Formula Units(Formula a) => Seq(Parenthesized(Op(a)),Caret,Grp(Times));
    private static Formula Group(Formula a) => Call("StabilizerGroup",a);
    private static Formula Basis(Formula a, Formula b) => Call("StabilizerBasis",a,b);
    private static Formula Unit(Formula a) => Call("UnitState",a);
    private static Formula Cast(Formula a, Formula type) => Parenthesized(Seq(Call("val",a),Colon,Sp,type));
    private static Formula RationalCast(Formula a) => Parenthesized(Seq(Call("Nat.cast",a),Colon,Sp,Q));
    private static Formula Norm(Formula a) => Seq(Vert,a,Vert);
    private static Formula SetOf(Formula a, Formula type, Formula body) => Seq(OpenBrace,a,Colon,Sp,type,Sp,Mid,Sp,body,CloseBrace);
    private static Formula Mem(Formula a, Formula b) => Seq(a,Sp,InMacro,Sp,b);
    private static Formula Leq(Formula a, Formula b) => Relation(a,FormulaRelationOperator.LessThanOrEqual,b);
    private static Formula LambdaOf(Formula a, Formula type, Formula body) => Seq(LambdaLower,Sp,a,Colon,Sp,type,Comma,Sp,body);
    private static Formula SumOf(Formula a, Formula type, Formula body) => Seq(Sum,Underscore,Grp(a,Colon,Sp,type),Sp,Parenthesized(body));
    private static Formula At(Formula f, Formula x) => new Formula.Apply(f,[x]);
    private static Formula SG(Formula a) => Call("subgroup",a);
    private static Formula Abelian(Formula a, Formula total)
    {
        Formula x=F.Id("x"),y=F.Id("y");
        return All(x,Units(total),Imp(Mem(x,a),All(y,Units(total),Imp(Mem(y,a),Equal(Mul(x,y),Mul(y,x))))));
    }
    private static Formula PauliGroupFormula()
    {
        Formula c=F.Id("c"),w=F.Id("w");
        return All(n,N,All(u,Units(n),Iff(Mem(u,Call("pauliGroup",n)),Some(c,C,And(Call("Phase",c),Some(w,Call("Word",n),Equal(Cast(u,Op(n)),Mul(c,Call("wordOp",w)))))))));
    }
    private static Formula GroupFormula()
    {
        Formula t=F.Id("T");
        Formula neg=new Formula.Not(Mem(Call("negIdentity",n),s));
        Formula maximal=All(t,Call("Subgroup",Units(n)),Imp(Leq(t,Call("pauliGroup",n)),Imp(Abelian(t,n),Imp(new Formula.Not(Mem(Call("negIdentity",n),t)),Imp(Leq(s,t),Equal(t,s))))));
        return All(n,N,Equal(Group(n),SetOf(s,Call("Subgroup",Units(n)),And(Leq(s,Call("pauliGroup",n)),And(Abelian(s,n),And(neg,maximal))))));
    }
    private static Formula EigenFormula()
    {
        Formula e=F.Id("e");
        return All(n,N,All(s,Group(n),All(v,State(n),Iff(Call("CommonEigenvector",s,v),All(u,Units(n),Imp(Mem(u,SG(s)),Some(e,C,Equal(Call("mulVec",Cast(u,Op(n)),v),Mul(e,v)))))))));
    }
    private static Formula JoinFormula()
    {
        Formula d=F.Id("d"),a=F.Id("a");
        return NM(All(d,Index(n),All(a,Index(m),Equal(Call("joinIndex",d,a),Call("Fin.addCases",d,a)))));
    }
    private static Formula CompressFormula()
    {
        Formula a=F.Id("a"),b=F.Id("b"),x=F.Id("x"),y=F.Id("y"),A=F.Id("A");
        Formula entry=new Formula.Apply(A,[Call("joinIndex",x,a),Call("joinIndex",y,b)]);
        Formula value=SumOf(a,Index(m),SumOf(b,Index(m),Mul(Mul(Call("star",At(Call("val",psi),a)),entry),At(Call("val",psi),b))));
        return NM(All(A,Op(Add(n,m)),All(psi,Unit(m),Equal(Call("compress",A,psi),Call("Matrix.of",LambdaOf(x,Index(n),LambdaOf(y,Index(n),value)))))));
    }
    private static Formula BasisFormula()
    {
        Formula g=F.Id("G"),i=F.Id("i"),j=F.Id("j"),x=F.Id("x"),total=Add(n,m);
        Formula orth=All(i,Index(total),All(j,Index(total),Equal(SumOf(x,Index(total),Mul(Call("star",new Formula.Apply(v,[i,x])),new Formula.Apply(v,[j,x]))),Call("ite",Equal(i,j),D(1),D(0)))));
        Formula eigen=All(i,Index(total),Call("CommonEigenvector",g,At(v,i)));
        Formula span=Equal(Call("span",C,Call("range",v)),Call("top",Call("Submodule",C,State(total))));
        Formula fields=Seq(Parenthesized(Seq(g,Colon,Sp,Group(total),Comma,Sp,v,Colon,Sp,Arrow(Index(total),State(total)))),Sp,Mid,Sp,And(orth,And(eigen,span)));
        return NM(Equal(Basis(n,m),Seq(OpenBrace,fields,CloseBrace)));
    }
    private static Formula SpanFormula()
    {
        Formula b=F.Id("b"),B=F.Id("B");
        Formula effects=LambdaOf(b,Index(Add(n,m)),Call(Mu,psi,At(Call("vectors",B),b)));
        return NM(All(psi,Unit(m),All(B,Basis(n,m),Equal(Call("smu",psi,B),Call("finrank",C,Call("span",C,Call("range",effects)))))));
    }
    private static Formula SupportFormula()
    {
        Formula J=F.Id("J"),c=F.Id("c"),w=F.Id("w"),i=F.Id("i");
        Formula support=All(i,Fin(n),Imp(new Formula.Not(Mem(i,J)),Equal(At(w,i),Call("Pauli.I"))));
        Formula body=Some(c,C,And(Call("Phase",c),Some(w,Call("Word",n),And(Equal(Cast(u,Op(n)),Mul(c,Call("wordOp",w))),support))));
        return All(n,N,All(J,Call("Set",Fin(n)),All(u,Units(n),Iff(Mem(u,Call("supportedPauliGroup",n,J)),body))));
    }
    private static Formula SupportSubgroupFormula(bool data)
    {
        Formula i=F.Id("i"),total=Add(n,m);
        Formula condition=data? Relation(Call("val",i),FormulaRelationOperator.LessThan,n):Leq(n,Call("val",i));
        Formula positions=SetOf(i,Fin(total),condition);
        return NM(All(s,Group(total),Equal(Call(data?"dataSubgroup":"ancillaSubgroup",s),Call("inf",SG(s),Call("supportedPauliGroup",total,positions)))));
    }
    private static Formula DimensionFormula(bool data) => NM(All(s,Group(Add(n,m)),Equal(Call(data?"dimData":"dimAncilla",s),Call("Nat.log",D(2),Call("Nat.card",Call(data?"dataSubgroup":"ancillaSubgroup",s))))));
    private static Formula ParameterFormula()
    {
        Formula numerator=Sub(Sub(Add(RationalCast(n),RationalCast(m)),RationalCast(Call("dimData",s))),RationalCast(Call("dimAncilla",s)));
        return NM(All(s,Group(Add(n,m)),Equal(Call("entanglementP",s),new Formula.Fraction(numerator,D(2)))));
    }
    private static Formula ClaimFormula()
    {
        Formula B=F.Id("B"),Bp=Seq(F.Id("B"),Apos);
        Formula optimal=All(Bp,Basis(n,m),Leq(Call("smu",psi,Bp),Call("smu",psi,B)));
        return Iff(F.Id("claim"),NM(All(psi,Unit(m),Some(B,Basis(n,m),And(Call("MaximallyEntangled",B),optimal)))));
    }
