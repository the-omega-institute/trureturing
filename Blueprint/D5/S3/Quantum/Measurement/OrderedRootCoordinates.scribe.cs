    private static Formula NJMBody(Formula q)
    {
        var a=Proj(q,1);var b=Proj(q,2);var x=Proj(a,1);var y=Proj(b,1);var av=Proj(a,2);var bv=Proj(b,2);
        var ha=Pow(Call("hYu",x,av),2);var hb=Pow(Call("hYu",y,bv),2);
        return And(Mem(a,X("V")),And(Mem(b,X("V")),Less(Pow(Sub(Call("inner",R(),av,bv),Mul(x,y)),2),
            Mul(Sub(Sub(N(1),ha),hb),Sub(Sub(N(1),Div(Pow(x,2),ha)),Div(Pow(y,2),hb))))));
    }
    private static Formula Ordered(Formula u,Formula v) => And(Leq(N(0),v),And(Leq(v,u),Leq(u,N(1))));
    private static Formula RootCoordinates()
    {
        var u=X("u");var v=X("v");var x=Call("xCoord",u,v);var r=Call("rCoord",u,v);
        var h=Call("hYu",x,App(Q("PiLp","single"),N(2),N(0),r));
        return All("u",R(),All("v",R(),Impl(Ordered(u,v),Impl(Less(N(0),u),And(Equal(Pow(h,2),u),Equal(Div(Pow(x,2),Pow(h,2)),v))))));
    }
    private static Formula AngularVolume()
    {
        var u=X("u");var v=X("v");var U=X("U");var V=X("V");var s=X("s");
        var A=Sub(Sub(N(1),u),U);var B=Sub(Sub(N(1),v),V);
        var r=Mul(Call("rCoord",u,v),Call("rCoord",U,V));var x=Mul(Call("xCoord",u,v),Call("xCoord",U,V));
        var body=And(Leq(new Formula.Negate(N(1)),s),And(Leq(s,N(1)),Less(Pow(Sub(Mul(r,s),x),2),Mul(A,B))));
        var rhs=Conditional(Less(N(0),A),OfReal(Div(Mul(N(2),SqrtOf(Mul(A,B))),r)),N(0));
        return All("u",R(),All("v",R(),All("U",R(),All("V",R(),Impl(Ordered(u,v),Impl(Ordered(U,V),Equal(Volume(SetOf("s",R(),body)),rhs)))))));
    }

