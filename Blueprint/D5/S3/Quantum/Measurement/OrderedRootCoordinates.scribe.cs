        X("d"), Q("MeasureTheory", "volume"));
    private static DocumentBlock SourceParagraph(string prose)
    {
        var spans = prose.Split('$');
        List<Inline> content = [];
        for (var i = 0; i < spans.Length; i++)
        {
            if (spans[i].Length == 0) continue;
            if (i % 2 == 0) { content.Add(Text(spans[i])); continue; }
            if (spans[i] == @"\mathbf{Pr}[\Theta^{\mathrm{NJM}}_{2,2}]=\frac14.")
            {
                content.Add(Text("𝐏𝐫[Θᴺᴶᴹ₂,₂] = "));
                content.Add(Math(Div(N(1), N(4))));
                content.Add(Text("."));
            }
            else content.Add(QuotationInline(spans[i]));
        }
        return Paragraph([.. content]);
    }
    private static Inline QuotationInline(string span) => span switch
    {
        @"\mathbf A" => Math(Seq(Mathbf, Grp(X("A")))),
        @"\mathbf B" => Math(Seq(Mathbf, Grp(X("B")))),
        @"(a_0,\boldsymbol a)" => Text("(a₀, 𝒂)"),
        @"(b_0,\boldsymbol b)" => Text("(b₀, 𝒃)"),
        _ => throw new ArgumentException("Unknown source quotation formula.")
    };
    private static DocumentBlock Node(string name, string title, string prose, DescribeRole role,
        Formula formula, AssessedProvenance? provenance = null) => Describe.Lean(
            DescribeId.Create(name.Replace('_','-').ToLowerInvariant()),
            DeclarationHandle.Create(Prefix + name), H(title),
            StatementSource.FromAuthor(Disp(formula)), provenance ?? AssessedProvenance.FromRepo(),
            Blocks(SourceParagraph(prose)), role);
