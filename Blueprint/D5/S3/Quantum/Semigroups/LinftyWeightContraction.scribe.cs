    private static DocumentBlock Entry(string id, string name, string title, Formula formula,
        string prose, DescribeRole role, bool literature) => Describe.Lean(
            DescribeId.Create(id), DeclarationHandle.Create(Prefix + name), H(title),
            StatementSource.FromAuthor(formula),
            literature ? AssessedProvenance.FromLiterature(Source) : AssessedProvenance.FromRepo(Source),
            Blocks(Paragraph(Text(prose))), role,
            name == "result" ? new OpenProblemResolutionClaim(
                ProblemSlugRef.Create("madou-remizov-vafadar-2024-linf-weight-contraction"),
                ResolutionKind.Refuted) : null);

    private static Formula V(string name) => F.Id(name);
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula Call(string name, params Formula[] args) =>
        new Formula.FunctionCall(FormulaIdentifier.Create(name), [.. args]);
    private static Formula Nat => Seq(Mathbb, Grp(V("N")));
    private static Formula Real => Seq(Mathbb, Grp(V("R")));
    private static Formula Complex => Seq(Mathbb, Grp(V("C")));
    private static Formula Fin => Call("Fin", V("n"));
    private static Formula Vec => Seq(Fin, Sp, To, Sp, Complex);
    private static Formula Weight => Seq(Fin, Sp, To, Sp, Real);
    private static Formula Mat => Call("Matrix", Fin, Fin, Complex);
    private static Formula All(string name, Formula type, Formula body) =>
        Seq(Forall, Sp, V(name), Colon, Sp, type, Comma, Sp, body);
    private static Formula Ex(string name, Formula type, Formula body) =>
        Seq(Exists, Sp, V(name), Colon, Sp, type, Comma, Sp, body);
    private static Formula And(Formula a, Formula b) =>
        new Formula.Logic(Parenthesized(a), FormulaLogicOperator.And, Parenthesized(b));
    private static Formula Imp(Formula a, Formula b) =>
        new Formula.Logic(Parenthesized(a), FormulaLogicOperator.Implies, Parenthesized(b));
    private static Formula Iff(Formula a, Formula b) =>
        new Formula.Logic(a, FormulaLogicOperator.Iff, Parenthesized(b));
    private static Formula Eqn(Formula a, Formula b) =>
        new Formula.Relation(a, FormulaRelationOperator.Equal, b);
    private static Formula Le(Formula a, Formula b) =>
        new Formula.Relation(a, FormulaRelationOperator.LessThanOrEqual, b);
    private static Formula Lt(Formula a, Formula b) =>
        new Formula.Relation(a, FormulaRelationOperator.LessThan, b);
    private static Formula Mul(Formula a, Formula b) =>
        new Formula.Binary(a, FormulaBinaryOperator.Multiply, b);
    private static Formula Image => Call("mulVec", Call("semigroup", V("A"), V("t")), V("u"));
    private static Formula Norm(Formula u) => Call("supNorm", u);

    private static Formula SupNorm() => Disp(All("n", Nat, All("u", Vec,
        Eqn(Norm(V("u")), Seq(Vert, Sp, V("u"), Vert)))));

    private static Formula Sectorial()
    {
        Formula q = Seq(Sum, Underscore, Grp(Seq(V("i"), Colon, Sp, Fin)), Sp,
            Mul(Call("coord", Call("mulVec", V("A"), V("u")), V("i")),
                Call("conj", Call("coord", V("u"), V("i")))));
        Formula re = Call("re", q), im = Call("abs", Call("im", q));
        return Disp(All("n", Nat, All("A", Mat,
            Iff(Call("IsSectorialMatrix", V("A")), Ex("C", Real, All("u", Vec,
                And(Le(D(0), re), Le(im, Mul(V("C"), re)))))))));
    }

    private static Formula Semigroup() => Disp(All("n", Nat, All("A", Mat, All("t", Real,
        Eqn(Call("semigroup", V("A"), V("t")),
            Call("exp", Call("smul", Call("ofReal", Seq(Minus, V("t"))), V("A"))))))));

    private static Formula Claim()
    {
        Formula bound = Ex("M", Real, All("t", Real, Imp(Le(D(0), V("t")), All("u", Vec,
            Le(Norm(Image), Mul(V("M"), Norm(V("u"))))))));
        Formula positive = All("i", Fin, Lt(D(0), Call("coord", V("g"), V("i"))));
        Formula contract = All("t", Real, Imp(Le(D(0), V("t")), All("u", Vec,
            Le(Norm(Call("weighted", V("g"), Image)), Norm(Call("weighted", V("g"), V("u")))))));
        Formula conclusion = Ex("g", Weight, And(positive, contract));
        return Disp(Iff(V("claim"), All("n", Nat, All("A", Mat,
            Imp(Call("IsSectorialMatrix", V("A")), Imp(bound, conclusion))))));
    }
