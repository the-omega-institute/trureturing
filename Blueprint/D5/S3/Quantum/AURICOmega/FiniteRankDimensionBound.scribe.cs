    private static DocumentBlock Node(
        string id, string selector, string title, StatementSource statement,
        AssessedProvenance provenance, string prose, DescribeRole role) =>
        Describe.Lean(DescribeId.Create("finite-rank-dimension-bound-" + id),
            DeclarationHandle.Create(Prefix + selector), H(title), statement, provenance,
            Blocks(Paragraph(Text(prose))), role);

    private static Formula Call(string name, params Formula[] arguments) =>
        new Formula.FunctionCall(FormulaIdentifier.Create(name), [.. arguments]);
    private static Formula Reals => Seq(Mathbb, Grp(F.Id("R")));
    private static Formula Naturals => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula TypeStar => Seq(Operatorname, Grp(F.Id("Type")), Star);
    private static Formula Euclid(Formula n) => Call("EuclideanSpace", Reals, Call("Fin", n));
    private static Formula Mul(Formula x, Formula y) => Seq(x, Sp, Cdot, Sp, y);
    private static Formula Instance(Formula body) => Seq(OpenBracket, body, CloseBracket);
    private static Formula Imp => Seq(Sp, Rightarrow, Sp);

    private static Formula LocalMap(Formula space, Formula v, Formula point, Formula d)
    {
        Formula f = F.Id("f");
        return Seq(
            Forall, Sp, v, Colon, Sp, Call("Set", space), Comma, Sp,
            v, Sp, InMacro, Sp, Call("nhds", point), Imp,
            Forall, Sp, f, Colon, Sp, space, Sp, To, Sp, Euclid(d), Comma, Sp,
            Call("ContinuousOn", f, v), Imp, Call("InjOn", f, v));
    }

    private static Formula GroupFormula()
    {
        Formula d = F.Id("d"), n = F.Id("n"), g = F.Id("G"), v = F.Id("V"), a = F.Id("a"), b = F.Id("b");
        return Disp(Seq(
            Forall, Sp, d, Comma, Sp, n, Colon, Sp, Naturals, Comma, Sp,
            Forall, Sp, g, Colon, Sp, TypeStar, Comma, Sp,
            Instance(Call("TopologicalSpace", g)), Comma, Sp, Instance(Call("Group", g)), Comma, Sp,
            Instance(Call("IsTopologicalGroup", g)), Comma, Sp,
            Instance(Call("LocallyCompactSpace", g)), Comma, Sp,
            Instance(Call("PreconnectedSpace", g)), Comma, Sp,
            LocalMap(g, v, D(1), d), Imp,
            Forall, Sp, Rho, Colon, Sp,
            Call("MonoidHom", g, Call("orthogonalGroup", Call("Fin", n), Reals)), Comma, Sp,
            Call("Continuous", Rho), Imp, Call("Injective", Rho), Imp,
            Open, Exists, Sp, a, Comma, Sp, b, Colon, Sp, g, Comma, Sp,
            Mul(a, b), Sp, Neq, Sp, Mul(b, a), Close, Imp,
            D(3), Sp, Leq, Sp, d));
    }

    private static Formula ChainFormula()
    {
        Formula m = F.Id("M"), c = F.Id("C"), x = F.Id("x");
        return Disp(Seq(
            Forall, Sp, m, Colon, Sp, TypeStar, Comma, Sp,
            Instance(Call("TopologicalSpace", m)), Comma, Sp,
            Instance(Call("PreconnectedSpace", m)), Comma, Sp,
            Forall, Sp, c, Colon, Sp, Call("TernaryComparison", m), Comma, Sp,
            Open, Forall, Sp, x, Colon, Sp, m, Comma, Sp, Call("ContinuousAt", Call("kappa", c, x), x), Close,
            Imp, Call("ChainConnected", c)));
    }

    private static Formula StructureFormula()
    {
        Formula d = F.Id("d"), m = F.Id("M"), c = F.Id("C"), x = F.Id("x"), p = F.Id("p"),
            r = F.Id("r"), o = F.Id("o"), v = F.Id("V");
        Formula pair = Seq(m, Sp, Times, Sp, m, Sp, Times, Sp, m);
        Formula transfer = Seq(Open, p, Colon, Sp, pair, Close, Sp, Mapsto, Sp,
            Call("tri", c, Seq(p, Dot, D(1)), Seq(p, Dot, D(2), Dot, D(1)), Seq(p, Dot, D(2), Dot, D(2))));
        return Disp(Seq(
            Forall, Sp, d, Colon, Sp, Naturals, Comma, Sp,
            Forall, Sp, m, Colon, Sp, TypeStar, Comma, Sp,
            Instance(Call("TopologicalSpace", m)), Comma, Sp,
            Instance(Call("LocallyCompactSpace", m)), Comma, Sp,
            Instance(Call("PreconnectedSpace", m)), Comma, Sp,
            Forall, Sp, c, Colon, Sp, Call("TernaryComparison", m), Comma, Sp,
            Call("Continuous", transfer), Imp,
            Open, Forall, Sp, x, Colon, Sp, m, Comma, Sp, Call("ContinuousAt", Call("kappa", c, x), x), Close, Imp,
            Call("Noncommutative", c), Imp,
            Forall, Sp, r, Colon, Sp, Naturals, Comma, Sp, Call("HasFeatureRank", c, r), Imp,
            Forall, Sp, o, Colon, Sp, m, Comma, Sp,
            LocalMap(m, v, o, d), Imp,
            D(3), Sp, Leq, Sp, d, Sp, Land, Sp, D(5), Sp, Leq, Sp, r));
    }
