                "Let C be a ternary comparison structure on a preconnected topological space M such that, for every x, the reading kappa x is continuous at the point x. Then C is chain connected: for every positive e, any two points are joined by a finite chain in which consecutive points a and b satisfy 1 - e < kappa a b. "
                    + "Fix e. Since kappa a a = 1 and kappa a is continuous at a, the points b with 1 - e < kappa a b form a neighbourhood of a, and by symmetry of the reading they also satisfy 1 - e < kappa b a. "
                    + "The relation of being joined by such a chain is an equivalence relation that relates every point to all points of a neighbourhood, so on a preconnected space it relates any two points.",
                DescribeRole.Theorem),
            Node("three-le-dim-of-has-feature-rank", "three_le_dim_of_hasFeatureRank",
