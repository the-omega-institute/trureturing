                    + "Suppose that C is noncommutative, that it has feature rank r, and that some neighbourhood V of a point o admits a map f into Euclidean space of dimension d that is continuous and injective on V. "
                    + "Then d >= 3 and r >= 5. "
                    + "The hypotheses are local compactness, preconnectedness and one neighbourhood with a continuous injective map into Euclidean space of dimension d; a connected manifold of dimension d is a special case, using the chart at o. "
                    + "The group at o, with product tri x o y and identity o, is a topological group because the transfer is continuous. "
