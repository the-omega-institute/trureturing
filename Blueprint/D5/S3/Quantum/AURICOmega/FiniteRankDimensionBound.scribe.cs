                    + "Both bounds are attained together: the unit quaternions with transfer x y^-1 z and reading (1 + <x, y>) / 2 form a noncommutative structure of feature rank five, by the theorem quaternionModel_hasFeatureRank_five, on the unit three-sphere, a compact connected manifold of dimension three.",
