    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "A noncommutative, preconnected, locally compact group with a continuous injective homomorphism into an orthogonal group, a neighbourhood of the identity of which maps continuously and injectively into R^d, has d >= 3; a noncommutative ternary comparison structure of finite feature rank r on a preconnected, locally compact space with continuous transfer and a reading continuous on the diagonal, a neighbourhood of which maps continuously and injectively into R^d, has d >= 3 and r >= 5.",
        H("Dimension bound for finite-rank ternary comparison structures"),
        Blocks(
            Node("three-le-of-orthogonal", "three_le_of_orthogonal",
                "Noncommutative orthogonal groups need dimension at least three",
                StatementSource.FromAuthor(GroupFormula()), AssessedProvenance.FromRepo(),
                "Let G be a topological group that is locally compact, preconnected and noncommutative, with a continuous injective homomorphism rho into the orthogonal group of size n. "
                    + "Suppose that some neighbourhood V of the identity admits a map f into Euclidean space of dimension d that is continuous and injective on V. Then d >= 3. "
                    + "No charts and no manifold structure are assumed; a group locally homeomorphic to Euclidean space of dimension d is a special case, since its charts give local compactness and the chart at the identity is such a map f. "
                    + "A real matrix X is a one-parameter generator of rho when the curve t -> exp (t X) lifts through rho to a continuous curve in G, that is, when there is a continuous map c from the real line to G with rho (c t) = exp (t X) for every real t; these generators form a real Lie subalgebra L of matrices. "
                    + "Because rho takes orthogonal values, every generator is skew: the product of the transpose of exp (t X) with exp (t X) is constant equal to 1, and its derivative at t = 0 is the transpose of X plus X. "
                    + "The trace form of L for its natural action on column vectors in R^n is (X, Y) -> tr (X Y); like the trace form of any Lie module it is invariant, and on a Lie algebra of skew matrices it is separating, since tr (X X) is minus the sum of the squares of the entries of X. "
                    + "A real Lie algebra of dimension at most two with an invariant separating bilinear form is abelian. "
                    + "If L were abelian, the exponential chart would map an open neighbourhood of 0 in L onto a neighbourhood of the identity in G whose elements commute pairwise; the subgroup generated by this neighbourhood is open, hence closed, hence all of the preconnected group G, so G would be commutative. "
                    + "Hence L has dimension k >= 3. The exponential chart is injective on an open neighbourhood of 0 in L, so composing it with f gives a continuous injection of a nonempty open subset of Euclidean space of dimension k into Euclidean space of dimension d; for d <= 2 < k this is excluded by the low-dimensional invariance of domain, so d >= 3. "
                    + "The argument uses the one-parameter subgroup method of von Neumann's theorem on closed linear groups, with local compactness of G in place of closedness of the image; the classical route through the theorem of Gleason, Montgomery and Zippin that a locally Euclidean group is a Lie group is not used. "
                    + "Noncommutativity is necessary: the circle group of rotations of the plane is commutative, compact and connected, embeds into the orthogonal group of size two, and a neighbourhood of the identity maps injectively onto an interval, so d = 1 there.",
