{
    private const string Prefix = "D5/S3/Quantum/AURICOmega/TernaryComparisonRankFive.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "A noncommutative, chain-connected ternary comparison structure admits no feature rank below five; at feature rank five, with readings arbitrarily close to zero, it embeds into the unit quaternions.",
        H("Feature rank of noncommutative ternary comparison structures"),
        Blocks(
            Node("five-le-of-has-feature-rank", "five_le_of_hasFeatureRank",
                "Noncommutative structures need feature rank at least five",
                StatementSource.FromAuthor(FiveLeFormula()), AssessedProvenance.FromRepo(),
                "Let C be a ternary comparison structure on M whose transfer is order sensitive and whose reading is chain connected. "
                    + "If the reading is the Gram kernel of a map f from M into Euclidean r-space, that is, kappa x y equals the inner product of f x and f y for all x and y, then r >= 5. "
                    + "Fix a base point o (M is nonempty since the transfer is order sensitive) and let W be the span of the image of f. The image consists of unit vectors, since kappa x x = 1, with pairwise nonnegative inner products, since the reading is nonnegative. "
                    + "Left translations x -> tri g o x of the group at o preserve the reading, so they extend to linear isometries of W permuting the image. "
                    + "They therefore fix the point m of least norm in the closed convex hull of the image; m is nonzero, and the inner product of m with f x equals the squared norm of m for every x. "
                    + "The vectors f x - m span the orthogonal complement E of m in W, whose dimension is less than r, and their Gram kernel is kappa minus the squared norm of m. "
                    + "On E, left and right translations act by two commuting families of linear isometries. "
                    + "The left translations have no common nonzero fixed vector, and by chain connectivity the group they form is generated by translations whose readings against the identity are close to one; such a translation sends no nonzero vector to its negative. "
                    + "The right translations do not all commute, because the group at o is noncommutative. "
                    + "Suppose r <= 4. Then E has dimension at most three, so these facts make the left translations act irreducibly on E with the right translations in their commutant, "
                    + "and the quaternionic coordinates for such a pair force E to have dimension exactly four, a contradiction. Hence r >= 5.",
                DescribeRole.Theorem),
            Node("exists-unit-quaternion-embedding", "exists_unitQuaternion_embedding",
                "Feature rank five and the unit quaternions",
                StatementSource.FromAuthor(EmbeddingFormula()), AssessedProvenance.FromRepo(),
                "Let C be a ternary comparison structure on M whose transfer is order sensitive, whose reading is chain connected, takes values arbitrarily close to zero (for every positive e some reading is below e), and is the Gram kernel of a map into Euclidean 5-space. "
                    + "Then there is an injective map u from M into the unit quaternions with u (tri x y z) = u x * (u y)^-1 * u z for all x, y, z, "
                    + "and kappa x y = (1 + <u x, u y>) / 2 for all x and y, where the inner product is the real inner product of the quaternions u x and u y in H. "
                    + "In the notation of the feature-rank bound, the quaternionic coordinates on the four-dimensional space E give a product-reversing injective map q into the unit quaternions with kappa x y = a + (1 - a) * <q x, q y>, where a is the squared norm of m and a < 1. "
                    + "Readings arbitrarily close to zero give a <= 1/2. "
                    + "A unit quaternion p different from 1 has a power whose real part is at most minus the real part of p, so every reading between distinct points is at most 2 a; "
                    + "chain connectivity supplies readings between distinct points arbitrarily close to one, which gives a >= 1/2. "
                    + "Hence a = 1/2, and u x is the conjugate of q x, which turns the product-reversing map q into a map carrying tri x y z to u x * (u y)^-1 * u z.",
