    private static DocumentBlock Node(
        string id, string selector, string title, StatementSource statement,
        AssessedProvenance provenance, string prose, DescribeRole role) =>
        Describe.Lean(DescribeId.Create("ternary-comparison-rank-five-" + id),
            DeclarationHandle.Create(Prefix + selector), H(title), statement, provenance,
            Blocks(Paragraph(Text(prose))), role);

    private static Formula Call(string name, params Formula[] arguments) =>
        new Formula.FunctionCall(FormulaIdentifier.Create(name), [.. arguments]);
    private static Formula Rel(Formula x, FormulaRelationOperator op, Formula y) => new Formula.Relation(x, op, y);
    private static Formula Equal(Formula x, Formula y) => Rel(x, FormulaRelationOperator.Equal, y);
    private static Formula Logic(Formula x, FormulaLogicOperator op, Formula y) => new Formula.Logic(x, op, y);
    private static Formula Implies(Formula x, Formula y) => Logic(x, FormulaLogicOperator.Implies, y);
    private static Formula And(Formula x, Formula y) => Logic(x, FormulaLogicOperator.And, y);
    private static Formula ForAll(string name, Formula domain, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), domain, body);
    private static Formula Exists(string name, Formula domain, Formula body) =>
        new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create(name), domain, body);
    private static Formula ForAllMany(Formula domain, Formula body, params string[] names) =>
        new Formula.BindMany(FormulaQuantifier.ForAll,
            [.. names.Select(name => new Formula.BoundVariable(FormulaIdentifier.Create(name), domain))], body);
    private static Formula At(Formula function, Formula argument) => new Formula.Apply(function, [argument]);
    private static Formula Mul(Formula x, Formula y) => new Formula.Binary(x, FormulaBinaryOperator.Multiply, y);

    private static Formula M => F.Id("M");
    private static Formula C => F.Id("C");
    private static Formula Reals => Seq(Mathbb, Grp(F.Id("R")));
    private static Formula Naturals => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula Quaternions => Seq(Mathbb, Grp(F.Id("H")));
    private static Formula TypeStar => Seq(Operatorname, Grp(F.Id("Type")), Star);

    /// <summary>Closes a body over the carrier M and the structure C on M.</summary>
    private static Formula OverStructure(Formula body) =>
        Disp(ForAll("M", TypeStar, ForAll("C", Call("TernaryComparison", M), body)));

    private static Formula Tri(Formula x, Formula y, Formula z) => Call("tri", C, x, y, z);
    private static Formula Kappa(Formula x, Formula y) => Call("kappa", C, x, y);

    private static Formula FiveLeFormula()
    {
        Formula r = F.Id("r");
        return OverStructure(Implies(Call("Noncommutative", C), Implies(Call("ChainConnected", C),
            ForAll("r", Naturals, Implies(Call("HasFeatureRank", C, r),
                Rel(D(5), FormulaRelationOperator.LessThanOrEqual, r))))));
    }

    private static Formula EmbeddingFormula()
    {
        Formula u = F.Id("u"), x = F.Id("x"), y = F.Id("y"), z = F.Id("z");
        Formula inverse = new Formula.Power(At(u, y), new Formula.Negate(D(1)));
        Formula transfer = ForAllMany(M,
            Equal(At(u, Tri(x, y, z)), Mul(Mul(At(u, x), inverse), At(u, z))), "x", "y", "z");
        Formula inner = new Formula.Subscript(
            Seq(Langle, Sp, At(u, x), Comma, Sp, At(u, y), Sp, Rangle), Reals);
        Formula reading = ForAllMany(M,
            Equal(Kappa(x, y), new Formula.Fraction(
                new Formula.Binary(D(1), FormulaBinaryOperator.Add, inner), D(2))), "x", "y");
        Formula embedding = Exists("u", new Formula.TypeArrow(M, Call("unitary", Quaternions)),
            And(Call("Injective", u), And(transfer, reading)));
        return OverStructure(Implies(Call("Noncommutative", C), Implies(Call("ChainConnected", C),
            Implies(Call("TouchesZero", C), Implies(Call("HasFeatureRank", C, D(5)), embedding)))));
    }
}
