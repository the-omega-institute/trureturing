{
    private const string Prefix = "D5/S3/Quantum/AURICOmega/ReflectedDisplacementRefutation.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Must a reflected displacement square to the identity on the equal-row quotient at sharp contrast?",
        H("A reflected displacement with square fidelity below one"),
        Blocks(
            Describe.Lean(DescribeId.Create("reflected-square-claim"), DeclarationHandle.Create(Prefix + "claim"),
                H("The proposed rigidity property"),
                StatementSource.WithoutFormula(), AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "Consider a symmetric, normalized, entrywise nonnegative rational kernel on a group. "
                    + "Assume invariance under common left and right multiplication, and nonnegative Gram "
                    + "forms on all finite rationally weighted samples. Set t = k(x,y), d = k(x,z) − k(y,z), "
                    + "and g = z⁻¹(xz⁻¹y). The proposed implication is that 0 < t < 1 and d² = 1 − t "
                    + "force k(1,g²) = 1."))),
                DescribeRole.Definition),
            Describe.Lean(DescribeId.Create("reflected-square-counterexample"),
                DeclarationHandle.Create(Prefix + "result"),
                H("A counterexample at overlap 272/441"),
                StatementSource.WithoutFormula(), AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text("Take the quadratic rational algebra R generated by s with s² = 545. "
                        + "Set D = (305 + s)/578 and adjoin J with J² = −D, using the involution J ↦ −J "
                        + "that fixes R. The group consists of elements h = u + vJ with u² + Dv² = 1. "
                        + "Both real embeddings of R make D positive.")),
                    Paragraph(Text("Use the two group characters h and h⁴ in this algebra. Let a and b be the "
                        + "unitary elements with coordinates ((209 − s)/674, (883 − s)/674) and "
                        + "((−1429 − s)/1766, (5729 − 17s)/7064). Set c to the first coordinate of ab and "
                        + "T(u) = 8u⁴ − 8u² + 1. The raw reading at h is C + L u + T(u), with "
                        + "L = −16c(2c² − 1) and C = −Lc − T(c). Use the rational coordinate in R of "
                        + "the raw reading at x⁻¹y and divide it by its value at the identity.")),
                    Paragraph(Text("The raw reading factors as 8(u − c)²((u + c)² + 2c² − 1). "
                        + "Under each real embedding c < −3/4, so the reading is nonnegative. "
                        + "The same embeddings make C and L nonnegative. They turn the Gram form into a "
                        + "weighted sum of the constant square and the coordinate norm squares from h and h⁴. "
                        + "The rational coordinate is the average under these two embeddings.")),
                    Paragraph(Text("At x = a, y = b and z = 1 the overlap is 272/441 and the signed contrast "
                        + "is 13/21. Their squared-contrast equality is exact. The reflected displacement "
                        + "is ab and k(1,(ab)²) < 1."))),
                DescribeRole.Theorem)),
        []));
}
