    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula Named(string name) => Seq(Operatorname, Grp(name.Split('.').SelectMany((part, index) =>
        index == 0 ? new[] { F.Id(part) } : new Formula[] { Dot, F.Id(part) }).ToArray()));
    private static Formula Call(string name, params Formula[] arguments) => new Formula.Apply(Named(name), [.. arguments]);
    private static Formula At(Formula function, params Formula[] arguments) => new Formula.Apply(function, [.. arguments]);
    private static Formula All(Formula variable, Formula type, Formula body) =>
        Seq(Forall, Sp, variable, Colon, Sp, type, Comma, Sp, body);
    private static Formula Some(Formula variable, Formula type, Formula body) =>
        Seq(Exists, Sp, variable, Colon, Sp, type, Comma, Sp, body);
    private static Formula Fun(Formula variable, Formula type, Formula body) =>
        Seq(Operatorname, Grp(F.Id("fun")), Sp, Parenthesized(Seq(variable, Colon, Sp, type)), Sp, Mapsto, Sp, body);
    private static Formula Rel(Formula left, FormulaRelationOperator op, Formula right) => new Formula.Relation(left, op, right);
    private static Formula Eq(Formula left, Formula right) => Rel(left, FormulaRelationOperator.Equal, right);
    private static Formula Ne(Formula left, Formula right) => Rel(left, FormulaRelationOperator.NotEqual, right);
    private static Formula Mem(Formula left, Formula right) => Rel(left, FormulaRelationOperator.MemberOf, right);
    private static Formula LeTo(Formula left, Formula right) => Rel(left, FormulaRelationOperator.LessThanOrEqual, right);
    private static Formula And(Formula left, Formula right) => new Formula.Logic(Parenthesized(left), FormulaLogicOperator.And, Parenthesized(right));
    private static Formula Imp(Formula left, Formula right) => new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Implies, right);
    private static Formula IffTo(Formula left, Formula right) => new Formula.Logic(left, FormulaLogicOperator.Iff, Parenthesized(right));
    private static Formula Add(Formula left, Formula right) => new Formula.Binary(left, FormulaBinaryOperator.Add, right);
    private static Formula Sub(Formula left, Formula right) => new Formula.Binary(left, FormulaBinaryOperator.Subtract, right);
    private static Formula Mul(Formula left, Formula right) => new Formula.Binary(left, FormulaBinaryOperator.Multiply, right);
    private static Formula Negate(Formula value) => Seq(Minus, value);
    private static Formula Naturals() => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula Reals() => Seq(Mathbb, Grp(F.Id("R")));
    private static Formula Complexes() => Seq(Mathbb, Grp(F.Id("C")));
    private static Formula FinOf(Formula n) => Call("Fin", n);
    private static Formula BitType(Formula n) => Call("Lex", Parenthesized(Seq(FinOf(n), To, FinOf(D(2)))));
    private static Formula MatType(Formula n) => Call("Matrix", BitType(n), BitType(n), Complexes());
    private static Formula UnitType(Formula n) => new Formula.Power(Parenthesized(MatType(n)), Times);
    private static Formula Typed(Formula value, Formula type) => Parenthesized(Seq(value, Colon, Sp, type));
    private static Formula SetOf(Formula variable, Formula type, Formula predicate) =>
        Seq(OpenBrace, variable, Colon, Sp, type, Bar, Sp, predicate, CloseBrace);
    private static Formula SetList(params Formula[] values) => Seq(OpenBrace,
        Seq(values.SelectMany((value, index) => index == 0 ? new[] { value } : new Formula[] { Comma, Sp, value }).ToArray()), CloseBrace);
    private static Formula SumOf(Formula v, Formula domain, Formula body) => Seq(new Formula.Subscript(Sum, Seq(v, Colon, Sp, domain)), Sp, body);
    private static Formula ProdIn(Formula v, Formula domain, Formula body) => Seq(new Formula.Subscript(Prod, Seq(v, InMacro, Sp, domain)), Sp, body);

