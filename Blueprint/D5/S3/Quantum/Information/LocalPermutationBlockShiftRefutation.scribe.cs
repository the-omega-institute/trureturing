        Seq(Begin, Grp(F.Id("pmatrix")),
            D(1), Amp, D(0), Amp, D(0), Amp, D(0), RowBreak,
            D(0), Amp, D(0), Amp, D(1), Amp, D(0), RowBreak,
            D(0), Amp, Negate(D(1)), Amp, D(0), Amp, D(0), RowBreak,
            D(0), Amp, D(0), Amp, D(0), Amp, D(1), End, Grp(F.Id("pmatrix")))));


    private static Formula LocalFormula()
    {
        Formula n = F.Id("n"), m = F.Id("M"), p = F.Id("P"), k = F.Id("k");
        var factors = All(k, FinOf(n), Mem(At(p, k), SetList(D(1), Negate(D(1)), F.Id("J"), Negate(F.Id("J")))));
        var predicate = Some(p, Parenthesized(Seq(FinOf(n), To, Call("Matrix", FinOf(D(2)), FinOf(D(2)), Complexes()))),
            And(factors, Eq(m, Call("tensorOp", p))));
        return Disp(All(n, Naturals(), Eq(Call("PiLoc", n), SetOf(m, MatType(n), predicate))));
    }

    private static Formula AdjacentFormula()
    {
        Formula n = F.Id("n"), k = F.Id("k"), x = F.Id("x"), y = F.Id("y"), j = F.Id("j");
        var kv = Call("val", k);
        var a = Call("Fin.mk", kv);
        var b = Call("Fin.mk", Add(kv, D(1)));
        var row = Call("finProdFinEquiv", Parenthesized(Seq(At(x, a), Comma, At(x, b))));
        var col = Call("finProdFinEquiv", Parenthesized(Seq(At(y, a), Comma, At(y, b))));
        var filter = Call("Finset.filter", Parenthesized(Fun(j, FinOf(n),
            And(Ne(Call("val", j), kv), Ne(Call("val", j), Add(kv, D(1)))))), Typed(Named("Finset.univ"), Call("Finset", FinOf(n))));
        var value = Mul(Call("Pout", row, col), ProdIn(j, filter,
            At(Typed(D(1), Call("Matrix", FinOf(D(2)), FinOf(D(2)), Complexes())), At(x, j), At(y, j))));
        return Disp(All(n, Naturals(), All(k, FinOf(Parenthesized(Sub(n, D(1)))),
            All(x, BitType(n), All(y, BitType(n), Eq(Call("adjacent", k, x, y), value))))));
    }

    private static Formula GeneratorsFormula()
    {
        Formula n = F.Id("n"), u = F.Id("u"), k = F.Id("k");
        var predicate = Some(k, FinOf(Parenthesized(Sub(n, D(1)))), Eq(Typed(u, MatType(n)), Call("adjacent", k)));
        return Disp(All(n, Naturals(), Eq(Call("outGenerators", n), SetOf(u, UnitType(n), predicate))));
    }

    private static Formula OutFormula()
    {
        Formula n = F.Id("n");
        return Disp(All(n, Naturals(), Eq(Call("PiOut", n), Call("Subgroup.closure", Call("outGenerators", n)))));
    }

    private static Formula ExtendedFormula()
    {
        Formula n = F.Id("n"), m = F.Id("M"), p = F.Id("p"), q = F.Id("q");
        var predicate = Some(p, MatType(n), And(Mem(p, Call("PiLoc", n)), Some(q, UnitType(n),
            And(Mem(q, Call("PiOut", n)), Eq(m, Mul(p, Typed(q, MatType(n))))))));
        return Disp(All(n, Naturals(), Eq(Call("PiEx", n), SetOf(m, MatType(n), predicate))));
    }

    private static Formula TorusFormula()
    {
        Formula n = F.Id("n"), d = F.Id("D"), lam = F.Id("lam"), k = F.Id("k"), j = F.Id("j");
        var term = Call("ite", Eq(j, k), Seq(Parenthesized(Mul(Named("Complex.I"), Typed(At(lam, k), Complexes()))), Cdot, Sp, Named("qubitZ")), D(1));
        var predicate = Some(lam, Parenthesized(Seq(FinOf(n), To, Reals())), Eq(d,
            SumOf(k, FinOf(n), Call("tensorOp", Parenthesized(Fun(j, FinOf(n), term))))));
        return Disp(All(n, Naturals(), Eq(Call("tloc", n), SetOf(d, MatType(n), predicate))));
    }

    private static Formula RootFormula()
    {
        Formula n = F.Id("n"), a = F.Id("A"), d = F.Id("D"), phi = F.Id("phi");
        var eigen = Eq(Sub(Mul(d, a), Mul(a, d)), Seq(Parenthesized(Mul(Named("Complex.I"), Typed(phi, Complexes()))), Cdot, Sp, a));
        var predicate = Some(d, MatType(n), And(Mem(d, Call("tloc", n)), Some(phi, Reals(), And(Ne(phi, D(0)), eigen))));
        return Disp(All(n, Naturals(), Eq(Call("E", n), SetOf(a, MatType(n), predicate))));
    }

    private static Formula BlockFormula()
    {
        Formula n = F.Id("n"), m = F.Id("M"), beta = F.Id("beta"), r = F.Id("r"), c = F.Id("c");
        var entries = All(r, BitType(n), All(c, BitType(n), Imp(Ne(At(m, r, c), D(0)), Eq(At(beta, r), Add(At(beta, c), D(1))))));
        var body = Some(beta, Parenthesized(Seq(BitType(n), To, Naturals())), And(Call("Monotone", beta), entries));
        return Disp(All(n, Naturals(), All(m, MatType(n), IffTo(Call("IsBlockShift", m), body))));
    }

    private static Formula ClaimFormula()
    {
        Formula n = F.Id("n"), a = F.Id("A"), p = F.Id("P");
        var conjugate = Mul(Mul(p, a), new Formula.Power(p, Negate(D(1))));
        var conclusion = Some(p, MatType(n), And(Mem(p, Call("PiEx", n)), Call("IsBlockShift", conjugate)));
        var body = All(n, Naturals(), Imp(LeTo(D(2), n), All(a, MatType(n), Imp(Mem(a, Call("E", n)), conclusion))));
        return Disp(IffTo(F.Id("claim"), body));
    }
