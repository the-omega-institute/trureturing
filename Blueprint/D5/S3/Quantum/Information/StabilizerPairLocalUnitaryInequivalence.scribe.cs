    private static Formula Named(string name) => Seq(Operatorname, Grp(F.Id(name)));
    private static Formula Call(string name, params Formula[] arguments) =>
        new Formula.Apply(Named(name), [.. arguments]);
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula Equal(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.Equal, right);
    private static Formula And(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.And, right);
    private static Formula Or(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Or, Parenthesized(right));
    private static Formula Iff(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.Iff, Parenthesized(right));
    private static Formula All(string variable, Formula domain, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(variable), domain, body);
    private static Formula Some(string variable, Formula domain, Formula body) =>
        new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create(variable), domain, body);
    private static Formula Sub(Formula value, Formula index) => new Formula.Subscript(value, index);
    private static Formula Complexes() => Seq(Mathbb, Grp(F.Id("C")));
    private static Formula Bits(Formula n) => new Formula.TypeArrow(Call("Fin", n), Call("Fin", D(2)));

    private static Formula PauliFormula() => Disp(Equal(Named("Pauli"),
        new Formula.SetLiteral([Named("I"), Named("X"), Named("Y"), Named("Z")])));

    private static Formula PauliMatrixFormula()
    {
        Formula Image(string label) => Call("pauliMatrix", Named(label));
        return Disp(And(And(Equal(Image("I"), D(1)), Equal(Image("X"), Named("qubitX"))),
            And(Equal(Image("Y"), Seq(F.Id("i"), Sp, Cdot, Sp, Parenthesized(
                Seq(Named("qubitX"), Sp, Cdot, Sp, Named("qubitZ"))))),
                Equal(Image("Z"), Named("qubitZ")))));
    }

    private static Formula TensorFormula()
    {
        Formula m = F.Id("M"), x = F.Id("x"), y = F.Id("y"), i = F.Id("i"), n = F.Id("n");
        Formula entry = new Formula.Apply(Sub(m, i), [Sub(x, i), Sub(y, i)]);
        Formula product = Seq(Sub(Prod, Seq(i, Sp, InMacro, Sp, Call("Fin", n))), Sp, entry);
        return Disp(All("x", Bits(n), All("y", Bits(n),
            Equal(new Formula.Apply(Call("tensorOp", m), [x, y]), product))));
    }

    private static Formula WordFormula()
    {
        Formula g = F.Id("g"), i = F.Id("i");
        return Disp(Equal(Call("wordOp", g), Call("tensorOp",
            Parenthesized(Seq(i, Sp, Mapsto, Sp, Call("pauliMatrix", Sub(g, i)))))));
    }

    private static Formula PermutationFormula()
    {
        Formula x = F.Id("x"), y = F.Id("y"), sigma = F.Id("sigma"), n = F.Id("n");
        Formula condition = Equal(y, Seq(x, Sp, Circ, Sp, sigma));
        Formula value = Seq(Named("if"), Sp, condition, Sp, Named("then"), Sp, D(1), Sp,
            Named("else"), Sp, D(0));
        return Disp(All("x", Bits(n), All("y", Bits(n),
            Equal(new Formula.Apply(Call("qubitPermutation", sigma), [x, y]), value))));
    }

    private static Formula CodespaceFormula()
    {
        Formula s = F.Id("S"), psi = F.Id("psi"), j = F.Id("j");
        Formula fixedBy = All("j", Call("Fin", D(3)),
            Equal(Seq(Call("wordOp", Sub(s, j)), Sp, psi), psi));
        return Disp(Equal(Call("codespace", s),
            Seq(OpenBrace, psi, Sp, Mid, Sp, fixedBy, CloseBrace)));
    }

    private static Formula Words(string name, string first, string second, string third) =>
        Disp(Equal(Named(name), Seq(Langle, Sp, F.Id(first), Comma, Sp, F.Id(second), Comma, Sp,
            F.Id(third), Sp, Rangle)));

    private static Formula Equivalent(byte qubits, string source, string target)
    {
        Formula u = F.Id("U"), sigma = F.Id("sigma"), n = D(qubits);
        Formula map = Seq(Call("tensorOp", u), Sp, Cdot, Sp, Call("qubitPermutation", sigma));
        Formula toLin = new Formula.Apply(Seq(Operatorname, Grp(F.Id("toLin"), Apos)), [map]);
        Formula image = Call("map", toLin, Call("codespace", Named(source)));
        return Some("U", new Formula.TypeArrow(Call("Fin", n), Call("unitaryGroup", Call("Fin", D(2)), Complexes())),
            Some("sigma", Call("Perm", Call("Fin", n)), Equal(image, Call("codespace", Named(target)))));
    }

    private static Formula ClaimFormula() => Disp(Iff(F.Id("claim"),
        Or(Equivalent(5, "SA", "SB"), Equivalent(6, "Splus", "Sminus"))));
