    private static Formula Named(string name)
    {
        string[] words = name.Split('.');
        Formula[] items = new Formula[words.Length * 2 - 1];
        for (int i = 0; i < words.Length; i++)
        {
            items[2 * i] = F.Id(words[i]);
            if (i + 1 < words.Length) items[2 * i + 1] = Dot;
        }
        return Seq(Operatorname, Grp(items));
    }

    private static Formula Call(string name, params Formula[] args) => new Formula.Apply(Named(name), [.. args]);
    private static Formula Apply(Formula f, params Formula[] args) => new Formula.Apply(f, [.. args]);
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula All(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), type, body);
    private static Formula Some(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create(name), type, body);
    private static Formula Equal(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.Equal, b);
    private static Formula Less(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThan, b);
    private static Formula LeqTo(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThanOrEqual, b);
    private static Formula And(Formula a, Formula b) => new Formula.Logic(Parenthesized(a), FormulaLogicOperator.And, Parenthesized(b));
    private static Formula Imp(Formula a, Formula b) => new Formula.Logic(Parenthesized(a), FormulaLogicOperator.Implies, Parenthesized(b));
    private static Formula IffTo(Formula a, Formula b) => new Formula.Logic(a, FormulaLogicOperator.Iff, Parenthesized(b));
    private static Formula Add(Formula a, Formula b) => new Formula.Binary(a, FormulaBinaryOperator.Add, b);
    private static Formula Sub(Formula a, Formula b) => new Formula.Binary(a, FormulaBinaryOperator.Subtract, b);
    private static Formula Mul(Formula a, Formula b) => new Formula.Binary(a, FormulaBinaryOperator.Multiply, b);
    private static Formula Product(Formula a, Formula b) => Parenthesized(Seq(a, Sp, Times, Sp, b));
    private static Formula Pair(Formula a, Formula b) => Parenthesized(Seq(a, Comma, Sp, b));
    private static Formula MatrixOf(Formula rows, Formula cols) => Call("Matrix", rows, cols, Complexes);
    private static Formula Complexes => Seq(Mathbb, Grp(F.Id("C")));
    private static Formula Reals => Seq(Mathbb, Grp(F.Id("R")));
    private static Formula Naturals => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula FinOf(Formula d) => Call("Fin", d);
    private static Formula Instances(Formula body, params Formula[] carriers)
    {
        for (int i = carriers.Length - 1; i >= 0; i--)
        {
            Formula t = carriers[i];
            body = Seq(OpenBracket, Call("Fintype", t), CloseBracket, Sp,
                OpenBracket, Call("DecidableEq", t), CloseBracket, Sp, body);
        }
        return body;
    }
    private static Formula SumOver(Formula i, Formula type, Formula body) =>
        Seq(Sum, Underscore, Grp(i, Colon, type), Sp, Parenthesized(body));
    private static Formula LambdaOf(Formula x, Formula type, Formula body) =>
        Seq(Named("fun"), Sp, Parenthesized(Seq(x, Colon, type)), Sp, Mapsto, Sp, body);
    private static Formula LetIn(Formula x, Formula type, Formula value, Formula body) =>
        Seq(Named("let"), Sp, x, Colon, type, Sp, Colon, Eq, Sp, value, Comma, Sp, body);

    private static Formula CorrectableFormula()
    {
        Formula a = F.Id("a"), b = F.Id("b"), iota = F.Id("iota"), k = F.Id("K"),
            o = F.Id("O"), i = F.Id("i"), j = F.Id("j");
        Formula predicate = All("i", iota, All("j", iota,
            Call("Commute", o, Mul(Call("conjTranspose", Apply(k, i)), Apply(k, j)))));
        Formula set = Seq(OpenBrace,
            o, Colon, MatrixOf(a, a), Sp, Mid, Sp, predicate,
            CloseBrace);
        return Disp(All("a", Named("Type"), All("b", Named("Type"),
            Instances(Seq(OpenBracket, Call("Fintype", b), CloseBracket, Sp,
                All("iota", Named("Type"), All("K", new Formula.TypeArrow(iota, MatrixOf(b, a)),
                    Equal(Call("correctable", k), Call("Algebra.adjoin", Complexes, set))))), a))));
    }

    private static Formula EntropyFormula()
    {
        Formula a = F.Id("a"), m = F.Id("M"), h = F.Id("h"), i = F.Id("i");
        Formula value = Seq(Named("if"), Sp, h, Colon, Call("Matrix.IsHermitian", m), Sp,
            Named("then"), Sp, SumOver(i, a, Call("Real.negMulLog", Call("Matrix.IsHermitian.eigenvalues", h, i))),
            Sp, Named("else"), Sp, D(0));
        return Disp(All("a", Named("Type"), Instances(All("M", MatrixOf(a, a),
            Equal(Call("entropy", m), value)), a)));
    }

    private static Formula CmiFormula()
    {
        Formula a = F.Id("A"), b = F.Id("B"), c = F.Id("C"), m = F.Id("M"),
            r = F.Id("R"), n = F.Id("N"), x = F.Id("x");
        Formula abc = Product(Product(a, b), c), regrouped = Product(a, Product(b, c));
        Formula map = LambdaOf(x, regrouped, Pair(Pair(Call("Prod.fst", x),
            Call("Prod.fst", Call("Prod.snd", x))), Call("Prod.snd", Call("Prod.snd", x))));
        Formula bc = Call("partialTraceLeft", n);
        Formula value = Sub(Sub(Add(Call("entropy", Call("partialTraceRight", m)),
            Call("entropy", bc)), Call("entropy", Call("partialTraceRight", bc))), Call("entropy", m));
        Formula body = LetIn(r, new Formula.TypeArrow(regrouped, abc), map,
            LetIn(n, MatrixOf(regrouped, regrouped), Call("Matrix.submatrix", m, r, r),
                Equal(Call("cmi", m), value)));
        return Disp(All("A", Named("Type"), All("B", Named("Type"), All("C", Named("Type"),
            Instances(All("M", MatrixOf(abc, abc), body), a, b, c)))));
    }

    private static Formula ClaimFormula()
    {
        Formula n = F.Id("n"), np = F.Id("nPrime"), iota = F.Id("iota"), k = F.Id("K"),
            i = F.Id("i"), eta = F.Id("eta"), da = F.Id("dA"), db = F.Id("dB"),
            rho = F.Id("rho"), l = F.Id("L");
        Formula ab = Product(FinOf(da), FinOf(db));
        Formula abc = Product(ab, FinOf(n));
        Formula x = Call("CStarMatrix.ofMatrix.symm", Call("val", rho));
        Formula lifted = LambdaOf(i, iota, Call("Matrix.kronecker", Parenthesized(Seq(D(1), Colon, MatrixOf(ab, ab))), Apply(k, i)));
        Formula bound = LetIn(l, new Formula.TypeArrow(iota, MatrixOf(Product(ab, FinOf(np)), abc)), lifted,
            LeqTo(Call("cmi", Call("ofKraus", l, l, x)), Mul(eta, Call("cmi", x))));
        Formula states = All("dA", Naturals, All("dB", Naturals,
            All("rho", Call("DensityState", abc), bound)));
        Formula contraction = Some("eta", Reals, And(Less(eta, D(1)), states));
        Formula hypothesis = Imp(Equal(SumOver(i, iota, Mul(Call("conjTranspose", Apply(k, i)), Apply(k, i))), D(1)),
            Imp(Equal(Call("correctable", k), Seq(Perp)), contraction));
        Formula body = All("n", Naturals, All("nPrime", Naturals, All("iota", Named("Type"),
            Seq(OpenBracket, Call("Fintype", iota), CloseBracket, Sp,
                All("K", new Formula.TypeArrow(iota, MatrixOf(FinOf(np), FinOf(n))), hypothesis)))));
        return Disp(IffTo(F.Id("claim"), body));
    }
