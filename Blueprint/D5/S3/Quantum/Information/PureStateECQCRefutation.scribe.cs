    private static DocumentBlock Node(string name, string title, Formula formula, string prose,
        DescribeRole role, AssessedProvenance provenance,
        OpenProblemResolutionClaim? resolution = null) => Describe.Lean(
            DescribeId.Create("ecqc-" + name.ToLowerInvariant()), DeclarationHandle.Create(Prefix + name), H(title),
            StatementSource.FromAuthor(formula), provenance, Blocks(Paragraph(QuotedProse(prose))), role, resolution);

    private static Inline[] QuotedProse(string prose) => prose.Split('$')
        .SelectMany((part, index) => index % 2 == 0 ? new[] { Text(part) } : SourceInlines(part))
        .ToArray();

    private static Inline[] SourceInlines(string source)
    {
        Formula d = F.Id("d"), s = Seq(Mathcal,Grp(F.Id("S"))), i = F.Id("i");
        var a = new Formula.Power(new Formula.Subscript(F.Id("M"), i), F.Id("A"));
        var b = new Formula.Power(new Formula.Subscript(F.Id("M"), i), F.Id("B"));
        Formula value = source switch
        {
            "3" => D(3),
            "5" => D(5),
            "d" => d,
            "d + 1" => Add(d,D(1)),
            "\\rho_{AB}" => new Formula.Subscript(Rho,F.Id("AB")),
            "\\mathcal{S}" => s,
            "I(A : B) \\ge \\underset{\\mathcal{S} \\in [d + 1]^d}{\\min} \\sum_{i \\in \\mathcal{S}} I(M^A_i : M^B_i)" =>
                new Formula.Relation(Call("I",Seq(F.Id("A"),Colon,F.Id("B"))),
                FormulaRelationOperator.GreaterThanOrEqual,
                Seq(new Formula.Subscript(Seq(Operatorname,Grp(F.Id("min"))),
                    Seq(s,InMacro,Sp,new Formula.Power(Seq(OpenBracket,Add(d,D(1)),CloseBracket),d))),
                    Sp,SumOf(i,s,Call("I",Seq(a,Colon,b))))),
            _ => throw new InvalidOperationException("Unrecognized source formula: " + source),
        };
        return [Math(value)];
    }

    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula Call(string name, params Formula[] args) => new Formula.Apply(
        Seq(Operatorname, Grp(name.Split('.').SelectMany((part, index) => index == 0
            ? new[] { F.Id(part) } : new Formula[] { Dot, F.Id(part) }).ToArray())), [.. args]);
    private static Formula All(Formula v, Formula type, Formula body) =>
        Seq(Forall, Sp, v, Colon, Sp, type, Comma, Sp, body);
    private static Formula Some(Formula v, Formula type, Formula body) =>
        Seq(Exists, Sp, v, Colon, Sp, type, Comma, Sp, body);
    private static Formula EqTo(Formula x, Formula y) => new Formula.Relation(x, FormulaRelationOperator.Equal, y);
    private static Formula LeTo(Formula x, Formula y) => new Formula.Relation(x, FormulaRelationOperator.LessThanOrEqual, y);
    private static Formula Mul(Formula x, Formula y) => new Formula.Binary(x, FormulaBinaryOperator.Multiply, y);
    private static Formula Add(Formula x, Formula y) => new Formula.Binary(x, FormulaBinaryOperator.Add, y);
    private static Formula Fr(Formula x, Formula y) => new Formula.Fraction(x, y);
    private static Formula Field() => Call("ZMod", D(5));
    private static Formula Complexes() => Seq(Mathbb, Grp(F.Id("C")));
    private static Formula Reals() => Seq(Mathbb, Grp(F.Id("R")));
    private static Formula PairType() => Parenthesized(Seq(Field(), Times, Field()));
    private static Formula Amplitudes() => Seq(PairType(), To, Complexes());
    private static Formula FinSix() => Call("Fin", D(6));
    private static Formula SumOf(Formula v, Formula domain, Formula body) =>
        Seq(new Formula.Subscript(Sum, Seq(v, InMacro, Sp, domain)), Sp, body);
    private static Formula Basis(Formula i, Formula a, Formula x) => Call("bases", i, a, x);
    private static Formula LogTwo() => Call("log", D(2));

    private static Formula BasesFormula()
    {
        Formula i = F.Id("i"), a = F.Id("a"), x = F.Id("x");
        var k = Call("castZMod5", Call("ite", EqTo(i,D(0)),D(0),Call("natSub",Call("val",i),D(1))));
        var phase = Add(Mul(k,new Formula.Power(x,D(2))),Mul(a,x));
        var value = Call("ite",EqTo(i,D(1)),Call("Pi.single",a,D(1),x),
            Fr(Call("stdAddChar",phase),Call("ofReal",Call("sqrt",D(5)))));
        return Disp(All(i,FinSix(),All(a,Field(),All(x,Field(),EqTo(Basis(i,a,x),value)))));
    }

    private static Formula JointFormula()
    {
        Formula i = F.Id("i"), psi = F.Id("psi"), ab = F.Id("ab"), xy = F.Id("xy");
        var summand = Mul(Mul(Call("star",Basis(i,Call("fst",ab),Call("fst",xy))),
            Call("star",Basis(i,Call("snd",ab),Call("snd",xy)))),new Formula.Apply(psi,[xy]));
        return Disp(All(i,FinSix(),All(psi,Amplitudes(),All(ab,PairType(),
            EqTo(Call("jointLaw",i,psi,ab),Call("normSq",SumOf(xy,PairType(),summand)))))));
    }

    private static Formula ClaimFormula()
    {
        Formula psi = F.Id("psi"), hp = F.Id("hpsi"), r = F.Id("r"), s = F.Id("S"), i = F.Id("i");
        var normalization = EqTo(Call("dotProduct",Call("star",psi),psi),D(1));
        var sum = SumOf(i,s,Fr(Call("mutualInformation",Call("jointLaw",i,psi)),LogTwo()));
        var predicate = Some(s,Call("Finset",FinSix()),new Formula.Logic(
            Parenthesized(EqTo(Call("card",s),D(5))),FormulaLogicOperator.And,Parenthesized(EqTo(r,sum))));
        var sums = Seq(OpenBrace,r,Colon,Reals(),Bar,Parenthesized(predicate),CloseBrace);
        var inequality = LeTo(Call("sInf",sums),
            Fr(Call("quantumMutualInformation",Call("pureDensityState",psi,hp)),LogTwo()));
        return Disp(new Formula.Logic(F.Id("claim"),FormulaLogicOperator.Iff,
            Parenthesized(All(psi,Amplitudes(),All(hp,Parenthesized(normalization),inequality)))));
    }
