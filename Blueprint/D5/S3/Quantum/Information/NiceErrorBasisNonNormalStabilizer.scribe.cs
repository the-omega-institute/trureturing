    private static Formula Named(string name)
    {
        var tokens = new List<Formula>();
        foreach (var part in name.Split('.'))
        {
            if (tokens.Count > 0) tokens.Add(Dot);
            tokens.Add(F.Id(part));
        }
        return Seq(Operatorname, Grp(Seq([.. tokens])));
    }
    private static Formula Call(string name, params Formula[] arguments) =>
        new Formula.Apply(Named(name), [.. arguments]);
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula Equal(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.Equal, right);
    private static Formula Member(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.MemberOf, right);
    private static Formula Times(Formula left, Formula right) =>
        new Formula.Binary(left, FormulaBinaryOperator.Multiply, right);
    private static Formula And(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.And, Parenthesized(right));
    private static Formula Or(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Or, Parenthesized(right));
    private static Formula Implies(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Implies, Parenthesized(right));
    private static Formula Iff(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.Iff, Parenthesized(right));
    private static Formula All(string variable, Formula domain, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(variable), domain, body);
    private static Formula Some(string variable, Formula domain, Formula body) =>
        new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create(variable), domain, body);
    private static Formula Complexes() => Seq(Mathbb, Grp(F.Id("C")));
    private static Formula Naturals() => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula UnitNorm(Formula c) => Equal(new Formula.Norm(c), D(1));
    private static Formula Pi(Formula x) => Call("pi", x);
    private static Formula Proj(Formula v) => Call("P", F.Id("W"), v);

    private static Formula ProjRepFormula()
    {
        Formula x = F.Id("x"), y = F.Id("y"), c = F.Id("c"), g = F.Id("G");
        Formula unitary = All("x", g, Member(Pi(x), Call("unitaryGroup", F.Id("d"))));
        Formula relation = All("x", g, All("y", g, Some("c", Complexes(),
            And(UnitNorm(c), Equal(Times(Pi(x), Pi(y)), Times(c, Pi(Times(x, y))))))));
        return Disp(Iff(Call("IsProjRep", F.Id("pi")), And(unitary, relation)));
    }

    private static Formula FaithfulFormula()
    {
        Formula x = F.Id("x"), y = F.Id("y"), c = F.Id("c"), g = F.Id("G");
        return Disp(Iff(Call("ProjFaithful", F.Id("pi")), All("x", g, All("y", g,
            Implies(Some("c", Complexes(), Equal(Pi(x), Times(c, Pi(y)))), Equal(x, y))))));
    }

    private static Formula IrreducibleFormula()
    {
        Formula u = F.Id("U"), x = F.Id("x"), v = F.Id("v"), g = F.Id("G");
        Formula invariant = All("x", g, All("v", u, Member(Call("apply", Pi(x), v), u)));
        Formula trivial = Or(Equal(u, D(0)), Equal(u, F.Id("V")));
        return Disp(Iff(Call("IrredProj", F.Id("pi")),
            All("U", Call("Submodule", Call("EuclideanSpace", Complexes(), F.Id("d"))), Implies(invariant, trivial))));
    }

    private static Formula ModelFormula()
    {
        Formula pi = F.Id("pi");
        return Disp(Iff(Call("IsPEM", pi),
            And(And(Call("IsProjRep", pi), Call("ProjFaithful", pi)), Call("IrredProj", pi))));
    }

    private static Formula LogicalFormula()
    {
        Formula x = F.Id("x"), v = F.Id("v"), g = F.Id("G");
        return Disp(All("x", g, Iff(Member(x, Call("logicalOps", F.Id("pi"), F.Id("W"))),
            All("v", Call("EuclideanSpace", Complexes(), F.Id("d")),
                Equal(Proj(Call("apply", Pi(x), v)), Call("apply", Pi(x), Proj(v)))))));
    }

    private static Formula StabilizerFormula()
    {
        Formula x = F.Id("x"), v = F.Id("v"), c = F.Id("c"), g = F.Id("G");
        return Disp(All("x", g, Iff(Member(x, Call("stabilizers", F.Id("pi"), F.Id("W"))),
            Some("c", Complexes(), And(UnitNorm(c), All("v", Call("EuclideanSpace", Complexes(), F.Id("d")),
                Equal(Proj(Call("apply", Pi(x), Proj(v))), Times(c, Proj(v)))))))));
    }

    private static Formula ClaimBody()
    {
        Formula d = F.Id("d"), g = F.Id("G"), s = F.Id("s"), h = F.Id("g");
        Formula pi = F.Id("pi"), w = F.Id("W");
        Formula stab = Call("stabilizers", pi, w);
        Formula counting = Equal(Times(Call("ncard", Call("logicalOps", pi, w)), Call("ncard", stab)),
            Call("card", g));
        Formula conclusion = All("g", g, All("s", stab, Member(Times(Times(h, s), Call("inv", h)), stab)));
        Formula hypotheses = And(And(Call("IsPEM", pi), Equal(Call("card", g), new Formula.Power(d, D(2)))), counting);
        return All("d", Naturals(), All("G", Named("FiniteGroup"), All("pi", new Formula.TypeArrow(g, Call("Matrix", d, d, Complexes())),
            All("W", Call("Submodule", Call("EuclideanSpace", Complexes(), d)), Implies(hypotheses, conclusion)))));
    }

    private static Formula ClaimDefinitionFormula() => Disp(
        new Formula.Logic(F.Id("claim"), FormulaLogicOperator.Iff, Parenthesized(ClaimBody())));
}
