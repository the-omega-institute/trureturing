    private static Formula AmplitudeFormula()
    {
        Formula matrices = LambdaOf("i", FinOf(X("n")), At(X("a"), At(X("w"), X("i"))));
        Formula trace = At(Qualified("D5", "S3", "Observer", "SourceJetCyclicTraces", "orderedTraceWord"),
            matrices, Qualified("id"));
        return FamilyBinders(All("n", Naturals(), All("w", Words(),
            Equal(Typed(LocalCall("amplitude", X("a"), X("n"), X("w")), Complexes()), trace))));
    }

    private static Formula RepresentationFormula()
    {
        Formula exponent = Multiply(Multiply(CastComplex(X("φ")), CastComplex(At(X("ch"), X("k")))),
            Qualified("Complex", "I"));
        Formula diagonal = At(Qualified("Matrix", "diagonal"),
            LambdaOf("k", FinOf(D(4)), At(Qualified("Complex", "exp"), exponent)));
        Formula conjugation = At(Qualified("Unitary", "conjStarAlgAut"),
            Complexes(), Matrices(D(4)), X("w"));
        return ActionBinders(All("φ", Reals(),
            Equal(Typed(LocalCall("u1Rep", X("w"), X("ch"), X("φ")), Matrices(D(4))),
                At(conjugation, diagonal))));
    }

    private static Formula SymmetryFormula()
    {
        Formula labelTypes = At(Qualified("Function", "const"), FinOf(X("n")), FinOf(D(4)));
        Formula actions = At(Qualified("Function", "const"), FinOf(X("n")),
            LocalCall("u1Rep", X("w"), X("ch"), X("φ")));
        Formula tensor = At(Qualified("D5", "S3", "Quantum", "Recovery", "ProductPrefixRigidity", "productMap"),
            labelTypes, actions);
        Formula evolution = At(Qualified("Matrix", "mulVec"), tensor,
            LocalCall("amplitude", X("a"), X("n")));
        Formula phase = At(Qualified("Complex", "exp"),
            Multiply(CastComplex(X("θ")), Qualified("Complex", "I")));
        Formula target = LambdaOf("v", Words(),
            Multiply(phase, LocalCall("amplitude", X("a"), X("n"), X("v"))));
        Formula body = All("φ", Reals(), All("n", Naturals(),
            Arrow(Less(Typed(D(0), Naturals()), X("n")),
                Some("θ", Reals(), Equal(evolution, target)))));
        return FamilyBinders(ActionBinders(Equivalence(
            LocalCall("IsSymmetric", X("a"), X("w"), X("ch")), body)));
    }

    private static Formula InjectivityFormula()
    {
        Formula entries = LambdaOf("i", FinOf(X("n")), At(X("a"), At(X("w"), X("i"))));
        Formula word = At(Qualified("List", "prod"), At(Qualified("List", "ofFn"), entries));
        Formula trace = At(Qualified("Matrix", "trace"), Multiply(X("x"), word));
        Formula boundaryMap = LambdaOf("x", Matrices(X("d")), LambdaOf("w", Words(), trace));
        return FamilyBinders(Equivalence(LocalCall("IsInjective", X("a")),
            Some("n", Naturals(), At(Qualified("Function", "Injective"), boundaryMap))));
    }

    private static Formula ClaimFormula()
    {
        Formula nonzeroMatrices = All("k", FinOf(D(4)),
            NotEqual(At(X("a"), X("k")), Typed(D(0), Matrices(X("d")))));
        Formula summand = Multiply(At(X("a"), X("k")),
            At(Qualified("star"), At(X("a"), X("k"))));
        Formula normalization = Equal(SumOver("k", FinOf(D(4)), summand), Typed(D(1), Matrices(X("d"))));
        Formula nonzeroEigenvalues = All("k", FinOf(D(4)),
            NotEqual(At(X("ch"), X("k")), Typed(D(0), Reals())));
        Formula distinctEigenvalues = Some("k", FinOf(D(4)), Some("l", FinOf(D(4)),
            NotEqual(At(X("ch"), X("k")), At(X("ch"), X("l")))));
        Formula conclusion = Arrow(LocalCall("IsSymmetric", X("a"), X("w"), X("ch")),
            new Formula.Not(Parenthesized(LocalCall("IsInjective", X("a")))));
        return Equivalence(Local("claim"), FamilyBinders(ActionBinders(
            Arrow(nonzeroMatrices, Arrow(normalization, Arrow(nonzeroEigenvalues,
                Arrow(distinctEigenvalues, conclusion)))))));
    }

    private static Formula FamilyBinders(Formula body) => All("d", Naturals(),
        All("a", Arrow(FinOf(D(4)), Matrices(X("d"))), body));
    private static Formula ActionBinders(Formula body) =>
        All("w", At(Qualified("Matrix", "unitaryGroup"), FinOf(D(4)), Complexes()),
            All("ch", Arrow(FinOf(D(4)), Reals()), body));
    private static Formula Words() => Arrow(FinOf(X("n")), FinOf(D(4)));
    private static Formula Matrices(Formula size) => At(Qualified("Matrix"), FinOf(size), FinOf(size), Complexes());
    private static Formula FinOf(Formula size) => At(Qualified("Fin"), size);
    private static Formula Local(string name) => Qualified("D5", "S3", "Quantum", "SpinChains",
        "FourLevelU1SymmetricInjectiveMPS", name);
    private static Formula LocalCall(string name, params Formula[] args) => At(Local(name), args);
    private static Formula CastComplex(Formula value) => At(Qualified("Complex", "ofReal"), value);
    private static Formula X(string name) => name switch { "φ" => Varphi, "θ" => Theta, _ => F.Id(name) };
    private static Formula Qualified(params string[] parts)
    {
        var items = new System.Collections.Generic.List<Formula>();
        foreach (var part in parts)
        {
            if (items.Count > 0) items.Add(Dot);
            items.Add(F.Id(part));
        }
        return Seq(Operatorname, Grp(Seq([.. items])));
    }
    private static Formula At(Formula function, params Formula[] args) => new Formula.Apply(function, [.. args]);
    private static Formula Parenthesized(Formula value) => Seq(Left, Open, value, Right, Close);
    private static Formula Typed(Formula value, Formula type) => Parenthesized(Seq(value, Colon, Sp, type));
    private static Formula Naturals() => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula Reals() => Seq(Mathbb, Grp(F.Id("R")));
    private static Formula Complexes() => Seq(Mathbb, Grp(F.Id("C")));
    private static Formula All(string name, Formula type, Formula body) =>
        Seq(Forall, Sp, Typed(X(name), type), Comma, Sp, Parenthesized(body));
    private static Formula Some(string name, Formula type, Formula body) =>
        Seq(Exists, Sp, Typed(X(name), type), Comma, Sp, Parenthesized(body));
    private static Formula LambdaOf(string name, Formula type, Formula body) =>
        Parenthesized(Seq(LambdaLower, Sp, Typed(X(name), type), Sp, Mapsto, Sp, Parenthesized(body)));
    private static Formula SumOver(string name, Formula type, Formula body) =>
        Seq(new Formula.Subscript(Sum, Seq(X(name), Colon, Sp, type)), Sp, Parenthesized(body));
    private static Formula Arrow(Formula domain, Formula codomain) =>
        new Formula.TypeArrow(Parenthesized(domain), Parenthesized(codomain));
    private static Formula Equal(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.Equal, right);
    private static Formula NotEqual(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.NotEqual, right);
    private static Formula Less(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.LessThan, right);
    private static Formula Equivalence(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Iff, Parenthesized(right));
    private static Formula Multiply(Formula left, Formula right) =>
        new Formula.Binary(Parenthesized(left), FormulaBinaryOperator.Multiply, Parenthesized(right));
