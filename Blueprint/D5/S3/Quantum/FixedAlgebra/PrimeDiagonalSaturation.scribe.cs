    private static Formula OperatorEntryFormula()
    {
        Formula d = F.Id("d");
        Formula p = F.Id("p");
        Formula i = F.Id("i");
        Formula j = F.Id("j");
        Formula occupation = Call("primeOccupancy", p, Seq(i, Plus, D(1)));
        return Disp(Seq(
            Forall, Sp, d, Comma, Sp, p, Comma, Sp, i, Comma, Sp, j, Comma, Sp,
            Call("primeOccupationOperator", d, p, i, j), Sp, Eq, Sp,
            Call("if", Seq(i, Sp, Eq, Sp, j), occupation, D(0)), Dot));
    }

    private static Formula AlgebraContainmentFormula()
    {
        Formula d = F.Id("d");
        Formula primes = F.Id("P");
        Formula algebra = Call("primeDiagonalAlgebra", d, primes);
        Formula diagonalRange = Call("range", Call("diagonalAlgHom", F.Id("C")));
        return Disp(Seq(
            Forall, Sp, d, Comma, Sp, primes, Comma, Sp,
            algebra, Sp, Subseteq, Sp, diagonalRange, Dot));
    }

    private static Formula SaturationFormula()
    {
        Formula d = F.Id("d");
        Formula primes = F.Id("P");
        Formula rho = Rho;
        Formula observable = F.Id("A");
        Formula algebra = Call("primeDiagonalAlgebra", d, primes);
        Formula pinched = Call("projectiveReadout", rho);
        return Disp(Seq(
            Forall, Sp, d, Comma, Sp, primes, Comma, Sp, rho, Comma, Sp, observable, Comma,
            observable, Sp, InMacro, Sp, algebra, Sp, Rightarrow, Sp,
            Call("Tr", Seq(rho, Sp, observable)), Sp, Eq, Sp,
            Call("Tr", Seq(pinched, Sp, observable)), Dot));
    }

    private static Formula DegenerateAuditFormula()
    {
        Formula saturation = F.Id("Sat");
        Formula d = F.Id("d");
        Formula primes = F.Id("P");
        Formula rho = Rho;
        Formula observable = F.Id("A");
        Formula fixedInput = Seq(
            Call("projectiveReadout", rho), Sp, Eq, Sp, rho, Sp, Rightarrow, Sp,
            Call("Sat", d, primes, rho, observable));
        return Disp(Seq(
            Call("Sat", D(0), Emptyset), Sp, Land, Sp,
            Call("Sat", D(1), Emptyset), Sp, Land, Sp,
            Forall, Sp, d, Comma, Sp, primes, Comma, Sp, rho, Comma, Sp,
            Call("Sat", d, primes, rho, D(1)), Sp, Land, Sp,
            Forall, Sp, observable, Comma, Sp, fixedInput, Comma, Sp,
            saturation, Sp, Eq, Sp, Call("primeDiagonalSaturation"), Dot));
    }

    private static Formula NecessityFormula()
    {
        Formula rho = Call("single", D(0), D(1), D(1));
        Formula observable = Call("single", D(1), D(0), D(1));
        Formula algebra = Call("primeDiagonalAlgebra", D(2), Emptyset);
        Formula pinched = Call("projectiveReadout", rho);
        return Disp(Seq(
            Neg, Grp(observable, Sp, InMacro, Sp, algebra), Sp, Land, Sp,
            Call("Tr", Seq(rho, Sp, observable)), Sp, Neq, Sp,
            Call("Tr", Seq(pinched, Sp, observable)), Dot));
    }
}
