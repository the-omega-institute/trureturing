using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Arith.FibonacciAtomic.LocalWiring;

internal sealed class LocalTwoStepRecognizerDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S3/Arith/FibonacciAtomic/LocalWiring/LocalTwoStepRecognizer.";
    private static Formula X => F.Id("X");
    private static Formula U => F.Id("U");
    private static Formula Dloc => Seq(F.Id("D"), Underscore, Grp(F.Id("loc")));

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "A physical tree shape after two actual local updates has an exact decoder: "
        + "it recovers the unique labelled physical predecessor, and distinguishes its unordered class.",
        H("Exact local two-step Fibonacci recognizer"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("gpo-locally-wired-two-updates"),
                DeclarationHandle.Create(Prefix + "Expanded"),
                H("Two actual updates followed by label erasure"),
                StatementSource.FromAuthor(Disp(Seq(
                    Call("Expanded", U, X), Iff, Sp, Exists, Sp, F.Id("V"), Comma, F.Id("W"),
                    Quad, Call("Step", U, F.Id("V")), Sp, Land, Sp,
                    Call("Step", F.Id("V"), F.Id("W")), Sp, Land, Sp,
                    Call("sh", F.Id("W")), Eq, X))),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "An α leaf becomes β. A splitting β leaf may put its β and α children in either physical order. The old branches and their left and right physical links persist. The update relation permits every finite combination of the local orientations, independently of other births and of earlier updates; it specifies no probability law.")),
                    Paragraph(Text(
                        "The labelled occurrences are finite non-associative binary trees. Label erasure preserves each physical parent-child link and its order, and the two-step relation is defined independently of the decoder."))),
                DescribeRole.Definition),
            Describe.Lean(
                DescribeId.Create("gpo-exact-local-two-step-recognizer"),
                DeclarationHandle.Create(Prefix + "exact_local_two_step"),
                H("Exact decoding, local exchanges, and class injection"),
                StatementSource.FromAuthor(Disp(Seq(
                     Open, Dloc, Open, X, Close, Eq, Call("some", U), Sp, Iff, Sp,
                    Call("Expanded", U, X), Close, Quad, Land, Quad, Open,
                    Call("Grammar", X), Sp, Iff, Sp, Exists, Bang, Sp, U, Quad,
                    Call("Expanded", U, X), Close))),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "Let t be a leaf and C=(t,t). The grammar is generated by C, (C,t), (t,C), and the ordered pairs of recursively accepted shapes. A lone leaf rejects. A double leaf returns α; a mixed branch and leaf returns β exactly when the branch is C, and rejects when the branch is larger.")),
                    Paragraph(Text(
                        "A double branch returns the corresponding ordered pair of predecessors exactly when both recursive calls return a predecessor; one failed child is enough to reject. Each recursive call is on an immediate subtree.")),
                    Paragraph(Text(
                        "The two-step relation makes both directions literal: any two actual updates yield the decoder's original labelled physical tree, and every accepted code is realized by two such updates. Only the labelled predecessor is unique, not the hidden birth orientations or the final labelled tree.")),
                    Paragraph(Text(
                        "An arbitrary node-local exchange preserves rejection and, on acceptance, exchanges the decoded descendants as rooted label-preserving unordered isomorphism. For any two actual expansions the two shape classes are equal exactly when the two original labelled classes are equal. The induced map from labelled classes to shape classes is well defined for every allowed orientation and injective."))),
                DescribeRole.Theorem))));

    private static Formula Call(string name, params Formula[] args) =>
        new Formula.FunctionCall(FormulaIdentifier.Create(name), [.. args]);
}
