using static StrataLint.Scribe.DefinitionDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Arith.CyclotomicFields;

internal sealed class MercaQuadraticSubfieldDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S3/Arith/CyclotomicFields/MercaQuadraticSubfield.";
    private static readonly LibraryNoteRef Source =
        LibraryNoteRef.Create("D5/L/ArithUnits/mazhang2026quartic");

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "The quadratic Gauss sum in the actual prime cyclotomic field identifies "
            + "the Merca quartic field's maximal real subfield with Q(sqrt(r)).",
        H("The Actual Merca Real Quadratic Subfield"),
        Blocks(
            Paragraph(Text("For every prime r congruent to five modulo eight, the "
                + "quadratic Gauss sum squares to r. The actual quartic kernel has "
                + "odd order, so the quadratic character is one on it. Galois "
                + "action on the Gauss sum is a multiplicative shift, proving "
                + "that this root lies in the actual quartic fixed field. Every "
                + "complex embedding of the root has positive real square r, "
                + "hence real image. The resulting quadratic embedding is onto "
                + "the degree-two maximal real subfield. No choice of sign for "
                + "the Gauss root is needed for this field identification.")),
            Node("gauss-root", "The actual quadratic Gauss root", "gaussRoot",
                DescribeRole.Definition,
                "Use the actual quadratic multiplicative character and the additive "
                    + "character of the primitive r-th root in CyclotomicField r over "
                    + "the rationals. The resulting finite Gauss sum is an ambient "
                    + "field element, not a supplied square-root parameter."),
            Node("quartic-root", "The root in the actual quartic field", "quarticGaussRoot",
                DescribeRole.Definition,
                "The kernel-fixed Gauss root is an element of the actual quartic "
                    + "intermediate field. Its square is r and all its complex "
                    + "embeddings are real."),
            Node("real-equivalence", "Identification with Q(sqrt(r))", "realEquiv",
                DescribeRole.Definition,
                "The algebra Q[X]/(X squared minus r), represented by QuadraticAlgebra, "
                    + "is a field because a prime is not a rational square. Sending "
                    + "its generator to the kernel-fixed Gauss root gives an actual "
                    + "rational algebra equivalence with the maximal real subfield."),
            Node("maximal-order", "The genuine maximal integer ring", "realMaximalOrderEquiv",
                DescribeRole.Definition,
                "The order generated by (1 plus sqrt(r)) divided by two has "
                    + "integer polynomial X squared minus X minus (r minus one) "
                    + "divided by four. Its order discriminant is the prime r. "
                    + "The existing squarefree-discriminant maximality theorem "
                    + "identifies this order with the actual ring of integers "
                    + "of Q(sqrt(r)), through an explicit algebra equivalence."),
            Node("discriminant", "Actual real discriminant r", "real_discriminant",
                DescribeRole.Theorem,
                "Both the square-root number field and the maximal real subfield "
                    + "of the quartic fixed field have genuine number-field "
                    + "discriminant r. The maximal-order theorem supplies the "
                    + "first discriminant; the Gauss-root equivalence transports "
                    + "it to the actual maximal real subfield. The four-slot "
                    + "author audit remains unfinished at "
                    + "https://github.com/the-omega-institute/trureturing/issues/27629."),
            Paragraph(Text("The historical Ma–Zhang note and its CC BY 4.0 credit, "
                + "Farland's criterion attribution, the joint Ma–Merca–Zhang "
                + "application, and the classical, Louboutin and Hudson sources "
                + "remain recorded in the Library entry. This field identification "
                + "feeds MercaRelativeClassNumber; the signed imaginary-quadratic "
                + "formula is proved separately in MercaImaginaryClassNumber."))),
        edges: [
            DocumentEdge.Dependency.Create(
                GidRef.Create("D5/S3/Arith/CyclotomicFields/MercaQuarticField")),
            DocumentEdge.Dependency.Create(
                GidRef.Create("D5/S3/Arith/QuadraticFields/QuadraticOrderMaximal"))]));

    private static DocumentBlock Node(string id, string title, string declaration,
        DescribeRole role, string prose) =>
        Describe.Lean(DescribeId.Create("merca-real-subfield-" + id),
            DeclarationHandle.Create(Prefix + declaration), H(title),
            StatementSource.WithoutFormula(), AssessedProvenance.FromLiterature(Source),
            Blocks(Paragraph(Text(prose))), role);
}
