using static StrataLint.Scribe.DefinitionDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Arith.CyclotomicFields;

internal sealed class MercaQuarticFieldDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S3/Arith/CyclotomicFields/MercaQuarticField.";
    private static readonly LibraryNoteRef Source =
        LibraryNoteRef.Create("D5/L/ArithUnits/mazhang2026quartic");

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "The actual fixed field of the normalized quartic character kernel is cyclic "
            + "quartic and CM. For conductor r greater than five its roots of unity "
            + "have order two and its Hasse unit index is one.",
        H("The Actual Merca Quartic Field"),
        Blocks(
            Paragraph(Text("This is the actual-object field construction needed by the "
                + "historical Ma–Zhang theorem. It does not define a field through its "
                + "desired class number. Identification of the maximal real field with "
                + "Q(sqrt(r)) and the analytic relative-class-number formula remain "
                + "separate obligations. The historical note's CC BY 4.0 attribution, "
                + "Farland's sign criterion, the joint Ma–Merca–Zhang application and "
                + "Louboutin, Hudson and classical class-number sources are retained "
                + "in the Library entry. Four-slot author audits remain unfinished at "
                + "https://github.com/the-omega-institute/trureturing/issues/27629; "
                + "this document claims no validated registration.")),
            Node("fixed-field", "The kernel-fixed intermediate field", "fixedField",
                DescribeRole.Definition,
                "Inside CyclotomicField r over the rationals, transport the actual "
                    + "unit kernel of the unique character taking two to i through "
                    + "the cyclotomic Galois equivalence, and take its fixed field. "
                    + "Field r is this same intermediate field viewed as a number field."),
            Node("structure", "Cyclic quartic and CM structure", "field_structure",
                DescribeRole.Theorem,
                "For every prime r congruent to five modulo eight, the actual fixed "
                    + "field has degree four, cyclic Galois group and CM structure. "
                    + "Its maximal real subfield has degree two. The index-four "
                    + "kernel gives the degree by Galois correspondence. Ambient "
                    + "conjugation maps to minus one and lies outside the kernel; "
                    + "extending a hypothetical real embedding would force it to fix "
                    + "the field, contradicting that exclusion."),
            Node("torsion", "Exactly two roots of unity", "torsion_order",
                DescribeRole.Theorem,
                "For r greater than five the genuine maximal-order torsion group "
                    + "has order two. Its order divides the ambient cyclotomic "
                    + "torsion order 2r. An r-th primitive root inside a degree-four "
                    + "field would force r minus one at most four. Thus r cannot "
                    + "divide the torsion order, whereas minus one supplies order two. "
                    + "The conductor-five exception is explicitly excluded."),
            Node("unit-index", "The Hasse unit index", "unit_index",
                DescribeRole.Theorem,
                "For r greater than five the index of the subgroup generated by "
                    + "real units and roots of unity in the actual maximal-order "
                    + "unit group is one. A putative index two supplies a unit whose "
                    + "ratio to its conjugate is minus one. If sigma generates the "
                    + "cyclic group of order four, x equals u times sigma(u) and "
                    + "sigma(x) equals minus x. The four-conjugate norm is x squared "
                    + "and is an integer unit, hence x to the fourth is one. The "
                    + "proved torsion order then makes x equal to plus or minus one, "
                    + "contradicting sigma(x) equals minus x.")),
        edges: [DocumentEdge.Dependency.Create(
            GidRef.Create("D5/S3/ArithUnits/MercaQuarticCharacter"))]));

    private static DocumentBlock Node(string id, string title, string declaration,
        DescribeRole role, string prose) =>
        Describe.Lean(DescribeId.Create("merca-quartic-field-" + id),
            DeclarationHandle.Create(Prefix + declaration), H(title),
            StatementSource.WithoutFormula(), AssessedProvenance.FromLiterature(Source),
            Blocks(Paragraph(Text(prose))), role);
}
