                            + "compares coefficients in the rational basis (1, alpha, gamma). "
                            + "Conversely, divisibility supplies the order coefficients. This "
                            + "identifies the field order with the triangular coordinate lattice; "
                            + "it does not identify an original-depth radical with this field."))),
                DescribeRole.Theorem))));
