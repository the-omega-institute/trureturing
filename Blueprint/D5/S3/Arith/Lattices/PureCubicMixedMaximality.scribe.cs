    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "The mixed cubic lattice is the integer ring, with field discriminant minus three times the square of mn.",
        H("Mixed Pure Cubic Integer Ring"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("pure-cubic-mixed-maximality"),
                DeclarationHandle.Create(
                    "D5/S3/Arith/Lattices/PureCubicMixedMaximality.pure_cubic_mixed_maximality_and_discriminant"),
                H("Maximality and field discriminant"),
                StatementSource.WithoutFormula(),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "Let K be a cubic number field with a rational power basis generated by alpha. "
                            + "Let m and n be positive, squarefree, and coprime integers, with alpha cubed "
                            + "equal to m times n squared. Choose integers c, a, k, and v such that v is "
                            + "one or minus one, c cubed times m n squared is one plus nine a, and "
                            + "c squared times n is v plus three k. Put beta = alpha squared divided "
                            + "by n, gamma = (1 + c alpha + v beta)/3, and let S be the integer span "
                            + "of 1, alpha, and gamma.")),
                    Paragraph(Text(
