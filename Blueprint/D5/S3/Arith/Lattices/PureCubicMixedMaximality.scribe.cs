                            + "Its field discriminant is -3(mn) squared.")),
                    Paragraph(Text(
                        "To remove a factor of three from an integral element, scale alpha to "
                            + "theta = c alpha. The cubic equation theta cubed = 1 + 9a gives a "
                            + "three-saturated lattice generated by 1, theta, and "
                            + "(1 + theta + theta squared)/3. Explicit lattice inclusions and "
                            + "Bezout's identity transfer that saturation to S. At any other prime "
                            + "dividing the power-basis discriminant, squarefreeness and coprimality "
                            + "select one of the two mixed-radicand prime-saturation cases. "
                            + "Discriminant clearing followed by prime removal puts every integral "
                            + "element in S. Integral coordinate changes between this basis and an "
                            + "integral basis identify its trace discriminant with the field discriminant."))),
                DescribeRole.Theorem))));
}
