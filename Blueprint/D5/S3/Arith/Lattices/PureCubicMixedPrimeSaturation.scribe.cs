        "A mixed pure-cubic lattice is saturated at primes simple in either cubic radicand.",
        H("Mixed-Radicand Prime Saturation"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("pure-cubic-mixed-prime-saturation"),
                DeclarationHandle.Create(
                    "D5/S3/Arith/Lattices/PureCubicMixedPrimeSaturation.pure_cubic_mixed_prime_saturation"),
