                    Paragraph(Text(
                        "In the first case the minimal polynomial of alpha is Eisenstein at p, "
                            + "and 3n times S lies in the ring generated by alpha. "
                            + "In the second case beta cubed is m squared n, beta squared is m alpha, "
                            + "and 3m times S lies in the ring generated by beta. "
                            + "Each Eisenstein criterion returns the cleared element to its generated "
                            + "ring; cubic reduction returns that ring to S. "
                            + "Coprimality of p with the clearing factor then removes the factor by "
                            + "Bezout's identity."))),
                DescribeRole.Theorem))));
