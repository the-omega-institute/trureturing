using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Arith.Partitions;

internal sealed class BilgiciThetaQuarticDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S3/Arith/Partitions/BilgiciThetaQuartic.";
    private static readonly LibraryNoteRef Source =
        LibraryNoteRef.Create("D5/L/Fourier/bilgici2026ninecolored");

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "The weight-eleven component of Bilgici's polynomial factors by the cubic in the theta quotient.",
        H("A quartic cofactor in Bilgici's theta quotient"),
        Blocks(
            Paragraph(Text("Work in the polynomial ring R over the field of 19 elements on nine "
                + "independent variables, indexed from 1 through 9. In Lean, index j is variable j−1.")),
            Definition("Z", "Signed integer indices",
                SignedFormula(),
                "Write x = 19q + r with 0 ≤ r < 19. The value is zero when r = 0. Otherwise it is "
                + "the variable at min(r, 19−r) multiplied by (−1) to the integer power q. "
                + "This gives reflection about 19/2, oddness, and sign reversal under translation by 19."),
            Definition("w", "Weights of the nine variables", WeightFormula(),
                "The displayed integer is reduced modulo 19. Monomial weights add with multiplicity, "
                + "and the weight component retains every term of the specified weight."),
            Definition("paperC", "The complete linear polynomial", CFormula(),
                "The sum uses every integer a from 1 through 9."),
            Definition("paperB", "The complete quartic polynomial", BFormula(),
                "The sum uses every integer pair 1 ≤ a < b ≤ 9, with the signed extension "
                + "at a+b and b−a. The projection in the result acts on the whole product BC³."),
            Definition("S_Z", "The invariant cubic",
                Seq(Script(F.Id("S"), F.Id("Z")), Eq, Z(D(1)), Z(D(7)), Z(D(8)), Minus,
                    Z(D(2)), Z(D(3)), Z(D(5)), Plus, Z(D(4)), Z(D(6)), Z(D(9))),
                "This is the cubic of Section 7.2."),
            Definition("theta", "The three-term polynomial", ThetaFormula(),
                "All four indices are integers. The products use the same signed extension as B."),
            Definition("ITheta", "The theta ideal",
                Seq(ThetaIdeal(), Eq, Langle, ThetaAt(), Thin, Bar, Thin,
                    Parenthesized(Seq(A, Comma, B, Comma, C, Comma, DIndex)), InMacro, Power(Seq(Mathbb, Grp(F.Id("Z"))), D(4)), Rangle),
                "The ideal is generated by the full integer family."),
            Describe.Lean(DescribeId.Create("bilgici-theta-quartic-result"),
                DeclarationHandle.Create(Prefix + "result"), H("The algebraic existence clause of Question 1"),
                StatementSource.FromAuthor(Disp(ResultFormula())),
                AssessedProvenance.FromRepo(Source),
                Blocks(Paragraph(Text("The same cofactor Q is nonzero in the polynomial ring and in "
                    + "the theta quotient. Each monomial has total degree four and weight "
                    + "nine. The ideal membership is equivalent to the equality "
                    + "of the classes of the entire weight-eleven component and S_Z Q.")),
                    Paragraph(Text("The cofactor is the sum of 5 to the j times the j-fold signed "
                        + "doubling image of 6 Z₁ Z₂ Z₃ Z₉ + 14 Z₁² Z₅ Z₇, for j from zero "
                        + "through eight. The difference from the weight component is a sum of thirteen "
                        + "weighted orbits of cubic multiples of theta relations. Doubling transports "
                        + "each relation to the relation at the doubled tuple. The polynomial identity "
                        + "comes from checking every coefficient.")),
                    Paragraph(Text("Independently, substituting X to the integer weight exponent "
                        + "for each variable sends every theta generator to a multiple of X¹⁰. "
                        + "Periodicity and reflection of the paired factors reduce this check to "
                        + "indices zero through nine. The image of Q has coefficient one at X⁹. "
                        + "A direct derivation of the factorization without coefficient comparisons remains open."))),
                DescribeRole.Theorem))));

    private static DocumentBlock Definition(string name, string title, Formula body, string prose) =>
        Describe.Lean(DescribeId.Create("bilgici-theta-" + name.Replace("_", "-").ToLowerInvariant()),
            DeclarationHandle.Create(Prefix + name), H(title), StatementSource.FromAuthor(Disp(body)),
            AssessedProvenance.FromLiterature(Source), Blocks(Paragraph(Text(prose))), DescribeRole.Definition);

    private static Formula Parenthesized(Formula body) => Seq(Open, body, Close);
    private static Formula Script(Formula symbol, Formula index) => Seq(symbol, Underscore, Grp(index));
    private static Formula Power(Formula symbol, Formula exponent) => Seq(symbol, Caret, Grp(exponent));
    private static Formula Z(Formula index) => Script(F.Id("Z"), index);
    private static Formula ThetaIdeal() => Script(Seq(Mathcal, Grp(F.Id("I"))), Theta);
    private static Formula Name(string name) => Seq(Operatorname, Grp(F.Id(name)));
    private static Formula A { get; } = F.Id("a");
    private static Formula B { get; } = F.Id("b");
    private static Formula C { get; } = F.Id("c");
    private static Formula DIndex { get; } = F.Id("d");

    private static Formula SignedFormula()
    {
        var r = F.Id("r");
        var q = F.Id("q");
        return Seq(Z(F.Id("x")), Eq, Begin, Grp(F.Id("cases")),
            D(0), Amp, r, Eq, D(0), RowBreak,
            Power(Parenthesized(Seq(Minus, D(1))), q),
            Z(Seq(Name("min"), Parenthesized(Seq(r, Comma, D(1, 9), Minus, r)))),
            Amp, r, Neq, D(0), End, Grp(F.Id("cases")));
    }

    private static Formula WeightFormula() =>
        Seq(Name("wt"), Parenthesized(Z(F.Id("j"))), Eq, Frac,
            Grp(Parenthesized(Seq(D(9), Minus, F.Id("j"))),
                Parenthesized(Seq(D(1, 0), Minus, F.Id("j")))),
            Grp(D(2)), Pmod, Grp(D(1, 9)));

    private static Formula CFormula() =>
        Seq(F.Id("C"), Eq, Power(Script(Sum, Seq(A, Eq, D(1))), D(9)),
            Power(Parenthesized(Seq(Minus, D(1))), A), Thin, D(2), A, Thin, Z(A));

    private static Formula BFormula() =>
        Seq(F.Id("B"), Eq, Minus, D(3), Script(Sum, Seq(D(1), Leq, Sp, A, Lt, B, Leq, D(9))),
            Power(Parenthesized(Seq(Minus, D(1))), Seq(A, Plus, B)), Thin, A, B,
            Parenthesized(Seq(Power(B, D(2)), Minus, Power(A, D(2)))),
            Z(A), Z(B), Z(Seq(A, Plus, B)), Z(Seq(B, Minus, A)));

    private static Formula ThetaAt() =>
        Seq(Theta, Parenthesized(Seq(A, Comma, B, Comma, C, Comma, DIndex)));

    private static Formula Pair(Formula u, Formula v) => Seq(Z(Seq(u, Plus, v)), Z(Seq(u, Minus, v)));

    private static Formula ThetaFormula() =>
        Seq(ThetaAt(), Eq, Pair(A, DIndex), Pair(B, C), Minus, Pair(A, C), Pair(B, DIndex),
            Plus, Pair(A, B), Pair(C, DIndex));

    private static Formula ResultFormula()
    {
        var q = F.Id("Q");
        var zero = D(0);
        var ring = Seq(Script(Seq(Mathbb, Grp(F.Id("F"))), D(1, 9)), OpenBracket,
            Z(D(1)), Comma, Dot, Dot, Dot, Comma, Z(D(9)), CloseBracket);
        var weightEleven = Script(Seq(OpenBracket, F.Id("B"), Power(F.Id("C"), D(3)),
            CloseBracket), D(1, 1));
        return Seq(Exists, Thin, q, InMacro, ring, Comma, Quad, Sp,
            q, Neq, zero, Sp, Land, Sp,
            Name("Homogeneous"), Parenthesized(Seq(q, Comma, D(4))), Sp, Land, Sp,
            Name("WeightedHomogeneous"), Parenthesized(Seq(q, Comma, F.Id("w"), Comma, D(9))),
            Sp, Land, Sp, weightEleven, Minus, Script(F.Id("S"), F.Id("Z")), q,
            InMacro, ThetaIdeal(), Sp, Land, Sp, Overline, Grp(q), Neq, zero);
    }
}
