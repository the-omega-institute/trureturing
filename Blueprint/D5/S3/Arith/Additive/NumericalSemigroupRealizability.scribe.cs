        return Disp(All("T", Call("AddSubmonoid", nat), new Formula.Logic(
            Call("Finite", Call("complement", t)), FormulaLogicOperator.Implies,
            Ex("M", nat, Ex("S", Call("Finset", nat), body)))));
    }
