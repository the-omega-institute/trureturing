        var plus = new Formula.SetBuilder(Bin(m, FormulaBinaryOperator.Add, x), x, s);
        var generators = Seq(Call("singleton", m), Sp, Cup, Sp, minus, Sp, Cup, Sp, plus);
        var positive = All("s", nat, new Formula.Logic(
