    private static Formula R => F.Id("R");
    private static Formula Natural => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula Submonoids => Seq(F.Id("AddSubmonoid"), Sp, R);
    private static Formula C => Seq(F.Id("C"), Open, R, Close);

    private static Formula Parens(Formula body) => Seq(Open, body, Close);

    private static Formula Bind(Formula quantifier, string name, Formula type, Formula body) =>
        Seq(quantifier, Sp, Open, F.Id(name), Colon, Sp, type, Close, Comma, Sp, body);

    private static Formula And(Formula left, Formula right) => Seq(left, Sp, Land, Sp, right);
    private static Formula Equal(Formula left, Formula right) => Seq(left, Sp, Eq, Sp, right);
    private static Formula Product(Formula left, Formula right) => Seq(left, Sp, Cdot, Sp, right);
    private static Formula Member(Formula element, Formula carrier) => Seq(element, Sp, InMacro, Sp, carrier);
    private static Formula UnitLaws(Formula unit, Formula element) =>
        And(Equal(Product(unit, element), element), Equal(Product(element, unit), element));

    private static Formula SemiringStatement(Formula body, bool cancellative = false)
    {
        Formula semiring = Seq(OpenBracket, F.Id(cancellative ? "NonUnitalSemiring" : "NonUnitalNonAssocSemiring"),
            Sp, R, CloseBracket, Comma, Sp);
        Formula hypotheses = cancellative
            ? Seq(semiring, OpenBracket, F.Id("IsLeftCancelAdd"), Sp, R, CloseBracket, Comma, Sp)
            : semiring;
        return Disp(Bind(Forall, "R", F.Id("Type"), Seq(hypotheses, body)));
    }

    private static Formula MultiplierMembership()
    {
        Formula c = F.Id("c");
        Formula x = F.Id("x");
        Formula left = Bind(Exists, "m", Natural, Equal(Product(F.Id("m"), x), Product(c, x)));
        Formula right = Bind(Exists, "n", Natural, Equal(Product(F.Id("n"), x), Product(x, c)));
        return SemiringStatement(Bind(Forall, "c", R, Seq(Member(c, C), Sp, Leftrightarrow, Sp,
            Parens(Bind(Forall, "x", R, And(Parens(left), Parens(right)))))));
    }

    private static Formula CriterionStatement()
    {
        Formula e = F.Id("E");
        Formula x = F.Id("x");
        Formula left = Bind(Exists, "l", R, And(Member(F.Id("l"), C), Equal(Product(F.Id("l"), x), x)));
        Formula right = Bind(Exists, "r", R, And(Member(F.Id("r"), C), Equal(Product(x, F.Id("r")), x)));
        Formula unit = Bind(Forall, "M", Submonoids, UnitLaws(e, F.Id("M")));
        Formula fixers = Bind(Forall, "x", R, And(Parens(left), Parens(right)));
        return SemiringStatement(Bind(Forall, "E", Submonoids,
            Seq(Parens(unit), Sp, Leftrightarrow, Sp, And(Equal(e, C), Parens(fixers)))));
    }

    private static Formula KilledByPrimePower(Formula element) =>
        Bind(Exists, "j", Natural, Equal(Product(Seq(F.Id("p"), Caret, Grp(F.Id("j"))), element), D(0)));

    private static Formula ClassificationStatement()
    {
        Formula unit = F.Id("u");
        Formula x = F.Id("x");
        Formula quantaleUnit = Bind(Exists, "E", Submonoids,
            Bind(Forall, "M", Submonoids, UnitLaws(F.Id("E"), F.Id("M"))));
        Formula semiringUnit = Bind(Exists, "u", R, Bind(Forall, "x", R, UnitLaws(unit, x)));
        Formula torsion = Bind(Forall, "a", R,
            Seq(D(0), Sp, Lt, Sp, F.Id("addOrderOf"), Open, F.Id("a"), Close));
        Formula primaryUnits = Bind(Forall, "p", F.Id("Primes"),
            Bind(Exists, "u", R, And(Parens(KilledByPrimePower(unit)),
                Parens(Bind(Forall, "x", R, Seq(Parens(KilledByPrimePower(x)),
                    Sp, Rightarrow, Sp, Parens(UnitLaws(unit, x))))))));
        return SemiringStatement(Seq(Parens(quantaleUnit), Sp, Leftrightarrow, Sp, Parens(semiringUnit),
            Sp, Lor, Sp, Parens(And(Parens(torsion), Parens(primaryUnits)))), cancellative: true);
    }
}
