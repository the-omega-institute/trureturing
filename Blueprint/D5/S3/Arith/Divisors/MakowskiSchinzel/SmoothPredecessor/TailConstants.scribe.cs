using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Arith.Divisors.MakowskiSchinzel.SmoothPredecessor;

internal sealed class SmoothPredecessorTailConstantsDocument : IScribeDocumentDefinition
{
    private const string Prefix =
        "D5/S3/Arith/Divisors/MakowskiSchinzel/SmoothPredecessor/TailConstants.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Exact meaning of the smooth tail constants",
        H("Exact meaning of the smooth tail constants"), Blocks(
            Node("smooth_floor_sum_le", "Floored reciprocal mass", FloorSum(),
                "For distinct primes and natural d, assume for an empty list that X is at least 1 " +
                "or floor(scale/d)=0. " +
                "the sum of floor(scale/(d m)) over the enumerated smooth integers, divided " +
                "by scale, is no greater than their exact sum of 1/(d m). Flooring each " +
                "term decreases the sum. The notation floorReciprocalWeight(scale,d) is " +
                "the natural weight m mapped to floor(scale/(d m)). With X=0 a nonempty " +
                "generator list returns zero, while the empty list retains its start 1; " +
                "taking d=1 explains the remaining condition. When floor(scale/d)=0 the empty fold " +
                "already has zero mass, including d=0 and d greater than scale."),
            Node("tail_floor_sum_le", "The finite subtraction is conservative", TailFloor(),
                "The third component of tailData(p), divided by scale, is at most the exact " +
                "reciprocal mass generated by allPrimes filtered at p, through bound/(2p), weighted " +
                "by 1/(2p m). The notation smoothUpTo(b,k) denotes the k-smooth integers " +
                "in the interval from 1 through b. Subtracting the stored value therefore " +
                "leaves at least as much Euler mass as subtracting the exact finite sum."),
            Node("tail_euler_ratio", "The finite Euler product ratio", TailEuler(),
                "For p at most 100, the first two components of tailData(p) are products of r and r-1 over " +
                "the primes at most p. Their ratio is precisely the Euler product at " +
                "exponent one exactly when p is at most 100. Above 100 the stored ratio remains " +
                "fixed, whereas the Euler product acquires the strict factor 101/100. " +
                "This identity and the conservative finite subtraction " +
                "allow a finite certificate to bound every finite set in the unbounded tail."),
            Node("reciprocal_tail_bound", "The remaining reciprocal mass", ReciprocalTail(),
                "For p positive, let T be a finite set of successors 2pm+1 whose positive " +
                "multipliers m exceed b and are (p+1)-smooth. If fs/scale is a lower " +
                "bound for the reciprocal mass through b, the sum of 1/q over T is at " +
                "most eulerProduct(p,1)/(2p)-fs/scale, and is strictly smaller when T " +
                "is nonempty. The finite and tail sets enter the same Euler sum."))));

    private static DocumentBlock Node(string name, string title, Formula formula, string prose) =>
        Describe.Lean(DescribeId.Create("smooth-predecessor-tail-constants-" +
            name.Replace('_', '-').ToLowerInvariant()), DeclarationHandle.Create(Prefix + name),
            H(title), StatementSource.FromAuthor(Disp(formula)), AssessedProvenance.FromRepo(),
            Blocks(Paragraph(Text(prose))), DescribeRole.Theorem);

    private static Formula FloorSum()
    {
        var ps = V("ps"); var x = V("X"); var d = V("d"); var m = V("m");
        var scale = Call("scale");
        var weight = Call("floorReciprocalWeight", scale, d);
        Formula body = Le(Div(Call("smoothSum", weight, ps, x, D(1)), scale),
            Sum("m", Call("factoredMultiples", Call("toFinset", ps), x, D(1)),
                Div(D(1), Mul(d, m))));
        body = Imp(Imp(Eq(ps, Call("nil")), new Formula.Logic(Le(D(1), x),
            FormulaLogicOperator.Or, Eq(Call("natDiv", scale, d), D(0)))), body);
        body = All("d", Nat(), body);
        body = All("X", Nat(), body);
        body = Imp(Call("Nodup", ps), body);
        body = Imp(All("p", Nat(), Imp(Call("Mem", V("p"), ps),
            Call("Prime", V("p")))), body);
        return All("ps", Call("List", Nat()), body);
    }

    private static Formula TailFloor()
    {
        var p = V("p");
        return All("p", Nat(), Le(
            Div(Call("snd", Call("snd", Call("tailData", p))), Call("scale")),
            Sum("m", Call("factoredMultiples",
                    Call("toFinset", Call("filterLe", Call("allPrimes"), p)),
                    Call("natDiv", Call("bound"), Mul(D(2), p)), D(1)), Div(D(1), Mul(Mul(D(2), p), V("m"))))));
    }

    private static Formula TailEuler()
    {
        var p = V("p"); var t = Call("tailData", p);
        return All("p", Nat(), new Formula.Logic(
            Eq(Call("eulerProduct", p, D(1)), Div(Call("fst", t), Call("fst", Call("snd", t)))),
            FormulaLogicOperator.Iff, Le(p, D(1,0,0))));
    }

    private static Formula ReciprocalTail()
    {
        var p = V("p"); var b = V("b"); var fs = V("fs"); var t = V("T");
        var lhs = Sum("q", t, Div(D(1), V("q")));
        var rhs = new Formula.Binary(Div(Call("eulerProduct", p, D(1)), Mul(D(2), p)),
            FormulaBinaryOperator.Subtract, Div(fs, Call("scale")));
        var cond = All("q", Nat(), Imp(Call("Mem", V("q"), t),
            Call("SmoothTailSuccessor", p, b, V("q"))));
        var small = Sum("m", Call("smoothUpTo", b, Add(p, D(1))),
            Div(D(1), Mul(Mul(D(2), p), V("m"))));
        Formula body = new Formula.Logic(Le(lhs, rhs), FormulaLogicOperator.And,
            Imp(Call("Nonempty", t), Lt(lhs, rhs)));
        body = Imp(Le(Div(fs, Call("scale")), small), body);
        body = Imp(cond, body);
        body = All("T", Call("Finset", Nat()), body);
        body = Imp(Lt(D(0), p), body);
        body = All("fs", Nat(), body);
        body = All("b", Nat(), body);
        return All("p", Nat(), body);
    }

    private static Formula V(string name) => F.Id(name);
    private static Formula Nat() => Seq(Mathbb, Grp(V("N")));
    private static Formula Call(string name, params Formula[] args) =>
        new Formula.Apply(Seq(Operatorname, Grp(V(name))), [.. args]);
    private static Formula All(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), type, body);
    private static Formula Eq(Formula a, Formula b) =>
        new Formula.Relation(a, FormulaRelationOperator.Equal, b);
    private static Formula Le(Formula a, Formula b) =>
        new Formula.Relation(a, FormulaRelationOperator.LessThanOrEqual, b);
    private static Formula Lt(Formula a, Formula b) =>
        new Formula.Relation(a, FormulaRelationOperator.LessThan, b);
    private static Formula Imp(Formula a, Formula b) =>
        new Formula.Logic(a, FormulaLogicOperator.Implies, b);
    private static Formula Mul(Formula a, Formula b) =>
        new Formula.Binary(a, FormulaBinaryOperator.Multiply, b);
    private static Formula Add(Formula a, Formula b) =>
        new Formula.Binary(a, FormulaBinaryOperator.Add, b);
    private static Formula Div(Formula a, Formula b) => new Formula.Fraction(a, b);
    private static Formula Sum(string name, Formula set, Formula body) =>
        Seq(new Formula.Subscript(F.Sum, Seq(V(name), Sp, InMacro, Sp, set)), Sp, body);
}
