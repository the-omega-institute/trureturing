    private static DocumentBlock Def(string name, string title, Formula body, string prose, bool literature = false) =>
        Node("Params." + name, title, DescribeRole.Definition, All(body, ("P", V("Params"))), prose, literature);

    private static DocumentBlock Node(string name, string title, DescribeRole role, Formula statement,
        string prose, bool literature = false, OpenProblemResolutionClaim? openProblemResolutionClaim = null) =>
        Describe.Lean(DescribeId.Create(name.Replace('.', '-').Replace('_', '-').ToLowerInvariant()),
            DeclarationHandle.Create(Gid + "." + name[(name.LastIndexOf('.') + 1)..]), H(title),
            StatementSource.FromAuthor(F.Disp(statement)),
            literature ? AssessedProvenance.FromLiterature(Source) : AssessedProvenance.FromRepo(),
            Blocks(Paragraph(Text(prose))), role, openProblemResolutionClaim);

    private static Formula N => F.Seq(F.Mathbb, F.Grp(V("N")));
    private static Formula A => V("a");
    private static Formula B => V("b");
    private static Formula K => V("k");
    private static Formula P => V("P");
    private static Formula Q => V("q");
    private static Formula S => V("s");
    private static Formula X => V("x");
    private static Formula Y => V("y");
    private static Formula I => V("i");
    private static Formula J => V("j");
    private static Formula Z => V("z");
    private static Formula CornerX => Subtract(Field("b"), Num(1));
    private static Formula CornerY => Subtract(Field("k"), Num(1));
    private static Formula V(string name) => Id(name);
    private static Formula Field(string name) => F.Seq(P, F.Dot, V(name));
    private static Formula C(string name, params Formula[] args) =>
        new Formula.Apply(F.Seq(F.Operatorname, F.Grp(V(name))), [.. args]);
    private static Formula Rect(Formula p) => C("Rect", p);
    private static Formula First(Formula q) => new Formula.Subscript(q, Num(1));
    private static Formula Second(Formula q) => new Formula.Subscript(q, Num(2));
    private static Formula Mod(Formula value, Formula d) => new Formula.Modulo(value, d);
    private static Formula Rel(Formula lhs, FormulaRelationOperator op, Formula rhs) =>
        new Formula.Relation(lhs, op, rhs);
    private static Formula Lt(Formula lhs, Formula rhs) => Rel(lhs, FormulaRelationOperator.LessThan, rhs);
    private static Formula Le(Formula lhs, Formula rhs) => Rel(lhs, FormulaRelationOperator.LessThanOrEqual, rhs);
    private static Formula Member(Formula lhs, Formula rhs) => Rel(lhs, FormulaRelationOperator.MemberOf, rhs);
    private static Formula And(params Formula[] items) =>
        items.Aggregate((lhs, rhs) => new Formula.Logic(lhs, FormulaLogicOperator.And, rhs));
    private static Formula Imp(Formula lhs, Formula rhs) => new Formula.Logic(lhs, FormulaLogicOperator.Implies, rhs);
    private static Formula Iff(Formula lhs, Formula rhs) => new Formula.Logic(lhs, FormulaLogicOperator.Iff, rhs);
    private static Formula All(Formula body, params (string Name, Formula Domain)[] variables) =>
        new Formula.BindMany(FormulaQuantifier.ForAll,
            [.. variables.Select(v => new Formula.BoundVariable(FormulaIdentifier.Create(v.Name), v.Domain))], body);
    private static Formula Parenthesized(Formula body) => F.Seq(F.Open, body, F.Close);
    private static Formula Tuple(Formula a, Formula b, Formula c) =>
        Parenthesized(F.Seq(a, F.Comma, b, F.Comma, c));
    private static Formula SuchThat(Formula element, Formula predicate) =>
        F.Seq(F.OpenBrace, element, F.Sp, F.Mid, F.Sp, predicate, F.CloseBrace);

    private static Formula Hypotheses => And(Lt(Num(0), A), Lt(A, B), Equal(C("gcd", A, B), Num(1)), Le(Num(3), K));

    private static Formula Height(Formula p, Formula x, Formula y, bool left) =>
        new Formula.Floor(new Formula.Fraction(
            left ? Subtract(Add(C("L", p, x, y), C("d", p)), Num(1)) : C("W", p, x, y), C("d", p)));

    private static Formula BlockCount(bool left)
    {
        var name = left ? "evalBeta" : "evalGamma";
        var index = left ? I : J;
        var residue = C("rightRes", P, Q);
        var holes = SuchThat(residue,
            And(Member(Q, Rect(P)), Lt(Num(0), residue), Lt(index, Height(P, First(Q), Second(Q), left))));
        var count = C("runTotal", holes, Subtract(C("d", P), Num(1)));
        return All(Equal(C(name, P, index), count), (left ? "i" : "j", N));
    }

    private static Formula LeastAt(Formula value, Formula residue, params Formula[] generators)
    {
        var t = V("t");
        return C("IsLeast", value, SuchThat(t, And(
            Member(t, C("closure", new Formula.SetLiteral([.. generators]))),
            Equal(Mod(t, C("d", P)), residue))));
    }

    private static Formula ResidueWitness => All(F.Seq(F.Exists, F.Bang, F.Sp, Q, F.Colon, F.Sp,
        Rect(P), F.Comma, F.Sp, Parenthesized(And(
            Equal(C("rightRes", P, Q), S),
            LeastAt(C("L", P, First(Q), Second(Q)), C("negRes", P, S), Field("a"), Field("b"), C("d", P)),
            LeastAt(C("W", P, First(Q), Second(Q)), S,
                Subtract(C("d", P), Field("a")), Subtract(C("d", P), Field("b")), C("d", P))))),
        ("P", V("Params")), ("s", C("Fin", C("d", P))));

    private static Formula FamilySpectrum
    {
        get
        {
            var p = C("P", A, B, K);
            var n = V("n");
            var list = C("spectrumList", p);
            var term = C("spectrum", p, n);
            var count = C("count", Z, list);
            var leftIndices = SuchThat(I, And(Member(I, C("range", Subtract(C("U", p), Num(1)))),
                Equal(C("evalBeta", p, Add(I, Num(1))), Z)));
            var rightIndices = SuchThat(J, And(Member(J, C("range", C("V", p))),
                Equal(C("evalGamma", p, J), Z)));
            return All(Imp(Hypotheses, And(
                All(Equal(term, C("sourceSpectrum", p, n)), ("n", N)),
                C("SortedGE", list),
                All(Iff(Lt(Num(0), term), Lt(n, Subtract(Add(B, K), Num(3)))), ("n", N)),
                All(Equal(count, Add(C("card", leftIndices), C("card", rightIndices))), ("z", N)),
                All(Le(count, Num(2)), ("z", N)))), ("a", N), ("b", N), ("k", N));
        }
    }
}
