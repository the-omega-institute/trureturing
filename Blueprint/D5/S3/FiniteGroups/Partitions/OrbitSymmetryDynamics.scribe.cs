using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.FiniteGroups.Partitions;

internal sealed class OrbitSymmetryDynamicsDocument : IScribeDocumentDefinition
{
    private static Formula V(string s) => F.Id(s);
    private static Formula Call(string s, params Formula[] a) =>
        new Formula.Apply(Seq(Operatorname, Grp(F.Id(s))), [.. a]);
    private static Formula SubgroupCall(string s, params Formula[] a) =>
        new Formula.Apply(Seq(Seq(Operatorname, Grp(V("Subgroup"))), Dot, Seq(Operatorname, Grp(V(s)))), [.. a]);
    private static Formula All(string s, Formula t, Formula b) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(s), t, b);
    private static Formula Eq(Formula a, Formula b) =>
        new Formula.Relation(a, FormulaRelationOperator.Equal, b);
    private static Formula Imp(Formula a, Formula b) =>
        new Formula.Logic(a, FormulaLogicOperator.Implies, b);
    private static Formula Iff(Formula a, Formula b) =>
        new Formula.Logic(a, FormulaLogicOperator.Iff, b);
    private static Formula Singleton(Formula x) => new Formula.SetLiteral([x]);
    private static Formula Perm(Formula x) => Call("Perm", x);
    private static Formula Orbit(Formula t, Formula x, Formula y) => Call("SameCycle", t, x, y);
    private static Formula OrbitAut(Formula t) => Call("orbitAut", t);
    private static Formula Centralizer(Formula t) => Call("centralizer", Singleton(t));
    private static Formula Pow2(Formula t) => new Formula.Power(t, D(2));
    private static Formula Scope(Formula b) => All("X", V("Typeu"), All("t", Perm(V("X")), b));
    private static Formula And(Formula a, Formula b) =>
        new Formula.Logic(a, FormulaLogicOperator.And, b);
    private static Formula Or(Formula a, Formula b) =>
        new Formula.Logic(a, FormulaLogicOperator.Or, b);
    private static Formula Pow6(Formula t) => new Formula.Power(t, D(6));
    private static Formula ZPowers(Formula t) => SubgroupCall("zpowers", t);
    private static Formula Normalizer(Formula t) => SubgroupCall("normalizer", ZPowers(t));
    private static Formula IsCycle(Formula t) => Call("IsCycle", t);
    private static Formula RelationAgreement(Formula s)
    {
        Formula body = Iff(Orbit(s, V("x"), V("y")), Orbit(V("t"), V("x"), V("y")));
        return All("x", V("X"), All("y", V("X"), body));
    }
    private static Formula Determination() =>
        All("s", Perm(V("X")), Imp(RelationAgreement(V("s")), Eq(V("s"), V("t"))));

    private static DocumentBlock.Describe Desc(string name, string title, Formula f,
        string text, DescribeRole role = DescribeRole.Theorem) =>
        Describe.Lean(DescribeId.Create("orbit-symmetry-dynamics-" + name.Replace('_', '-').ToLowerInvariant()),
            DeclarationHandle.Create("D5/S3/FiniteGroups/Partitions/OrbitSymmetryDynamics." + name),
            H(title), StatementSource.FromAuthor(Disp(f)), AssessedProvenance.FromRepo(),
            Blocks(Paragraph(Text(text))), role);

    public DocumentDefinition Create()
    {
        var x = V("X");
        var t = V("t");
        var orbitAutDef = Scope(Call("Subgroup", Perm(x)));
        var centralizerLe = Scope(new Formula.Relation(Centralizer(t), FormulaRelationOperator.SubsetOf, OrbitAut(t)));
        var uniqueness = Scope(Iff(Determination(), Eq(Pow2(t), D(1))));
        var equality = Scope(Iff(Eq(Centralizer(t), OrbitAut(t)), Eq(Pow2(t), D(1))));
        var normalizerLe = Scope(new Formula.Relation(Normalizer(t),
            FormulaRelationOperator.SubsetOf, OrbitAut(t)));
        var normalizerEquality = Scope(Iff(
            Eq(Normalizer(t), OrbitAut(t)),
            Or(Eq(Pow2(t), D(1)),
                And(IsCycle(Pow2(t)), Eq(Pow6(t), D(1))))));
        return DocumentDefinition.Create(ScribeNode.Create(
            "On any type, the chosen-step centralizer and the cyclic normalizer are contained in the complete orbit-relation automorphism subgroup. The cyclic normalizer equals that subgroup exactly when t squared is one, or when t squared is a single nontrivial cycle and t sixth power is one.",
            H("Orbit Relations, Centralizers, and Cyclic Normalizers"), Blocks(
                Paragraph(Text("For an arbitrary type X and chosen step t, orbitAut is the subgroup "
                    + "of permutations preserving and reflecting SameCycle for t. It is the complete "
                    + "relation stabilizer. Preserving the relation allows exchanging its orbits; "
                    + "fixing every invariant subset individually requires each orbit union to be fixed "
                    + "as a set, while normalizing the cyclic subgroup generated by t requires conjugation "
                    + "to preserve that subgroup. These are different definitions, but their subgroups "
                    + "can coincide in degenerate or involutive cases; no universal strict inequality "
                    + "is claimed. There is no finiteness restriction.")),
                Desc("orbitAut", "The full orbit-relation automorphism subgroup", orbitAutDef,
                    "orbitAut t has type Subgroup (Perm X) and is defined as SuccessorQuotient.relationAut t.SameCycle, so both preservation and reflection of the complete orbit relation are required.",
                    DescribeRole.Definition),
                Desc("centralizer_le_orbitAut", "The chosen-step centralizer preserves orbit structure", centralizerLe,
                    "Every permutation commuting with the chosen generator t preserves and reflects SameCycle. This is a centralizer of the selected step, not merely a normalizer of its cyclic subgroup."),
                Desc("orbit_relation_determines_iff", "The complete orbit relation determines the step exactly for involutions", uniqueness,
                    "If every permutation with the same complete orbit relation equals t, the inverse t inverse has the same relation and forces t squared to be one. Conversely, when t is involutive, each orbit is a singleton or a two-point orbit, so relation agreement determines the image of every point. Empty and infinite X, identity permutations, singleton orbits and two-point orbits all remain in scope."),
                Desc("centralizer_eq_orbitAut_iff", "Centralizer and full orbit stabilizer coincide exactly in the involutive case", equality,
                    "Necessity: the within-orbit swap of x and t x lies in orbitAut; equality with the centralizer makes this swap commute with t, forcing t squared x = x for every x. Sufficiency: for t squared = 1 and p in orbitAut, p*t*p inverse has the same complete orbit relation as t, so reconstruction gives p*t*p inverse = t and hence commutation. This differs from the uniqueness theorem's necessity argument using t inverse. Empty and infinite types and fixed points remain in scope. Invariant sets on arbitrary X are exactly orbit unions; fixing every invariant subset individually fixes each such subset as a set. Finite invariant subsets alone do not recover infinite orbits."),
                Desc("normalizer_le_orbitAut", "The cyclic normalizer preserves the complete orbit relation", normalizerLe,
                    "For every arbitrary type X and permutation t, the subgroup normalizer of the actual integer-power set Subgroup.zpowers t is contained in orbitAut t. Conjugating any power by a normalizer element produces another integer power, so the same global power witness transports every SameCycle relation in both directions."),
                Desc("normalizer_eq_orbitAut_iff", "Sharp arbitrary-type cyclic-normalizer classification", normalizerEquality,
                    "The equality holds exactly when t is involutive, or when the square t squared is a literal Mathlib IsCycle and t sixth power is one. A within-orbit transposition forces one common integer exponent; its period cases are 1, 2, or 3, and the same global exponent rules out two distinct three-orbits. The non-involutive branch therefore has one three-orbit, characterized precisely by IsCycle(t squared) together with t sixth power equal to one. For sufficiency, an orbitAut permutation preserves the three-orbit and its complement explicitly; restricting both t and the permutation to the complement gives the existing involution centralizer theorem before the two orientations are combined globally. Permutations may exchange two-point orbits, and infinitely many such orbits are allowed."),
                Paragraph(Text("For the arithmetic step t = (finRotate n)^a with n > 0, the existing residue chart "
                    + "identifies the physical zero-family subgroup with the full orbit-relation stabilizer. "
                    + "The exact compiled application gives centralizer equality precisely when n divides 2a, "
                    + "including a = 0 and n = 1. "
                    + "The same arithmetic transport and the sharp cyclic-normalizer theorem give equality "
                    + "between the cyclic normalizer of that step and the zero-family subgroup exactly when "
                    + "n divides 2a or n equals 3. For n at least 2, the remaining branch requires 2a coprime "
                    + "to n and n dividing 6a, which force n = 3. This includes the non-involutive triangular "
                    + "case while retaining a = 0 and n = 1. "
                    + "Thus zero-subset observations forget the cyclic direction and "
                    + "retain only the orbit partition; the arithmetic transport uses ambient conjugation by "
                    + "residueChart rather than an abstract zeroFamilyEquiv."))
            ), []));
    }
}
