internal sealed class MaDistinctPowersFourDocument : IScribeDocumentDefinition
{
    private static readonly LibraryNoteRef Ma =
        LibraryNoteRef.Create("D5/L/FiniteGroups/ma2026distinctpowers");

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Finite group subsets with generator classes of size at most four have distinct powers.",
        H("Ma's distinct powers question"),
        Blocks(Describe.Lean(
            DescribeId.Create("ma-distinct-powers-four"),
            DeclarationHandle.Create("D5/S3/FiniteGroups/SubsetProducts/MaDistinctPowersFour.result"),
            H("The size-four extension of Theorem 1.1"),
            StatementSource.FromAuthor(Disp(Statement())),
            AssessedProvenance.FromRepo(Ma),
            Blocks(
                Paragraph(Text(
                    "Remark 2.2 and Section 9 ask about every positive subset size n. "
                    + "The group is arbitrary and finite. The order exclusion applies to every element of G "
                    + "and every integer from 2 through n + 1, inclusive. For each x in A, the subtype "
                    + "in the class bound counts precisely the members of A generating the same cyclic "
                    + "subgroup as x. The equivalence enumerates the members of A once and gives exponents "
                    + "1 through n by adding one to the zero-based index. The last implication expresses "
                    + "pairwise distinctness. The hypotheses include subsets containing the identity.")),
                Paragraph(Text(
                    "As in Ma's proof of Theorem 1.1, an admissible exponent preserves the cyclic subgroup "
                    + "generated by the element, so powers from different classes cannot coincide. "
                    + "Complementary endpoint pairs go to two-element classes, consecutive triples and "
                    + "quadruples go to the corresponding classes in the remaining interval, and the last "
                    + "positions go to singletons.")),
                Paragraph(Text(
                    "In a four-element class the four distinct coordinates are units modulo the full "
                    + "common order. The order-four Latin-array proof gives a transversal, equal column "
                    + "symbol sets, or a specified motif. A commutative product array excludes the motif. "
                    + "Equal columns would force a multiplicative coset after reduction to a prime "
                    + "dividing the order. The first and second power sums of the four consecutive "
                    + "coefficients rule it out. The transversal therefore supplies a valid block even "
                    + "when the reduced generator coordinates repeat."))),
            DescribeRole.Theorem))));

    private static Formula Statement()
    {
        var n = F.Id("n");
        var g = F.Id("G");
        var a = F.Id("A");
        var x = F.Id("x");
        var y = F.Id("y");
        var k = F.Id("k");
        var i = F.Id("i");
        var j = F.Id("j");
        var nat = Seq(Mathbb, Grp(F.Id("N")));
        var index = App(F.Id("Fin"), n);
        var order = Par(Seq(Forall, Sp, Binder(x, g), Sp, Binder(k, nat), Comma, Sp,
            D(2), Sp, Le, Sp, k, Sp, To, Sp, k, Sp, Le, Sp, n, Sp, Plus, Sp, D(1),
            Sp, To, Sp, App(F.Id("orderOf"), x), Sp, Neq, Sp, k));
        var fiber = Subtype(y, g, Seq(y, Sp, InMacro, Sp, a, Sp, Land, Sp,
            App(Qualified("Subgroup", "zpowers"), y), Sp, Eq, Sp,
            App(Qualified("Subgroup", "zpowers"), x)));
        var sizes = Par(Seq(Forall, Sp, Binder(x, g), Comma, Sp, x, Sp, InMacro, Sp, a, Sp,
            To, Sp, App(Qualified("Nat", "card"), fiber), Sp, Le, Sp, D(4)));
        var enumeration = Seq(Exists, Sp,
            Binder(F.Id("a"), Seq(index, Sp, Equiv, Sp, Subtype(x, g, Seq(x, Sp, InMacro, Sp, a)))),
            Comma, Sp, Forall, Sp, Par(Seq(i, Sp, j, Sp, Colon, Sp, index)), Comma, Sp,
            Power(i, g), Sp, Eq, Sp, Power(j, g), Sp, To, Sp, i, Sp, Eq, Sp, j);
        return Seq(Forall, Sp, Binder(n, nat), Sp, Binder(g, F.Id("Type")), Sp,
            Instance("Group", g), Sp, Instance("Finite", g), Sp, Binder(a, App(F.Id("Finset"), g)),
            Comma, Sp, D(0), Sp, Lt, Sp, n, Sp, To, Sp,
            a, Dot, F.Id("card"), Sp, Eq, Sp, n, Sp, To, Sp,
            order, Sp, To, Sp, sizes, Sp, To, Sp, enumeration);
    }

    private static Formula Power(Formula i, Formula g) =>
        new Formula.Power(Binder(App(F.Id("a"), i), g),
            Seq(i, Dot, F.Id("val"), Sp, Plus, Sp, D(1)));

    private static Formula Qualified(string owner, string name) =>
        Seq(Operatorname, Grp(Seq(F.Id(owner), Dot, F.Id(name))));

    private static Formula App(Formula fn, Formula value) => new Formula.Apply(fn, [value]);
    private static Formula Par(Formula value) => Seq(Open, value, Close);
    private static Formula Binder(Formula value, Formula type) => Par(Seq(value, Sp, Colon, Sp, type));
    private static Formula Instance(string name, Formula type) =>
        Seq(OpenBracket, App(F.Id(name), type), CloseBracket);
    private static Formula Subtype(Formula value, Formula type, Formula predicate) =>
        Seq(OpenBrace, value, Sp, Colon, Sp, type, Sp, Mid, Sp, predicate, CloseBrace);
}
