using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.FiniteGroups.Aliabadi;

internal sealed class AliabadiTwoLetterConstructionDocument : IScribeDocumentDefinition
{
    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "A nonidentity element generates a two-letter right-quotient permutation with exact support order.",
        H("A cyclic two-letter right-quotient construction"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("aliabadi-two-letter-construction"),
                DeclarationHandle.Create(
                    "D5/S3/FiniteGroups/Aliabadi/AliabadiTwoLetterConstruction."
                        + "exists_rightQuotient_perm_of_ne_one"),
                H("A cyclic subgroup supplies an exact two-letter realization"),
                StatementSource.FromAuthor(Disp(TheoremFormula())),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "Let G be a finite group and let a be a nonidentity element. "
                            + "The subgroup generated by a is finite and has cardinality orderOf(a). "
                            + "Define a map on G by left multiplication by a on that subgroup and "
                            + "the identity outside it. The subgroup is closed under left multiplication, "
                            + "so this map is injective and hence a permutation of G.")),
                    Paragraph(Text(
                        "Every point in the generated subgroup moves because a is nonidentity, "
                            + "while every point outside it is fixed. Thus the support has exactly "
                            + "orderOf(a) elements. Its literal right quotient sigma(x) times x inverse "
                            + "is a when x lies in the generated subgroup and is one otherwise. "
                            + "The result is a constructive two-letter realization; it does not assert "
                            + "the separate classification or counting formula for every possible support size."))),
                DescribeRole.Theorem))));

    private static Formula Call(string name, params Formula[] args) =>
        new Formula.Apply(Seq(Operatorname, Grp(F.Id(name))), [.. args]);

    private static Formula All(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), type, body);

    private static Formula Ex(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create(name), type, body);

    private static Formula Eq(Formula a, Formula b) =>
        new Formula.Relation(a, FormulaRelationOperator.Equal, b);

    private static Formula And(Formula a, Formula b) =>
        new Formula.Logic(a, FormulaLogicOperator.And, b);

    private static Formula Or(Formula a, Formula b) =>
        new Formula.Logic(a, FormulaLogicOperator.Or, b);

    private static Formula Type => F.Id("Typeu");

    private static Formula TheoremFormula()
    {
        var g = F.Id("G");
        var a = F.Id("a");
        var sigma = F.Id("sigma");
        var x = F.Id("x");
        var quotient = Call("RightQuotient", sigma, x);
        var result = Ex("sigma", Call("EquivPerm", g),
            And(
                Eq(Call("SupportCard", sigma), Call("orderOf", a)),
                All("x", g,
                    Or(Eq(quotient, a), Eq(quotient, D(1))))));
        return All("G", Type,
            All("group", Call("Group", g),
                All("finite", Call("Fintype", g),
                    All("eq", Call("DecidableEq", g),
                        All("a", g,
                            All("ha", new Formula.Not(Eq(a, D(1))), result))))));
    }
}
