namespace StrataLint.Scribe.Blueprint.D5.S3.FiniteGroups;

internal sealed class CFMPCoxeterIndexObstructionDocument : IScribeDocumentDefinition
{
    private static readonly LibraryNoteRef Source =
        LibraryNoteRef.Create("D5/L/cfmp2026cycledegree9index72obstruction");

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "The even subgroup of the Coxeter group with string labels four, nine and three "
        + "has no torsionfree normal subgroup of index seventy-two.",
        H("The native Coxeter quotient obstruction"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("cfmp-native-normal-index-claim"),
                DeclarationHandle.Create("D5/S3/FiniteGroups/CFMPCoxeterIndexObstruction.claim"),
                H("The normal finite-cover assertion"),
                StatementSource.FromAuthor(Existence()),
                AssessedProvenance.FromRepo(Source),
                Blocks(Paragraph(Text(
                    "The group W is the Coxeter presentation on a, b, c and d. Each generator "
                    + "squares to the identity; ab has fourth power one, bc has ninth power "
                    + "one, and cd has third power one. The pairs a,c and a,d and b,d commute. "
                    + "Wplus is the kernel of the homomorphism sending every simple reflection "
                    + "to minus one. A subgroup Gamma is normal only in Wplus. Torsionfree means "
                    + "that every finite-order element of Gamma is the identity. No finiteness "
                    + "assumption is imposed on W, and Gamma may be trivial."))),
                DescribeRole.Definition),
            Describe.Lean(
                DescribeId.Create("cfmp-native-normal-index-obstruction"),
                DeclarationHandle.Create("D5/S3/FiniteGroups/CFMPCoxeterIndexObstruction.result"),
                H("No torsionfree normal orientation quotient of order seventy-two"),
                StatementSource.FromAuthor(Disp(Seq(Neg, Sp, Existence()))),
                AssessedProvenance.FromRepo(Source),
                Blocks(
                    Paragraph(Text(
                        "A representation into three by three matrices over the field with "
                        + "nineteen elements separates the required finite orders. It sends a "
                        + "to the identity. The matrix for b changes the first coordinate to "
                        + "minus itself plus twelve times the second. The matrix for c changes "
                        + "the second coordinate to twelve times the first minus itself plus "
                        + "the third. The matrix for d changes the third coordinate to the "
                        + "second minus itself. All other coordinates are preserved. The matrices "
                        + "satisfy every relation of W; their bc, cd and bd products have exact "
                        + "orders nine, three and two. The native power relations give the upper "
                        + "bounds, and this homomorphism gives the matching lower bounds.")),
                    Paragraph(Text(
                        "Passing to a quotient by a torsionfree normal subgroup preserves the "
                        + "order of every finite-order element: any power killed by the quotient "
                        + "belongs to the torsionfree kernel and still has finite order, so is "
                        + "the identity. Thus the quotient images of bc and cd have exact orders "
                        + "nine and three, and their product, which is bd, has exact order two.")),
                    Paragraph(Text(
                        "Let H be the subgroup generated by those two images in Wplus modulo "
                        + "Gamma. It need not be the whole quotient. Its cardinality divides "
                        + "seventy-two, and its two displayed generators meet every hypothesis "
                        + "of CycleNineThreeObstruction.result. Applying that existing abstract "
                        + "finite-group theorem gives the contradiction.")),
                    Paragraph(Text(
                        "The conclusion concerns the stated normal orientation quotient. "
                        + "A geometric count of tetrahedral blocks requires a separate "
                        + "identification with the actual six-sector block orbits. Arbitrary "
                        + "pseudo-simplicial pairings of twenty-four tetrahedra and unrestricted "
                        + "minimality lie outside this conclusion."))),
                DescribeRole.Theorem))));

    private static Formula Existence()
    {
        Formula gamma = F.Id("Gamma");
        Formula normal = new Formula.Apply(F.Id("Normal"), [gamma]);
        Formula torsionfree = new Formula.Apply(F.Id("Torsionfree"), [gamma]);
        Formula index = new Formula.Relation(
            new Formula.Apply(F.Id("index"), [gamma]), FormulaRelationOperator.Equal, D(7, 2));
        Formula assumptions = new Formula.Logic(normal, FormulaLogicOperator.And,
            new Formula.Logic(torsionfree, FormulaLogicOperator.And, index));
        return new Formula.BindMany(FormulaQuantifier.Exists,
            [new Formula.BoundVariable(FormulaIdentifier.Create("Gamma"),
                new Formula.Apply(F.Id("Subgroup"), [F.Id("Wplus")]))], assumptions);
    }
}
