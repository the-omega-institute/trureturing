        LibraryNoteRef.Create("D5/L/FiniteGroups/bajnokbersonjust2022perfectrestricted");

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Every finite abelian group with a perfect restricted basis of size s + 1 is cyclic.",
        H("Perfect restricted bases of size s + 1"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("bajnok-perfect-restricted-basis"),
                DeclarationHandle.Create(Owner + "IsPerfectRestrictedBasis"),
                H("Perfect restricted s-bases"),
                StatementSource.FromAuthor(Disp(PerfectRestrictedBody())),
                AssessedProvenance.FromLiterature(Source),
                Blocks(Paragraph(Text(
                    "The paper states (abstract, p. 1): \"A is a perfect restricted s-basis of G if each element of G can be written uniquely as the sum of at most s distinct elements of A.\" "
                    + "The Lean predicate uses a finset T of distinct elements, requires T ⊆ A and T.card ≤ s, and records the sum over T. "
                    + "The empty finset supplies the empty sum."))),
                DescribeRole.Definition),
            Describe.Lean(
                DescribeId.Create("bajnok-question-six-claim"),
                DeclarationHandle.Create(Owner + "claim"),
                H("The cyclic conclusion for Question 6"),
                StatementSource.FromAuthor(Disp(Iff(Call("claim"), ClaimBody()))),
                AssessedProvenance.FromLiterature(Source),
                Blocks(Paragraph(Text(
                    "Question 6 (p. 8) asks: \"Are there any noncyclic groups that have a perfect restricted s-basis of size s + 1?\" "
                    + "The displayed proposition answers the question for finite abelian groups: positive s, a basis with cardinality s + 1, and the perfect restricted basis condition imply IsAddCyclic."))),
                DescribeRole.Definition),
            Describe.Lean(
                DescribeId.Create("bajnok-question-six-result"),
                DeclarationHandle.Create(Owner + "result"),
                H("Question 6 has a negative answer"),
                StatementSource.FromAuthor(Disp(ClaimBody())),
                AssessedProvenance.FromRepo(Source),
                Blocks(Paragraph(Text(
                    "The proof first identifies the admissible subsets with the proper subsets of A, giving the odd cardinality 2 raised to A.card minus 1 for G. "
                    + "For each a in A, the map that toggles a is a fixed-point-free involution on every selected coset of the subgroup generated by a, so each such fiber has even cardinality. "
                    + "Lagrange's divisibility and the proper-subset count make the subgroup cardinality odd; excluding the coset containing the full subset forces that subgroup to be all of G."))),
                DescribeRole.Theorem))));

    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula Call(string name, params Formula[] arguments) =>
        new Formula.FunctionCall(FormulaIdentifier.Create(name), [.. arguments]);
    private static Formula QualifiedCall(string owner, string name, params Formula[] arguments) =>
        new Formula.Apply(Seq(F.Id(owner), Dot, F.Id(name)), [.. arguments]);
    private static Formula Typed(Formula value, Formula type) =>
        Parenthesized(Seq(value, Colon, Sp, type));
    private static Formula All(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), type, body);
    private static Formula ExistsUnique(Formula variable, Formula type, Formula body) =>
        Call("ExistsUnique", Typed(variable, type), body);
    private static Formula Instance(string name, Formula type) =>
        Seq(OpenBracket, Call(name, type), CloseBracket, Sp);
    private static Formula TypeStar() => Seq(F.Id("Type"), Star);
    private static Formula Nat() => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula Finset(Formula type) => Call("Finset", type);
    private static Formula Card(Formula value) => QualifiedCall("Finset", "card", value);
    private static Formula SumIn(string name, Formula set, Formula body) =>
        Seq(new Formula.Subscript(Sum, Member(F.Id(name), set)), Sp, body);
    private static Formula Member(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.MemberOf, right);
    private static Formula SubsetOf(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.SubsetOf, right);
    private static Formula Equal(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.Equal, right);
    private static Formula LessEqual(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.LessThanOrEqual, right);
    private static Formula And(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.And, Parenthesized(right));
    private static Formula Implies(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Implies, Parenthesized(right));
    private static Formula Iff(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Iff, Parenthesized(right));

    private static Formula PerfectRestrictedBody()
    {
        var g = F.Id("g");
        var t = F.Id("T");
        var x = F.Id("x");
        var G = F.Id("G");
        var s = F.Id("s");
        var A = F.Id("A");
        var property = And(
            SubsetOf(t, A),
            And(LessEqual(Card(t), s), Equal(SumIn("x", t, x), g)));
        var unique = ExistsUnique(t, Finset(G), property);
        return All("G", TypeStar(),
            Seq(Instance("AddCommGroup", G),
                Instance("DecidableEq", G),
                All("s", Nat(),
                    All("A", Finset(G),
                        Iff(Call("IsPerfectRestrictedBasis", s, A),
                            All("g", G, unique))))));
    }

    private static Formula ClaimBody()
    {
        var G = F.Id("G");
        var s = F.Id("s");
        var A = F.Id("A");
        return All("G", F.Id("Type"),
            Seq(Instance("AddCommGroup", G),
                Instance("Fintype", G),
                Instance("DecidableEq", G),
                All("s", Nat(),
                    All("A", Finset(G),
                        Implies(LessEqual(Num(1), s),
                            Implies(Equal(Card(A), Seq(s, Plus, Num(1))),
                                Implies(Call("IsPerfectRestrictedBasis", s, A),
                                    Call("IsAddCyclic", G))))))));
    }
}
