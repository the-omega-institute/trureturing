using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.ConceptDynamics.MeasurableRefinement;

internal sealed class DoobDynkinFactorizationDocument : IScribeDocumentDefinition
{
    private const string Declaration =
        "D5/S3/ConceptDynamics/MeasurableRefinement/DoobDynkinFactorization."
            + "measurable_refinement_iff_generated_information_inclusion";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Standard-Borel measurable refinement is generated-information inclusion.",
        H("Doob-Dynkin Factorization"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("measurable-refinement-information-inclusion"),
                DeclarationHandle.Create(Declaration),
                H("Measurable refinement is information inclusion"),
                StatementSource.FromAuthor(FactorizationFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "The information generated by a concept is the pullback measurable "
                            + "space along its readout. Measurability of C for the pullback "
                            + "along D therefore means that C observes no more events than D.")),
                    Paragraph(Text(
                        "For a nonempty standard-Borel codomain, the pinned Mathlib "
                            + "Doob-Dynkin theorem supplies a measurable map p with C equal "
                            + "to p composed with D.")),
                    Paragraph(Text(
                        "Conversely, composing a measurable p with the canonical measurable "
                            + "map into D's pullback space proves inclusion of the generated "
                            + "measurable spaces. The two directions give the stated "
                            + "equivalence."))),
                DescribeRole.Theorem))));

    private static Formula TypeUniverse() =>
        Seq(Operatorname, Grp(F.Id("Type")));

    private static Formula Arrow(Formula domain, Formula codomain) =>
        new Formula.TypeArrow(domain, codomain);

    private static Formula Typed(Formula value, Formula type) =>
        Seq(value, Colon, Sp, type);

    private static Formula Factorization(
        Formula concept,
        Formula conditioning,
        Formula conceptType,
        Formula conditioningType)
    {
        Formula factor = F.Id("p");
        return Seq(
            Exists, Sp, Typed(factor, Arrow(conditioningType, conceptType)), Comma, Sp,
            Call("Measurable", factor), Sp, Land, Sp,
            concept, Sp, Eq, Sp, Call("compose", factor, conditioning));
    }

    private static Formula FactorizationFormula()
    {
        Formula stateType = F.Id("X");
        Formula conceptType = F.Id("BC");
        Formula conditioningType = F.Id("BD");
        Formula concept = F.Id("C");
        Formula conditioning = F.Id("D");
        Formula generatedConcept = Call("generated", concept);
        Formula generatedConditioning = Call("generated", conditioning);
        Formula factorization =
            Factorization(concept, conditioning, conceptType, conditioningType);

        return Disp(Seq(
            Begin, Grp(F.Id("gathered")),
            Forall, Sp,
            Typed(Seq(stateType, Comma, Sp, conceptType, Comma, Sp, conditioningType),
                TypeUniverse()),
            Comma, RowBreak, Grp(),
            OpenBracket, Call("MeasurableSpace", conceptType), CloseBracket, Comma, Sp,
            OpenBracket, Call("MeasurableSpace", conditioningType), CloseBracket,
            Comma, RowBreak, Grp(),
            OpenBracket, Call("Nonempty", conceptType), CloseBracket, Comma, Sp,
            OpenBracket, Call("StandardBorelSpace", conceptType), CloseBracket,
            Comma, RowBreak, Grp(),
            Typed(concept, Arrow(stateType, conceptType)), Comma, Sp,
            Typed(conditioning, Arrow(stateType, conditioningType)), Comma,
            RowBreak, Grp(),
            Open, Call("Measurable", concept, generatedConditioning), Sp,
            Rightarrow, Sp, factorization, Close, Sp, Land,
            RowBreak, Grp(),
            Open, factorization, Sp, Iff, Sp,
            generatedConcept, Sp, Subseteq, Sp, generatedConditioning, Close, Dot,
            End, Grp(F.Id("gathered"))));
    }
}
