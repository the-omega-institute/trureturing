using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.ConceptDynamics.MeasurableRefinement;

internal sealed class MeasurableFactorInformationInclusionDocument : IScribeDocumentDefinition
{
    private const string Declaration =
        "D5/S3/ConceptDynamics/MeasurableRefinement/MeasurableFactorInformationInclusion."
            + "measurable_factorization_generated_information_inclusion";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "A measurable factorization includes the generated information space.",
        H("Measurable Factor Information Inclusion"),
        Blocks(Describe.Lean(
            DescribeId.Create("measurable-factor-information-inclusion"),
            DeclarationHandle.Create(Declaration),
            H("Measurable factorization implies generated-information inclusion"),
            StatementSource.FromAuthor(TheoremFormula()),
            AssessedProvenance.FromRepo(),
            Blocks(
                Paragraph(Text(
                    "The information generated by a readout is its codomain measurable space "
                        + "pulled back to the state carrier. The displayed factorization and "
                        + "measurability conditions are the complete hypotheses.")),
                Paragraph(Text(
                    "Pullback along a composite equals iterated pullback. Measurability of p "
                        + "then makes the pullback along C no larger than the pullback along D, "
                        + "which is exactly the displayed event inclusion."))),
            DescribeRole.Theorem))));

    private static Formula Arrow(Formula domain, Formula codomain) =>
        new Formula.TypeArrow(domain, codomain);

    private static Formula Typed(Formula value, Formula type) =>
        Seq(value, Colon, Sp, type);

    private static Formula TheoremFormula()
    {
        Formula state = F.Id("X");
        Formula conceptType = F.Id("BC");
        Formula detailType = F.Id("BD");
        Formula concept = F.Id("C");
        Formula detail = F.Id("D");
        Formula factor = F.Id("p");
        Formula type = Seq(Operatorname, Grp(F.Id("Type")));

        return Disp(Seq(
            Begin, Grp(F.Id("gathered")),
            Forall, Sp,
            Typed(Seq(state, Comma, Sp, conceptType, Comma, Sp, detailType), type),
            Comma, RowBreak, Grp(),
            OpenBracket, Call("MeasurableSpace", conceptType), CloseBracket,
            Comma, Sp,
            OpenBracket, Call("MeasurableSpace", detailType), CloseBracket,
            Comma, RowBreak, Grp(),
            Typed(concept, Arrow(state, conceptType)), Comma, Sp,
            Typed(detail, Arrow(state, detailType)), Comma, Sp,
            Typed(factor, Arrow(detailType, conceptType)), Comma,
            RowBreak, Grp(),
            Open, Call("Measurable", factor), Sp, Land, Sp,
            concept, Sp, Eq, Sp, Call("compose", factor, detail), Close,
            Sp, Rightarrow, RowBreak, Grp(),
            Call("generated", concept), Sp, Subseteq, Sp,
            Call("generated", detail), Dot,
            End, Grp(F.Id("gathered"))));
    }
}
