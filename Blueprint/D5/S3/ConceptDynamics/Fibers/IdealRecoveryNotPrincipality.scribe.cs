using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.ConceptDynamics.Fibers;

internal sealed class IdealRecoveryNotPrincipalityDocument
    : IScribeDocumentDefinition
{
    private const string Prefix =
        "D5/S3/ConceptDynamics/Fibers/IdealRecoveryNotPrincipality.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Exact recovery of an ideal does not supply a global generator. A concrete "
            + "nonprincipal prime ideal is contrasted with principal-ideal rings and "
            + "the degenerate zero and unit ideals.",
        H("Ideal Recovery Does Not Imply Principality"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("recovered-prime-ideal-is-not-principal"),
                DeclarationHandle.Create(
                    Prefix + "uniquely_recovered_prime_ideal_need_not_be_principal"),
                H("A uniquely identified prime ideal can be nonprincipal"),
                StatementSource.FromAuthor(RecoveredNonprincipalFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "The named data is the existing ideal generated by 2 and "
                            + "1 + sqrt(-5). Equality with that named ideal determines it "
                            + "uniquely, while the imported D5 theorem supplies its global "
                            + "nonprincipality without repeating the norm obstruction.")),
                    Paragraph(Text(
                        "Its quotient is identified with ZMod two. The quotient is a field, "
                            + "so the ideal is maximal and hence prime. Primality strengthens "
                            + "the witness but is not used to infer nonprincipality.")),
                    Paragraph(Text(
                        "This is distinct from FPOD 191.1: that gauge theorem starts with a "
                            + "principal ideal and compares generators up to a unit. Here no "
                            + "global generator exists."))),
                DescribeRole.Theorem),
            Describe.Lean(
                DescribeId.Create("principal-ideal-rings-have-only-principal-ideals"),
                DeclarationHandle.Create(
                    Prefix + "every_ideal_is_principal_in_principal_ideal_ring"),
                H("Every ideal is principal in a principal-ideal ring"),
                StatementSource.FromAuthor(PrincipalIdealRingFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "Mathlib's principal-ideal-ring structure gives this conclusion "
                        + "directly. Only a semiring is required by the actual class "
                        + "definition; no field or domain hypothesis is added."))),
                DescribeRole.Theorem),
            Describe.Lean(
                DescribeId.Create("principal-ideal-ring-hypothesis-is-essential"),
                DeclarationHandle.Create(
                    Prefix + "principal_ideal_ring_hypothesis_is_necessary"),
                H("The principal-ideal-ring hypothesis cannot be dropped"),
                StatementSource.FromAuthor(NecessaryHypothesisFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "The minus-five quadratic order has the concrete nonprincipal ideal "
                        + "from the first theorem, so it cannot carry a principal-ideal-ring "
                        + "instance. This is the named counterexample required by the "
                        + "hypothesis audit."))),
                DescribeRole.Theorem),
            Describe.Lean(
                DescribeId.Create("zero-and-unit-ideals-remain-principal"),
                DeclarationHandle.Create(
                    Prefix + "zero_and_unit_ideals_are_principal"),
                H("Zero and unit ideals are principal"),
                StatementSource.FromAuthor(DegenerateIdealsFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "Both degenerate ideals are principal in every semiring. The empty "
                        + "carrier is excluded by zero, and the singleton semiring ZMod one "
                        + "also has only principal ideals. Thus the counterexample must be a "
                        + "proper nonzero ideal outside the PID case."))),
                DescribeRole.Theorem))));

    private static Formula IdealType(Formula ring) => Call("Ideal", ring);

    private static Formula Principal(Formula ideal) => Call("IsPrincipal", ideal);

    private static Formula RecoveredNonprincipalFormula()
    {
        Formula ideal = F.Id("I");
        Formula order = F.Id("QuadraticOrder");
        Formula namedIdeal = F.Id("normTwoIdeal");
        return Disp(Seq(
            Open, Exists, Bang, Sp, ideal, Colon, Sp, IdealType(order), Comma, Sp,
            ideal, Sp, Eq, Sp, namedIdeal, Close, Sp, Land, RowBreak, Grp(),
            Call("IsPrime", namedIdeal), Sp, Land, Sp,
            Neg, Sp, Principal(namedIdeal), Dot));
    }

    private static Formula PrincipalIdealRingFormula()
    {
        Formula ring = F.Id("R");
        Formula ideal = F.Id("I");
        return Disp(Seq(
            Forall, Sp, ring, Comma, Sp,
            Call("Semiring", ring), Sp, Land, Sp,
            Call("IsPrincipalIdealRing", ring), Sp, Rightarrow, RowBreak, Grp(),
            Forall, Sp, ideal, Colon, Sp, IdealType(ring), Comma, Sp,
            Principal(ideal), Dot));
    }

    private static Formula NecessaryHypothesisFormula() => Disp(Seq(
        Neg, Sp, Call("IsPrincipalIdealRing", F.Id("QuadraticOrder")), Dot));

    private static Formula DegenerateIdealsFormula() => Disp(Seq(
        Principal(F.Id("bot")), Sp, Land, Sp, Principal(F.Id("top")), Dot));
}
