using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.ConceptDynamics.Attribution;

internal sealed class CoordinateFlagCouplingDocument : IScribeDocumentDefinition
{
    private const string Result =
        "D5/S3/ConceptDynamics/Attribution/CoordinateFlagCoupling.invariant_coupling_iff";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Boolean-profile couplings realize the same masses as a family of coordinate fixed events.",
        H("Coordinate subgroups and prescribed common masses"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("coordinate-flag-couplings"),
                DeclarationHandle.Create(Result),
                H("Exact invariant realization of two-row profile couplings"),
                StatementSource.FromAuthor(Disp(Seq(F.Id("L"), Sp, Iff, Sp, F.Id("R")))),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text("Let I be finite. Let the elementary abelian group of binary "
                        + "vectors on I act on a profile p together with a binary colour. "
                        + "The action keeps the profile and adds to the colour the sum of "
                        + "the coordinates of the acting vector where the profile is false. "
                        + "The subgroup generated by the coordinate vector at i fixes an "
                        + "output precisely when its profile is true at i.")),
                    Paragraph(Text("Take two real row weight functions on profiles and a "
                        + "real matrix w on pairs of profiles. Let R assert that w is a "
                        + "nonnegative coupling with the two given profile marginals. "
                        + "Let L assert that there is a nonnegative invariant coupling on coloured "
                        + "outputs, with each row weight divided equally between the two colours. "
                        + "Summing over both colours recovers every entry of w. "
                        + "At each coordinate its fixed-pair mass equals the mass of "
                        + "pairs in w where both profiles are true at that coordinate.")),
                    Paragraph(Text("From a coloured coupling, sum over both colours. From a "
                        + "profile coupling, divide each pair weight equally among its four "
                        + "colour pairs. The action preserves that equal split, and the "
                        + "subgroup tests depend only on the profiles, so the two constructions "
                        + "preserve the marginals and all the specified masses."))),
                DescribeRole.Theorem))));
}
