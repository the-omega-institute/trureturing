using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.ConceptDynamics.DagSemantics;

internal sealed class PrerequisiteClosureDocument : IScribeDocumentDefinition
{
    private const string Prefix =
        "D5/S3/ConceptDynamics/DagSemantics/PrerequisiteClosure.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Reachability generates the least predecessor-closed set containing a target set.",
        H("Prerequisite Closure"),
        Blocks(Describe.Lean(
            DescribeId.Create("prerequisite-closure-is-least"),
            DeclarationHandle.Create(Prefix + "prerequisiteClosure_least"),
            H("Prerequisite closure is the least closed superset"),
            StatementSource.FromAuthor(LeastFormula()),
            AssessedProvenance.FromRepo(),
            Blocks(
                Paragraph(Text(
                    "Fix target and closed sets. If the closed set contains every target and is "
                        + "closed under direct prerequisites, it contains the full prerequisite "
                        + "closure generated by reachability.")),
                Paragraph(Text(
                    "Both containment and predecessor closure are explicit antecedents. The "
                        + "conclusion is only the resulting subset relation."))),
            DescribeRole.Theorem))));

    private static Formula LeastFormula()
    {
        Formula edge = F.Id("edge");
        Formula targets = F.Id("targets");
        Formula closed = F.Id("closed");
        Formula hypotheses = Seq(
            targets, Sp, Subseteq, Sp, closed, Sp, Land, Sp,
            Call("PredecessorClosed", edge, closed));

        return Disp(Seq(
            Forall, Sp, edge, Colon, Sp,
            F.Id("V"), Sp, To, Sp, F.Id("V"), Sp, To, Sp, F.Id("Prop"), Comma, Sp,
            targets, Comma, Sp, closed, Colon, Sp, Call("Set", F.Id("V")),
            Comma, RowBreak, Grp(), Open, hypotheses, Close, Sp, Rightarrow,
            RowBreak, Grp(),
            Call("prerequisiteClosure", edge, targets), Sp, Subseteq, Sp, closed, Dot));
    }
}
