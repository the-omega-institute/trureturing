    private static Formula.BoundVariable Bound(string name, Formula domain) =>
        new(FormulaIdentifier.Create(name), domain);

    private static Formula Apply(Formula function, params Formula[] arguments)
    {
        var items = new List<Formula> { function, Open };
        for (var index = 0; index < arguments.Length; index++)
        {
            if (index > 0) items.AddRange([Comma, Sp]);
            items.Add(arguments[index]);
        }
        items.Add(Close);
        return Seq([.. items]);
    }

    private static Formula Arrow(Formula domain, Formula codomain) =>
        Seq(domain, Sp, To, Sp, codomain);

    private static Formula Typed(Formula value, Formula type) =>
        Seq(value, Colon, Sp, type);

    private static Formula Parenthesize(Formula value) => Seq(Open, value, Close);

    private static Formula Concept(Formula domain, Formula codomain) =>
        Call("Concept", domain, codomain);

    private static Formula SetOf(Formula type) => Call("Set", type);

    private static Formula Lambda(Formula binder, Formula type, Formula body) =>
        Seq(Open, Typed(binder, type), Close, Sp, Mapsto, Sp, body);

    private static Formula LambdaPair(
        Formula first,
        Formula firstType,
        Formula second,
        Formula secondType,
        Formula body) =>
        Seq(
            Open, Typed(first, firstType), Comma, Sp, Typed(second, secondType), Close,
            Sp, Mapsto, Sp, body);

    private static Formula Equal(Formula left, Formula right) =>
        Seq(left, Sp, Eq, Sp, right);

    private static Formula NotEqual(Formula left, Formula right) =>
        Seq(left, Sp, Neq, Sp, right);

    private static Formula LessThan(Formula left, Formula right) =>
        Seq(left, Sp, Lt, Sp, right);

    private static Formula LessThanOrEqual(Formula left, Formula right) =>
        Seq(left, Sp, Leq, Sp, right);

    private static Formula Member(Formula value, Formula set) =>
        Seq(value, Sp, InMacro, Sp, set);

    private static Formula NotMember(Formula value, Formula set) =>
        Seq(Neg, Open, Member(value, set), Close);

    private static Formula Subset(Formula left, Formula right) =>
        Seq(left, Sp, Subseteq, Sp, right);

    private static Formula And(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.And, right);

    private static Formula Implies(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.Implies, right);

    private static Formula Conjoin(params Formula[] clauses)
    {
        Formula result = clauses[^1];
        for (var index = clauses.Length - 2; index >= 0; index--)
        {
            result = And(clauses[index], result);
        }
        return result;
    }

    private static Formula ConstantPolicy(
        Formula evidenceType,
        Formula evidence,
        Formula action) =>
        Parenthesize(Lambda(evidence, evidenceType, action));

    private static Formula Admissible(Formula candidates, Formula actionsAfter) =>
        Call("admissiblePolicies", candidates, actionsAfter);

    private static Formula UninformedImage(
        Formula expectation,
        Formula utility,
        Formula actionsBefore) =>
        Call(
            "image",
            Call("uninformedExpectedValue", expectation, utility),
            actionsBefore);

    private static Formula InformedImage(
        Formula expectation,
        Formula observe,
        Formula world,
        Formula utility,
        Formula cost,
        Formula candidates,
        Formula actionsAfter) =>
        Call(
            "image",
            Call(
                "informedExpectedValue",
                expectation,
                observe,
                world,
                utility,
                cost),
            Admissible(candidates, actionsAfter));

    private static Formula Greatest(Formula values, Formula value) =>
        Call("IsGreatest", values, value);

    private static Formula WorldUnchanged(
        Formula evidenceType,
        Formula stateType,
        Formula world,
        string evidenceName,
        string stateName)
    {
        Formula evidence = F.Id(evidenceName);
        Formula state = F.Id(stateName);
        return new Formula.BindMany(
            FormulaQuantifier.ForAll,
            [Bound(evidenceName, evidenceType), Bound(stateName, stateType)],
            Equal(Apply(world, evidence, state), state));
    }

    private static Formula ConstantPolicies(
        Formula actionType,
        Formula evidenceType,
        Formula actionsBefore,
        Formula candidates,
        string actionName,
        string evidenceName)
    {
        Formula action = F.Id(actionName);
        return new Formula.BindMany(
            FormulaQuantifier.ForAll,
            [Bound(actionName, actionType)],
            Implies(
                Member(action, actionsBefore),
                Member(
                    ConstantPolicy(evidenceType, F.Id(evidenceName), action),
                    candidates)));
    }

    private static Formula ActionsPreserved(
        Formula evidenceType,
        Formula actionsBefore,
        Formula actionsAfter,
        string evidenceName)
    {
        Formula evidence = F.Id(evidenceName);
        return new Formula.BindMany(
            FormulaQuantifier.ForAll,
            [Bound(evidenceName, evidenceType)],
            Subset(actionsBefore, Apply(actionsAfter, evidence)));
    }

    private static Formula SimulationClause(Formula type)
    {
        Formula evidenceType = F.Id("E");
        Formula actionType = F.Id("U");
        Formula actionsBefore = F.Id("A0");
        Formula actionsAfter = F.Id("A1");
        Formula candidates = F.Id("P");
        Formula action = F.Id("u");
        Formula conditions = Conjoin(
            ConstantPolicies(
                actionType, evidenceType, actionsBefore, candidates, "u", "e"),
            ActionsPreserved(evidenceType, actionsBefore, actionsAfter, "e"));
        Formula simulation = new Formula.BindMany(
            FormulaQuantifier.ForAll,
            [Bound("u", actionType)],
            Implies(
                Member(action, actionsBefore),
                Member(
                    ConstantPolicy(evidenceType, F.Id("e"), action),
                    Admissible(candidates, actionsAfter))));

        return new Formula.BindMany(
            FormulaQuantifier.ForAll,
            [
                Bound("E", type),
                Bound("U", type),
                Bound("A0", SetOf(actionType)),
                Bound("A1", Arrow(evidenceType, SetOf(actionType))),
                Bound("P", SetOf(Arrow(evidenceType, actionType))),
            ],
            Implies(conditions, simulation));
    }

    private static Formula NonnegativeValueClause(Formula type, Formula real)
    {
        Formula stateType = F.Id("X");
        Formula evidenceType = F.Id("E");
        Formula actionType = F.Id("U");
        Formula expectation = F.Id("M");
        Formula observe = F.Id("q");
        Formula world = F.Id("T");
        Formula utility = F.Id("V");
        Formula cost = F.Id("c");
        Formula actionsBefore = F.Id("A0");
        Formula actionsAfter = F.Id("A1");
        Formula candidates = F.Id("P");
        Formula uninformed = F.Id("W0");
        Formula informed = F.Id("W1");
        Formula conditions = Conjoin(
            Equal(cost, D(0)),
            WorldUnchanged(evidenceType, stateType, world, "e", "x"),
            ConstantPolicies(
                actionType, evidenceType, actionsBefore, candidates, "u", "e"),
            ActionsPreserved(evidenceType, actionsBefore, actionsAfter, "e"));

        return new Formula.BindMany(
            FormulaQuantifier.ForAll,
            [
                Bound("X", type),
                Bound("E", type),
                Bound("U", type),
                Bound("M", Concept(Arrow(stateType, real), real)),
                Bound("q", Concept(stateType, evidenceType)),
                Bound("T", Arrow(evidenceType, Arrow(stateType, stateType))),
                Bound("V", Concept(stateType, Arrow(actionType, real))),
                Bound("c", real),
                Bound("A0", SetOf(actionType)),
                Bound("A1", Arrow(evidenceType, SetOf(actionType))),
                Bound("P", SetOf(Arrow(evidenceType, actionType))),
                Bound("W0", real),
                Bound("W1", real),
                Bound("h0", Greatest(
                    UninformedImage(expectation, utility, actionsBefore), uninformed)),
                Bound("h1", Greatest(
                    InformedImage(
                        expectation, observe, world, utility, cost, candidates, actionsAfter),
                    informed)),
            ],
            Implies(conditions, LessThanOrEqual(uninformed, informed)));
    }

    private static Formula OpportunityLossCountermodel(Formula real)
    {
        Formula unit = F.Id("Unit");
        Formula boolean = F.Id("Bool");
        Formula expectation = F.Id("M2");
        Formula observe = F.Id("q2");
        Formula world = F.Id("T2");
        Formula utility = F.Id("V2");
        Formula actionsBefore = F.Id("A20");
        Formula actionsAfter = F.Id("A21");
        Formula candidates = F.Id("P2");
        Formula uninformed = F.Id("W20");
        Formula informed = F.Id("W21");
        Formula evidence = F.Id("e2");
        Formula action = F.Id("u2");
        Formula opportunityLoss = new Formula.BindMany(
            FormulaQuantifier.Exists,
            [Bound("e2", unit), Bound("u2", boolean)],
            Conjoin(
                Member(action, actionsBefore),
                NotMember(action, Apply(actionsAfter, evidence))));

        return new Formula.BindMany(
            FormulaQuantifier.Exists,
            [
                Bound("M2", Concept(Arrow(unit, real), real)),
                Bound("q2", Concept(unit, unit)),
                Bound("T2", Arrow(unit, Arrow(unit, unit))),
                Bound("V2", Concept(unit, Arrow(boolean, real))),
                Bound("A20", SetOf(boolean)),
                Bound("A21", Arrow(unit, SetOf(boolean))),
                Bound("P2", SetOf(Arrow(unit, boolean))),
                Bound("W20", real),
                Bound("W21", real),
            ],
            Conjoin(
                WorldUnchanged(unit, unit, world, "e2", "x2"),
                ConstantPolicies(boolean, unit, actionsBefore, candidates, "u2", "e2"),
                opportunityLoss,
                Greatest(UninformedImage(expectation, utility, actionsBefore), uninformed),
                Greatest(
                    InformedImage(
                        expectation, observe, world, utility, D(0), candidates, actionsAfter),
                    informed),
                LessThan(informed, uninformed)));
    }

