    private static Formula ExposureCountermodel(Formula real)
    {
        Formula unit = F.Id("Unit");
        Formula expectation = F.Id("M5");
        Formula observe = F.Id("q5");
        Formula world = F.Id("T5");
        Formula utility = F.Id("V5");
        Formula disclosure = F.Id("d5");
        Formula penalty = F.Id("c5");
        Formula actionsBefore = F.Id("A50");
        Formula actionsAfter = F.Id("A51");
        Formula candidates = F.Id("P5");
        Formula uninformed = F.Id("W50");
        Formula exposed = F.Id("W51");
        Formula policy = F.Id("p5");
        Formula state = F.Id("x5");
        Formula observed = Apply(observe, state);
        Formula worldState = Apply(world, observed, state);
        Formula selectedAction = Apply(policy, observed);
        Formula exposedPayoff = Seq(
            Apply(utility, worldState, selectedAction),
            Sp, Minus, Sp,
            Apply(penalty, Apply(disclosure, observed)));
        Formula exposedExpectedValue = Lambda(
            policy,
            Arrow(unit, unit),
            Apply(expectation, Lambda(state, unit, exposedPayoff)));
        Formula exposedImage = Call(
            "image",
            exposedExpectedValue,
            Admissible(candidates, actionsAfter));
        Formula positiveExposure = new Formula.BindMany(
            FormulaQuantifier.Exists,
            [Bound("x5", unit)],
            LessThan(D(0), Apply(penalty, Apply(disclosure, Apply(observe, state)))));

        return new Formula.BindMany(
            FormulaQuantifier.Exists,
            [
                Bound("M5", Concept(Arrow(unit, real), real)),
                Bound("q5", Concept(unit, unit)),
                Bound("T5", Arrow(unit, Arrow(unit, unit))),
                Bound("V5", Concept(unit, Arrow(unit, real))),
                Bound("d5", Concept(unit, unit)),
                Bound("c5", Arrow(unit, real)),
                Bound("A50", SetOf(unit)),
                Bound("A51", Arrow(unit, SetOf(unit))),
                Bound("P5", SetOf(Arrow(unit, unit))),
                Bound("W50", real),
                Bound("W51", real),
            ],
            Conjoin(
                WorldUnchanged(unit, unit, world, "e5", "x5"),
                ConstantPolicies(unit, unit, actionsBefore, candidates, "u5", "e5"),
                ActionsPreserved(unit, actionsBefore, actionsAfter, "e5"),
                positiveExposure,
                Greatest(UninformedImage(expectation, utility, actionsBefore), uninformed),
                Greatest(exposedImage, exposed),
                LessThan(exposed, uninformed)));
    }

    private static Formula ThirdPartyResponseCountermodel(Formula real)
    {
        Formula unit = F.Id("Unit");
        Formula boolean = F.Id("Bool");
        Formula expectation = F.Id("M6");
        Formula observe = F.Id("q6");
        Formula world = F.Id("T6");
        Formula response = F.Id("R6");
        Formula utility = F.Id("V6");
        Formula actionsBefore = F.Id("A60");
        Formula actionsAfter = F.Id("A61");
        Formula candidates = F.Id("P6");
        Formula uninformed = F.Id("W60");
        Formula informed = F.Id("W61");
        Formula evidence = F.Id("e6");
        Formula state = F.Id("x6");
        Formula worldState = Apply(world, evidence, state);
        Formula responseChangesWorld = new Formula.BindMany(
            FormulaQuantifier.Exists,
            [Bound("e6", unit), Bound("x6", boolean)],
            NotEqual(Apply(response, evidence, worldState), worldState));
        Formula responseWorld = LambdaPair(
            evidence,
            unit,
            state,
            boolean,
            Apply(response, evidence, worldState));

        return new Formula.BindMany(
            FormulaQuantifier.Exists,
            [
                Bound("M6", Concept(Arrow(boolean, real), real)),
                Bound("q6", Concept(boolean, unit)),
                Bound("T6", Arrow(unit, Arrow(boolean, boolean))),
                Bound("R6", Arrow(unit, Arrow(boolean, boolean))),
                Bound("V6", Concept(boolean, Arrow(unit, real))),
                Bound("A60", SetOf(unit)),
                Bound("A61", Arrow(unit, SetOf(unit))),
                Bound("P6", SetOf(Arrow(unit, unit))),
                Bound("W60", real),
                Bound("W61", real),
            ],
            Conjoin(
                WorldUnchanged(unit, boolean, world, "e6", "x6"),
                responseChangesWorld,
                ConstantPolicies(unit, unit, actionsBefore, candidates, "u6", "e6"),
                ActionsPreserved(unit, actionsBefore, actionsAfter, "e6"),
                Greatest(UninformedImage(expectation, utility, actionsBefore), uninformed),
                Greatest(
                    InformedImage(
                        expectation,
                        observe,
                        responseWorld,
                        utility,
                        D(0),
                        candidates,
                        actionsAfter),
                    informed),
                LessThan(informed, uninformed)));
    }

    private static Formula TheoremFormula()
    {
        Formula type = Seq(Operatorname, Grp(F.Id("Type")));
        Formula real = Seq(Mathbb, Grp(F.Id("R")));
        Formula simulation = SimulationClause(type);
        Formula nonnegativeValue = NonnegativeValueClause(type, real);
        Formula opportunityLoss = OpportunityLossCountermodel(real);
        Formula positiveCost = PositiveCostCountermodel(real);
        Formula worldChange = WorldChangeCountermodel(real);
        Formula exposure = ExposureCountermodel(real);
        Formula response = ThirdPartyResponseCountermodel(real);

        return Disp(new Formula.Aligned([
            Seq(Parenthesize(simulation), Sp, Land),
            Seq(Grp(), Parenthesize(nonnegativeValue), Sp, Land),
            Seq(Grp(), Parenthesize(opportunityLoss), Sp, Land),
            Seq(Grp(), Parenthesize(positiveCost), Sp, Land),
            Seq(Grp(), Parenthesize(worldChange), Sp, Land),
            Seq(Grp(), Parenthesize(exposure), Sp, Land),
            Seq(Grp(), Parenthesize(response), Dot),
        ]));
    }
