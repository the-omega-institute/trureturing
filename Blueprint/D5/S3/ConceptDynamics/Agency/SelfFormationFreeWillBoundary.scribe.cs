using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.ConceptDynamics.Agency;

internal sealed class SelfFormationFreeWillBoundaryDocument
    : IScribeDocumentDefinition
{
    private const string DeclarationPrefix =
        "D5/S3/ConceptDynamics/Agency/SelfFormationFreeWillBoundary.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "History-sensitive identity and autonomous action need not contradict functional "
            + "determinism, while genuinely branching freedom does.",
        H("Self-Formation and the Boundary of Free Will"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("total-future-functional-iff-not-branching"),
                DeclarationHandle.Create(
                    DeclarationPrefix + "total_future_functional_iff_not_branching"),
                H("A total future is functional exactly when it does not branch"),
                StatementSource.FromAuthor(TotalFutureFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "A total future relation assigns at least one successor to every "
                            + "history. If it is generated by a transition function, each "
                            + "successor set is a singleton and no genuine branch exists.")),
                    Paragraph(Text(
                        "Conversely, totality selects a successor at each history. Absence of "
                            + "branching makes every other successor equal to the selected one, "
                            + "so the whole relation is the singleton graph of a function. "
                            + "Thus libertarian freedom understood as multiple real futures is "
                            + "incompatible with functional determinism in this model."))),
                DescribeRole.Theorem),
            Describe.Lean(
                DescribeId.Create("reductive-self-agency-iff-no-obstruction"),
                DeclarationHandle.Create(
                    DeclarationPrefix + "reductive_self_agency_iff_no_obstruction"),
                H("Self and agency are reductive exactly when no obstruction remains"),
                StatementSource.FromAuthor(ReductiveBoundaryFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "The reductive account has three clauses: identity factors through the "
                            + "current presentation, voluntariness factors through the observed "
                            + "action, and the future relation factors through one transition "
                            + "function.")),
                    Paragraph(Text(
                        "Its exact obstruction is the disjunction of three witnesses: two "
                            + "histories look the same now but have different identities; two "
                            + "histories produce the same action but differ in voluntariness; or "
                            + "one history has two distinct possible futures. The theorem proves "
                            + "that the reductive account holds exactly when none occurs.")),
                    Paragraph(Text(
                        "The first obstruction formalizes a history-constituted self: current "
                            + "presentation alone does not recover identity. It does not assert "
                            + "that any biological or phenomenological self satisfies the model."))),
                DescribeRole.Theorem),
            Describe.Lean(
                DescribeId.Create(
                    "history-sensitive-self-and-deterministic-autonomy-coexist"),
                DeclarationHandle.Create(
                    DeclarationPrefix
                        + "history_sensitive_self_and_deterministic_autonomy_coexist"),
                H("History-sensitive self and deterministic autonomy coexist"),
                StatementSource.FromAuthor(CoexistenceFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "A concrete Boolean history model has a constant current presentation "
                            + "but identity equal to the full history. Hence two histories can "
                            + "look identical now while retaining different identities, and "
                            + "identity cannot be reduced to current presentation.")),
                    Paragraph(Text(
                        "Its transition process ignores the external input, so it is autonomous, "
                            + "yet each history has exactly its identity successor, so it is also "
                            + "functionally deterministic. This is a consistency witness for a "
                            + "compatibilist notion of freedom, not evidence that human action is "
                            + "in fact deterministic or free."))),
                DescribeRole.Theorem))));

    private static Formula TypeUniverse() =>
        Seq(Operatorname, Grp(F.Id("Type")));

    private static Formula Arrow(Formula domain, Formula codomain) =>
        new Formula.TypeArrow(domain, codomain);

    private static Formula Apply(Formula function, params Formula[] arguments) =>
        new Formula.Apply(function, [.. arguments]);

    private static Formula And(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.And, right);

    private static Formula Implies(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.Implies, right);

    private static Formula.BoundVariable Bound(string name, Formula domain) =>
        new(FormulaIdentifier.Create(name), domain);

    private static Formula TotalFuture(Formula history, Formula future)
    {
        Formula point = F.Id("h");
        return new Formula.Bind(
            FormulaQuantifier.ForAll,
            FormulaIdentifier.Create("h"),
            history,
            Call("Nonempty", Apply(future, point)));
    }

    private static Formula TotalFutureFormula()
    {
        Formula history = F.Id("History");
        Formula future = F.Id("future");
        Formula futureType = Arrow(history, Call("Set", history));
        Formula boundary = new Formula.Logic(
            Call("FunctionalFuture", future),
            FormulaLogicOperator.Iff,
            new Formula.Not(Call("BranchingFree", future)));

        return Disp(new Formula.BindMany(
            FormulaQuantifier.ForAll,
            [Bound("History", TypeUniverse()), Bound("future", futureType)],
            Implies(TotalFuture(history, future), boundary)));
    }

    private static Formula ReductiveBoundaryFormula()
    {
        Formula history = F.Id("History");
        Formula presentType = F.Id("Present");
        Formula identityType = F.Id("Identity");
        Formula actionType = F.Id("Action");
        Formula voluntarinessType = F.Id("Voluntariness");
        Formula present = F.Id("present");
        Formula identity = F.Id("identity");
        Formula action = F.Id("action");
        Formula voluntariness = F.Id("voluntariness");
        Formula future = F.Id("future");
        Formula boundary = new Formula.Logic(
            Call(
                "ReductiveSelfAgency",
                present,
                identity,
                action,
                voluntariness,
                future),
            FormulaLogicOperator.Iff,
            new Formula.Not(Call(
                "SelfAgencyObstruction",
                present,
                identity,
                action,
                voluntariness,
                future)));

        return Disp(new Formula.BindMany(
            FormulaQuantifier.ForAll,
            [
                Bound("History", TypeUniverse()),
                Bound("Present", TypeUniverse()),
                Bound("Identity", TypeUniverse()),
                Bound("Action", TypeUniverse()),
                Bound("Voluntariness", TypeUniverse()),
                Bound("inhabited", Call("Nonempty", history)),
                Bound("present", Arrow(history, presentType)),
                Bound("identity", Arrow(history, identityType)),
                Bound("action", Arrow(history, actionType)),
                Bound("voluntariness", Arrow(history, voluntarinessType)),
                Bound("future", Arrow(history, Call("Set", history))),
            ],
            Implies(TotalFuture(history, future), boundary)));
    }

    private static Formula CoexistenceFormula()
    {
        Formula boolean = F.Id("Bool");
        Formula unit = F.Id("Unit");
        Formula present = F.Id("present");
        Formula identity = F.Id("identity");
        Formula process = F.Id("process");
        Formula step = F.Id("step");
        Formula external = F.Id("external");
        Formula history = F.Id("history");
        Formula processGraph = new Formula.BindMany(
            FormulaQuantifier.ForAll,
            [Bound("external", boolean), Bound("history", boolean)],
            Equal(
                Apply(process, external, history),
                new Formula.SetLiteral([Apply(step, history)])));
        Formula statement = And(
            Call("MoralLuckWitness", present, identity),
            And(
                new Formula.Not(Call("ControlPrinciple", present, identity)),
                And(Call("AutonomousFree", process), processGraph)));

        return Disp(new Formula.BindMany(
            FormulaQuantifier.Exists,
            [
                Bound("present", Arrow(boolean, unit)),
                Bound("identity", Arrow(boolean, boolean)),
                Bound("process", Arrow(boolean, Arrow(boolean, Call("Set", boolean)))),
                Bound("step", Arrow(boolean, boolean)),
            ],
            statement));
    }
}
