using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.ConceptDynamics.DependencyTopology;

internal sealed class FiniteSupportPatternRealizationDocument : IScribeDocumentDefinition
{
    private const string Prefix =
        "D5/S3/ConceptDynamics/DependencyTopology/FiniteSupportPatternRealization.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Every accessible finite family closed under union has an exact decidable propositional proof kernel.",
        H("Finite support patterns"),
        Blocks(
            Paragraph(Text(
                "Fix a finite enumerated carrier, represented by Fin n. A family F of its subsets "
                + "contains the empty set, is closed under binary union, and allows deletion of "
                + "one point from every nonempty member while remaining in F. Elements of the "
                + "carrier need not occur in any member. There is no positivity assumption on n.")),
            Definition("Formula", "Propositional syntax", F.Id("Formula"),
                "Formulas are finite syntax trees generated by natural-number variables, falsity "
                + "and implication. This is a countable type with decidable syntactic equality. "
                + "Negation is implication into falsity. A valuation assigns a Boolean to every "
                + "natural-number variable, and evaluation uses the ordinary truth tables. "
                + "Syntactic equality does not identify logically equivalent formulas."),
            Definition("e", "Distinct tautologies", Call("e", F.Id("x")),
                "The formula assigned to x is the implication from its indexed variable to itself. "
                + "The assignment is injective because the variables retain their indices. "
                + "Each assigned formula is true under every valuation."),
            Definition("kernel", "The pattern kernel", Call("kernel", F.Id("F")),
                "A legal proof symbol consists of a pair (S,x) with S in F, x outside S, "
                + "and S with x inserted in F. Its unique accepted conclusion is e(x), and its "
                + "references are precisely the image of S under e. There is exactly one additional "
                + "dummy proof symbol; it accepts no formula and has no references. Every axiom "
                + "readout and the permitted axiom set are empty. The proof alphabet is finite, "
                + "and acceptance and both readouts are executable functions of the finite table "
                + "and formula syntax. When n is zero only the dummy symbol remains."),
            Describe.Lean(
                DescribeId.Create("finite-support-pattern-realization"),
                DeclarationHandle.Create(Prefix + "finite_support_pattern_realization"),
                H("Exact support realization"),
                StatementSource.FromAuthor(Disp(Seq(
                    Forall, Sp, F.Id("n"), Comma, Sp, F.Id("F"), Comma, Sp,
                    Call("Pattern", F.Id("F")), Sp, Implies, Sp,
                    Call("SourceLaws", Call("kernel", F.Id("F"))), Sp, Land, Sp,
                    Call("supportFamily", Call("kernel", F.Id("F"))), Sp, Eq, Sp,
                    OpenBrace, Call("eImage", F.Id("A")), Sp, Mid, Sp,
                    F.Id("A"), Sp, InMacro, Sp, F.Id("F"), CloseBrace))),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "Here eImage(A) is the set of formulas e(x) for x in A. The support family "
                    + "is existential over actual CertifiedNodes: a finite set of formulas with "
                    + "one accepted proof per formula, closed under the references of those selected "
                    + "proofs, and with an acyclic selected reference relation. SourceLaws comprises "
                    + "soundness in all models of the permitted axioms, existence of such a certificate "
                    + "for every provable formula, and consistency with syntactic negation.")),
                    Paragraph(Text(
                    "For the forward inclusion, induct on a feasible set A. The empty set has an "
                    + "empty selection. For a nonempty A, choose a point x whose deletion B is feasible. "
                    + "Keep the selected proofs and ranks on B and select the legal symbol (B,x) at "
                    + "the new node e(x). Give the new node rank equal to the cardinality of B. "
                    + "The inductive ranks are strictly smaller, so every actual selected edge "
                    + "strictly increases rank. StrictDependencyCoordinate.acyclic_of_strictCoordinate "
                    + "then gives acyclicity. The same construction applied to S with x inserted "
                    + "supplies a certificate containing any accepted conclusion. It may choose "
                    + "a different proof at that conclusion.")),
                    Paragraph(Text(
                    "For the reverse inclusion, every node of an actual certificate is e(x) for "
                    + "a unique carrier point. Let A be the finite preimage of its nodes. The chosen "
                    + "proof at e(x) is a legal pair (S,x). Reference closure and injectivity give "
                    + "S contained in A. Each set S with x inserted belongs to F, is contained in A, "
                    + "and contains x. Their finite union is A. Finset.sup_mem, using the empty "
                    + "member and binary union closure, therefore puts A in F.")),
                    Paragraph(Text(
                    "Soundness follows because every accepted formula is a tautology. Consistency "
                    + "follows from ordinary negation at the all-false valuation, which is an actual "
                    + "model of the empty axiom set. Different supports may use different proof "
                    + "selections and ranks; no common acyclic graph is asserted. The conclusion "
                    + "concerns this explicitly defined mathematical kernel."))),
                DescribeRole.Theorem))));

    private static DocumentBlock Definition(string selector, string title, Formula formula,
        string prose) => Describe.Lean(
            DescribeId.Create("finite-pattern-" + selector.ToLowerInvariant()),
            DeclarationHandle.Create(Prefix + selector), H(title),
            StatementSource.FromAuthor(Disp(formula)), AssessedProvenance.FromRepo(),
            Blocks(Paragraph(Text(prose))), DescribeRole.Definition);
}
