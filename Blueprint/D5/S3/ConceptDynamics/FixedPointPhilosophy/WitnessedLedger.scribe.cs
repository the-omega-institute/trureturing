using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.ConceptDynamics.FixedPointPhilosophy;

internal sealed class WitnessedLedgerDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S3/ConceptDynamics/FixedPointPhilosophy/WitnessedLedger.";
    private static Formula S => F.Id("s");
    private static Formula B => F.Id("B");
    private static Formula L => F.Id("L");
    private static Formula C => F.Id("C");
    private static Formula P => F.Id("p");
    private static Formula N(Formula core) => Call("N", core);
    private static Formula Core(Formula ledger) => Call("core", ledger);
    private static Formula Ancestors(Formula core, Formula p) => Call("Anc", core, p);
    private static Formula Primes(Formula core) => Call("Prime", B, core);

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Finite accepted witness ledgers are generated by their ancestor primes.",
        H("Witnessed Ledgers and Prime Generation"),
        Blocks(
            Describe.Remark(
                DescribeId.Create("kernel-and-witnesses"),
                DeclarationHandle.Create(Prefix + "ProofSystem"),
                H("Kernel, witnesses, and provability"), AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "A proof system consists of a proposition type P, a proof type, an axiom type, "
                    + "a Boolean kernel K, finite axiom and direct-reference readouts ax and refs, "
                    + "and a permitted axiom set A. A proposition belongs to Thm exactly when some "
                    + "proof is accepted by K and every axiom read from it belongs to A. "
                    + "This definition makes no assertion about semantic truth or consistency.")))),
            Describe.Remark(
                DescribeId.Create("cores-and-snapshots"),
                DeclarationHandle.Create(Prefix + "LegalLedger"),
                H("Frozen cores and finite snapshots"), AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "A witnessed core consists of a frozen set N and a selected proof w(p) for each "
                    + "member p. Each selected proof is accepted and permitted, and all its direct "
                    + "references lie in N. The edge a to b means that a occurs in refs(w(b)); "
                    + "this derived relation must be acyclic. Both endpoints therefore belong to N. "
                    + "A presentation also has a registered frontier O disjoint from N, equivalently "
                    + "contained in the complement of N. A legal snapshot requires N to be finite; "
                    + "neither O nor the ambient proposition type is required to be finite.")))),
            Theorem("not-own-ancestor", "not_own_ancestor", "Ancestry is proper",
                QuantifyCore(Seq(Forall, Sp, P, Colon, Sp, Call("P", S), Comma, Sp,
                    Neg, Open, P, Sp, InMacro, Sp, Ancestors(C, P), Close)),
                "Anc(C,p) consists of vertices joined to p by a nonempty directed path. "
                + "Acyclicity excludes p itself. Reference closure also puts every ancestor in N(C)."),
            Describe.Lean(
                DescribeId.Create("ancestor-primes"), DeclarationHandle.Create(Prefix + "Prime"),
                H("Primes relative to a closure operator"),
                StatementSource.FromAuthor(QuantifyClosureCore(Seq(
                    P, Sp, InMacro, Sp, Primes(C), Sp, Iff, Sp,
                    P, Sp, InMacro, Sp, N(C), Sp, Land, Sp,
                    Neg, Open, P, Sp, InMacro, Sp, Call("B", Ancestors(C, P)), Close))),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "The displayed equivalence holds for every proposition p. B is an arbitrary "
                    + "closure operator on sets of propositions: it is extensive, monotone, and "
                    + "idempotent. Reading B as the operations of instantiation, projection, "
                    + "discharging assumptions, and normalization is an interpretation; the "
                    + "mathematics uses exactly the three closure laws. Primality depends on "
                    + "the selected witness graph, through its proper ancestor sets."))),
                DescribeRole.Definition),
            Theorem("finite-ancestry-well-founded", "node_ancestors_wellFounded",
                "Finite ancestry is well founded",
                QuantifyLedger(Seq(Call("WellFounded", Seq(
                    F.Id("a"), Comma, Sp, F.Id("b"), Colon, Sp, N(L), Sp, Mapsto, Sp,
                    F.Id("a"), Sp, InMacro, Sp, Ancestors(Core(L), F.Id("b")))))),
                "On the subtype of frozen nodes, proper ancestry is transitive and irreflexive. "
                + "Finiteness of the snapshot therefore makes this relation well founded. "
                + "No depth or rank function is assumed."),
            Theorem("finite-prime-generation", "frozen_subset_bind_prime",
                "Every frozen node lies in the closure of the primes",
                Disp(Seq(Forall, Sp, S, Colon, Sp, F.Id("ProofSystem"), Comma, Sp,
                    B, Colon, Sp, ClosureType(), Comma, Sp,
                    L, Colon, Sp, Call("LegalLedger", S), Comma, RowBreak, Grp(),
                    N(L), Sp, Subseteq, Sp, Call("B", Primes(Core(L))))),
                "Suppose a frozen node lies outside B(Prime(B,core(L))). The nonempty set of such "
                + "nodes has a minimal member q in the well-founded ancestor relation. Every proper "
                + "ancestor of q then lies in B(Prime(B,core(L))). If q is prime, extensivity is a "
                + "contradiction. Otherwise q lies in B(Anc(core(L),q)); monotonicity followed by "
                + "idempotence again puts it in B(Prime(B,core(L))). This includes the empty snapshot."),
            Theorem("source-core-extension", "coreExtends_iff_source",
                "Witness preservation also preserves edges", ExtensionFormula(),
                "CoreExtends(C,D) means N(C) is contained in N(D) and D retains the selected "
                + "witness of every old node. Since edges are read from those witnesses, this is "
                + "equivalent to the full conjunction of node, edge, and witness preservation. "
                + "The restriction notation in the formula transports along the displayed inclusion. "
                + "Mutual extension implies equality of cores; it imposes no equality on frontiers."),
            Theorem("frontier-choice-independent", "frontier_independent",
                "Disjoint frontier choices leave the core unchanged", FrontierFormula(),
                "For any witnessed core C and any O disjoint from N(C), withFrontier(C,O) is a "
                + "presentation of exactly C. Its ancestors and primes are therefore unchanged. "
                + "The empty frontier is always available. This statement does not concern "
                + "convergence of a sequence of registered frontiers."))));

    private static DocumentBlock Theorem(string id, string name, string title,
        Formula formula, string proof) => Describe.Lean(
            DescribeId.Create(id), DeclarationHandle.Create(Prefix + name), H(title),
            StatementSource.FromAuthor(formula), AssessedProvenance.FromRepo(),
            Blocks(Paragraph(Text(proof))), DescribeRole.Theorem);

    private static Formula ClosureType() => Call("ClosureOperator", Call("Set", Call("P", S)));

    private static Formula QuantifyCore(Formula body) => Disp(Seq(
        Forall, Sp, S, Colon, Sp, F.Id("ProofSystem"), Comma, Sp,
        C, Colon, Sp, Call("WitnessedCore", S), Comma, RowBreak, Grp(), body));

    private static Formula QuantifyClosureCore(Formula body) => QuantifyCore(Seq(
        Forall, Sp, B, Colon, Sp, ClosureType(), Comma, Sp,
        P, Colon, Sp, Call("P", S), Comma, RowBreak, Grp(), body));

    private static Formula QuantifyLedger(Formula body) => Disp(Seq(
        Forall, Sp, S, Colon, Sp, F.Id("ProofSystem"), Comma, Sp,
        L, Colon, Sp, Call("LegalLedger", S), Comma, RowBreak, Grp(), body));

    private static Formula ExtensionFormula()
    {
        Formula other = F.Id("D");
        return QuantifyCore(Seq(Forall, Sp, other, Colon, Sp, Call("WitnessedCore", S), Comma,
            RowBreak, Grp(), Call("CoreExtends", C, other), Sp, Iff, Sp,
            N(C), Sp, Subseteq, Sp, N(other), Sp, Land, Sp,
            Call("E", C), Sp, Subseteq, Sp, Call("E", other), Sp, Land, Sp,
            Call("restrict", Call("w", other), N(C)), Sp, Eq, Sp, Call("w", C)));
    }

    private static Formula FrontierFormula()
    {
        Formula frontier = F.Id("O");
        Formula presented = Core(Call("withFrontier", C, frontier));
        return QuantifyCore(Seq(Forall, Sp, B, Colon, Sp, ClosureType(), Comma, Sp,
            frontier, Colon, Sp, Call("Set", Call("P", S)), Comma, Sp,
            Call("Disjoint", N(C), frontier), Sp, Rightarrow, RowBreak, Grp(),
            presented, Sp, Eq, Sp, C, Sp, Land, Sp,
            Call("Anc", presented), Sp, Eq, Sp, Call("Anc", C), Sp, Land, Sp,
            Primes(presented), Sp, Eq, Sp, Primes(C)));
    }
}
