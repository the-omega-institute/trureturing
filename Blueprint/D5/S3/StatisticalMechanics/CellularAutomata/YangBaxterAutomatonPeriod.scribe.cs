    private static DocumentBlock Node(
        string id, string title, Formula formula, string prose,
        string declaration, DescribeRole role, AssessedProvenance provenance,
        OpenProblemResolutionClaim? resolution = null) =>
        Describe.Lean(
            DescribeId.Create("ybautomaton-" + id), DeclarationHandle.Create(Prefix + declaration),
            H(title), StatementSource.FromAuthor(formula), provenance,
            Blocks(Paragraph(Text(prose))), role, resolution);

    private static Formula Named(Formula name) => Seq(Operatorname, Grp(name));
    private static Formula Call(Formula name, params Formula[] arguments) =>
        new Formula.Apply(Named(name), [.. arguments]);
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula Rel(Formula left, FormulaRelationOperator op, Formula right) =>
        new Formula.Relation(left, op, right);
    private static Formula Equal(Formula left, Formula right) =>
        Rel(left, FormulaRelationOperator.Equal, right);
    private static Formula Iff(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.Iff, Parenthesized(right));
    private static Formula Implies(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Implies, right);
    private static Formula All(string variable, Formula domain, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(variable), domain, body);
    private static Formula Add(Formula left, Formula right) =>
        new Formula.Binary(left, FormulaBinaryOperator.Add, right);
    private static Formula Sub(Formula left, Formula right) =>
        new Formula.Binary(left, FormulaBinaryOperator.Subtract, right);
    private static Formula Nats() => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula Apply1(Formula fn, Formula arg) => new Formula.Apply(fn, [arg]);
    private static Formula Pair(Formula left, Formula right) => Seq(Open, left, Comma, Sp, right, Close);

    private static Formula RmatFormula()
    {
        Formula f = F.Id("f"), x = F.Id("x"), y = F.Id("y");
        Formula fxy = Apply1(f, Add(x, y));
        return Disp(Equal(Call(F.Id("rmat"), f, x, y), Pair(Add(y, fxy), Sub(x, fxy))));
    }

    private static Formula CarryFormula()
    {
        Formula f = F.Id("f"), x = F.Id("x"), b = F.Id("b"), i = F.Id("i");
        Formula carryI = Call(F.Id("carry"), f, x, b, i);
        Formula next = Call(F.Id("carry"), f, x, b, Add(i, D(1)));
        Formula xi = new Formula.Subscript(F.Id("x"), F.Id("i"));
        return Disp(Seq(
            Equal(Call(F.Id("carry"), f, x, b, D(0)), b), Comma, Qquad,
            Equal(next, Call(F.Id("snd"), Call(F.Id("rmat"), f, xi, carryI))), Sp,
            Parenthesized(Seq(F.Id("i"), Sp, Lt, Sp, F.Id("N")))));
    }

    private static Formula StepFormula()
    {
        Formula f = F.Id("f"), x = F.Id("x"), b = F.Id("b"), i = F.Id("i"), n = F.Id("N");
        Formula xi = new Formula.Subscript(F.Id("x"), F.Id("i"));
        Formula cell = Call(F.Id("fst"), Call(F.Id("rmat"), f, xi, Call(F.Id("carry"), f, x, b, i)));
        Formula cells = Seq(Parenthesized(cell), Underscore, Grp(i, Sp, Lt, Sp, n));
        return Disp(Equal(Call(F.Id("step"), f, Pair(x, b)), Pair(cells, Call(F.Id("carry"), f, x, b, n))));
    }

    private static Formula ClaimFormula()
    {
        Formula field = F.Id("F"), f = F.Id("f"), x = F.Id("x"), y = F.Id("y");
        Formula fyb = All("x", field, All("y", field, Equal(
            Add(Apply1(f, x), Apply1(f, Add(x, Apply1(f, y)))),
            Apply1(f, Add(x, Apply1(f, Add(y, Apply1(f, x))))))));
        Formula charTwo = Equal(Call(F.Id("char"), field), D(2));
        Formula bij = Call(F.Id("Bijective"), f);
        Formula stateSpace = Seq(new Formula.Power(field, F.Id("N")), Sp, F.Times, Sp, field);
        Formula period = Equal(
            Seq(Call(F.Id("step"), f), Caret, Grp(new Formula.Absolute(field))),
            new Formula.Subscript(Named(F.Id("id")), stateSpace));
        Formula body = All("F", Named(F.Id("FiniteField")),
            Implies(charTwo, All("f", Seq(field, Sp, To, Sp, field),
                Implies(bij, Implies(fyb, All("N", Nats(), period))))));
        return Disp(Iff(F.Id("claim"), body));
    }
}
