    private static DocumentBlock Node(
        string id, string title, Formula formula, string prose,
        string declaration, DescribeRole role, AssessedProvenance provenance,
        OpenProblemResolutionClaim? resolution = null) =>
        Describe.Lean(
            DescribeId.Create("lazyca-" + id), DeclarationHandle.Create(Prefix + declaration),
            H(title), StatementSource.FromAuthor(formula), provenance,
            Blocks(Paragraph(Text(prose))), role, resolution);

    private static Formula Named(Formula name) => Seq(Operatorname, Grp(name));
    private static Formula Call(Formula name, params Formula[] arguments) =>
        new Formula.Apply(Named(name), [.. arguments]);
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula Rel(Formula left, FormulaRelationOperator op, Formula right) =>
        new Formula.Relation(left, op, right);
    private static Formula Equal(Formula left, Formula right) =>
        Rel(left, FormulaRelationOperator.Equal, right);
    private static Formula Member(Formula left, Formula right) =>
        Rel(left, FormulaRelationOperator.MemberOf, right);
    private static Formula Iff(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.Iff, Parenthesized(right));
    private static Formula Implies(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Implies, right);
    private static Formula And(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.And, Parenthesized(right));
    private static Formula AllOf(Formula variables, Formula body) =>
        Seq(Forall, Sp, variables, Comma, Sp, body);
    private static Formula SomeOf(Formula variables, Formula body) =>
        Seq(Exists, Sp, variables, Comma, Sp, body);
    private static Formula Power(Formula b, Formula e) => new Formula.Power(b, e);
    private static Formula Configurations() => Power(F.Id("A"), F.Id("G"));
    private static Formula Patterns() => Power(F.Id("A"), F.Id("S"));

    private static Formula LocalRule()
    {
        Formula x = F.Id("x"), g = F.Id("g");
        Formula shifted = new Formula.Apply(F.Id("x"),
            [new Formula.Binary(F.Id("s"), FormulaBinaryOperator.Multiply, g)]);
        return AllOf(Seq(x, Sp, InMacro, Sp, Configurations(), Comma, Sp, g, Sp, InMacro, Sp, F.Id("G")),
            Equal(new Formula.Apply(new Formula.Apply(F.Id("T"), [x]), [g]),
                new Formula.Apply(F.Id("mu"), [Seq(F.Id("s"), Sp, Mapsto, Sp, shifted)])));
    }

    private static Formula CaFormula() =>
        Disp(Iff(Call(F.Id("IsCA"), F.Id("T")),
            SomeOf(Seq(Member(F.Id("S"), Call(F.Id("Finset"), F.Id("G"))), Comma, Sp,
                    F.Id("mu"), Colon, Patterns(), To, Sp, F.Id("A")),
                LocalRule())));

    private static Formula LazyFormula()
    {
        Formula z = F.Id("z"), e = F.Id("e");
        Formula active = AllOf(Seq(z, Sp, InMacro, Sp, Patterns()),
            new Formula.Logic(Equal(new Formula.Apply(F.Id("mu"), [z]), new Formula.Apply(z, [e])),
                FormulaLogicOperator.Iff,
                Rel(z, FormulaRelationOperator.NotEqual, F.Id("p"))));
        return Disp(Iff(Call(F.Id("IsLazy"), F.Id("T")),
            SomeOf(Seq(Member(F.Id("S"), Call(F.Id("Finset"), F.Id("G"))), Comma, Sp,
                    Member(e, F.Id("S")), Comma, Sp, F.Id("mu"), Colon, Patterns(), To, Sp, F.Id("A"), Comma, Sp,
                    Member(F.Id("p"), Patterns())),
                And(active, LocalRule()))));
    }

    private static Formula InvertibleFormula()
    {
        Formula t = F.Id("T"), t2 = Seq(F.Id("T"), Apos);
        return Disp(Iff(Call(F.Id("IsInvertibleCA"), t),
            And(Call(F.Id("IsCA"), t),
                SomeOf(t2, And(Call(F.Id("IsCA"), t2),
                    And(Equal(new Formula.Binary(t2, FormulaBinaryOperator.Multiply, t), D(1)),
                        Equal(new Formula.Binary(t, FormulaBinaryOperator.Multiply, t2), D(1))))))));
    }

    private static Formula ClaimFormula()
    {
        Formula u = F.Id("U");
        Formula generators = Seq(
            OpenBrace, u, Sp, Colon, Sp, Call(F.Id("IsInvertibleCA"), u), CloseBrace, Sp, Cup, Sp,
            OpenBrace, u, Sp, Colon, Sp, Call(F.Id("IsLazy"), u), CloseBrace);
        Formula closure = Seq(Langle, Sp, generators, Rangle);
        return Disp(Iff(F.Id("claim"),
            AllOf(Seq(F.Id("G"), Comma, Sp, F.Id("A")),
                Implies(And(And(Call(F.Id("Group"), F.Id("G")), Call(F.Id("Finite"), F.Id("A"))),
                        Rel(new Formula.Absolute(F.Id("A")), FormulaRelationOperator.GreaterThanOrEqual, D(2))),
                    AllOf(Seq(F.Id("T"), Colon, Configurations(), To, Sp, Configurations()),
                        Implies(Call(F.Id("IsCA"), F.Id("T")), Member(F.Id("T"), closure)))))));
    }
}
