                "claim", DescribeRole.Definition, AssessedProvenance.FromLiterature(Source)),
            Node("result", "A cellular automaton that is not generated", Disp(new Formula.Not(F.Id("claim"))),
                "Let G be the Klein four-group and A = {0, 1}, let w(x) be the number of cells of x equal to 1, and let F complement x when w(x) = 1 and fix x otherwise; F is a cellular automaton with neighborhood G because w is invariant under the shifts. Every cellular automaton commutes with the shifts. In the Klein four-group every configuration of even weight is fixed by a shift by some k different from e, since a support {u, v} is fixed by k = u^(-1) v, and every configuration fixed by such a shift has even weight, being a union of cosets of {e, k}; hence a cellular automaton sends even weight to even weight, and it sends the two constant configurations to constant configurations. A lazy automaton whose pattern p is constant equal to b sends both constant configurations to the constant 1 - b. If p is not constant, it has a cell s with p(s) = 1, and in a configuration with a single cell u equal to 1 the pattern can occur only at the position s^(-1) u; with a cell where p is 0 the same holds for weight three, so on a configuration of odd weight the lazy automaton changes at most one cell, and its image is either the configuration itself or of even weight. Consider the property of a cellular automaton T: if T separates the two constant configurations, then T is injective on the configurations of odd weight whose image has odd weight. Invertible automata have it because they are injective, lazy automata have it by the previous step, and it is preserved under composition: a composition that separates the constants has a first factor that permutes the two constants and a second factor that separates them, and a configuration whose final image has odd weight has odd weight at every intermediate stage. So every element of the generated submonoid has the property. But F separates the constants and sends both the configuration with the single 1 at e and its complement, of weight three, to that complement.",
