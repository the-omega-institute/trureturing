        LibraryNoteRef.Create("D5/L/StatisticalMechanics/alcalaarroyo2025lazy");

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Over the Klein four-group with the binary alphabet, the cellular automaton that complements the configurations with exactly one cell equal to 1 and fixes all others is not a finite composition of invertible and lazy cellular automata. This answers Problem 2 of E. Alcala-Arroyo and A. Castillo-Ramirez (arXiv:2510.14841) negatively: the invertible and the lazy cellular automata do not generate the monoid of all cellular automata.",
        H("Lazy and invertible cellular automata do not generate all cellular automata"),
