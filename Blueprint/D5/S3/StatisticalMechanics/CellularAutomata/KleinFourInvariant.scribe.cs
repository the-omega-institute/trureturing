    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "The binary Klein-four shift has two fixed configurations, three two-point orbits, and two free orbits. The free orbits consist of weight-one and weight-three configurations. An equivariant map satisfies Criterion when a common free image of these two orbits forces both constants and one two-point orbit to share one constant image. The structural argument is adapted from the MIT-licensed public supplementary formalization by E. Alcala-Arroyo, A. Castillo-Ramirez, H. Ma and W. Zhang, version v1.1.0, DOI 10.5281/zenodo.23280244.",
