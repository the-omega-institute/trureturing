                AssessedProvenance.FromLiterature(Source),
                Blocks(Paragraph(Text("Here M is the submonoid generated by every bijective equivariant map and every binary lazy map, on any neighborhood containing the identity. Units cannot merge the two free orbits. Every lawful lazy map satisfies the criterion, and the identity does too. Closure under composition therefore gives the assertion, including the empty word."))),
                DescribeRole.Theorem)), []));

