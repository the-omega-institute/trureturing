                    Call("Criterion", F.Id("A")), Sp, Land, Sp, Call("Criterion", F.Id("B")),
                    Sp, Implies, Sp, Call("Criterion", Seq(F.Id("A"), F.Id("B")))))),
                AssessedProvenance.FromLiterature(Source),
                Blocks(Paragraph(Text("Suppose the composite A B maps both free orbits onto one free orbit. A nonfree configuration cannot acquire a free image under an equivariant map. Thus both intermediate images are free. If they lie in the same free orbit, B has a merger witness, and postcomposition by A preserves it. If they lie in different free orbits, A has a merger witness; precomposition by B preserves it because constant and two-point strata cannot leave their stabilizer classes. Composition acts right-to-left."))),
