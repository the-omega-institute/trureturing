using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Combinatorics.BinomialBases;

internal sealed class ShiftedBinomialPowerLinearizationDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S3/Combinatorics/BinomialBases/ShiftedBinomialPowerLinearization.";
    private static readonly LibraryNoteRef Source =
        LibraryNoteRef.Create("D5/L/Combinatorics/thanatipanonda2014zudilin");

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Every positive power of choose(n+dk,k) has an integral expansion in choose(n+dj,j), with coefficients generated by one integer recursion independent of the power index.",
        H("Thanatipanonda's shifted binomial power linearization"),
        Blocks(
            Node("B", "The shifted binomial family", BFormula(),
                "The argument and the shift parameters are natural numbers. The binomial coefficient is computed in Nat and then cast to Int; the power and the expansion are evaluated in Int.",
                DescribeRole.Definition, AssessedProvenance.FromLiterature(Source)),
            Node("a", "The coefficient recursion", AFormula(),
                "The initial coefficients are the Kronecker delta at k. For positive powers the next row is obtained using T(j,i), which has no power index. The unused row at power zero is defined to be zero. All sums use Finset.range(m) = {0,...,m-1}.",
                DescribeRole.Definition, AssessedProvenance.FromLiterature(Source)),
            Node("claim", "Conjecture 4.1 with finite support", ClaimFormula(true),
                "The encoding uses d,k,n,j,i,r in Nat and T(j,i) in Int for S_d(k,j,i), with d and k fixed before T is chosen. The coefficients are a(k,T,r,j). The support clauses justify replacing the source sums by ranges ending at rk and i+k. Both sentences are included; no positivity of the integer coefficients is asserted.",
                DescribeRole.Definition, AssessedProvenance.FromLiterature(Source)),
            Node("result", "Integral linearization for every nonnegative shift", ClaimFormula(false),
                "Vandermonde's identity expresses each B(d,t,n) as an integer combination of choose(n,v), with diagonal coefficient one. Strong induction constructs an integral triangular inverse. The binomial product identity and this inverse give integer structure constants for B(d,k,n) times B(d,i,n), supported at j≤i+k. Induction on the positive power then gives the fixed recursion and the bound j≤rk. Conjecture 4.2 on holonomicity is a separate question.",
                DescribeRole.Theorem, AssessedProvenance.FromRepo(Source),
                new OpenProblemResolutionClaim(
                    ProblemSlugRef.Create("thanatipanonda-2014-shifted-binomial-power-linearization"),
                    ResolutionKind.Proved))), []));

    private static DocumentBlock Node(string name, string title, Formula formula, string prose,
        DescribeRole role, AssessedProvenance provenance, OpenProblemResolutionClaim? resolution = null) =>
        Describe.Lean(DescribeId.Create("shifted-binomial-" + name.ToLowerInvariant()),
            DeclarationHandle.Create(Prefix + name), H(title),
            StatementSource.FromAuthor(formula), provenance,
            name == "claim" ? Blocks(SourceQuotation(), Paragraph(Text(prose)))
                : Blocks(Paragraph(Text(prose))), role, openProblemResolutionClaim: resolution);

    private static Formula Naturals() => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula Integers() => Seq(Mathbb, Grp(F.Id("Z")));
    private static Formula Coefficients() =>
        new Formula.TypeArrow(Naturals(), new Formula.TypeArrow(Naturals(), Integers()));
    private static Formula Call(string name, params Formula[] arguments) =>
        new Formula.FunctionCall(FormulaIdentifier.Create(name), [.. arguments]);
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula All(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), type, body);
    private static Formula ExistsIn(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create(name), type, body);
    private static Formula Equal(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.Equal, right);
    private static Formula Less(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.LessThan, right);
    private static Formula AtMost(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.LessThanOrEqual, right);
    private static Formula Add(Formula left, Formula right) =>
        new Formula.Binary(left, FormulaBinaryOperator.Add, right);
    private static Formula Times(Formula left, Formula right) =>
        new Formula.Binary(left, FormulaBinaryOperator.Multiply, right);
    private static Formula And(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.And, Parenthesized(right));
    private static Formula Implies(Formula left, Formula right) =>
        new Formula.Logic(Parenthesized(left), FormulaLogicOperator.Implies, Parenthesized(right));
    private static Formula SumRange(Formula index, Formula bound, Formula body) =>
        Seq(Sum, Underscore, Grp(index, Sp, InMacro, Sp, Call("range", bound)), Sp,
            Parenthesized(body));

    private static Formula SourceChoose(Formula top, Formula bottom) =>
        Parenthesized(Seq(Begin, Grp(F.Id("matrix")), top, RowBreak, bottom,
            End, Grp(F.Id("matrix"))));
    private static Formula SourceCoefficient(Formula power, Formula index) =>
        Seq(F.Id("a"), Caret, Grp(Parenthesized(power)), Underscore,
            Grp(F.Id("d"), Comma, F.Id("k"), Comma, index));
    private static Formula SourceStructureConstant() =>
        Seq(F.Id("S"), Underscore, Grp(F.Id("d")),
            Parenthesized(Seq(F.Id("k"), Comma, Sp, F.Id("j"), Comma, Sp, F.Id("i"))));
    private static DocumentBlock SourceQuotation()
    {
        Formula d = F.Id("d"), k = F.Id("k"), j = F.Id("j"),
            i = F.Id("i"), n = F.Id("n"), r = F.Id("r");
        var identity = Equal(new Formula.Power(SourceChoose(Seq(n, Plus, d, k), k), r),
            Seq(Sum, Underscore, Grp(j), Sp, SourceCoefficient(r, j), Sp,
                SourceChoose(Seq(n, Plus, d, j), j)));
        var recursion = Equal(SourceCoefficient(Add(r, D(1)), j),
            Seq(Sum, Underscore, Grp(i), Sp, SourceStructureConstant(), Sp,
                SourceCoefficient(r, i)));
        return Paragraph(
            Text("Conjecture 4.1 (arXiv:1403.4962v1, p. 6): \"For any integers d, k ≥ 0 and r ≥ 1, there exist integers "),
            Math(SourceCoefficient(r, j)), Text(" such that "), Math(identity),
            Text(" for all n = 0, 1, 2, .... Moreover "), Math(SourceCoefficient(r, j)),
            Text(" can be defined as following: "), Math(Equal(SourceCoefficient(D(1), k), D(1))),
            Text(", "), Math(Equal(SourceCoefficient(D(1), j), D(0))),
            Text(" for j ≠ k and "), Math(recursion), Text(", where, "),
            Math(SourceStructureConstant()),
            Text(" are integers, independent of r, for all d, k, j, i.\""));
    }

    private static Formula BFormula()
    {
        Formula d = F.Id("d"), j = F.Id("j"), n = F.Id("n");
        return Disp(All("d", Naturals(), All("j", Naturals(), All("n", Naturals(),
            Equal(Call("B", d, j, n),
                Parenthesized(Seq(Call("choose", Add(n, Times(d, j)), j),
                    Sp, Colon, Sp, Integers())))))));
    }

    private static Formula AFormula()
    {
        Formula k = F.Id("k"), t = F.Id("T"), j = F.Id("j"), r = F.Id("r"), i = F.Id("i");
        var initial = Seq(F.Id("if"), Sp, Equal(j, k), Sp, F.Id("then"), Sp, D(1),
            Sp, F.Id("else"), Sp, D(0));
        var next = All("r", Naturals(), Equal(Call("a", k, t, Add(r, D(2)), j),
            SumRange(i, Add(Times(Parenthesized(Add(r, D(1))), k), D(1)),
                Times(Call("T", j, i), Call("a", k, t, Add(r, D(1)), i)))));
        return Disp(All("k", Naturals(), All("T", Coefficients(), All("j", Naturals(),
            And(Equal(Call("a", k, t, D(0), j), D(0)),
                And(Equal(Call("a", k, t, D(1), j), initial), next))))));
    }

    private static Formula ClaimFormula(bool definition)
    {
        Formula d = F.Id("d"), k = F.Id("k"), t = F.Id("T"), i = F.Id("i"),
            j = F.Id("j"), r = F.Id("r"), n = F.Id("n");
        var structureSupport = All("i", Naturals(), All("j", Naturals(),
            Implies(Less(Add(i, k), j), Equal(Call("T", j, i), D(0)))));
        var coefficientSupport = All("j", Naturals(),
            Implies(Less(Times(r, k), j), Equal(Call("a", k, t, r, j), D(0))));
        var identity = All("n", Naturals(),
            Equal(new Formula.Power(Call("B", d, k, n), r),
                SumRange(j, Add(Times(r, k), D(1)),
                    Times(Call("a", k, t, r, j), Call("B", d, j, n)))));
        var body = All("d", Naturals(), All("k", Naturals(), ExistsIn("T", Coefficients(),
            And(structureSupport, All("r", Naturals(),
                Implies(AtMost(D(1), r), And(coefficientSupport, identity)))))));
        return Disp(definition
            ? new Formula.Logic(F.Id("claim"), FormulaLogicOperator.Iff, Parenthesized(body))
            : body);
    }
}
