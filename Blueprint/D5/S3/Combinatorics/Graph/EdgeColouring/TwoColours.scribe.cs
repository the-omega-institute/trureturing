    private static Formula Statement()
    {
        Formula v = F.Id("V"), e = F.Id("E"), l = F.Id("l"), r = F.Id("r"), c = F.Id("C");
        Formula loopless = All("a", e, Rel(Call("l", F.Id("a")), FormulaRelationOperator.NotEqual, Call("r", F.Id("a"))));
        Formula degree = All("x", v, Implies(Member(F.Id("x"), c),
            Rel(D(2), FormulaRelationOperator.LessThanOrEqual, Call("card", Call("star", l, r, F.Id("x"))))));
        Formula colouring = new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create("colour"),
            Call("Functions", e, F.Id("Bool")), All("x", v, Implies(Member(F.Id("x"), c),
                Call("Mixed", l, r, F.Id("colour"), F.Id("x")))));
        return Disp(All("V", Call("Type"), All("E", Call("Type"),
            Seq(OpenBracket, Call("Fintype", v), CloseBracket, Sp,
                OpenBracket, Call("Fintype", e), CloseBracket, Sp,
                OpenBracket, Call("DecidableEq", v), CloseBracket, Sp,
                OpenBracket, Call("DecidableEq", e), CloseBracket, Sp,
                All("l", Call("Functions", e, v), All("r", Call("Functions", e, v),
                    All("C", Call("Finset", v), Implies(And(loopless, degree),
                        Logic(colouring, FormulaLogicOperator.Iff,
                            new Formula.Not(Call("OddComponent", l, r, c)))))))))));
    }
    private static Formula Call(string name, params Formula[] args) => args.Length == 0
        ? new Formula.NamedConstant(FormulaIdentifier.Create(name))
        : new Formula.Apply(new Formula.NamedConstant(FormulaIdentifier.Create(name)), [.. args]);
    private static Formula All(string name, Formula domain, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), domain, body);
    private static Formula Member(Formula a, Formula b) => Rel(a, FormulaRelationOperator.MemberOf, b);
    private static Formula Rel(Formula a, FormulaRelationOperator op, Formula b) => new Formula.Relation(a, op, b);
    private static Formula And(Formula a, Formula b) => Logic(a, FormulaLogicOperator.And, b);
    private static Formula Implies(Formula a, Formula b) => Logic(a, FormulaLogicOperator.Implies, b);
    private static Formula Logic(Formula a, FormulaLogicOperator op, Formula b) =>
        new Formula.Logic(Seq(Open, a, Close), op, Seq(Open, b, Close));
}
