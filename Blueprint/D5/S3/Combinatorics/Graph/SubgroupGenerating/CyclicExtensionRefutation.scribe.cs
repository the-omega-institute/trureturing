    private static Formula Call(string name, params Formula[] args) =>
        new Formula.FunctionCall(FormulaIdentifier.Create(name), [.. args]);
    private static Formula Eq(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.Equal, b);
    private static Formula Ne(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.NotEqual, b);
    private static Formula Le(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThanOrEqual, b);
    private static Formula Lt(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThan, b);
    private static Formula Iff(Formula a, Formula b) => new Formula.Logic(a, FormulaLogicOperator.Iff, b);
    private static Formula Imp(Formula a, Formula b) => new Formula.Logic(a, FormulaLogicOperator.Implies, b);
    private static Formula And(Formula a, Formula b) => new Formula.Logic(a, FormulaLogicOperator.And, b);
    private static Formula All(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), type, body);
    private static Formula Exists(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create(name), type, body);
    private static Formula Sub(Formula a, Formula b) => new Formula.Binary(a, FormulaBinaryOperator.Subtract, b);
    private static Formula Mul(Formula a, Formula b) => new Formula.Binary(a, FormulaBinaryOperator.Multiply, b);
    private static Formula Reals() => Seq(Mathbb, Grp(F.Id("R")));
    private static Formula Cast(Formula a) => Seq(Open, a, Sp, Colon, Sp, Reals(), Close);
    private static Formula Energy(Formula g, string kind) => Call("graphEnergy", g, F.Id(kind));
    private static Formula Integral(Formula g, string kind) => Call("IntegralSpectrum", Call("graphSpectrum", g, F.Id(kind)));
    private static Formula Instance(Formula type, Formula body) => Seq(OpenBracket, type, CloseBracket, Comma, Sp, body);

    private static Formula GraphFormula()
    {
        var g = F.Id("G"); var p = F.Id("p"); var q = F.Id("q"); var h = F.Id("H"); var j = F.Id("J");
        Formula Adj(Formula a, Formula b) => Call("Adj", Call("sgbGraph", g), a, b);
        var generates = Eq(Call("closure", new Formula.SetLiteral([Call("fst", p), Call("snd", p)])), h);
        return Disp(new Formula.Aligned([
            Iff(Adj(Call("inl", p), Call("inr", h)), generates),
            Iff(Adj(Call("inr", h), Call("inl", p)), generates),
            new Formula.Not(Adj(Call("inl", p), Call("inl", q))),
            new Formula.Not(Adj(Call("inr", h), Call("inr", j)))]));
    }

    private static Formula CommonFormula()
    {
        var g = F.Id("g"); var i = F.Id("i"); var j = F.Id("j"); var k = F.Id("k");
        var condition = And(Ne(k, i), And(Ne(k, j), And(Call("Adj", g, i, k), Call("Adj", g, j, k))));
        var set = Seq(OpenBrace, k, Sp, Mid, Sp, condition, CloseBrace);
        var cases = Seq(Left, OpenBrace, new Formula.Aligned([
            Seq(D(0), Sp, Amp, Sp, Eq(i, j)),
            Seq(Cast(Call("card", set)), Sp, Amp, Sp, Ne(i, j))]), Right, Dot);
        return Disp(Eq(Call("commonNeighbourMatrix", g, i, j), cases));
    }

    private static Formula MatricesFormula()
    {
        var g = F.Id("g"); var a = Call("adjMatrix", g, Reals()); var d = Call("degMatrix", g, Reals());
        return Disp(new Formula.Aligned([
            Eq(Call("sourceMatrix", g, F.Id("adjacency")), a),
            Eq(Call("sourceMatrix", g, F.Id("laplacian")), Sub(d, a)),
            Eq(Call("sourceMatrix", g, F.Id("signless")), new Formula.Binary(d, FormulaBinaryOperator.Add, a)),
            Eq(Call("sourceMatrix", g, F.Id("commonNeighbour")), Call("commonNeighbourMatrix", g))]));
    }

    private static Formula SpectrumFormula()
    {
        var g = F.Id("g"); var kind = F.Id("kind"); var h = F.Id("hM");
        return Disp(Seq(F.Text, Grp(F.Id("let")), Sp, h, Sp, Colon, Sp,
            Call("IsHermitian", Call("sourceMatrix", g, kind)), Comma, Sp,
            Eq(Call("graphSpectrum", g, kind), Call("map", Call("eigenvalues", h), Call("univ", F.Id("V"))))));
    }

    private static Formula IntegralFormula()
    {
        var s = F.Id("s"); var x = F.Id("x"); var z = F.Id("z");
        return Disp(Iff(Call("IntegralSpectrum", s), All("x", Reals(),
            Imp(new Formula.Relation(x, FormulaRelationOperator.MemberOf, s),
                Exists("z", new Formula.Integers(), Eq(x, Cast(z)))))));
    }

    private static Formula AverageFormula() => Disp(Eq(Call("averageDegree", F.Id("g")),
        new Formula.Fraction(Mul(D(2), Cast(Call("card", Call("edgeFinset", F.Id("g"))))),
            Cast(Call("card", F.Id("V"))))));

    private static Formula EnergyFormula()
    {
        var g = F.Id("g"); var kind = F.Id("kind"); var x = F.Id("x"); var center = Call("center", g, kind);
        var sum = Seq(F.Sum, Underscore, Grp(new Formula.Relation(x, FormulaRelationOperator.MemberOf,
            Call("graphSpectrum", g, kind))), new Formula.Absolute(Sub(x, center)));
        return Disp(new Formula.Aligned([
            Eq(Call("graphEnergy", g, kind), sum),
            Eq(Call("center", g, F.Id("laplacian")), Call("averageDegree", g)),
            Eq(Call("center", g, F.Id("signless")), Call("averageDegree", g)),
            Eq(Call("center", g, F.Id("adjacency")), D(0)),
            Eq(Call("center", g, F.Id("commonNeighbour")), D(0))]));
    }

    private static Formula BundleFormula()
    {
        var g = F.Id("g"); var complete = Call("K", F.Id("V"));
        Formula[] clauses = [
            new Formula.Not(Integral(g, "adjacency")), Integral(g, "laplacian"),
            Integral(g, "signless"), Integral(g, "commonNeighbour"),
            Lt(Energy(g, "adjacency"), Cast(Call("card", F.Id("V")))),
            Le(Energy(g, "adjacency"), Energy(complete, "adjacency")),
            Le(Energy(g, "laplacian"), Energy(complete, "laplacian")),
            Le(Energy(g, "signless"), Energy(complete, "signless")),
            Le(Energy(g, "commonNeighbour"), Energy(complete, "commonNeighbour")),
            Le(Energy(g, "adjacency"), Energy(g, "laplacian"))];
        var conjunction = clauses[9];
        for (var i = 8; i >= 0; i--) conjunction = And(clauses[i], conjunction);
        return Disp(Iff(Call("sourceBundle", g), conjunction));
    }

    private static Formula ClaimFormula()
    {
        var g = F.Id("G");
        return Disp(Iff(F.Id("claim"), All("G", F.Id("Type"),
            Instance(Call("Group", g), Instance(Call("Fintype", g), Instance(Call("IsCyclic", g),
                Call("sourceBundle", Call("sgbGraph", g))))))));
    }
