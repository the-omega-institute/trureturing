using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Combinatorics.Graph.LeapGroups;

internal sealed class LeapGroupDocument : IScribeDocumentDefinition
{
    private const string Owner = "D5/S3/Combinatorics/Graph/LeapGroups/LeapGroup.";
    private const string Bib = "D5/L/FiniteGroups/schachnerudell2026leapgroups";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Cross-edge swaps and generation of a parity-class stabilizer.",
        H("Generating leap groups within parity classes"),
        Blocks(
            Node("hop", "Hops on a labelled graph", "IsHop", Hop(),
                "A hop sends every vertex to a neighbor. The original vertex set is both the domain and codomain of the bijection. See Question 1.1 on PDF page 2.",
                DescribeRole.Definition, AssessedProvenance.FromLiterature(LibraryNoteRef.Create(Bib))),
            Node("leap-group", "Subgroup generated by the hops", "leapGroup", Group(),
                "The closure is the subgroup closure in the full permutation group of the given vertex type. See Question 1.3 on PDF page 2.",
                DescribeRole.Definition, AssessedProvenance.FromLiterature(LibraryNoteRef.Create(Bib))),
            Node("parity-stabilizer", "Stabilizer of the unordered parity fibers", "parityStabilizer",
                Stabilizer(),
                "The action sends each subset to its image under the permutation and acts on the outer set by taking the image of every member. The fibers may be empty.",
                DescribeRole.Definition, AssessedProvenance.FromRepo()),
            Node("cross-edge-swap", "Two cross-edges suffice for a transposition",
                "swap_mem_of_cross_edges", CrossEdge(),
                "Postcompose the hop with the transposition. Only the two preimages of its endpoints can change their images, and the cross-edges supply adjacency there. The new hop times the inverse of the old hop is the transposition.",
                DescribeRole.Theorem, AssessedProvenance.FromRepo()),
            Node("generation", "Same-class swaps and a hop generate the stabilizer",
                "eq_parityStabilizer", Generation(),
                "Every hop exchanges parity. A permutation preserving parity sends each vertex within its orbit under the available swaps, so the transposition closure theorem supplies membership. Multiplication by the fixed hop reduces an exchanging permutation to a preserving one.",
                DescribeRole.Theorem, AssessedProvenance.FromRepo()))));

    private static DocumentBlock Node(string id, string title, string name, Formula formula,
        string prose, DescribeRole role, AssessedProvenance provenance) =>
        Describe.Lean(DescribeId.Create(id), DeclarationHandle.Create(Owner + name), H(title),
            StatementSource.FromAuthor(Disp(formula)), provenance, Blocks(Paragraph(Text(prose))), role);

    private static Formula Call(string name, params Formula[] args) =>
        new Formula.FunctionCall(FormulaIdentifier.Create(name), [.. args]);
    private static Formula All(string name, Formula domain, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), domain, body);
    private static Formula Rel(Formula l, Formula symbol, Formula r) => Seq(l, Sp, symbol, Sp, r);
    private static Formula Imp(Formula l, Formula r) => new Formula.Logic(l, FormulaLogicOperator.Implies, r);
    private static Formula V => F.Id("V");
    private static Formula G => F.Id("G");
    private static Formula P => F.Id("p");
    private static Formula Hh => F.Id("h");
    private static Formula Perm => Call("Perm", V);
    private static Formula Type => new Formula.NamedConstant(FormulaIdentifier.Create("Type"));
    private static Formula Color => Call("ZMod", D(2));
    private static Formula Colors => new Formula.TypeArrow(V, Color);
    private static Formula Context(Formula body) => All("V", Type, All("G", Call("SimpleGraph", V), body));
    private static Formula Instance(string name) => Seq(OpenBracket, Call(name, V), CloseBracket);
    private static Formula Fiber(byte c) => Seq(OpenBrace, F.Id("x"), Sp, Mid, Sp,
        Call("p", F.Id("x")), Sp, Eq, Sp, D(c), CloseBrace);

    private static Formula Hop() => Context(All("h", Perm,
        Rel(Call("IsHop", G, Hh), Iff, All("x", V, Call("Adj", G, F.Id("x"), Call("h", F.Id("x")))))));

    private static Formula Group() => Context(Rel(Call("leapGroup", G), Eq,
        Call("closure", Seq(OpenBrace, Hh, Sp, Mid, Sp, Call("IsHop", G, Hh), CloseBrace))));

    private static Formula Stabilizer() => All("V", Type, All("p", Colors,
        Rel(Call("parityStabilizer", P), Eq, Call("stabilizer", Perm,
            new Formula.SetLiteral([Fiber(0), Fiber(1)])))));

    private static Formula CrossEdge()
    {
        var a = F.Id("a");
        var c = F.Id("c");
        return Context(Seq(Instance("DecidableEq"), Sp, All("h", Perm,
            Imp(Call("IsHop", G, Hh), All("a", V, All("c", V,
                Imp(Call("Adj", G, Call("inv", Hh, a), c),
                    Imp(Call("Adj", G, Call("inv", Hh, c), a),
                        Rel(Call("swap", a, c), InMacro, Call("leapGroup", G))))))))));
    }

    private static Formula Generation()
    {
        var x = F.Id("x");
        var y = F.Id("y");
        var flip = All("x", V, All("y", V, Imp(Call("Adj", G, x, y),
            Rel(Call("p", y), Eq, Seq(Call("p", x), Plus, D(1))))));
        var swaps = All("x", V, All("y", V, Imp(Rel(Call("p", x), Eq, Call("p", y)),
            Rel(Call("swap", x, y), InMacro, Call("leapGroup", G)))));
        return Context(Seq(Instance("Finite"), Sp, Instance("DecidableEq"), Sp,
            All("p", Colors, Imp(flip, Imp(swaps, All("h", Perm, Imp(Call("IsHop", G, Hh),
                Rel(Call("leapGroup", G), Eq, Call("parityStabilizer", P)))))))));
    }
}
