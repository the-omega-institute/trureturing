    private static DocumentBlock Definition(string selector, string title, Formula formula, string meaning) =>
        Describe.Lean(DescribeId.Create(selector.ToLowerInvariant()), DeclarationHandle.Create(Prefix + selector),
            H(title), StatementSource.FromAuthor(Disp(formula)), AssessedProvenance.FromRepo(),
            Blocks(Paragraph(Text(meaning))), DescribeRole.Definition);

    private static Formula FullTuple() => Call("Append", PrefixTuple(), Call("Singleton", Call("Terminal", F.Id("F"))));
    private static Formula PrefixTuple() => Call("Append", Call("Selected", F.Id("F")), Call("Base", F.Id("F")));
    private static Formula BC() => Call("Multiply", Call("b", F.Id("m")), Call("c", F.Id("m")));
    private static Formula Right(Formula i) => Call("rightPort", F.Id("F"), i);
    private static Formula Left(Formula i) => Call("leftPort", F.Id("F"), i);
    private static Formula Edge(Formula x, Formula y) => Call("Adj", Call("NativeCayleyGraph", F.Id("m")), x, y);
    private static Formula CoordinateFormula()
    {
        Formula m = F.Id("m"), k = F.Id("k"), i = F.Id("i");
        Formula rotated = Call("Rotate", PrefixTuple(), i), last = Call("Singleton", Call("Terminal", F.Id("F")));
        Formula step = Eq(Call("Multiply", Left(i), Call("c", m)), Right(Call("Add", i, D(1))));
        Formula each = All("i", Call("Nat"), And(
            Eq(Call("Tuple", Right(i)), Call("Append", rotated, last)), And(
            Eq(Call("Tuple", Left(i)), Call("Append", Call("Reverse", rotated), last)),
            And(step, Edge(Left(i), Right(Call("Add", i, D(1))))))));
        Formula final = Left(Call("Subtract", m, D(1)));
        Formula closes = And(Eq(Call("Multiply", final, Call("c", m)), Right(D(0))), Edge(final, Right(D(0))));
        return Disp(All("m", Call("Nat"), Implies(Le(D(3), m), All("k", Call("Nat"),
            All("F", Call("SupplyFrame", m, k), And(each, closes))))));
    }
    private static Formula InjectiveFormula()
    {
        Formula m = F.Id("m"), k = F.Id("k");
        return Disp(All("m", Call("Nat"), Implies(Le(D(3), m), All("k", Call("Nat"),
            All("F", Call("SupplyFrame", m, k), Implies(Lt(k, m),
                Call("Injective", Call("specialPort", F.Id("F")))))))));
    }
    private static Formula Call(string name, params Formula[] args) => args.Length == 0
        ? new Formula.NamedConstant(FormulaIdentifier.Create(name))
        : new Formula.Apply(new Formula.NamedConstant(FormulaIdentifier.Create(name)), [.. args]);
    private static Formula All(string name, Formula domain, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), domain, body);
    private static Formula Eq(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.Equal, b);
    private static Formula Le(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThanOrEqual, b);
    private static Formula Lt(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThan, b);
    private static Formula Implies(Formula a, Formula b) => new Formula.Logic(a, FormulaLogicOperator.Implies, b);
    private static Formula And(Formula a, Formula b) => new Formula.Logic(a, FormulaLogicOperator.And, b);
}
