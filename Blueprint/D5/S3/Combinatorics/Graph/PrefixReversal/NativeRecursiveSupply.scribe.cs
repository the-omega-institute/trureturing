using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Combinatorics.Graph.PrefixReversal;

internal sealed class NativeRecursiveSupplyDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S3/Combinatorics/Graph/PrefixReversal/NativeRecursiveSupply.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "A full literal label tuple supplies actual recursive boundary ports, their native c edges, and their distinctness.",
        H("Actual Anchored Recursive Supply"),
        Blocks(
            Definition("SupplyFrame", "Independent Full Label Frames", Call("SupplyFrame", F.Id("m"), F.Id("k")),
                "SupplyFrame(m,k) contains selected and base lists and a terminal label. The selected list has length k; selected followed by base has length m. The full tuple selected, base, terminal is nodup and contains every label in Fin(m+1). The frame does not contain a path, coverage premise, or recursive construction certificate."),
            Definition("anchor", "The Actual Literal Anchor", Eq(Call("Tuple", Call("anchor", F.Id("F"))), FullTuple()),
                "The nodup complete tuple determines an actual permutation of Fin(m+1), with precisely selected followed by base followed by the terminal as its literal list."),
            Definition("rightPort", "Actual Right Supply Ports", Eq(Right(F.Id("i")),
                Call("Multiply", Call("anchor", F.Id("F")), Call("Power", BC(), F.Id("i")))),
                "R_i is anchor(F) multiplied on the right by (b_m c_m)^i. Its prefix rotates forward by i and its terminal label stays fixed."),
            Definition("leftPort", "Actual Left Supply Ports", Eq(Left(F.Id("i")),
                Call("Multiply", Right(F.Id("i")), Call("b", F.Id("m")))),
                "L_i is R_i b_m. It reverses the entire prefix and keeps the terminal; the base is not independently reversed in the frame."),
            Definition("specialPort", "The Distinguished k Plus One Port Pairs", Call("specialPort", F.Id("F"), F.Id("p")),
                "For p in Fin(k+1) times Fin(2), side zero selects R at p's first coordinate and side one selects L at that same coordinate."),
            Describe.Lean(DescribeId.Create("native-anchored-supply-coordinates"),
                DeclarationHandle.Create(Prefix + "native_anchored_supply_coordinates"),
                H("Every Supply Coordinate and Closing Seam Is Actual"),
                StatementSource.FromAuthor(CoordinateFormula()), AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "For every m at least three, every k, every full SupplyFrame(m,k), and every natural supply position i, the right tuple is rotate(selected ++ base,i) followed by terminal. The left tuple is the reverse of that same prefix followed by terminal. Multiplication by the actual c generator takes L_i to R_(i+1), and these configurations are adjacent in the actual Cayley graph generated by a, b and c. The final full-supply seam takes L_(m-1) to R_0 and is also a native edge.")),
                    Paragraph(Text(
                    "The tuple and generator formulas are proved from the actual permutation coordinates. Full supplier closure uses the earned order-m prefix rotation. The c generator is nonidentity when m is at least three. No abstract boundary graph is supplied as a premise. This theorem does not assert a Hamilton cycle, a prior-cycle edge inventory, or the recursive all-size closure."))), DescribeRole.Theorem),
