                        + "that owner's own cut exclusion. Suppose instead it were a c seam. "
                        + "An undirected edge generated by an involution determines its generator "
                        + "under either endpoint orientation. Actual prefix reversal coordinates "
                        + "distinguish c from both a and b, so a c seam cannot equal an old cut.")),
                    Paragraph(Text(
                        "The full inventory in native_core_hamiltonian_cycle_with_full_inventory "
                        + "therefore gives actual absence of every old T cut on that same constructed "
                        + "core Hamilton cycle. Further E grafts and the six J2 marked cuts require "
                        + "their own complete surgery inventories and path legality proofs."))),
                DescribeRole.Theorem))));

    private static Formula DisjointFormula()
    {
        Formula m = F.Id("m"), e = F.Id("e");
        return Disp(All("m", Call("Nat"), Implies(Le(D(4), m),
            All("e", Call("Sym2Type", Call("Configuration", m)),
                Implies(Call("CoreDeletedEdge", m, e),
                    new Formula.Not(new Formula.Logic(Call("CoreUncut", m, e),
                        FormulaLogicOperator.Or, Call("TSeam", m, e))))))));
    }

    private static Formula Call(string name, params Formula[] args) =>
        args.Length == 0 ? new Formula.NamedConstant(FormulaIdentifier.Create(name))
            : new Formula.Apply(new Formula.NamedConstant(FormulaIdentifier.Create(name)), [.. args]);
    private static Formula All(string name, Formula domain, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), domain, body);
    private static Formula Le(Formula left, Formula right) =>
        new Formula.Relation(left, FormulaRelationOperator.LessThanOrEqual, right);
    private static Formula Implies(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.Implies, right);
}
