using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Combinatorics.Graph.PrefixReversal;

internal sealed class NativeCoreEdgeClassificationDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S3/Combinatorics/Graph/PrefixReversal/NativeCoreEdgeClassification.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Every literal old T cut is absent from the complete independently indexed native T surgery edge set.",
        H("Complete Native T Deleted Edge Classification"),
        Blocks(
            Paragraph(Text(
                "Configurations are actual permutations of Fin(m+1), with the three largest prefix "
                + "reversals a, b and c. CoreDeletedEdge(m,e) enumerates the old T a/b cuts from "
                + "their actual circle ports. CoreUncut(m,e) enumerates native edges in every "
                + "owned circle except its own cut. TSeam(m,e) enumerates the actual c connection "
                + "from each cut endpoint. All three sets are specified without choosing a cycle.")),
            Describe.Lean(DescribeId.Create("native-t-deleted-edge-disjoint"),
                DeclarationHandle.Create(Prefix + "native_t_deleted_edge_disjoint"),
                H("No Old T Cut Belongs to the Complete Surgery Edge Set"),
                StatementSource.FromAuthor(DisjointFormula()), AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "For every m at least four and every undirected configuration edge e, "
                        + "CoreDeletedEdge(m,e) excludes CoreUncut(m,e) and TSeam(m,e). This proves "
                        + "absence from the complete output edge set, rather than inferring it "
                        + "from preservation of other edges.")),
                    Paragraph(Text(
                        "Suppose a deleted cut were retained by some circle owner. The actual "
                        + "cut-start endpoint belongs to the edge, and native_circle_edge_endpoint "
                        + "places it in that retained circle. The earned unique native T circle "
