    private static Formula DeletionFormula()
    {
        Formula m = F.Id("m"), z = F.Id("z");
        Formula deleted = Call("delete", Call("apply", z, Call("lastPosition", m)),
            Call("configurationCycle", z));
        Formula residual = Call("circleOfList", Call("residualList", z));
        return Disp(All("m", Call("Nat"), All("z", Call("Configuration", m), Eq(deleted, residual))));
    }

    private static Formula ComplementFormula()
    {
        Formula m = F.Id("m"), t = F.Id("t"), residual = F.Id("W"), v = F.Id("v"), j = F.Id("j");
        Formula n = Add(m, D(1));
        Formula vb = Call("rightMultiply", v, Call("b", m));
        Formula star = Call("Star", t, residual, v);
        Formula position = Eq(Call("apply", v, Call("castSucc", j)), t);
        Formula graph = Call("deleteEdges", Call("starFactor", t, residual), Call("singletonEdge", v, vb));
        Formula w = F.Id("w");
        Formula length = Eq(Call("length", w), Sub(Mul(Mul(D(2), m), n), D(1)));
        Formula trace = Eq(Call("map", Call("support", w), Call("underlyingConfiguration")),
            Call("scanl", Call("rightMultiply"), v, Call("zWord", m, Call("val", j))));
        Formula conclusion = And(Call("Star", t, residual, vb),
            Exists("w", Call("Walk", graph, v, vb), And(Call("IsHamiltonian", w), And(length, trace))));
        return Disp(All("m", Call("Nat"), Implies(Le(D(6), m),
            All("t", Call("Fin", n), All("W", Call("Cycle", Call("Fin", n)),
                All("v", Call("Configuration", m), All("j", Call("Fin", m),
                    Implies(And(star, position), conclusion))))))));
    }

    private static Formula Call(string name, params Formula[] args) =>
        args.Length == 0 ? new Formula.NamedConstant(FormulaIdentifier.Create(name))
            : new Formula.Apply(new Formula.NamedConstant(FormulaIdentifier.Create(name)), [.. args]);
    private static Formula All(string name, Formula domain, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), domain, body);
    private static Formula Exists(string name, Formula domain, Formula body) =>
        new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create(name), domain, body);
    private static Formula Eq(Formula l, Formula r) => new Formula.Relation(l, FormulaRelationOperator.Equal, r);
    private static Formula Le(Formula l, Formula r) => new Formula.Relation(l, FormulaRelationOperator.LessThanOrEqual, r);
    private static Formula And(Formula l, Formula r) => new Formula.Logic(l, FormulaLogicOperator.And, r);
    private static Formula Implies(Formula l, Formula r) =>
        new Formula.Logic(Seq(Open, l, Close), FormulaLogicOperator.Implies, Seq(Open, r, Close));
    private static Formula Add(Formula l, Formula r) => new Formula.Binary(l, FormulaBinaryOperator.Add, r);
    private static Formula Sub(Formula l, Formula r) => new Formula.Binary(l, FormulaBinaryOperator.Subtract, r);
    private static Formula Mul(Formula l, Formula r) => new Formula.Binary(l, FormulaBinaryOperator.Multiply, r);
}
