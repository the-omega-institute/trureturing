using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Combinatorics.Matroids;

internal sealed class SpanningCircuitImageDocument : IScribeDocumentDefinition
{
    private const string Module = "D5/S3/Combinatorics/Matroids/SpanningCircuitImage";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Exact integral restriction image for arbitrary spanning circuits.",
        H("The integral image of signed restriction to a spanning circuit"),
        Blocks(Describe.Lean(
            DescribeId.Create("integral-image-of-an-arbitrary-spanning-circuit"),
            DeclarationHandle.Create(Module + ".exists_topCycle_signedRestriction_iff"),
            H("The image is generated by the dual parallel-class sizes"),
            StatementSource.FromAuthor(Disp(Statement())),
            AssessedProvenance.FromRepo(),
            Blocks(
                Paragraph(Text(
                    "Let M be a matroid on a finite linearly ordered carrier, and let K be a "
                    + "spanning circuit in M. A top augmented integral cycle is a function "
                    + "on finite faces that vanishes off the bases and has zero augmented "
                    + "boundary. Its signed restriction is the sum of its coefficients on the "
                    + "single-vertex deletions of K, weighted by the corresponding boundary signs. "
                    + "The attainable integers are exactly the multiples of the gcd of the "
                    + "sizes of the fibers in K of the dual singleton-closure map.")),
                Paragraph(Text(
                    "Write E for the matroid ground. Each deletion of a vertex a of K is "
                    + "a primal base because K is a spanning circuit. Its complement in E "
                    + "is the dual base consisting of a and all vertices in E outside K. "
                    + "Together these bases show that every ground vertex is a dual nonloop. "
                    + "If distinct a and b in K have the same dual singleton closure, they "
                    + "form a dual circuit. In the primal boundary at K with a and b deleted, "
                    + "every insertion except a and b has zero coefficient. A vertex outside "
                    + "E cannot give a base. Every insertion from E outside K leaves the dual "
                    + "circuit in the complement. The two remaining boundary terms equate "
                    + "the signed restriction coordinates at a and b, with the relative "
                    + "sign fixed by the identity that the simplex boundary has zero boundary.")),
                Paragraph(Text(
                    "For the converse, choose a representative p of a dual parallel class "
                    + "in K and start with the dual base consisting of p and E outside K. "
                    + "First contract the closure of p. Every singleton in that flat is a "
                    + "basis of the flat. The chosen base loses only p, and the contraction "
                    + "is again loopless on its ground. Repeat with a vertex of the residual "
                    + "base until the ground is empty, where the chain is the empty simplex. "
                    + "The signed join of the augmented "
                    + "simplex boundaries on the successive removed flats has zero boundary "
                    + "by the Leibniz rule. Every nonzero coefficient omits exactly one "
                    + "element from each flat. The basis rule for contraction makes the "
                    + "omitted set a dual base, so the coefficient is on a primal base.")),
                Paragraph(Text(
                    "At the deletion of p the join has a unit coefficient. At a deletion "
                    + "outside the first flat, that face retains the whole first flat and "
                    + "its coefficient vanishes. The first flat is contained in K, since "
                    + "the dual base contains every ground vertex outside K. Multiplying by "
                    + "the signed coordinate at p gives signed coordinate one throughout its "
                    + "class and zero elsewhere. These cycles realize the individual class "
                    + "sizes. Grouping the signed coordinates of any cycle by class gives "
                    + "divisibility by their gcd, and finite integer Bezout yields a linear "
                    + "combination of the class cycles for every multiple.")),
                Paragraph(Text(
                    "The ground can be proper in the carrier, and K can equal the ground. "
                    + "The augmented boundary convention includes the empty face for a singleton "
                    + "circuit. The statement uses the integral readout directly, including the "
                    + "rank-zero contraction coordinate."))),
            DescribeRole.Theorem))));

    private static Formula Statement()
    {
        Formula v = F.Id("V"), m = F.Id("M"), k = F.Id("K"), z = F.Id("z"), n = F.Id("n");
        var type = new Formula.Subscript(Seq(Operatorname, Grp(F.Id("Type"))), F.Id("u"));
        var integers = Seq(Mathbb, Grp(F.Id("Z")));
        var set = Typed(k, Call("Set", v));
        var circuit = Call("IsCircuit", m, set);
        var spanning = Call("Spanning", m, set);
        var readout = Equal(Call("signedRestriction", k, z), n);
        var cycle = new Formula.Logic(Call("TopCycle", m, z), FormulaLogicOperator.And, readout);
        var attained = Seq(Open, Exists, Sp, Typed(z, Call("Chain", v)), Comma, Sp, cycle, Close);
        var divides = new Formula.Relation(Typed(Call("dualClassGcd", m, k), integers),
            FormulaRelationOperator.Divides, n);
        var image = new Formula.Logic(attained, FormulaLogicOperator.Iff, Parenthesized(divides));
        return Seq(Forall, Sp, Typed(v, type), Sp,
            OpenBracket, Call("LinearOrder", v), CloseBracket, Sp,
            OpenBracket, Call("Fintype", v), CloseBracket, Sp,
            Typed(m, Call("Matroid", v)), Sp, Typed(k, Call("Finset", v)), Comma, Sp,
            circuit, Sp, Rightarrow, Sp, spanning, Sp, Rightarrow, Sp,
            Forall, Sp, Typed(n, integers), Comma, Sp, Parenthesized(image));
    }

    private static Formula Typed(Formula value, Formula type) =>
        Parenthesized(Seq(value, Colon, Sp, type));

    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
}
