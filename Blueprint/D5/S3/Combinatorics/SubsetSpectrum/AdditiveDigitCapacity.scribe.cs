using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Combinatorics.SubsetSpectrum;

internal sealed class AdditiveDigitCapacityDocument : IScribeDocumentDefinition
{
    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "The reduced denominator limits how many integer levels a weighted digit grid can cover.",
        H("Integer levels and relative additive orders"),
        Blocks(Describe.Lean(
            DescribeId.Create("integer-level-capacity-under-a-reduced-total"),
            DeclarationHandle.Create(
                "D5/S3/Combinatorics/SubsetSpectrum/AdditiveDigitCapacity.integral_levels_capacity"),
            H("A rational weight total bounds the number of distinct integer levels"),
            StatementSource.FromAuthor(Statement()),
            AssessedProvenance.FromRepo(),
            Blocks(
                Paragraph(Text(
                    "Let r, k, n, A and b be natural numbers. There are r plus one real weights w. "
                    + "The positive denominator b is coprime to A and the total weight is A divided by b. "
                    + "L lists n pairwise distinct integers. IntegerCoverage(r,k,w,L) means each listed "
                    + "integer is a weighted sum with one digit per weight, each from zero through k.")),
                Paragraph(Text(
                    "Reduce the weights modulo the integers. Process the weights in order and take "
                    + "the additive order of each new weight modulo the subgroup generated by the previous "
                    + "ones. For a prescribed sum, each such order c limits the next digit to a single "
                    + "class modulo c. This gives at most the integer quotient k divided by c plus one "
                    + "choices. Infinite order permits at most one choice.")),
                Paragraph(Text(
                    "The product of finite relative orders annihilates the total weight modulo the "
                    + "integers. Its finite order is b because the defining fraction is reduced. "
                    + "Combining two factors uses (k+c)(k+d) at most (k+1)(k+cd), whose difference "
                    + "is k times (c-1) times (d-1). Each represented integer needs its own digit "
                    + "vector in the zero fiber."))),
            DescribeRole.Theorem))));

    private static Formula Statement()
    {
        Formula r = F.Id("r");
        Formula k = F.Id("k");
        Formula n = F.Id("n");
        Formula a = F.Id("A");
        Formula b = F.Id("b");
        Formula w = F.Id("w");
        Formula levels = F.Id("L");
        return Disp(Seq(Forall, Sp, r, Sp, k, Sp, n, Sp, a, Sp, b, Sp, w, Sp, levels, Comma, Sp,
            D(0), Sp, Lt, Sp, b, Sp, Land, Sp, Call("Coprime", a, b),
            Sp, Land, Sp, Call("WeightTotal", w), Sp, Eq, Sp, new Formula.Fraction(a, b),
            Sp, Land, Sp, Call("DistinctLevels", levels, n),
            Sp, Land, Sp, Call("IntegerCoverage", r, k, w, levels), Sp, Rightarrow, Sp,
            b, Cdot, Sp, n, Sp, Le, Sp, Open, b, Plus, k, Close, Cdot, Sp,
            Open, k, Plus, D(1), Close, Caret, r));
    }

    private static Formula Call(string name, params Formula[] arguments) =>
        new Formula.FunctionCall(FormulaIdentifier.Create(name), [.. arguments]);
}
