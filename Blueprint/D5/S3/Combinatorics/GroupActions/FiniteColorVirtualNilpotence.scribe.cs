    private static Formula Statement()
    {
        Formula g = F.Id("G"), x = F.Id("X"), p = F.Id("p"), h = F.Id("H");
        Formula m = F.Id("m"), c = F.Id("c");
        Formula structures = And(Call("Group", g), Call("PseudoMetric", x),
            Call("IsometricAction", g, x));
        Formula premises = And(Call("nilpotent", h), Call("colorDiff", c, h));
        Formula conclusion = Call("VirtNil", Call("Gamma", g, x, p, m));
        return Disp(ForAll("G", F.Id("Typeu"), ForAll("X", F.Id("Typev"),
            Implies(structures, ForAll("p", x, ForAll("H", Call("Subgroups", g),
                ForAll("m", F.Id("Nat"), ForAll("c", Call("Colors", g, x, p, m),
                    Implies(premises, conclusion)))))))));
    }

    private static Formula ForAll(string name, Formula domain, Formula body) =>
        new Formula.BindMany(FormulaQuantifier.ForAll,
            [new Formula.BoundVariable(FormulaIdentifier.Create(name), domain)], body);

    private static Formula Call(string name, params Formula[] arguments) =>
        new Formula.Apply(F.Id(name), [.. arguments]);

    private static Formula Implies(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.Implies, right);

    private static Formula And(Formula first, params Formula[] rest)
    {
        Formula result = first;
        foreach (Formula next in rest)
            result = new Formula.Logic(result, FormulaLogicOperator.And, next);
        return result;
    }
