    private static DocumentBlock Node(string name, string title, Formula formula, string prose,
        DescribeRole role, AssessedProvenance provenance) => Describe.Lean(
            DescribeId.Create(name switch { "addChild" => "add-child", "mulChild" => "mul-child", "G" => "cardinality", _ => name }), DeclarationHandle.Create(Module + "." + name), H(title),
            StatementSource.FromAuthor(Disp(formula)), provenance, Blocks(Paragraph(Text(prose))), role);

    private static Formula ClaimBody()
    {
        Formula n = X("n");
        Formula rhs = Add(Sub(Mul(D(3), IntegerG(Sub(n, D(1)))),
            Mul(D(3), IntegerG(Sub(n, D(2))))), IntegerG(Sub(n, D(3))));
        return ExistsOver("N", Naturals(), And(Le(D(3), X("N")), All("n", Naturals(),
            Implies(Le(X("N"), n), Eq(IntegerG(n), rhs)))));
    }

    private static Formula X(string name) => F.Id(name);
    private static Formula Naturals() => Seq(Mathbb, Grp(X("N")));
    private static Formula Integers() => Seq(Mathbb, Grp(X("Z")));
    private static Formula Polynomials() => App(Q("Polynomial"), Integers());
    private static Formula IntegerG(Formula n) => Typed(Call("G", n), Integers());
    private static Formula SingletonZero() => App(Q("Finset", "singleton"), Typed(D(0), Polynomials()));
    private static Formula Union(Formula a, Formula b) => App(Q("Finset", "union"), a, b);
    private static Formula Image(Formula f, Formula a) => App(Q("Finset", "image"), f, a);
    private static Formula Q(params string[] parts)
    {
        var items = new System.Collections.Generic.List<Formula>();
        foreach (string part in parts)
        {
            if (items.Count > 0) items.Add(Dot);
            items.Add(X(part));
        }
        return Seq(Operatorname, Grp(Seq([.. items])));
    }
    private static Formula App(Formula f, params Formula[] args) => new Formula.Apply(f, [.. args]);
    private static Formula Call(string name, params Formula[] args) => App(Q(name), args);
    private static Formula Parenthesized(Formula x) => Seq(Open, x, Close);
    private static Formula Typed(Formula x, Formula type) => Parenthesized(Seq(x, Colon, Sp, type));
    private static Formula All(string name, Formula type, Formula body) =>
        Seq(Forall, Sp, Typed(X(name), type), Comma, Sp, Parenthesized(body));
    private static Formula ExistsOver(string name, Formula type, Formula body) =>
        Seq(Exists, Sp, Typed(X(name), type), Comma, Sp, Parenthesized(body));
    private static Formula Eq(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.Equal, b);
    private static Formula Le(Formula a, Formula b) => new Formula.Relation(a, FormulaRelationOperator.LessThanOrEqual, b);
    private static Formula Add(Formula a, Formula b) => new Formula.Binary(a, FormulaBinaryOperator.Add, b);
    private static Formula Sub(Formula a, Formula b) => new Formula.Binary(a, FormulaBinaryOperator.Subtract, b);
    private static Formula Mul(Formula a, Formula b) => new Formula.Binary(a, FormulaBinaryOperator.Multiply, b);
    private static Formula Pow(Formula a, Formula b) => new Formula.Power(a, b);
    private static Formula And(Formula a, Formula b) => new Formula.Logic(Parenthesized(a), FormulaLogicOperator.And, Parenthesized(b));
    private static Formula Implies(Formula a, Formula b) => new Formula.Logic(Parenthesized(a), FormulaLogicOperator.Implies, Parenthesized(b));
    private static Formula Iff(Formula a, Formula b) => new Formula.Logic(Parenthesized(a), FormulaLogicOperator.Iff, Parenthesized(b));
