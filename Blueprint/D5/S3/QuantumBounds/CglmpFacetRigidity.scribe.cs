using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.QuantumBounds;

internal sealed class CglmpFacetRigidityDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S3/QuantumBounds/CglmpFacetRigidity.";
    private static readonly LibraryNoteRef Masanes =
        LibraryNoteRef.Create("D5/L/QuantumBounds/masanes2003tightbell");
    private static readonly LibraryNoteRef Grandjean =
        LibraryNoteRef.Create("D5/L/QuantumBounds/grandjean2012mermincglmpfacet");

    private static readonly LibraryNoteRef Blore =
        LibraryNoteRef.Create("D5/L/QuantumBounds/blore2026cglmp");

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "A bipartite local functional vanishing on CGLMP saturation is a multiple of the Bell slack.",
        H("CGLMP rigidity from short cyclic arcs"),
        Blocks(
            Node("BipLocal", "Bipartite local functions", LocalFormula(),
                "Every linear functional of a deterministic two-party full behaviour is a sum over the four setting pairs of a function of the two outputs selected by that pair. The coefficients f are arbitrary real numbers. The lowercase outputs a,b belong to setting 0 and A,B to setting 1; these are settings 1 and 2 in the source.",
                DescribeRole.Definition, AssessedProvenance.FromRepo(Masanes)),
            Node("J2AB", "The relabelled CGLMP expression", ExpressionFormula(),
                "Grandjean et al., Section II, PDF p. 2, identify the C_1=C_2=0 restriction of (1) as CGLMP, after relabelling B_2 to its negative residue. J2AB is the four-bracket deterministic restriction before that relabelling. ZMod.val denotes the natural least nonnegative residue when K is nonzero.",
                DescribeRole.Definition, AssessedProvenance.FromLiterature(Grandjean)),
            Node("val_neg_sub_one", "Complementary residues", ComplementFormula(),
                "The residues of x and −x−1 add to K−1. All subtractions on the displayed right side are natural truncated subtraction. The residue bound makes them equal to ordinary subtraction in this expression.",
                DescribeRole.Lemma, AssessedProvenance.FromLiterature(Blore)),
            Node("bipartite_rigidity", "Rigidity on CGLMP saturation", RigidityFormula(),
                "Masanes, abstract, PDF p. 1, states: “In this paper we prove that the inequality introduced by Collins, Gisin, Linden, Massar and Popescu [11] is tight, or in other words, it is a facet of the convex polytope generated by all local-realistic joint probabilities of d outcomes.” The statement below is the dual-functional formulation of that facet conclusion. The conclusion is literature-attested; the short-arc proof here is a different argument. Saturating quadruples reduce every four-edge local function to H(a,b)+H(b,c)+H(c,d)−H(a,d). On arcs of total length less than K, H is additive. A potential P and a single wrap coefficient describe every H, and the potential telescopes. This yields one common multiplier for every quadruple, including K=1; the nontrivial facet interpretation concerns K >= 2.",
                DescribeRole.Theorem, AssessedProvenance.FromLiterature(Masanes)))));

    private static DocumentBlock Node(string name, string title, Formula formula, string prose,
        DescribeRole role, AssessedProvenance provenance) => Describe.Lean(
        DescribeId.Create("cglmp-rigidity-" + name.ToLowerInvariant().Replace('_', '-')),
        DeclarationHandle.Create(Prefix + name), H(title), StatementSource.FromAuthor(formula),
        provenance, Blocks(Paragraph(Text(prose))), role);
    private static Formula Parenthesized(Formula value) => Seq(Open, value, Close);
    private static Formula All(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), type, body);
    private static Formula Some(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create(name), type, body);
    private static Formula Logic(Formula a, FormulaLogicOperator op, Formula b) =>
        new Formula.Logic(Parenthesized(a), op, Parenthesized(b));
    private static Formula Sub(Formula a, Formula b) => Subtract(a, b);
    private static Formula Negate(Formula value) => new Formula.Negate(Parenthesized(value));
    private static Formula Nats() => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula Reals() => Seq(Mathbb, Grp(F.Id("R")));
    private static Formula Zmod(Formula k) => Call("ZMod", k);
    private static Formula Cast(Formula value, Formula type) => Parenthesized(Seq(value, Colon, type));
    private static Formula Arrow(Formula a, Formula b) => Seq(Parenthesized(a), To, b);
    private static Formula Coefficients(Formula k) => Arrow(Call("Fin", D(2)),
        Arrow(Call("Fin", D(2)), Arrow(Zmod(k), Arrow(Zmod(k), Reals()))));
    private static Formula Outputs(Formula k, Formula body)
    {
        foreach (string name in new[] { "B", "b", "A", "a" }) body = All(name, Zmod(k), body);
        return body;
    }
    private static Formula WithNonzero(Formula k, Formula body) =>
        Seq(OpenBracket, Call("NeZero", k), CloseBracket, Sp, body);
    private static Formula If(Formula test, Formula yes, Formula no) =>
        Seq(Call("if", test), Call("then", yes), Call("else", no));
    private static Formula LocalValue(Formula f) => Call("BipLocal", f,
        F.Id("a"), F.Id("A"), F.Id("b"), F.Id("B"));
    private static Formula JValue() => Call("J2AB", F.Id("a"), F.Id("A"), F.Id("b"), F.Id("B"));
    private static Formula SumOver(string name, Formula body) => Seq(
        new Formula.Subscript(Sum, Seq(F.Id(name), Colon, Call("Fin", D(2)))), Parenthesized(body));

    private static Formula LocalFormula()
    {
        Formula k = F.Id("K"), f = F.Id("f"), x = F.Id("x"), y = F.Id("y");
        Formula value = Seq(f, Parenthesized(Seq(x, Comma, y, Comma,
            Parenthesized(If(Equal(x, D(0)), F.Id("a"), F.Id("A"))), Comma,
            Parenthesized(If(Equal(y, D(0)), F.Id("b"), F.Id("B"))))));
        return Disp(All("K", Nats(), All("f", Coefficients(k), Outputs(k,
            Equal(LocalValue(f), SumOver("x", SumOver("y", value)))))));
    }

    private static Formula ExpressionFormula()
    {
        Formula k = F.Id("K"), a = F.Id("a"), aa = F.Id("A"), b = F.Id("b"), bb = F.Id("B");
        Formula terms = Add(Add(Add(Call("val", Sub(aa, b)), Call("val", Add(a, bb))),
            Call("val", Add(Negate(a), b))), Call("val", Sub(Sub(Negate(aa), bb), D(1))));
        return Disp(All("K", Nats(), Outputs(k, Equal(JValue(), terms))));
    }

    private static Formula ComplementFormula()
    {
        Formula k = F.Id("d"), x = F.Id("r");
        return Disp(All("d", Nats(), WithNonzero(k, All("r", Zmod(k),
            Equal(Call("val", Sub(Negate(x), D(1))), Sub(Sub(k, D(1)), Call("val", x)))))));
    }

    private static Formula RigidityFormula()
    {
        Formula k = F.Id("K"), f = F.Id("f"), lam = F.Id("lam");
        Formula saturation = Outputs(k, Logic(Equal(JValue(), Sub(k, D(1))),
            FormulaLogicOperator.Implies, Equal(LocalValue(f), D(0))));
        Formula conclusion = Some("lam", Reals(), Outputs(k, Equal(LocalValue(f),
            Multiply(lam, Parenthesized(Sub(Cast(JValue(), Reals()), Parenthesized(Sub(Cast(k, Reals()), D(1)))))))));
        return Disp(All("K", Nats(), WithNonzero(k, All("f", Coefficients(k),
            Logic(saturation, FormulaLogicOperator.Implies, conclusion)))));
    }
}
