using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Observer.Chronology;

internal sealed class TruncatedTensorHopfDocument
    : IScribeDocumentDefinition
{
    private const string Prefix =
        "D5/S3/Observer/Chronology/TruncatedTensorHopf.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Degree-two tensor signatures satisfy the truncated group-like balance.",
        H("Truncated Tensor Hopf Balance"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("tensor-flip"),
                DeclarationHandle.Create(Prefix + "tensorFlip"),
                H("Canonical tensor flip"),
                StatementSource.WithoutFormula(),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "The two degree-one tensor factors are interchanged by Mathlib's "
                        + "canonical tensor symmetry."))),
                DescribeRole.Definition),
            Describe.Lean(
                DescribeId.Create("group-like"),
                DeclarationHandle.Create(Prefix + "IsStepTwoGroupLike"),
                H("Step-two group-like equation"),
                StatementSource.WithoutFormula(),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "A doubled degree-two coordinate is group-like when its symmetric "
                        + "part is twice the tensor square of degree one."))),
                DescribeRole.Definition),
            Describe.Lean(
                DescribeId.Create("word"),
                DeclarationHandle.Create(
                    Prefix + "chronological_tensor_signature_is_step_two_group_like"),
                H("Every finite word is group-like"),
                StatementSource.FromAuthor(GroupLikeFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "The zero degree-one and degree-two coordinates satisfy the balance, and a pure tensor square is fixed by the tensor flip, so the empty and single-event signatures are group-like.")),
                    Paragraph(Text(
                        "The symmetric cross terms generated by chronological composition complete the tensor square of the summed degree-one coordinate, so group-likeness is closed under Chen multiplication; induction over the event list extends it to every finite chronological word."))),
                DescribeRole.Theorem)),
        [
            DocumentEdge.Dependency.Create(GidRef.Create(
                "D5/S3/Observer/Chronology/TruncatedTensorSignature")),
        ]));

    private static Formula Call(string name, params Formula[] arguments)
    {
        var items = new List<Formula> { Operatorname, Grp(F.Id(name)), Open };
        for (var index = 0; index < arguments.Length; index++)
        {
            if (index > 0) items.AddRange([Comma, Sp]);
            items.Add(arguments[index]);
        }
        items.Add(Close);
        return Seq([.. items]);
    }

    private static Formula GroupLikeFormula() => Disp(Seq(
        Forall, Sp, F.Id("f"), Comma, Sp, F.Id("L"), Comma, Sp,
        Call("IsStepTwoGroupLike",
            Call("chronologicalTensorSignature", F.Id("f"), F.Id("L"))), Dot));
}
