                "Closed mismatch families are quotiented by globally correctable families."),
            Def("class", "observerCocycleClass", "Observer cocycle class",
                "Every closed mismatch determines a class in first observer cohomology."),
            Thm("closed", "observer_coboundary_is_cocycle", "Every correction is closed",
                "The square-zero law sends every global coboundary into the cocycle module."),
