using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Observer.MetricGeometryLaws;

internal sealed class HiddenTranslationComponentChargeDocument
    : IScribeDocumentDefinition
{
    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "A hidden translation changes path component exactly when its canonical charge is nonzero.",
        H("Hidden Translation Component Charge"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("hidden-translation-component-charge"),
                DeclarationHandle.Create(
                    "D5/S3/Observer/MetricGeometryLaws/HiddenTranslationComponentCharge."
                        + "hidden_translation_component_charge"),
                H("Hidden translations cross components exactly at nonzero charge"),
                StatementSource.FromAuthor(TheoremFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "The translation is formed from a point of the universal solenoid "
                            + "and an element of the kernel of its visible projection.")),
                    Paragraph(Text(
                        "Path connectedness in one projection fiber is classified by integer "
                            + "times of the real flow. The canonical hidden unit offset "
                            + "generates exactly those integer-flow translations.")),
                    Paragraph(Text(
                        "Consequently, the translated point leaves the original path "
                            + "component exactly when the kernel element has nonzero class "
                            + "modulo the subgroup generated by the hidden unit offset."))),
                DescribeRole.Theorem))));

    private static Formula Call(string name, params Formula[] arguments) =>
        new Formula.Apply(F.Id(name), [.. arguments]);

    private static Formula TheoremFormula()
    {
        Formula point = F.Id("x");
        Formula offset = F.Id("kappa");
        Formula unitOffset = F.Id("hiddenUnitOffset");
        Formula translated = Seq(
            point, Sp, Plus, Sp, Call("kernelInclusion", offset));
        Formula changesComponent = new Formula.Not(
            Call("Joined", point, translated));
        Formula charge = Call(
            "QuotientClass", offset, Call("ZMultiples", unitOffset));
        Formula nonzeroCharge = new Formula.Relation(
            charge, FormulaRelationOperator.NotEqual, D(0));

        return Disp(new Formula.BindMany(
            FormulaQuantifier.ForAll,
            [
                new Formula.BoundVariable(
                    FormulaIdentifier.Create("x"), F.Id("UniversalSolenoid")),
                new Formula.BoundVariable(
                    FormulaIdentifier.Create("kappa"),
                    Call("Kernel", F.Id("projection"))),
            ],
            new Formula.Logic(
                changesComponent, FormulaLogicOperator.Iff, nonzeroCharge)));
    }
}
