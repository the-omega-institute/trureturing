using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Observer.WindowAlgebra;

internal sealed class OperationalClassicalSeparationDocument : IScribeDocumentDefinition
{
    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Full finite-window operations and state tomography do not yield a "
            + "multiplicative classical state.",
        H("Operational Completeness and Classical Separation"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("operational-completeness-does-not-imply-classical-completeness"),
                DeclarationHandle.Create(
                    "D5/S3/Observer/WindowAlgebra/OperationalClassicalSeparation."
                        + "operational_complete_not_classically_complete"),
                H("Operational completeness does not imply classical completeness"),
                StatementSource.FromAuthor(TheoremFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "For every finite cyclic window with more than one address, the "
                            + "algebra generated by the canonical clock and shift is the full "
                            + "matrix algebra. Its canonical centralizer is exactly the scalar "
                            + "matrices, and the generated algebra has no unital complex "
                            + "character.")),
                    Paragraph(Text(
                        "The trace functional is imported from the matrix-state family. Trace "
                            + "expectations against all matrices separate positive trace-one "
                            + "density matrices, while each such density gives a normalized "
                            + "complex-linear functional that is nonnegative on adjoint squares.")),
                    Paragraph(Text(
                        "The final clause constructs the basis density at address zero and the "
                            + "opposite matrix units from zero to one and one to zero. Their "
                            + "individual expectations vanish, but the expectation of their "
                            + "product is one, so the state is explicitly not multiplicative.")),
                    Paragraph(Text(
                        "The proof applies the existing window generation, scalar commutant, "
                            + "character exclusion, and matrix-state cone results together with "
                            + "Mathlib's trace-pairing separation and matrix-unit identities. "
                            + "No existing declaration combined all six public clauses."))),
                DescribeRole.Theorem))));

    private static Formula TheoremFormula()
    {
        Formula m = F.Id("M"), rho = Rho, sigma = SigmaLower;
        Formula a = F.Id("A"), b = F.Id("B"), identity = F.Id("I");
        Formula generated = Call("Generated", Call("clock", m), Call("shift", m));
        Formula densityRho = Call("Density", rho, m);
        Formula densitySigma = Call("Density", sigma, m);
        Formula omegaRhoA = Call("omega", rho, a);
        Formula omegaSigmaA = Call("omega", sigma, a);

        return Disp(Seq(
            Begin, Grp(F.Id("gathered")),
            Forall, Sp, m, Sp, InMacro, Sp,
            Mathbb, Grp(F.Id("N")), Underscore, Grp(Gt, D(1)), Comma,
            RowBreak, Grp(),
            generated, Sp, Eq, Sp, Call("Matrix", m), Sp, Land, Sp,
            RowBreak, Grp(),
            Call("centralizer", generated), Sp, Eq, Sp, Call("Scalars", m),
            Sp, Land, Sp, Call("Char", generated), Sp, Eq, Sp, Varnothing,
            Sp, Land, Sp, RowBreak, Grp(),
            Open, Forall, Sp, rho, Comma, Sp, sigma, Comma, Sp,
            densityRho, Sp, Land, Sp, densitySigma, Sp, Land, Sp,
            Open, Forall, Sp, a, Comma, Sp, omegaRhoA, Sp, Eq, Sp,
            omegaSigmaA, Close, Sp, Rightarrow, Sp, rho, Sp, Eq, Sp, sigma,
            Close, Sp, Land, Sp, RowBreak, Grp(),
            Open, Forall, Sp, rho, Comma, Sp, densityRho, Sp, Rightarrow, Sp,
            Call("Linear", Call("omega", rho)), Sp, Land, Sp,
            Call("Positive", Call("omega", rho)), Sp, Land, Sp,
            Call("omega", rho, identity), Sp, Eq, Sp, D(1), Close,
            Sp, Land, Sp, RowBreak, Grp(),
            Exists, Sp, rho, Comma, Sp, a, Comma, Sp, b, Comma, Sp,
            densityRho, Sp, Land, Sp,
            omegaRhoA, Sp, Eq, Sp, D(0), Sp, Land, Sp,
            Call("omega", rho, b), Sp, Eq, Sp, D(0), Sp, Land, Sp,
            Call("omega", rho, Seq(a, b)), Sp, Eq, Sp, D(1), Dot,
            End, Grp(F.Id("gathered"))));
    }
}
