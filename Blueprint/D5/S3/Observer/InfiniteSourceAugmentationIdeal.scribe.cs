using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Observer;

internal sealed class InfiniteSourceAugmentationIdealDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S3/Observer/InfiniteSourceAugmentationIdeal.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "The augmentation ideal of the infinite coordinatewise square-zero source algebra is not finitely generated.",
        H("Infinite Source Augmentation Ideal"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("infinite-source-augmentation-ideal-not-finitely-generated"),
                DeclarationHandle.Create(
                    Prefix + "infinite_source_augmentation_ideal_not_finitely_generated"),
                H("No finite family generates every source coordinate"),
                StatementSource.FromAuthor(TheoremFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "The carrier is the complex multivariable polynomial ring indexed by the "
                            + "integers, quotiented by the ideal generated by the square of each "
                            + "coordinate. The augmentation ideal is generated by the images of all "
                            + "coordinate variables.")),
                    Paragraph(Text(
                        "Choose polynomial representatives for a proposed finite family and then an "
                            + "integer outside the union of their finite variable sets. Evaluation at "
                            + "that coordinate descends to the dual numbers: it kills every proposed "
                            + "generator but sends the fresh coordinate to the nonzero dual unit.")),
                    Paragraph(Text(
                        "This proves the finite-family escape clause, which rules out finite generation. "
                            + "The pinned characterization of Noetherian rings by finite generation of "
                            + "all ideals then gives the final clause.")),
                    Paragraph(Text(
                        "Repository, pinned-Mathlib, and public Lean ecosystem searches found no exact "
                            + "owner for this infinite-index quotient theorem."))),
                DescribeRole.Theorem))));

    private static Formula Typed(Formula value, Formula type) => Seq(value, Colon, Sp, type);

    private static Formula Call(string name, params Formula[] arguments)
    {
        var items = new List<Formula> { Operatorname, Grp(F.Id(name)), Open };
        for (var index = 0; index < arguments.Length; index++)
        {
            if (index > 0) items.AddRange([Comma, Sp]);
            items.Add(arguments[index]);
        }
        items.Add(Close);
        return Seq([.. items]);
    }

    private static Formula TheoremFormula()
    {
        Formula algebra = F.Id("InfiniteSourceAlgebra");
        Formula ideal = F.Id("augmentationIdeal");
        Formula family = F.Id("s");
        Formula index = F.Id("h");
        Formula integers = new Formula.Integers();
        Formula freshClause = Seq(
            Forall, Sp, Typed(family, Call("Finset", algebra)), Comma, Sp,
            family, Sp, Subseteq, Sp, ideal, Sp, Rightarrow, Sp,
            Exists, Sp, Typed(index, integers), Comma, Sp,
            new Formula.Not(Seq(
                Call("sourceVariable", index), Sp, InMacro, Sp, Call("IdealSpan", family))));
        Formula notFinitelyGenerated = new Formula.Not(Call("FG", ideal));
        Formula notNoetherian = new Formula.Not(Call("IsNoetherianRing", algebra));

        return Disp(Seq(
            Begin, Grp(F.Id("gathered")),
            Open, freshClause, Close, Sp, Land, RowBreak, Grp(),
            notFinitelyGenerated, Sp, Land, RowBreak, Grp(),
            notNoetherian, Dot,
            End, Grp(F.Id("gathered"))));
    }
}
