    private static Formula Call(string name, params Formula[] arguments)
    {
        var items = new List<Formula> { Operatorname, Grp(F.Id(name)), Open };
        for (var index = 0; index < arguments.Length; index++)
        {
            if (index > 0) items.AddRange([Comma, Sp]);
            items.Add(arguments[index]);
        }
        items.Add(Close);
        return Seq([.. items]);
    }

    private static Formula Statement(bool word)
    {
        Formula h = F.Id("H");
        Formula a = F.Id("a");
        Formula index = F.Id(word ? "w" : "i");
        Formula r = Call("recoveredGram", a, Call("pairRead", h, a),
            Call("tripleRead", h, a));
        Formula left = Call("gauge", Call("anchorScale", h, a),
            Call(word ? "W" : "increment", h, index));
        Formula right = Call(word ? "W" : "increment", r, index);
        return Disp(Seq(
            Forall, Sp, h, Comma, Sp, a, Comma, Sp, index, Comma, Sp,
            Call("ZeroDiagonal", h), Sp, Land, Sp, Call("BidirectedStar", h, a),
            Sp, Rightarrow, Sp,
            new Formula.Relation(left, FormulaRelationOperator.Equal, right)));
    }
