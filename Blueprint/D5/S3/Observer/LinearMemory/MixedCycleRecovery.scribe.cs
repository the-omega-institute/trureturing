    private static Formula Sub(Formula value, Formula subscript) => Seq(value, Underscore, Grp(subscript));
    private static Formula Call(string name, params Formula[] arguments)
    {
        var items = new List<Formula> { Operatorname, Grp(F.Id(name)), Open };
        for (var i = 0; i < arguments.Length; i++)
        {
            if (i > 0) items.AddRange([Comma, Sp]);
            items.Add(arguments[i]);
        }
        items.Add(Close);
        return Seq([.. items]);
    }

    private static Formula Rank(Formula map) => Call("finrank", F.Id("R"), Call("range", map));
    private static Formula Eqn(Formula left, Formula right) => Seq(left, Sp, Eq, Sp, right);
    private static Formula Rec(Formula map) => Call("Rec", map);

    private static Formula TheoremFormula()
    {
        Formula r = F.Id("r");
        Formula k = F.Id("k");
        Formula v = F.Id("V");
        Formula b = F.Id("b");
        Formula e = F.Id("E");
        Formula w = Sub(F.Id("W"), r);
        Formula rows = Sub(F.Id("R"), r);
        Formula m = Sub(F.Id("M"), r);
        Formula pe = Sub(F.Id("P"), e);
        Formula pw = Sub(F.Id("P"), w);
        Formula threePlusR = Seq(D(3), Sp, Plus, Sp, r);
        Formula idE = Call("id", e);
        Formula idV = Call("id", v);
        Formula x = F.Id("x");
        Formula a = F.Id("a");
        Formula shifted = Seq(x, Sp, Plus, Sp, a, Sp, Sub(F.Id("f"), r));
        Formula escape = Seq(Forall, Sp, x, Colon, Sp, v, Comma, Sp,
            Forall, Sp, a, Colon, Sp, F.Id("R"), Comma, Sp,
            Eqn(Call("apply", m, shifted), Call("apply", m, x)), Sp, Land, Sp,
            Open, a, Sp, Neq, Sp, D(0), Sp, Rightarrow, Sp, shifted, Sp, Neq, Sp, x, Close);
        Formula[] claims = [
            Eqn(Sub(F.Id("C"), D(0)), Call("id", v)),
            Eqn(rows, w),
            Eqn(Call("finrank", F.Id("R"), rows), threePlusR),
            Eqn(Rank(idE), D(3)),
            Seq(Forall, Sp, x, Colon, Sp, e, Comma, Sp,
                Eqn(Call("apply", Call("y", Call("one", Sub(F.Id("G"), r))), x), x)),
            Eqn(Rank(pe), D(3)), Rec(pe),
            Seq(r, Sp, Lt, Sp, k, Sp, Rightarrow, Sp, Open, escape, Close),
            Seq(Rec(idV), Sp, Leftrightarrow, Sp, r, Sp, Eq, Sp, k),
            Eqn(Rank(pw), threePlusR), Rec(pw),
            Seq(Call("Full", idV), Sp, Leftrightarrow, Sp, r, Sp, Eq, Sp, k)
        ];
        var body = new List<Formula> {
            Begin, Grp(F.Id("gathered")), Forall, Sp, k, Comma, Sp, r, Colon, Sp,
            F.Id("N"), Comma, Sp, v, Colon, Sp, Seq(Operatorname, Grp(F.Id("Type"))), Comma, RowBreak, Grp(),
            OpenBracket, Call("NormedAddCommGroup", v), CloseBracket, Comma, Sp,
            OpenBracket, Call("InnerProductSpace", F.Id("R"), v), CloseBracket, Comma, Sp,
            OpenBracket, Call("FiniteDimensional", F.Id("R"), v), CloseBracket, Comma,
            RowBreak, Grp(), b, Colon, Sp,
            Call("OrthonormalBasis", Call("Sum", Call("Fin", D(3)), Call("Fin", k)), F.Id("R"), v),
            Comma, Sp, r, Sp, Leq, Sp, k, Sp, Rightarrow, RowBreak, Grp()
        };
        for (var i = 0; i < claims.Length; i++)
        {
            if (i > 0) body.AddRange([Sp, Land, RowBreak, Grp()]);
            body.AddRange([Open, claims[i], Close]);
        }
        body.AddRange([Dot, End, Grp(F.Id("gathered"))]);
        return Disp(Seq([.. body]));
    }
