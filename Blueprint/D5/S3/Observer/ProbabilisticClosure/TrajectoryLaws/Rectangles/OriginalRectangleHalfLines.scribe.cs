    private static Formula Call(string name, params Formula[] args)
    {
        Formula f = F.Seq(Operatorname, Grp(F.Id(name)), Open);
        for (int i = 0; i < args.Length; i++)
            f = i == 0 ? F.Seq(f, args[i]) : F.Seq(f, Comma, Sp, args[i]);
        return F.Seq(f, Close);
    }
    private static Formula Par(Formula f) => F.Seq(Open, f, Close);
    private static Formula All(string name, Formula type, Formula body) =>
        F.Seq(Forall, Sp, F.Id(name), Colon, Par(type), Comma, Sp, Par(body));
    private static Formula Lam(string name, Formula type, Formula body) =>
        F.Seq(Open, F.Id(name), Colon, type, Mapsto, Sp, body, Close);
    private static Formula Rel(Formula a, Formula relation, Formula b) => F.Seq(a, relation, Sp, b);
    private static Formula Imp(Formula a, Formula b) => F.Seq(Par(a), Implies, Sp, Par(b));
    private static Formula MinusOf(Formula a, Formula b) => F.Seq(Par(a), Minus, Par(b));
    private static Formula Ands(params Formula[] terms)
    {
        Formula f = terms[0];
        for (int i = 1; i < terms.Length; i++) f = F.Seq(f, Land, Sp, Par(terms[i]));
        return f;
    }
    private static Formula Visible() => F.Seq(F.Id("Int"), To, Sp, F.Id("Bool"));
    private static Formula AE(Formula p, Formula body) => Call("AE", p, Lam("z", Visible(), body));
    private static Formula RecordFormula()
    {
        var k=F.Id("k"); var n=F.Id("n"); var z=F.Id("z");
        return All("k", F.Id("Nat"), All("n", F.Id("Nat"),
            Rel(Call("recordField", k, n), Eq, Call("generatedField",
                Lam("z", Visible(), Call("pair", Call("leftWord", k, z), Call("rightWord", n, z)))))));
    }
    private static Formula BoundsFormula()
    {
        var p=F.Id("P"); var y=F.Id("Y"); var j=F.Id("j");
        var k=F.Id("k"); var n=F.Id("n"); var z=F.Id("z");
        var bl=F.Id("BL"); var br=F.Id("BR"); var nat=F.Id("Nat");
        var vr=F.Seq(Par(Visible()), To, Sp, F.Id("Real"));
        Formula CE(Formula field) => Call("condExp", p, y, field, z);
        Formula Diff(Formula a, Formula b, Formula bound) =>
            Rel(Call("abs", MinusOf(CE(a), CE(b))), Le, Call("apply", bound, z));
        var field=Call("recordField", k, n);
        var hl=All("k", nat, All("n", nat, Imp(Rel(j, Le, k),
            AE(p, Diff(field, Call("recordField", j, n), bl)))));
        var hr=All("k", nat, All("n", nat, Imp(Rel(j, Le, n),
            AE(p, Diff(field, Call("recordField", k, j), br)))));
        var result=Ands(
            AE(p, Diff(Call("generatedField", F.Id("exterior")),
                Call("generatedField", Call("leftObservation", j)), bl)),
            AE(p, Diff(Call("generatedField", F.Id("exterior")),
                Call("generatedField", Call("rightObservation", j)), br)));
        return All("P", Call("Measure", Visible()), F.Seq(
            OpenBracket, Call("IsProbabilityMeasure", p), CloseBracket,
            All("Y", vr, All("j", nat, All("BL", vr, All("BR", vr,
                Imp(hl, Imp(hr, result))))))));
    }

