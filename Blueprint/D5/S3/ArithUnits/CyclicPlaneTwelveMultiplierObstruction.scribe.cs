using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.ArithUnits;

internal sealed class CyclicPlaneTwelveMultiplierObstructionDocument
    : IScribeDocumentDefinition
{
    private const string Prefix =
        "D5/S3/ArithUnits/CyclicPlaneTwelveMultiplierObstruction.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Doubling orbits obstruct a thirteen-element affine multiplier relation modulo 157.",
        H("The Multiplier-Two Obstruction Modulo 157"),
        Blocks(
            Theorem(
                "affine-multiplier-conjugacy",
                "affine_multiplier_conjugacy",
                "Affine fixed-point translation gives multiplier invariance",
                AffineConjugacyFormula(),
                "Let D be a finite subset of a commutative ring. If multiplication by m "
                    + "takes D to its translate by shift and center is a fixed point of the "
                    + "associated affine map, translating D by negative center converts the "
                    + "relation into invariance under multiplication by m."),
            Theorem(
                "prime-modulus-nonzero-orbit-divisibility",
                "orderOf_dvd_card_erase_zero_of_image_mul_eq",
                "Nonzero multiplier orbits divide the invariant-set cardinality",
                OrbitDivisibilityFormula(),
                "For a prime modulus, the cyclic subgroup generated by a unit acts freely on "
                    + "the nonzero part of every invariant finite set. The orbit quotient times "
                    + "the cyclic subgroup is therefore equivalent to that nonzero part, so the "
                    + "unit order divides its cardinality."),
            Theorem(
                "order-of-two-modulo-157",
                "orderOf_two_zmod157",
                "Two has multiplicative order 52 modulo 157",
                OrderTwo157Formula(),
                "Kernel-checked modular powers establish exponent 52 and exclude the proper "
                    + "prime-divisor exponents required by the finite-order criterion."),
            Theorem(
                "doubling-invariant-cardinality-residue",
                "card_of_invariant_under_mul_two",
                "Doubling-invariant cardinalities have residue zero or one",
                InvariantCardinalityFormula(),
                "The nonzero part has cardinality divisible by 52. Splitting on whether zero is "
                    + "present leaves exactly the residues zero and one for the full set."),
            Theorem(
                "multiplier-two-obstruction",
                "multiplier_two_obstruction",
                "No thirteen-element affine multiplier relation exists modulo 157",
                ObstructionFormula(),
                "Translation by negative g conjugates a supposed affine relation to pure "
                    + "doubling invariance without changing cardinality. The resulting set would "
                    + "have cardinality 13, contradicting the zero-or-one residue theorem modulo 52."),
            Theorem(
                "thirteen-residues-nonvacuity-witness",
                "thirteenResidues_witness",
                "The explicit thirteen-residue set has a nontrivial doubling inequality",
                ThirteenResiduesFormula(),
                "The explicit residues from zero through twelve form a thirteen-element finite "
                    + "set modulo 157, and a kernel computation shows that its doubling image is "
                    + "not its zero translate. Both clauses are retained in one theorem."),
            Theorem(
                "modulo-seven-sharpness-witness",
                "doublingOrbitSeven_witness",
                "A three-element doubling orbit exists modulo seven",
                DoublingOrbitSevenFormula(),
                "Modulo seven, two has order three and the explicit set containing one, two, and "
                    + "four has cardinality three and is invariant under doubling. All three "
                    + "clauses are retained in one theorem."),
            Paragraph(Text(
                "This module proves only the multiplier-two orbit obstruction for a hypothetical "
                    + "cyclic (157,13,1) difference set. It does not formalize the First Multiplier "
                    + "Theorem bridge, the Singer correspondence, or nonexistence of an arbitrary "
                    + "projective plane of order twelve.")))));

    private static DocumentBlock.Describe Theorem(
        string id, string declaration, string heading, Formula formula, string paragraph) =>
        Describe.Lean(
            DescribeId.Create(id),
            DeclarationHandle.Create(Prefix + declaration),
            H(heading),
            StatementSource.FromAuthor(Disp(formula)),
            AssessedProvenance.FromRepo(),
            Blocks(Paragraph(Text(paragraph))),
            DescribeRole.Theorem);

    private static Formula AffineConjugacyFormula()
    {
        Formula r = F.Id("R");
        Formula d = F.Id("D");
        Formula m = F.Id("m");
        Formula shift = F.Id("shift");
        Formula center = F.Id("center");
        Formula assumptions = And(
            And(Call("CommRing", r), Call("DecidableEq", r)),
            And(
                Equal(Multiply(m, center), Add(center, shift)),
                Equal(ImageMul(d, m), ImageAdd(d, shift))));
        Formula conclusion = Equal(ImageMul(ImageSub(d, center), m), ImageSub(d, center));
        return ForAll(
            [Bound("R", F.Id("Type")), Bound("D", Finset(r)), Bound("m", r),
                Bound("shift", r), Bound("center", r)],
            Implies(assumptions, conclusion));
    }

    private static Formula OrbitDivisibilityFormula()
    {
        Formula p = F.Id("p");
        Formula u = F.Id("u");
        Formula s = F.Id("S");
        Formula zp = ZMod(p);
        Formula assumptions = And(
            Call("Prime", p),
            Equal(ImageMul(s, Call("coe", u)), s));
        Formula conclusion = Relation(
            Call("orderOf", u),
            FormulaRelationOperator.Divides,
            Card(Call("eraseZero", s)));
        return ForAll(
            [Bound("p", Naturals()), Bound("u", Call("Units", zp)), Bound("S", Finset(zp))],
            Implies(assumptions, conclusion));
    }

    private static Formula OrderTwo157Formula() =>
        Equal(Call("orderOf", Typed(Num(2), ZMod(Num(157)))), Num(52));

    private static Formula InvariantCardinalityFormula()
    {
        Formula s = F.Id("S");
        Formula invariant = Equal(ImageMul(s, Num(2)), s);
        Formula residue = Relation(
            new Formula.Modulo(Card(s), Num(52)),
            FormulaRelationOperator.MemberOf,
            new Formula.SetLiteral([Num(0), Num(1)]));
        return ForAll([Bound("S", Finset(ZMod(Num(157))))], Implies(invariant, residue));
    }

    private static Formula ObstructionFormula()
    {
        Formula d = F.Id("D");
        Formula g = F.Id("g");
        Formula conclusion = NotEqual(ImageMul(d, Num(2)), ImageAdd(d, g));
        return ForAll(
            [Bound("D", Finset(ZMod(Num(157)))), Bound("g", ZMod(Num(157)))],
            Implies(Equal(Card(d), Num(13)), conclusion));
    }

    private static Formula ThirteenResiduesFormula()
    {
        Formula residues = F.Id("thirteenResidues");
        return And(
            Equal(Card(residues), Num(13)),
            NotEqual(ImageMul(residues, Num(2)), ImageAdd(residues, Num(0))));
    }

    private static Formula DoublingOrbitSevenFormula()
    {
        Formula orbit = F.Id("doublingOrbitSeven");
        return And(
            Equal(Call("orderOf", Typed(Num(2), ZMod(Num(7)))), Num(3)),
            And(
                Equal(Card(orbit), Num(3)),
                Equal(ImageMul(orbit, Num(2)), orbit)));
    }

    private static Formula Call(string name, params Formula[] arguments) =>
        new Formula.Apply(F.Id(name), [.. arguments]);

    private static Formula.BoundVariable Bound(string name, Formula domain) =>
        new(FormulaIdentifier.Create(name), domain);

    private static Formula ForAll(Formula.BoundVariable[] variables, Formula body) =>
        new Formula.BindMany(FormulaQuantifier.ForAll, [.. variables], body);

    private static Formula Relation(
        Formula left, FormulaRelationOperator relation, Formula right) =>
        new Formula.Relation(left, relation, right);

    private static Formula Equal(Formula left, Formula right) =>
        Relation(left, FormulaRelationOperator.Equal, right);

    private static Formula NotEqual(Formula left, Formula right) =>
        Relation(left, FormulaRelationOperator.NotEqual, right);

    private static Formula And(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.And, right);

    private static Formula Implies(Formula left, Formula right) =>
        new Formula.Logic(left, FormulaLogicOperator.Implies, right);

    private static Formula Add(Formula left, Formula right) =>
        new Formula.Binary(left, FormulaBinaryOperator.Add, right);

    private static Formula Multiply(Formula left, Formula right) =>
        new Formula.Binary(left, FormulaBinaryOperator.Multiply, right);

    private static Formula Typed(Formula value, Formula type) =>
        Seq(value, Colon, Sp, type);

    private static Formula Naturals() => Seq(Mathbb, Grp(F.Id("N")));
    private static Formula ZMod(Formula modulus) => Call("ZMod", modulus);
    private static Formula Finset(Formula type) => Call("Finset", type);
    private static Formula Card(Formula set) => Call("card", set);
    private static Formula ImageMul(Formula set, Formula multiplier) =>
        Call("imageMul", set, multiplier);
    private static Formula ImageAdd(Formula set, Formula shift) =>
        Call("imageAdd", set, shift);
    private static Formula ImageSub(Formula set, Formula center) =>
        Call("imageSub", set, center);
}
