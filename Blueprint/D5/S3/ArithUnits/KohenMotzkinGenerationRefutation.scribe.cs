using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.ArithUnits;

internal sealed class KohenMotzkinGenerationRefutationDocument : IScribeDocumentDefinition
{
    private const string Prefix = "D5/S3/ArithUnits/KohenMotzkinGenerationRefutation.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "The unrestricted generalized central trinomial residue generation conjecture fails at p=3, a=3, b=1.",
        H("An identity-only residue set in Kohen's Conjecture 1"),
        Blocks(
            Paragraph(Text(
                "Nadav Kohen, Density and Symmetry in the Generalized Motzkin Numbers mod p, "
                + "arXiv:2411.03681v2, Conjecture 1, asks whether the first p generalized central "
                + "trinomial coefficients generate the multiplicative group of the prime field "
                + "whenever none is divisible by p. The conjecture quantifies over all integer "
                + "parameters a and b. Its defining constant term is taken in the integer Laurent "
                + "polynomial ring. The source is https://arxiv.org/html/2411.03681v2.")),
            Node("step", "The defining Laurent polynomial",
                "The integer parameters a and b give the Laurent polynomial aX^(-1)+b+aX. "
                + "LaurentPolynomial.C includes an integer as a constant, while LaurentPolynomial.T "
                + "takes an integer exponent, so the negative exponent is literal. No restriction "
                + "on either parameter is imposed."),
            Node("central", "Integer constant terms",
                "For every natural index n, central(a,b,n) is the coefficient of exponent zero "
                + "in step(a,b)^n. This is the source's generalized central trinomial coefficient, "
                + "computed as an integer before taking any residue. The generalized Motzkin "
                + "coefficients are a different sequence and are not substituted here."),
            Node("generators", "The first p residues in the unit group",
                "A unit u belongs to generators(p,a,b) exactly when its underlying residue is "
                + "central(a,b,n) modulo p for some natural n<p. The indices 0 through p-1 "
                + "are the canonical representatives of the source's indices in the prime field. "
                + "Under the nondivisibility premise every such residue is nonzero and hence "
                + "a unit. This set therefore retains all the source generators."),
            Node("claim", "The complete unrestricted generation assertion",
                "For every natural prime p and every pair of integers a,b, assume that p "
                + "divides none of central(a,b,n) for 0<=n<p. The conclusion says that the "
                + "subgroup generated by their residues is the whole multiplicative unit group "
                + "of ZMod p. Subgroup.closure includes the identity, inverses and arbitrary "
                + "finite products. The premise adds no condition that p does not divide a or b. "
                + "This is the generating assertion of Conjecture 1; the subsequent statements "
                + "introduced as equivalent or consequent in the source do not replace it."),
            Node("result", "The assertion is false",
                "Specialize the universal assertion to p=3, a=3 and b=1. Extracting the "
                + "constant terms of the zeroth, first and second powers gives 1, 1 and "
                + "1+2*3^2=19. These are all the indices less than three, and none of the "
                + "three integers is divisible by three. Their residues are all one. Thus "
                + "every generator belongs to the identity subgroup, and the least-subgroup "
                + "property of Subgroup.closure places the whole generated subgroup there. "
                + "The residue two is an actual unit modulo three and differs from one. "
                + "It belongs to the whole unit group but cannot belong to the generated "
                + "subgroup, contradicting the asserted equality. The coefficient extraction "
                + "uses distributivity and exact integer arithmetic; the subgroup obstruction "
                + "uses the group closure law. The proof refutes the unrestricted assertion. "
                + "A variant imposing that p does not divide a is a different assertion "
                + "and is not settled here.", DescribeRole.Theorem))));

    private static DocumentBlock Node(string selector, string title, string prose,
        DescribeRole role = DescribeRole.Definition) =>
        Describe.Lean(DescribeId.Create("kohen-" + selector),
            DeclarationHandle.Create(Prefix + selector), H(title),
            StatementSource.FromAuthor(Disp(Statement(selector))), AssessedProvenance.FromRepo(),
            Blocks(Paragraph(Text(prose))), role);

    private static Formula Statement(string selector)
    {
        var p = F.Id("p"); var a = F.Id("a"); var b = F.Id("b");
        var n = F.Id("n"); var u = F.Id("u");
        var z = Seq(Mathbb, Grp(F.Id("Z")));
        var naturals = Seq(Mathbb, Grp(F.Id("N")));
        var field = Call("ZMod", p);
        var term = Call("central", a, b, n);
        var generatingSet = Call("generators", p, a, b);
        Formula Parameters(Formula body) => All("a", z, All("b", z, body));
        var notDivisible = new Formula.Not(Parenthesized(new Formula.Relation(
            Cast(p, z), FormulaRelationOperator.Divides, term)));
        var assertion = All("p", naturals, Imp(Call("Nat.Prime", p), Parameters(
            Imp(All("n", naturals, Imp(Lt(n, p), notDivisible)),
                Eq(Call("Subgroup.closure", generatingSet), Seq(Operatorname, Grp(F.Id("top"))))))));
        return selector switch
        {
            "step" => Parameters(Eq(Call("step", a, b),
                Add(Add(Mul(Call("LaurentPolynomial.C", a),
                    Call("LaurentPolynomial.T", new Formula.Negate(D(1)))),
                    Call("LaurentPolynomial.C", b)),
                    Mul(Call("LaurentPolynomial.C", a), Call("LaurentPolynomial.T", D(1)))))),
            "central" => Parameters(All("n", naturals, Eq(term,
                Call("coeff", new Formula.Power(Call("step", a, b), n), D(0))))),
            "generators" => All("p", naturals, Parameters(All("u", Call("Units", field),
                Iff(new Formula.Relation(u, FormulaRelationOperator.MemberOf, generatingSet),
                    Exists("n", naturals, And(Lt(n, p), Eq(Cast(u, field), Cast(term, field)))))))),
            "claim" => Iff(F.Id("claim"), assertion),
            "result" => new Formula.Not(F.Id("claim")),
            _ => throw new ArgumentException("Unknown Kohen declaration selector.", nameof(selector))
        };
    }

    private static Formula D(byte n) => new Formula.Number(n);
    private static Formula Call(string name, params Formula[] args)
    {
        var parts = name.Split('.');
        Formula head = F.Id(parts[0]);
        for (var i = 1; i < parts.Length; i++)
            head = Seq(head, Dot, F.Id(parts[i]));
        return new Formula.Apply(head, [.. args]);
    }
    private static Formula Cast(Formula term, Formula type) =>
        Seq(Open, term, Sp, Colon, Sp, type, Close);
    private static Formula All(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.ForAll, FormulaIdentifier.Create(name), type, body);
    private static Formula Exists(string name, Formula type, Formula body) =>
        new Formula.Bind(FormulaQuantifier.Exists, FormulaIdentifier.Create(name), type, body);
    private static Formula Eq(Formula a, Formula b) =>
        new Formula.Relation(a, FormulaRelationOperator.Equal, b);
    private static Formula Lt(Formula a, Formula b) =>
        new Formula.Relation(a, FormulaRelationOperator.LessThan, b);
    private static Formula Imp(Formula a, Formula b) =>
        new Formula.Logic(a, FormulaLogicOperator.Implies, b);
    private static Formula Iff(Formula a, Formula b) =>
        new Formula.Logic(a, FormulaLogicOperator.Iff, b);
    private static Formula And(Formula a, Formula b) =>
        new Formula.Logic(a, FormulaLogicOperator.And, b);
    private static Formula Add(Formula a, Formula b) =>
        new Formula.Binary(a, FormulaBinaryOperator.Add, b);
    private static Formula Mul(Formula a, Formula b) =>
        new Formula.Binary(a, FormulaBinaryOperator.Multiply, b);
}
