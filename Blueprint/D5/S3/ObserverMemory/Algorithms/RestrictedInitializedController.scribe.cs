    private static Formula V(string name) => F.Id(name);
    private static Formula P(Formula body) => Seq(Open, body, Close);
    private static Formula C(string name, params Formula[] args)
    {
        var items = new List<Formula> { Operatorname, Sp, Grp(V(name)), Open };
        for (var i = 0; i < args.Length; i++)
        {
            if (i > 0) items.Add(Comma);
            items.Add(args[i]);
        }
        items.Add(Close);
        return Seq([.. items]);
    }
    private static Formula A(params Formula[] clauses)
    {
        var items = new List<Formula>();
        foreach (var clause in clauses)
        {
            if (items.Count > 0) items.Add(Land);
            items.Add(P(clause));
        }
        return Seq([.. items]);
    }
    private static Formula All(string name, Formula type, Formula body) =>
        Seq(Forall, Sp, V(name), Colon, type, Comma, P(body));
    private static Formula Ex(string name, Formula type, Formula body) =>
        Seq(Exists, Sp, V(name), Colon, type, Comma, P(body));
    private static Formula Imp(Formula premise, Formula body) =>
        Seq(P(premise), Implies, Sp, P(body));
    private static Formula E(Formula left, Formula right) => Seq(left, Eq, right);
    private static Formula NE(Formula left, Formula right) => Seq(left, Neq, Sp, right);
    private static Formula LE(Formula left, Formula right) => Seq(left, Le, Sp, right);
    private static Formula LT(Formula left, Formula right) => Seq(left, Lt, right);
    private static Formula Pair(Formula left, Formula right) => Seq(Open, left, Comma, right, Close);
    private static Formula Arr(Formula left, Formula right) => Seq(P(left), To, Sp, P(right));
    private static Formula Pow(Formula left, Formula right) => Seq(left, Caret, Grp(right));
    private static Formula Ty(string level) => Seq(V("Type"), Underscore, Grp(level == "zero" ? D(0) : V(level)));
    private static Formula N => Seq(Mathbb, Sp, Grp(V("N")));
    private static Formula Bit => C("ZMod", D(2));
    private static Formula Bool => C("Bool");
    private static Formula List(Formula type) => C("List", type);

    private static Formula Context(Formula body)
    {
        Formula d = V("d"), a = V("A"), b = V("B");
        return All("d", N, All("A", C("Submodule", Bit, C("Source", d)),
            All("B", C("Submodule", Bit, C("Source", d)), All("h", C("IsCompl", a, b), body))));
    }
    private static Formula LocalA => C("Local", V("A"), V("B"));
    private static Formula LocalB => C("Local", V("B"), V("A"));
    private static Formula Star => C("Cstar", V("h"));
    private static Formula RankA => C("finrank", Bit, V("A"));
    private static Formula RankB => C("finrank", Bit, V("B"));
    private static Formula Card(Formula type) => C("NatCard", type);
    private static Formula Log2(Formula n) => C("log2", n);
    private static Formula Width(Formula n) => C("clog", D(2), n);
    private static Formula Ceiling(Formula n) => C("natCeil", Log2(n));
    private static Formula Embed(Formula n, Formula target) =>
        C("Nonempty", C("Embedding", C("Fin", n), target));
    private static Formula Fiber(Formula carrier, Formula readout, Formula a) =>
        Seq(OpenBrace, V("m"), Colon, carrier, Mid, Sp, E(C("apply", readout, V("m")), a), CloseBrace);
    private static Formula FA(Formula a) => Fiber(LocalA, C("localRead"), a);
    private static Formula FB(Formula b) => Fiber(LocalB, C("localRead"), b);
    private static Formula FiberSize(Formula other) =>
        Seq(D(1), Plus, Pow(D(2), C("finrank", Bit, C("range", C("ell", other)))));

    private static Formula LocalFormula()
    {
        Formula a = V("A"), b = V("B"), h = V("h"), x = V("a"), q = V("q");
        Formula known = Seq(OpenBrace, Pair(x, q), Colon, C("Prod", a, Bit), Mid, Sp, Ex("b", b, E(q, Seq(C("apply", C("ell", a), x), Plus,
                C("apply", C("ell", b), V("b"))))), CloseBrace);
        Formula z = V("z"), ea = C("pA", z), eb = C("pB", z), control = C("snd", z);
        Formula imageUnknown = Pair(C("inl", ea), C("inl", eb));
        Formula imageKnown = Pair(C("inr", Pair(ea, control)), C("inr", Pair(eb, control)));
        return Disp(Context(A(
            E(C("pA"), C("projectionOnto", a, b, h)),
            E(C("pB"), C("projectionOnto", b, a, C("symm", h))),
            E(C("Known", a, b), known), E(LocalA, C("Sum", a, C("Known", a, b))),
            All("a", a, E(C("localRead", C("inl", x)), x)),
            All("a", a, E(C("localMode", C("inl", x)), C("false"))),
            All("a", a, E(C("localControl", C("inl", x)), D(0))),
            All("aq", C("Known", a, b), A(
                E(C("localRead", C("inr", V("aq"))), C("fst", C("val", V("aq")))),
                E(C("localMode", C("inr", V("aq"))), C("true")),
                E(C("localControl", C("inr", V("aq"))), C("snd", C("val", V("aq")))))),
            All("z", C("Source", V("d")), A(
                E(C("encode", h, C("false"), z), imageUnknown),
                E(C("encode", h, C("true"), z), imageKnown))))));
    }

    private static Formula ImplementationFormula()
    {
        Formula h = V("h"), d = V("d"), f = V("f"), k = V("k"), z = V("z");
        Formula data = C("data", h), word = V("word"), i = V("i");
        Formula alpha = C("pA", Pair(C("single", i, D(1)), D(0)));
        Formula beta = C("pB", Pair(C("single", i, D(1)), D(0)));
        Formula p = C("endpointProtocol", h, C("rewrite", i), k);
        Formula old = C("rewriteProtocol", C("ell", V("A")), C("ell", V("B")), alpha, beta);
        Formula leftScalar = C("if", k, C("localControl", V("a")),
            C("if", E(alpha, D(0)), D(0), Seq(C("apply", C("ell", V("A")),
            C("localRead", V("a"))), Plus, C("if", E(C("ell", V("B")), D(0)), D(0),
            C("if", C("getD", C("get", V("t"), D(0)), C("false")), D(1), D(0))))));
        Formula offset = C("if", A(NE(alpha, D(0)), NE(C("ell", V("B")), D(0))), D(1), D(0));
        Formula rightScalar = C("if", k, C("localControl", V("b")),
            C("if", E(beta, D(0)), D(0), Seq(C("apply", C("ell", V("B")),
            C("localRead", V("b"))), Plus, C("if", E(C("ell", V("A")), D(0)), D(0),
            C("if", C("getD", C("get", V("t"), offset), C("false")), D(1), D(0))))));
        Formula rewrite = All("i", C("Fin", d), All("k", Bool, A(
            All("t", List(Bool), E(C("node", p, V("t")),
                C("if", k, C("inr", C("unit")), C("mapQuestion", C("liftQuestion"),
                    C("node", old, V("t")))))),
            All("a", LocalA, All("t", List(Bool), E(C("outA", p, V("a"), V("t")),
                C("resetLocal", h, i, leftScalar)))),
            All("b", LocalB, All("t", List(Bool), E(C("outB", p, V("b"), V("t")),
                C("resetLocal", C("symm", h), i, rightScalar)))))));
        Formula localTranslation = All("t", C("Source", d), A(
            All("a", V("A"), E(C("translateLocal", h, V("t"), C("inl", V("a"))),
                C("inl", Seq(V("a"), Plus, C("pA", V("t")))))),
            All("aq", C("Known", V("A"), V("B")),
                E(C("translateLocal", h, V("t"), C("inr", V("aq"))),
                    C("inr", Pair(Seq(C("fst", C("val", V("aq"))), Plus, C("pA", V("t"))),
                        Seq(C("snd", C("val", V("aq"))), Plus, C("snd", V("t")))))))));
        Formula translationAction = All("f", C("Action", d), All("k", Bool,
            All("t", C("Source", d), Imp(Seq(P(E(f, C("controlTranslation"))), Lor, Sp, P(Ex("i", C("Fin", d), E(f, C("dataTranslation", i))))),
            Imp(E(V("t"), C("apply", f, D(0))), A(
                All("bits", List(Bool), E(C("node", C("endpointProtocol", h, f, k), V("bits")),
                    C("inr", C("unit")))),
                All("a", LocalA, All("bits", List(Bool),
                    E(C("outA", C("endpointProtocol", h, f, k), V("a"), V("bits")),
                        C("translateLocal", h, V("t"), V("a"))))),
                All("b", LocalB, All("bits", List(Bool),
                    E(C("outB", C("endpointProtocol", h, f, k), V("b"), V("bits")),
                        C("translateLocal", C("symm", h), V("t"), V("b")))))))))));
        Formula charges = All("k", Bool, A(
            All("i", C("Fin", d), E(C("nextMode", k, C("rewrite", i)), C("true"))),
            All("i", C("Fin", d), E(C("protocolCharge", h, k, C("rewrite", i)),
                C("if", k, D(0), C("splitCost", h, i)))),
            All("f", C("Action", d), Imp(C("IsTranslation", f), A(
                E(C("nextMode", k, f), k), E(C("protocolCharge", h, k, f), D(0)))))));
        Formula first = A(E(C("firstRewriteCost", h, C("nil")), D(0)),
            All("i", C("Fin", d), All("word", List(C("Action", d)),
                E(C("firstRewriteCost", h, C("cons", C("rewrite", i), word)), C("splitCost", h, i)))),
            All("f", C("Action", d), All("word", List(C("Action", d)),
                Imp(C("IsTranslation", f), E(C("firstRewriteCost", h, C("cons", f, word)),
                    C("firstRewriteCost", h, word))))));
        return Disp(Context(A(
            E(C("readA", data), C("localRead")), E(C("readB", data), C("localRead")),
            E(C("initA", data), C("inl")), E(C("initB", data), C("inl")),
            All("f", C("Action", d), A(
                E(C("rootA", data, f), C("localMode")), E(C("rootB", data, f), C("localMode")),
                E(C("protocol", data, f), C("endpointProtocol", h, f)))),
            All("i", C("Fin", d), All("q", Bit,
                E(C("resetLocal", h, i, V("q")),
                    C("inr", Pair(C("pA", Pair(C("single", i, V("q")), D(0))), D(0)))))),
            localTranslation, translationAction, rewrite, charges, first,
            All("word", List(C("Action", d)), Seq(C("TranslationWord", word), Iff, Sp, P(All("f", C("Action", d), Imp(C("mem", f, word), C("IsTranslation", f)))))))));
    }

    private static Formula ResultFormula()
    {
        Formula d = V("d"), h = V("h"), c = V("C"), m = V("m"), k = V("k"), z = V("z");
        Formula f = V("f"), t = V("t"), i = V("i"), word = V("word");
        Formula source = C("Source", d), actions = C("Action", d), words = List(actions);
        Formula data = C("data", h), image = C("encode", h, k, z);
        Formula pair = C("Prod", LocalA, LocalB);
        Formula support = All("m", pair, Seq(C("Reachable", data, m), Iff, Sp, P(Ex("k", Bool, Ex("z", source, E(m, image))))));
        Formula execution = All("k", Bool, All("z", source, All("f", actions,
            All("t", C("Trace", LocalA, LocalB), Imp(C("Exec", data, f, image, t), A(
                E(C("commit", data, f, image, t),
                    C("encode", h, C("nextMode", k, f), C("apply", f, z))),
                E(C("length", t), C("protocolCharge", h, k, f))))))));
        Formula knownReach = All("z", source, Ex("i", C("Fin", d), Ex("word", words, A(
            C("TranslationWord", word),
            E(C("val", C("runWord", C("step", c), C("cons", C("rewrite", i), word),
                C("initial", c, D(0), D(0)))), C("encode", h, C("true"), z))))));
        Formula initial = C("initial", c, C("pA", z), C("pB", z));
        Formula allWords = All("z", source, All("word", words, A(
            E(C("readout", c, C("runWord", C("step", c), word, initial)),
                C("runWord", C("ActionApply"), word, z)),
            E(C("Comm", C("step", c), C("cost", c), initial, word), C("firstRewriteCost", h, word)))));
        Formula budgets = Seq(OpenBrace, V("K"), Colon, N, Mid, Sp, Ex("MA", Ty("zero"), Ex("MB", Ty("zero"), Ex("Root", Ty("zero"),
                Ex("Cprime", C("Controller", h, V("MA"), V("MB"), V("Root")),
                    C("UniformCumulativeBudget", V("Cprime"), V("K")))))), CloseBrace);
        Formula result = Ex("C", C("Controller", h, LocalA, LocalB, Bool), A(
            E(C("toControllerData", c), data), support, execution, knownReach, allWords,
            C("UniformCumulativeBudget", c, Star),
            All("a", V("A"), E(Card(FA(V("a"))), FiberSize(V("B")))),
            All("b", V("B"), E(Card(FB(V("b"))), FiberSize(V("A")))),
            E(Card(LocalA), Seq(P(FiberSize(V("B"))), Times, Sp, Pow(D(2), RankA))),
            E(Card(LocalB), Seq(P(FiberSize(V("A"))), Times, Sp, Pow(D(2), RankB))),
            C("Finite", C("State", c)), E(Card(C("State", c)), Pow(D(2), Seq(d, Plus, D(2)))),
            C("IsLeast", budgets, Star), C("StorageOptimal", c)));
        return Disp(Context(Imp(A(LE(D(2), d), LT(D(0), RankA), LT(D(0), RankB)), result)));
    }

    private static Formula UniversalStorageFormula()
    {
        Formula c = V("C"), cp = V("Cprime"), ma = V("MA"), mb = V("MB"), h = V("h");
        Formula nA = Card(LocalA), nB = Card(LocalB), nQ = Card(C("State", c));
        Formula ka = V("kA"), kb = V("kB"), k = V("k"), budget = V("K");
        Formula fibers = A(
            All("a", V("A"), Embed(Card(FA(V("a"))),
                Fiber(ma, C("readA", cp), V("a")))),
            All("b", V("B"), Embed(Card(FB(V("b"))),
                Fiber(mb, C("readB", cp), V("b")))),
            Embed(nA, ma), Embed(nB, mb), Embed(nQ, C("State", cp)));
        Formula finiteLogs = Imp(C("Finite", ma), Imp(C("Finite", mb), A(
            LE(Seq(Log2(nA), Plus, Log2(nB)), Seq(Log2(Card(ma)), Plus, Log2(Card(mb)))),
            LE(Seq(Ceiling(nA), Plus, Ceiling(nB)),
                Seq(Ceiling(Card(ma)), Plus, Ceiling(Card(mb)))))));
        Formula endpoints = All("kA", N, All("kB", N,
            Imp(C("BinaryEncoding", ma, ka), Imp(C("BinaryEncoding", mb, kb),
                A(LE(Width(nA), ka), LE(Width(nB), kb))))));
        Formula joint = All("k", N, Imp(C("BinaryEncoding", C("State", cp), k),
            LE(Seq(V("d"), Plus, D(2)), k)));
        Formula universal = All("MA", Ty("u"), All("MB", Ty("v"), All("Root", Ty("w"),
            All("Cprime", C("Controller", h, ma, mb, V("Root")), All("K", N,
            Imp(C("UniformCumulativeBudget", cp, budget),
                A(fibers, finiteLogs, endpoints, joint, LE(Star, budget))))))));
        Formula encodings(Formula carrier) => Seq(OpenBrace, k, Colon, N, Mid, Sp, C("BinaryEncoding", carrier, k), CloseBrace);
        Formula rows = A(
            Imp(E(C("ell", V("A")), D(0)), Imp(NE(C("ell", V("B")), D(0)),
                C("StorageRow", h, D(3), D(2), D(2), D(1), D(6), D(4), D(1)))),
            Imp(E(C("ell", V("B")), D(0)), Imp(NE(C("ell", V("A")), D(0)),
                C("StorageRow", h, D(2), D(3), D(1), D(2), D(6), D(4), D(1)))),
            Imp(NE(C("ell", V("A")), D(0)), Imp(NE(C("ell", V("B")), D(0)),
                C("StorageRow", h, D(3), D(3), D(2), D(2), D(9), D(5), D(2)))));
        Formula body = A(C("IsLeast", encodings(LocalA), Width(nA)),
            C("IsLeast", encodings(LocalB), Width(nB)),
            C("IsLeast", encodings(C("State", c)), Seq(V("d"), Plus, D(2))),
            E(Log2(nQ), Seq(V("d"), Plus, D(2))), universal,
            E(Seq(RankA, Plus, RankB), Seq(V("d"), Plus, D(1))),
            Seq(P(NE(C("ell", V("A")), D(0))), Lor, Sp, P(NE(C("ell", V("B")), D(0)))), rows);
        return Disp(Context(All("C", C("Controller", h, LocalA, LocalB, Bool),
            Seq(C("StorageOptimal", c), Iff, Sp, P(body)))));
    }

