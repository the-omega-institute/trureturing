        Formula r = RankA, s = RankB;
        Formula body = A(
            All("a", V("A"), E(Card(FA(V("a"))), fA)),
            All("b", V("B"), E(Card(FB(V("b"))), fB)),
            E(nA, Seq(fA, Times, Sp, Pow(D(2), r))), E(nB, Seq(fB, Times, Sp, Pow(D(2), s))),
            E(Seq(Log2(nA), Plus, Log2(nB)), Seq(V("d"), Plus, D(1), Plus, Log2(factor))),
            E(Width(nA), Seq(r, Plus, tA)), E(Width(nB), Seq(s, Plus, tB)),
            E(Ceiling(nA), Seq(r, Plus, tA)), E(Ceiling(nB), Seq(s, Plus, tB)),
            E(Seq(Ceiling(nA), Plus, Ceiling(nB)), Seq(V("d"), Plus, overhead)), E(Star, budget));
        return Disp(Context(All("fA", N, All("fB", N, All("tA", N, All("tB", N,
            All("factor", N, All("overhead", N, All("budget", N, Seq(row, Iff, Sp, P(body)))))))))));
    }

    private static Formula StorageRowsFormula()
    {
        Formula ea = C("ell", V("A")), eb = C("ell", V("B")), dim = V("D");
        Formula row(Formula condition, byte fa, byte fb, byte ta, byte tb, byte log, byte overhead, byte budget)
        {
            Formula nA = Card(LocalA), nB = Card(LocalB);
            return Imp(condition, A(
                C("StorageRow", V("h"), D(fa), D(fb), D(ta), D(tb), D(log), D(overhead), D(budget)),
                All("a", V("A"), E(Card(FA(V("a"))), D(fa))),
                All("b", V("B"), E(Card(FB(V("b"))), D(fb))),
                E(nA, Seq(D(fa), Times, Sp, Pow(D(2), RankA))),
                E(nB, Seq(D(fb), Times, Sp, Pow(D(2), RankB))),
                E(Seq(Log2(nA), Plus, Log2(nB)), Seq(dim, Plus, Log2(D(log)))),
                Seq(Ceiling(nA), Eq, Width(nA), Eq, RankA, Plus, D(ta)),
                Seq(Ceiling(nB), Eq, Width(nB), Eq, RankB, Plus, D(tb)),
                Seq(Ceiling(nA), Plus, Ceiling(nB), Eq, V("d"), Plus, D(overhead),
                    Eq, dim, Plus, D((byte)(overhead - 1))), E(Star, D(budget))));
        }
        return Disp(Context(All("D", N, Imp(E(dim, Seq(V("d"), Plus, D(1))),
            All("C", C("Controller", V("h"), LocalA, LocalB, Bool),
            Imp(C("StorageOptimal", V("C")), A(
                Seq(RankA, Plus, RankB, Eq, V("d"), Plus, D(1), Eq, dim),
                Seq(V("d"), Plus, D(2), Eq, dim, Plus, D(1)),
                Seq(V("d"), Plus, D(4), Eq, dim, Plus, D(3)),
                Seq(V("d"), Plus, D(5), Eq, dim, Plus, D(4)),
                row(A(E(ea, D(0)), NE(eb, D(0))), 3, 2, 2, 1, 6, 4, 1),
                row(A(E(eb, D(0)), NE(ea, D(0))), 2, 3, 1, 2, 6, 4, 1),
                row(A(NE(ea, D(0)), NE(eb, D(0))), 3, 3, 2, 2, 9, 5, 2))))))));
    }
