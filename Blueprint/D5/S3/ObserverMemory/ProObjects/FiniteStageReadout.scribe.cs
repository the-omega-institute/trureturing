using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.ObserverMemory.ProObjects;

internal sealed class FiniteStageReadoutDocument : IScribeDocumentDefinition
{
    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Every ordinary readout from a cofiltered stage system is represented by a map from one presentation stage.",
        H("Ordinary Readouts Have Single-Stage Representatives"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("every-ordinary-readout-has-a-finite-stage"),
                DeclarationHandle.Create(
                    "D5/S3/ObserverMemory/ProObjects/FiniteStageReadout."
                        + "every_ordinary_readout_has_finite_stage"),
                H("Every ordinary readout has a finite stage"),
                StatementSource.FromAuthor(StageFormula()),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "Let I be a small cofiltered category, let X : I -> C be a stage diagram, "
                            + "and let D be an ordinary target object. Stage readouts form a functor "
                            + "on the opposite index category: a refinement map transports a readout "
                            + "by precomposition. An ordinary readout is constructed as the standard "
                            + "colimit quotient of these stage hom-sets.")),
                    Paragraph(Text(
                        "Every element of that colimit quotient is represented by one pair consisting "
                            + "of an index i and a morphism X_i -> D. This is the formal content of "
                            + "needing one sufficiently refined presentation stage rather than a "
                            + "simultaneous compatible family of readouts at every stage.")),
                    Paragraph(Text(
                        "The public theorem states the generic categorical clause and, as separate "
                            + "conjuncts, the real- and complex-valued clauses for type-valued stage "
                            + "systems. No discreteness or finiteness condition is placed on the real "
                            + "or complex target; finite-stage refers to presentation through one "
                            + "stage, not to the target's cardinality.")),
                    Paragraph(Text(
                        "Pinned Mathlib has no matching pro-category API. Its concrete colimit type "
                            + "is the quotient of the disjoint union of component values by the "
                            + "relation generated by transition maps, and the exact theorem "
                            + "Functor.ιColimitType_jointly_surjective is applied directly to obtain "
                            + "the representative."))),
                DescribeRole.Theorem))));

    private static Formula Sub(Formula value, Formula index) =>
        new Formula.Subscript(value, index);

    private static Formula Hom(Formula source, Formula target) =>
        Seq(Operatorname, Grp(F.Id("Hom")), Open, source, Comma, Sp, target, Close);

    private static Formula RepresentativeLine(Formula target)
    {
        Formula i = F.Id("i");
        Formula x = F.Id("X");
        Formula q = F.Id("q");
        Formula qi = Sub(q, i);
        return Seq(
            Forall, Sp, q, Sp, InMacro, Sp,
            Operatorname, Grp(F.Id("colim")), Underscore, Grp(i), Sp,
            Hom(Sub(x, i), target), Comma, Sp,
            Exists, Sp, i, Comma, Sp, qi, Colon, Sp,
            Sub(x, i), Sp, To, Sp, target, Comma, Sp,
            OpenBracket, qi, CloseBracket, Sp, Eq, Sp, q);
    }

    private static Formula StageFormula() => Disp(Seq(
        Begin, Grp(F.Id("gathered")),
        RepresentativeLine(F.Id("D")), Comma, RowBreak,
        RepresentativeLine(Seq(Mathbb, Grp(F.Id("R")))), Comma, RowBreak,
        RepresentativeLine(Seq(Mathbb, Grp(F.Id("C")))), Dot,
        End, Grp(F.Id("gathered"))));
}
