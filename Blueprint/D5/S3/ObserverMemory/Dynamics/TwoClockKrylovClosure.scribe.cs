    private static Formula Call(string name, params Formula[] arguments)
    {
        var items = new List<Formula> { Operatorname, Grp(F.Id(name)), Open };
        for (var i = 0; i < arguments.Length; i++)
        {
            if (i > 0) items.AddRange([Comma, Sp]);
            items.Add(arguments[i]);
        }
        items.Add(Close);
        return Seq([.. items]);
    }

    private static Formula Statement()
    {
        Formula v = F.Id("V"), a = F.Id("a"), b = F.Id("b"),
            op = F.Id("A"), w = F.Id("w"), initial = F.Id("W"),
            k = F.Id("k"), l = F.Id("l"), real = F.Id("R");
        Formula first = Call("exp", Seq(a, Sp, op));
        Formula second = Call("exp", Seq(b, Sp, op));
        Formula mixed = Seq(Grp(first), Caret, Grp(k), Sp,
            Grp(second), Caret, Grp(l), Sp, w);
        Formula power = Seq(op, Caret, Grp(k), Sp, w);
        Formula mixedSet = Seq(OpenBrace, mixed, Sp, Mid, Sp,
            k, Comma, l, Sp, InMacro, Sp, F.Id("N"), Comma, Sp,
            w, Sp, InMacro, Sp, initial, CloseBrace);
        Formula powerSet = Seq(OpenBrace, power, Sp, Mid, Sp,
            k, Sp, InMacro, Sp, F.Id("N"), Comma, Sp,
            w, Sp, InMacro, Sp, initial, CloseBrace);
        return Disp(Seq(Begin, Grp(F.Id("gathered")),
            Forall, Sp, v, Comma, op, Comma, initial, Comma, a, Comma, b, Comma,
            RowBreak, Grp(),
            Call("NormedAddCommGroup", v), Sp, Land, Sp,
            Call("NormedSpace", real, v), Sp, Land, Sp,
            Call("FiniteDimensional", real, v), Sp, Land,
            RowBreak, Grp(),
            op, Sp, InMacro, Sp, Call("ContinuousLinearMap", real, v, v), Sp, Land, Sp,
            initial, Sp, InMacro, Sp, Call("Submodule", real, v), Sp, Land, Sp,
            a, Comma, b, Sp, InMacro, Sp, real, Sp, Land, Sp,
            Call("Irrational", Seq(Frac, Grp(a), Grp(b))), Sp, Rightarrow,
            RowBreak, Grp(),
            Call("span", real, mixedSet), Sp, Eq, Sp, Call("span", real, powerSet),
            End, Grp(F.Id("gathered"))));
    }
