using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.Weil.Mertens.IntegratedExplicit;

internal sealed class MangoldtWindowPhaseDocument : IScribeDocumentDefinition
{
    private const string Module = "D5/S3/Weil/Mertens/IntegratedExplicit/MangoldtWindowPhase.";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Recurrence of the normalized Mangoldt primitive and the first Li mass",
        H("Bounded gaps between positive peaks"),
        Blocks(
            Paragraph(Text("Let U(x) be the complete Mangoldt remainder and write G(y) = "
                + "exp(−y/2) U(exp y). Write M for the first Li mass, 2+γ−2 log(2√π). "
                + "The first result samples G at nonnegative integer logarithmic times. "
                + "The second tests the arithmetic remainder at all real points of a window.")),
            Describe.Lean(DescribeId.Create("bounded-gap-peak"),
                DeclarationHandle.Create(Module + "bounded_gap_actual_G_peak"),
                H("Returns to the first Li mass under RH"),
                StatementSource.FromAuthor(Peak()), AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text("The phases of the actual zeros give a single rotation g "
                    + "on a product of circles. Under RH its continuous coefficient sum takes "
                    + "the value M at the identity. The nonnegative powers of g accumulate "
                    + "at every point in the closed subgroup generated by g. For each group "
                    + "element h in that subgroup, some k takes hgᵏ into the chosen open "
                    + "neighborhood of the identity. Compactness supplies a finite subcover, "
                    + "so one upper bound on k works for every starting exponent n.")),
                    Paragraph(Text("The residual in the normalized explicit formula tends to zero. "
                        + "Give the phase sum and the residual half the tolerance each. "
                        + "Enlarging the gap bound by the initial cutoff includes n = 0."))),
                DescribeRole.Theorem),
            Describe.Lean(DescribeId.Create("subcritical-obstruction"),
                DeclarationHandle.Create(Module + "no_windows_below_mass"),
                H("A coefficient below the first Li mass excludes cofinal windows"),
                StatementSource.FromAuthor(Obstruction()), AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text("If whole windows admitted coefficient C < M, they "
                    + "would also admit the larger coefficient M+1. The square-root window "
                    + "criterion would imply RH. For tolerance M−C, the first result then "
                    + "places a positive peak at time j between log Y and b log Y for "
                    + "every sufficiently large Y. Indeed, round log Y up to n and allow "
                    + "the fixed number of additional steps. At x = exp j one has "
                    + "U(x) > C√x, which contradicts the assumed whole-window inequality.")),
                    Paragraph(Text("At C = M, the critical-gap theorem gives "
                        + "M√x − U(x) → +∞ under RH. Thus U(x) ≤ M√x on every sufficiently "
                        + "late window. Conversely, arbitrarily late windows with coefficient M "
                        + "also admit coefficient M+1, so the square-root window criterion gives RH."))),
                DescribeRole.Theorem)),
        [DocumentEdge.NarrativeReference.ToDocument(
            GidRef.Create("D5/S3/Weil/Mertens/IntegratedExplicit/MangoldtCriticalGap"))]));

    private static Formula Real => F.Seq(F.Mathbb, F.Grp(F.Id("R")));
    private static Formula Nat => F.Seq(F.Mathbb, F.Grp(F.Id("N")));
    private static Formula Bind(FormulaQuantifier q, string name, Formula type, Formula body) =>
        new Formula.Bind(q, FormulaIdentifier.Create(name), type, body);
    private static Formula All(string name, Formula type, Formula body) => Bind(FormulaQuantifier.ForAll, name, type, body);
    private static Formula Exists(string name, Formula type, Formula body) => Bind(FormulaQuantifier.Exists, name, type, body);
    private static Formula Implies(Formula p, Formula q) => new Formula.Logic(p, FormulaLogicOperator.Implies, q);
    private static Formula And(Formula p, Formula q) => new Formula.Logic(p, FormulaLogicOperator.And, q);
    private static Formula Le(Formula x, Formula y) => new Formula.Relation(x, FormulaRelationOperator.LessThanOrEqual, y);
    private static Formula Less(Formula x, Formula y) => new Formula.Relation(x, FormulaRelationOperator.LessThan, y);
    private static Formula At(string name, params Formula[] args) => new Formula.FunctionCall(FormulaIdentifier.Create(name), [.. args]);

    private static Formula Peak()
    {
        var k = F.Id("k");
        var d = F.Id("d");
        var value = At("G", F.Seq(F.Id("n"), F.Plus, k));
        var close = Less(F.Seq(F.Bar, value, F.Minus, F.Id("M"), F.Bar), d);
        var hit = Exists("k", Nat, And(Le(k, F.Id("L")), close));
        return F.Disp(Implies(F.Id("RiemannHypothesis"), All("d", Real, Implies(Less(F.D(0), d),
            Exists("L", Nat, All("n", Nat, hit))))));
    }

    private static Formula Obstruction()
    {
        var x = F.Id("x");
        var y = F.Id("Y");
        var b = F.Id("b");
        var c = F.Id("C");
        var inside = And(Le(y, x), Le(x, F.Seq(y, F.Caret, F.Grp(b))));
        var bound = All("x", Real, Implies(inside, Le(At("U", x), F.Seq(c, F.Sqrt, F.Grp(x)))));
        var windows = All("R", Real, Exists("Y", Real, And(Le(At("max", F.Id("R"), F.D(2)), y), bound)));
        return F.Disp(All("C", Real, All("b", Real, Implies(Less(c, F.Id("M")),
            Implies(Less(F.D(1), b), F.Seq(F.Neg, F.Open, windows, F.Close))))));
    }
}
