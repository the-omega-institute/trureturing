using static StrataLint.Scribe.DefinitionDsl;
using static StrataLint.Scribe.FormulaDsl;
using F = StrataLint.Scribe.FormulaDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.PrimeForms.Splitting;

internal sealed class QuadraticCharacterProfileRedundancyDocument
    : IScribeDocumentDefinition
{
    public DocumentDefinition Create()
    {
        Formula unit = F.Id("u");
        Formula otherUnit = F.Id("v");
        Formula profile = F.Id("t");
        Formula character = Seq(F.Id("chi"), Underscore, Grp(F.Id("new")));
        Formula coefficients = F.Id("c");
        Formula gaussian = Seq(F.Id("chi"), Underscore, Grp(F.Id("G")));
        Formula eisenstein = Seq(F.Id("chi"), Underscore, Grp(F.Id("E")));
        Formula golden = Seq(F.Id("chi"), Underscore, Grp(D(5)));
        Formula image = F.Id("triRingImage");
        Formula unitsModSixty = Seq(
            Open, Mathbb, Grp(F.Id("Z")), Slash, D(6, 0),
            Mathbb, Grp(F.Id("Z")), Close, Caret, Grp(Times));
        Formula binary = Seq(
            Mathbb, Grp(F.Id("Z")), Slash, D(2), Mathbb, Grp(F.Id("Z")));

        Formula product = Seq(
            CharacterPower(gaussian, coefficients, unit, 0), Sp, Cdot, Sp,
            CharacterPower(eisenstein, coefficients, unit, 1), Sp, Cdot, Sp,
            CharacterPower(golden, coefficients, unit, 2));
        Formula fiber = Seq(
            OpenBrace, unit, Colon, Sp, unitsModSixty, Sp, Mid, Sp,
            Apply(image, unit), Sp, Eq, Sp, profile, CloseBrace);

        Formula statement = Disp(Seq(
            Begin, Grp(F.Id("gathered")),
            Open, Forall, Sp, character, Colon, Sp,
            Call("QuadraticObserver", unitsModSixty), Comma, RowBreak, Grp(),
            Exists, Sp, coefficients, Colon, Sp,
            Call("Fin", D(3)), Sp, To, Sp, binary, Comma, RowBreak, Grp(),
            Forall, Sp, unit, Colon, Sp, unitsModSixty, Comma, Sp,
            Apply(character, unit), Sp, Eq, Sp, product, Close,
            Sp, Land, RowBreak, Grp(),
            Open, Forall, Sp, character, Colon, Sp,
            Call("QuadraticObserver", unitsModSixty), Comma, Sp,
            unit, Comma, Sp, otherUnit, Colon, Sp, unitsModSixty,
            Comma, RowBreak, Grp(),
            Apply(image, unit), Sp, Eq, Sp, Apply(image, otherUnit),
            Sp, Rightarrow, Sp,
            Apply(character, unit), Sp, Eq, Sp, Apply(character, otherUnit), Close,
            Sp, Land, RowBreak, Grp(),
            Open, Forall, Sp, profile, Colon, Sp, F.Id("ThreeRingProfile"),
            Comma, Sp, Vert, Sp, fiber, Sp, Vert, Sp, Eq, Sp, D(2), Close, Dot,
            End, Grp(F.Id("gathered"))));

        return DocumentDefinition.Create(ScribeNode.Create(
            "Every mod-sixty quadratic character is generated by the Gaussian, "
                + "Eisenstein, and golden splitting characters and is redundant on their fibers.",
            H("Quadratic Character Profile Redundancy"),
            Blocks(Describe.Lean(
                DescribeId.Create(
                    "quadratic-characters-are-three-ring-products-and-fiber-redundant"),
                DeclarationHandle.Create(
                    "D5/S3/PrimeForms/Splitting/QuadraticCharacterProfileRedundancy."
                        + "quadratic_characters_are_three_ring_products_and_fiber_redundant"),
                H("Additional quadratic characters do not refine the three-ring profile"),
                StatementSource.FromAuthor(statement),
                AssessedProvenance.FromRepo(),
                Blocks(
                    Paragraph(Text(
                        "The three named characters are constructed from the existing "
                            + "Gaussian, Eisenstein, and golden split/inert readings. Split "
                            + "maps to the multiplicative identity and inert to the nonidentity "
                            + "binary value.")),
                    Paragraph(Text(
                        "The unit classes nineteen, twenty-nine, and thirteen give dual "
                            + "generators for these readings. Every unit modulo sixty decomposes "
                            + "over those generators, so the values of an arbitrary quadratic "
                            + "observer determine the displayed three coefficients.")),
                    Paragraph(Text(
                        "Equal three-ring profiles give equal values for each generating "
                            + "character and therefore for every quadratic observer. The frozen "
                            + "profile theorem supplies the exact cardinality two of every fiber."))),
                DescribeRole.Theorem))));
    }

    private static Formula Apply(Formula function, Formula argument) =>
        Seq(function, Open, argument, Close);

    private static Formula CharacterPower(
        Formula character,
        Formula coefficients,
        Formula unit,
        byte index) =>
        new Formula.Power(
            Apply(character, unit),
            Grp(Call("val", Apply(coefficients, D(index)))));
}
