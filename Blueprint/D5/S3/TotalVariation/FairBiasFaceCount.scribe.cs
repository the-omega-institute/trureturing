using static StrataLint.Scribe.DefinitionDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.TotalVariation;

internal sealed class FairBiasFaceCountDocument : IScribeDocumentDefinition
{
    private const string Module = "D5/S3/TotalVariation/FairBiasFaceCount";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "The signed fair-bias complex has explicit face counts and a Tutte evaluation of its reduced Euler characteristic.",
        H("Counting the faces of the fair-bias link"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("card-signed-faces"),
                DeclarationHandle.Create(Module + ".card_signed_faces"),
                H("A support of size k gives two to the k signed faces"),
                StatementSource.WithoutFormula(),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "Take a finite labelled family of columns in an additive commutative group and a positive " +
                    "integer k. The number of faces with k signed labels is two to the power k times the number " +
                    "of k-element sets of labels whose complementary columns generate the subgroup generated by all columns. " +
                    "For each allowed support, a sign function recovers the face by attaching exactly one sign to every label."))),
                DescribeRole.Theorem),
            Describe.Lean(
                DescribeId.Create("reduced-euler-eq-tutte"),
                DeclarationHandle.Create(Module + ".reducedEuler_eq_tutte"),
                H("The reduced Euler characteristic is a Tutte evaluation"),
                StatementSource.WithoutFormula(),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "For a family of n labelled columns in a finite vector space over the binary field, " +
                    "let h be the rank of all columns. The reduced Euler characteristic of the signed complex " +
                    "is minus the product of negative two raised to the power n minus h and the rank-subset " +
                    "Tutte polynomial of the original columns evaluated at one and one half. The empty face " +
                    "contributes minus one. The evaluation at first coordinate one retains precisely the subsets " +
                    "whose columns span the full column space."))),
                DescribeRole.Theorem))));
}
