using static StrataLint.Scribe.DefinitionDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.TotalVariation;

internal sealed class FairBiasLinkDocument : IScribeDocumentDefinition
{
    private const string Module = "D5/S3/TotalVariation/FairBiasLink";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "Signed faces describe the local directions that retain a spanning set of fair inputs.",
        H("The local link of the fair-bias coordinates"),
        Blocks(
            Describe.Lean(
                DescribeId.Create("fair-bias-link-realization"),
                DeclarationHandle.Create(Module + ".fair_bias_link_realization"),
                H("The link is homeomorphic to the realization of the signed complex"),
                StatementSource.WithoutFormula(),
                AssessedProvenance.FromRepo(),
                Blocks(Paragraph(Text(
                    "Fix a finite labelled family of columns in an additive commutative group. " +
                    "The link consists of real coordinate vectors whose absolute values sum to one " +
                    "and whose zero coordinates still index a generating family for the subgroup " +
                    "generated by all columns. A nonempty face of the signed complex uses at most " +
                    "one sign at each label and leaves a generating family at the unused labels. " +
                    "There is a homeomorphism from the link to the barycentric realization that " +
                    "sends a coordinate to its positive and negative parts. Taking the difference " +
                    "of the two weights recovers each coordinate, and the nonzero weights record " +
                    "its sign. The result includes the empty link."))),
                DescribeRole.Theorem))));
}
