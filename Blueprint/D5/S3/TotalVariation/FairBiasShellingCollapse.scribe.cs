using static StrataLint.Scribe.DefinitionDsl;

namespace StrataLint.Scribe.Blueprint.D5.S3.TotalVariation;

internal sealed class FairBiasShellingCollapseDocument : IScribeDocumentDefinition
{
    private const string Module = "D5/S3/TotalVariation/FairBiasShellingCollapse";

    public DocumentDefinition Create() => DocumentDefinition.Create(ScribeNode.Create(
        "A shelling step with a nonempty proper restriction face collapses to the preceding prefix.",
        H("Elementary collapses in the fair-bias shelling"),
        Blocks(Describe.Lean(
            DescribeId.Create("exists-prescribed-collapse"),
            DeclarationHandle.Create(Module + ".exists_prescribed_collapse"),
            H("Prescribed deletions at one facet"),
            StatementSource.WithoutFormula(),
            AssessedProvenance.FromRepo(),
            Blocks(Paragraph(Text(
                "Start with the subcomplex generated by a facet B and all earlier facets of the signed " +
                "fair-bias complex. Suppose the restriction face at B is nonempty. Fix a vertex v of B " +
                "outside it. List every new face avoiding v exactly once, in weakly decreasing " +
                "cardinality. There is a sequence of elementary collapses onto the subcomplex of earlier " +
                "facets whose lower faces occur in exactly that list and whose upper faces adjoin v. " +
                "Every other strict coface of a scheduled lower face belongs to a pair with a larger " +
                "lower face, so it has already been deleted."))),
            DescribeRole.Theorem))));
}
